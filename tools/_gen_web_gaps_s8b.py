#!/usr/bin/env python3
"""Expand S8 gitea/teamcity lessons toward 1200 real content words."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, 'content', 'web')

def expand(fname, extra):
    p = os.path.join(W, fname)
    t = open(p, encoding='utf-8').read()
    t = t.replace('\n## Квиз', '\n' + extra.strip() + '\n\n## Квиз', 1)
    open(p, 'w', encoding='utf-8').write(t)

expand('web-gitea-gogs.md', r"""
## Разбираем анатомию репозитория как источника секретов

Чтобы находить секреты быстро, нужно знать, **куда** смотреть. В типовом репозитории чувствительные данные лежат не в коде, а в служебных файлах:

- `.env`, `.env.production` — переменные окружения с паролями и ключами.
- `docker-compose.yml`, `Dockerfile` — образы и креды к registry.
- `config/*.yml`, `settings.py`, `application.properties` — конфиги приложений с доступами к БД.
- `.github/workflows/*.yml`, `.gitlab-ci.yml`, `.drone.yml` — CI-пайплайны, где бывают токены деплоя.
- `id_rsa`, `*.pem`, `*.key` — приватные ключи (редко, но бывает).
- `terraform.tfstate` — состояние инфраструктуры с секретами облака.
- `.git/config` — иногда содержит URL с встроенными кредами.

Хорошая практика при пентесте SCM: не читать весь код, а **грепать по шаблонам**. Ищи строки вида `password=`, `secret`, `token`, `api_key`, `BEGIN PRIVATE KEY`. В Gitea это делается через API поиска или через клонирование и локальный grep.

## Шаг 7: проверить настройки на утечки

Помимо файлов, у Gitea есть настройки, которые иногда открыты анонимно. Проверь `/api/v1/settings/api`, `/api/v1/settings/ui` — там видны параметры инстанса, включая разрешённые регистрации. Если регистрация открыта, можно создать пользователя и получить легитимный доступ к приватным репозиториям. Это уже не утечка, а полноценный вход.

```
$ curl -s http://gitea.target.example:3000/api/v1/settings/api
{"max_response_items":50,"default_paging_num":30,"default_git_trees_per_page":1000}
```

## Шаг 8: как отличить Gitea от GitLab

Обе системы — SCM, но CVE и векторы разные. Gitea: лёгкий Go-сервис, `/api/v1/version`, порт 3000, характерный минималистичный UI. GitLab: Ruby/Go, `/api/v4/version`, порт 80/443, тяжёлый интерфейс, свои CVE (CVE-2021-22205 ExifTool RCE, CVE-2023-2825 traversal). Определяй продукт до атаки: payload'ы не взаимозаменяемы.

## Шаг 9: что писать в отчёте

Отчёт по SCM фиксирует: продукт и версию; факт анонимного доступа (что именно видно); **список утёкших секретов** (тип, но не сами значения целиком); какие системы они открывают; рекомендацию (закрыть анонимный доступ, ротировать утёкшие секреты, включить 2FA, аудит коммитов на секреты).

## Ошибки и антипаттерны

Первая — выкачивать все репозитории целиком: это гигабайты и заметно. Достаточно найти несколько секретов как доказательство. Вторая — публиковать найденные пароли в открытом виде: маскируй их в отчёте. Третья — считать «публичный репозиторий» безобидным: именно в публичных чаще всего лежат забытые `.env`.
""")

