def insert(path, extra):
    with open(path, encoding='utf-8') as f:
        t = f.read()
    for marker in ('\n## Что мы теперь знаем', '\n## Квиз'):
        i = t.find(marker)
        if i != -1:
            break
    assert i != -1, path
    with open(path, 'w', encoding='utf-8') as f:
        f.write(t[:i] + '\n' + extra.strip() + '\n' + t[i:])

