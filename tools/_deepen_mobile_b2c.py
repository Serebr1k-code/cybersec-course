"""Third (prose-heavy) deepening pass for MOB-GAP-2 lessons to clear 1200 real words."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')

def add_before_quiz(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip:', lid); return
    i = t.index('\n## Квиз')
    open(p, 'w', encoding='utf-8').write(t[:i] + '\n' + extra.strip() + '\n' + t[i:])
    print('deepened:', lid)

SELINUX = '''
## Шаг 15: практическая модель угроз «root + SELinux»

На устройствах с Magisk root-процесс получает широкий домен, потому что сам Magisk правит
политику на лету. Но это лишь удобство исследователя: в «дикой» эксплуатации эксплойт даёт
выполнение кода внутри **конкретного** домена (например, домена медиа-сервиса), и дальше
атакующий ограничен именно его разрешениями. Отсюда типичная структура современной цепочки
эксплуатации Android: найти уязвимость в процессе с относительно широким доменом, выполнить
код в нём, затем либо перейти в ещё более привилегированный домен через domain transition, либо
загрузить модуль ядра, либо ослабить политику. Ключевой вывод для аудита: «получен root» само
по себе ничего не значит, пока не сказано, **в каком домене** и что этому домену разрешено.
Именно поэтому в отчётах по Android-эксплуатации всегда указывают scontext — иначе оценка
ущерба будет неверной.
'''

NOTIF = '''
## Шаг 16: комбинация с другими API

По отдельности чтение уведомлений — уже перехват OTP, но в реальных банковских троянах это
лишь часть триады: **NotificationListenerService** читает код, **Accessibility Service**
нажимает кнопки в интерфейсе банка, а **overlay** (`SYSTEM_ALERT_WINDOW`) рисует поддельный
экран поверх настоящего. Вместе они позволяют провести перевод целиком без участия жертвы.

Полезные детали, которые стоит искать при реверсе:

- `onListenerConnected()` вызывается при подключении; в нём малварь часто вызывает
  `getActiveNotifications()`, чтобы сразу слить **уже висящие** в шторке уведомления.
- `getActiveNotifications()` возвращает массив `StatusBarNotification` — весь текущий поток.
- `cancelNotification(key)` скрывает уведомление от пользователя, «заметая следы» операции.
- `sbn.getPostTime()` и `getPackageName()` позволяют фильтровать только свежие сообщения от
  нужных банков, игнорируя шум.

Если приложение одновременно просит роль слушателя уведомлений и доступность, это почти
наверняка троян: легитимному приложению обе роли вместе нужны крайне редко.
'''

ATTEST = '''
## Шаг 14: зачем это пентестеру

Аттестация — типичная «последняя линия» защиты банковских и DRM-приложений: даже если вы
обошли SSL pinning и root-детект, сервер может отказать, если не получит валидную аттестацию.
Поэтому в пентесте важно понять, **на чём именно держится доверие**: только на клиентской
проверке (обходится патчем smali), на подписанном вердикте Google (обходится только прокси с
чистого устройства) или на challenge, привязанном к сессии (обходится лишь если сервер его не
сверяет). Ответ определяет, какой из путей реально применим, и стоит ли вообще тратить время на
обход клиентских проверок, которые сервер всё равно не подтверждает.

## Шаг 15: сравнение механизмов

| Механизм | Платформа | Что проверяет | Слабое место |
|---|---|---|---|
| Key Attestation | Android | происхождение ключа, boot state | серверная проверка корня/challenge |
| Play Integrity | Android | целостность устройства + приложение | classic-запрос без nonce |
| DeviceCheck | iOS | две бита состояния устройства | не доказывает целостность |
| App Attest | iOS | аппаратный ключ + счётчик | серверная проверка счётчика |

Общий принцип один и тот же на обеих платформах: криптография надёжна, ломается **проверка**.
Клиент присылает доказательство, а сервер обязан проверить его полностью — корень, nonce,
привязку к приложению и срок. Если этого нет, механизм обходится подменой ответа.
'''

for lid, extra in [
    ('mobile-android-selinux', SELINUX),
    ('mobile-android-notification-listener', NOTIF),
    ('mobile-android-attestation', ATTEST),
]:
    add_before_quiz(lid, extra)

print('done')
