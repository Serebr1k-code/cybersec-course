def main():
    done=0
    for lid, extra in ADD.items():
        p=os.path.join(C, lid+'.md')
        text=open(p,encoding='utf-8').read()
        if MARK in text: continue
        idx=text.find('\n## Квиз')
        if idx==-1: print('no quiz',lid); continue
        block='\n'+extra.strip()+'\n\n'+MARK+'\n'
        open(p,'w',encoding='utf-8').write(text[:idx]+block+text[idx:])
        done+=1
    print('topped-up',done)
main()
