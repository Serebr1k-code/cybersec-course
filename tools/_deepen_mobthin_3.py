ANGR = '''
## Шаг 8: хуки и символьные ограничения

Реальные проверки часто используют хеш-функцию или CRC. Символически исполнять саму хеш-функцию
бессмысленно — angr утонет. Вместо этого функцию заменяют хуком, который добавляет ограничение
на результат:

```python
def hook_md5(state):
    inp = state.memory.load(state.regs.x0, 16)
    state.regs.x0 = 0xdeadbeef          # фиктивный «хеш»
    state.solver.add(inp == b'nto-4ngr')  # сразу задаём ожидаемое
proj.hook(0x1500, hook_md5, length=4)
```

Так сложная функция сворачивается в одно ограничение, и решатель находит вход. Это ключевой
приём: не эмулировать криптографию, а описывать её результат.

## Шаг 9: angr против Unicorn

Это разные инструменты для разных задач. Unicorn **исполняет** функцию с конкретным входом и
даёт конкретный выход — быстро, но без поиска. angr **ищет** вход, при котором выполняется
условие, — медленно, но автоматически. На практике их комбинируют: angr находит кандидата, а
Unicorn (или приложение) проверяет его на реальном коде. Если проверка не выражается формулой
(например, зависит от времени), angr не поможет, и остаётся только эмуляция или динамика.

## Пример: проверка со сравнением хеша

Пусть функция берёт строку, считает MD5 и сравнивает с константой. Порядок работы: в Ghidra
находим адрес вызова MD5 и адрес сравнения; в angr хукаем MD5, добавляя ограничение; запускаем
`explore` до адреса успеха. Решатель вернёт строку, чей MD5 совпадает с константой. Это и есть
пароль. Так обходится даже проверка, которую нереально прочитать глазами.

## Таблица типичных проблем angr

| Проблема | Причина | Решение |
|---|---|---|
| зависание | взрыв путей | `avoid`, ограничить вход |
| пусто в found | неверный адрес | сверить адрес из Ghidra |
| нет конкретных байтов | символический вход | вызвать `eval` на буфере |
| ошибка загрузки .so | зависимости | `auto_load_libs=False` |
| долгий поиск | циклы | хуки вместо эмуляции |

## Практический вывод

angr — это автоматический подбор входа для проверок, которые можно выразить формулой. Порядок:
найти функцию и адреса успеха/неудачи в Ghidra, смоделировать вход символическим буфером,
запустить `explore`, при необходимости свернуть сложные функции хуками. Когда проверка упирается
в окружение или криптографию, символьное исполнение уступает место эмуляции и динамике. Умение
вовремя переключиться между этими подходами и есть суть мобильного реверса.
'''

