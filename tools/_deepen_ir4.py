ADD['ir-threat-hunting'] = """
## Гипотезы из инцидентов прошлого

Самый богатый источник гипотез — **прошлые инциденты**. Если год назад атакующий закрепился
через задачу по расписанию, логично проверить: нет ли похожего закрепления сейчас, на
других хостах, которое тогда пропустили.

Такая охота называется «hunt backward»: мы возвращаемся к прошлому инциденту и ищем, не
осталось ли его следов в других местах. Часто обнаруживается, что атака была шире, чем
думали, или что тот же приём применялся к другим системам.

## Когда охота становится детектом

Найденный приём нужно **закрепить**. Иначе в следующий раз его опять придётся искать
вручную. Цикл превращения:

1. Нашли аномалию в ходе охоты.
2. Описали её как **правило** (какие поля, какие значения).
3. Проверили на исторических данных: не даёт ли ложных срабатываний.
4. Задеплоили как детект.
5. При необходимости — автоматизировали реакцию.

Так охотник кормит SOC новыми детектами, и его работа не пропадает.

## Охота — это навык, а не кнопка

Инструменты лишь помогают. Настоящий навык — **мышление атакующего**: понимать, как бы ты
действовал на месте злоумышленника в этой инфраструктуре, и искать именно это. Поэтому
лучшие охотники часто приходят из red team или из разбора инцидентов: они знают, как
выглядит атака изнутри.

Охота плохо автоматизируется до конца — это исследовательская работа. Но её результаты
хорошо автоматизируются: найденный приём превращается в детект и живёт дальше сам.
"""

