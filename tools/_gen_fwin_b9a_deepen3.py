ADD['win-dns-cache'] = r'''
## Реестр как источник DNS-настроек

Помимо самого кэша, настройки DNS-клиента хранятся в реестре — и их тоже правят:

```
HKLM\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters
HKLM\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces\<GUID>
```

Поля `NameServer`, `DhcpNameServer`, `SearchList` показывают, какие DNS-серверы
настроены. Атакующий может подменить DNS-сервер на свой (для перехвата) или добавить
суффикс поиска. Проверка этих ключей объясняет, **куда** уходили запросы, даже если
кэша уже нет. Вместе с `hosts` это полная картина разрешения имён на хосте.

## Хронология и часовые пояса

События DNS Client пишутся в UTC, а кэш не содержит времени вовсе. При построении
таймлайна это критично: нельзя смешивать времена из кэша (без времени) и журнала (UTC)
без нормализации. Всегда фиксируйте, из какого источника взято время, и переводите в
единый пояс. Иначе можно «доказать», что запрос был до заражения, хотя на самом деле он
шёл после — просто время интерпретировали неверно.
'''

ADD['win-wer'] = r'''
## Устойчивость WER и следы очистки

WER — один из самых живучих артефактов, но его тоже пытаются чистить. Признаки
вмешательства:

- **пустой ReportArchive** при непустом `ReportQueue` — кто-то удалил архив;
- **аномально свежий LastWriteTime** каталога WER при старых системных файлах;
- **отключённая служба** `WerSvc` — тогда новые отчёты не создаются;
- реестровый ключ `HKLM\SOFTWARE\Microsoft\Windows\Windows Error Reporting\Disabled=1`.

Если WER выключен, это само по себе подозрительно: штатно он включён. Поэтому проверку
службы и ключа добавляют в чек-лист анти-форензик-индикаторов наравне с очисткой журналов.
'''

