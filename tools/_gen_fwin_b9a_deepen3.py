ADD['win-app-compat'] = r'''
## Откуда берётся AppCompatCache и когда он обновляется

Значение `AppCompatCache` пишется при обращении системы к каталогам с исполняемыми
файлами — индексатором, сканером или при запуске. Поэтому оно обновляется не только при
запуске, но и при простом «просмотре» каталога системой. Отсюда важная оговорка: запись
доказывает, что файл **существовал** на диске и был замечен, но не всегда что его
запускал пользователь.

На практике кэш обновляется при перезагрузке и при сканировании, а старые записи
вытесняются новыми. Поэтому AppCompatCache — это «окно» последних нескольких сотен
путей, а не полная история. Для долгой ретроспективы его комбинируют с AmCache, который
хранит больше записей и хеши.

## Частая ошибка интерпретации

Самая распространённая ошибка новичка — прочитать путь в ShimCache как «файл
запускался». Корректная логика: путь означает «файл присутствовал». Признак запуска
появляется только там, где версия Windows пишет соответствующий флаг, и только вместе с
подтверждающим артефактом (Prefetch, AmCache, WER, событие 4688). В отчёте всегда
указывают версию Windows и наличие флага — иначе вывод легко опровергнуть.
'''

