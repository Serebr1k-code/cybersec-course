import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PWNDIR = os.path.join(ROOT, 'content', 'pwn')
MARKER = '## Что мы теперь знаем'
SENT = '<!-- EXPANDED_B16E -->'

EXTRA = {}

EXTRA['pwn-windows-token-stealing'] = r"""
## Сводка по шагам

Ещё раз, коротко и по порядку, что делает эксплойт token stealing:

1. **Утечка** даёт базу `ntoskrnl.exe` (KASLR сломан).
2. Примитив **чтения** находит адрес `_EPROCESS` нашего процесса через список
   `ActiveProcessLinks` или по известному смещению.
3. Из `_EPROCESS` читается поле `Token` (смещение зависит от сборки).
4. Отдельно находится `Token` процесса SYSTEM (PID 4).
5. Примитив **записи** кладёт SYSTEM-токен в поле `Token` нашего процесса.
6. Проверка: `whoami` возвращает `nt authority\system`.

Обрати внимание: шаги 2–5 — чисто **data-only**. Ни одной инструкции нашего
кода в ring 0 не исполняется. Именно поэтому цепочка работает даже при HVCI, где
исполнение неподписанного кода запрещено. Это делает token stealing базовым
приёмом для любого современного Windows kernel-эксплойта.

"""

EXTRA['pwn-windows-iop'] = r"""
## Сводка

I/O ring — недокументированный механизм асинхронного ввода-вывода, похожий на
Linux `io_uring`. Для эксплойт-разработчика он ценен тремя свойствами: общими
очередями в памяти, возможностью регистрировать файлы и буферы, и слабыми
проверками по сравнению с публичными API.

Использовать его стоит аккуратно: структуры версионны, ошибка роняет систему, а
HVCI и PatchGuard ограничивают прямые правки. Правильная стратегия — применять
ring как **data-only** примитив доступа к внутренностям ядра, а не как способ
исполнить свой код.

Вместе с уязвимым драйвером (или BYOVD) ring замыкает цепочку: баг даёт запись,
а недокументированный механизм помогает добраться до нужной структуры ядра.

"""

EXTRA['pwn-hyperv-escape'] = r"""
## Сводка

Побег из Hyper-V — это атака на **границу** между гостем и хостом. Гость шлёт
запросы через VMBus к синтетическим устройствам, а хост обязан их обрабатывать.
Баг в этой обработке (переполнение, OOB, type confusion, UAF) даёт примитив в
памяти родительского раздела, из которого строится компрометация хоста.

Исследование начинается с инвентаризации доступных гостю интерфейсов и разбора
формата сообщений, продолжается аудитом/фаззингом хост-парсеров и завершается
обходом VBS/HVCI. Высокая сложность компенсируется высшей категорией риска:
компрометация гипервизора ломает изоляцию между всеми ВМ на хосте.

"""

EXTRA['pwn-vbs-hvci'] = r"""
## Сводка

VBS использует гипервизор для изоляции критичных компонентов Windows, а HVCI
запрещает исполнять неподписанный код в режиме ядра. Это меняет парадигму
эксплуатации: вместо захвата потока управления и shellcode мы атакуем **данные**,
которые исполняет доверенный код.

Практические пути при VBS/HVCI: data-only примитивы (token stealing), загрузка
подписанного уязвимого драйвера (BYOVD) и, в редких случаях, атака на сам secure
kernel. Credential Guard дополнительно ломает классическую кражу учётных данных,
заставляя использовать существующие сессии и делегирование. Понимание VBS/HVCI —
обязательная часть современной Windows kernel-эксплуатации.

"""


def main():
    for lid, extra in EXTRA.items():
        path = os.path.join(PWNDIR, lid + '.md')
        with open(path, encoding='utf-8') as f:
            txt = f.read()
        if SENT in txt:
            print('SKIP (already):', lid)
            continue
        if MARKER not in txt:
            print('SKIP (no marker):', lid)
            continue
        txt = txt.replace(MARKER, extra.strip() + '\n\n' + SENT + '\n\n' + MARKER, 1)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(txt)
        print('expanded:', lid)


if __name__ == '__main__':
    main()
