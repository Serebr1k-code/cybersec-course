def main():
    n = 0
    for lid, extra in EXTRA.items():
        path = os.path.join(CONTENT, lid + '.md')
        with open(path, encoding='utf-8') as f:
            text = f.read()
        if '<!-- b10exp8 -->' in text:
            continue
        marker = '\n## Квиз\n'
        assert marker in text, 'no quiz heading in ' + lid
        text = text.replace(marker, '\n' + extra + '<!-- b10exp8 -->\n' + marker, 1)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
        n += 1
    print('expanded8 lessons:', n)


if __name__ == '__main__':
    main()
