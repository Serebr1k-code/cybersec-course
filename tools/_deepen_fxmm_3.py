ADD['misc-crt-fault'] = r"""
## Разбор: почему blinding помогает

Без blinding сбой коррелирует с конкретным сообщением: подпись `m_p'` «привязана» к `m`,
и разность выдаёт множитель. Blinding разрывает эту связь:

```
s = (m · r^e)^d mod n · r^{-1} mod n
```

Вычисление идёт над `m·r^e` — случайной величиной. Даже если в CRT произойдёт сбой,
полученное `s'` не связано с исходным `m` предсказуемо, и классический `gcd(s_ok − s_bad, n)`
не даёт делителя. Это дёшево (два умножения) и закрывает атаку Bellcore. Проверяй в
исходниках, есть ли blinding и проверка подписи перед выдачей: их отсутствие —
типичная находка в embedded и самодельных реализациях.
"""

