def find_file(lid):
    for cat in ("misc", "mobile"):
        p = os.path.join(ROOT, "content", cat, lid + ".md")
        if os.path.exists(p):
            return p
    return None


def main() -> int:
    n = 0
    for lid, add in ADD.items():
        path = find_file(lid)
        if not path:
            print("MISSING", lid, file=sys.stderr)
            continue
        t = open(path, encoding="utf-8").read()
        if MARK in t:
            print("skip (already)", lid)
            continue
        m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
        if not m:
            m = re.search(r"^## Что мы теперь знаем\s*$", t, re.MULTILINE)
        if not m:
            print("NO ANCHOR", lid, file=sys.stderr)
            continue
        block = MARK + "\n" + add.strip() + "\n\n"
        t = t[:m.start()] + block + t[m.start():]
        open(path, "w", encoding="utf-8").write(t)
        print("deepened3", lid)
        n += 1
    print("done:", n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
