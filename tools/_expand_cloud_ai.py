def main():
    for lid, extra in EXTRA.items():
        p = os.path.join(ROOT, 'content', 'cloud', lid + '.md')
        if not os.path.exists(p):
            print('missing', p)
            continue
        t = open(p, encoding='utf-8').read()
        m = re.search(r'^## Квиз\s*$', t, re.MULTILINE)
        if not m:
            print('no quiz', p)
            continue
        add = extra.strip('\n')
        out = t[:m.start()] + add + '\n\n' + t[m.start():]
        open(p, 'w', encoding='utf-8').write(out)
        print('expanded', lid)


if __name__ == '__main__':
    main()
