#!/usr/bin/env python3
"""Third top-up pass for batch A (three lessons still under 1200)."""
import re

ADD = {}

ADD["win-activity-timeline"] = r'''
## Практический чек-лист по ActivitiesCache.db

Чтобы не потерять важное при разборе, держи короткий порядок действий. Сначала опознай
формат (`file ActivitiesCache.db`). Затем посмотри таблицы и схему — не угадывай имена
колонок. Дальше выгрузи активности за интересующий интервал, отсортировав по `StartTime`.
Для каждой подозрительной сессии достань `ContentInfo` и разбери JSON, чтобы получить путь
к объекту. После этого свериться с `Windows.edb`, JumpLists и Prefetch и зафиксируй время в
явном поясе. В конце сохрани выгрузку в CSV, чтобы приложить к отчёту и воспроизвести вывод
на защите. Такой чек-лист переносится на любой похожий SQLite-артефакт профиля.
'''

ADD["win-notification-db"] = r'''
## Типичные сценарии и что они доказывают

Уведомления особенно полезны в трёх ситуациях. Первая — восстановление коммуникаций, когда
само приложение удалено: текст тоста остаётся в системной базе. Вторая — подтверждение
**времени** события: тост о встрече или платеже датирует взаимодействие, даже если других
логов нет. Третья — установление **списка приложений**: хендлеры в базе показывают, какие
программы уведомляли пользователя, что косвенно говорит о его инструментарии. Во всех трёх
случаях база уведомлений выступает независимым источником, и его ценность растёт, когда
другие данные вычищены. Помни только об ограничении срока хранения и по возможности
работай с историческим снимком профиля.
'''

ADD["win-cortana-search"] = r'''
## Итоговый вывод по артефакту

Поисковая история — это редкий тип артефакта, который фиксирует **намерение**, а не
результат. В отличие от запущенного процесса или созданного файла, запрос показывает, что
пользователь хотел сделать, и потому хорошо работает как отправная точка расследования.
Собери запросы, разложи их по категориям, свяжи по времени с последующими действиями и
обязательно оговори ограничения (сбор мог быть отключён, историю могли очистить). В отчёте
запросы лучше приводить таблицей: время, текст, категория и сопоставленное действие — так
читатель видит не разрозненные строки, а выстроенную линию поведения.
'''

for lid, add in ADD.items():
    p = f"content/forensics/{lid}.md"
    t = open(p, encoding="utf-8").read()
    m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
    out = t[:m.start()] + add.strip() + "\n\n" + t[m.start():]
    open(p, "w", encoding="utf-8").write(out)
    print("topup", lid)
