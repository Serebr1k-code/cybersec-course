ADD['tl-cross-artifact'] = """
## Формат супер-таймлайна

Чтобы объединять события из разных источников, их приводят к единому формату. Минимальный
набор полей:

| Поле | Значение |
|------|----------|
| timestamp | время в UTC |
| source | откуда событие (файл, журнал, дамп) |
| host | на каком хосте |
| user | под кем |
| event | что произошло |
| key | ключ корреляции (PID, путь, IP) |

Такой формат позволяет сортировать всё вместе и фильтровать по любому полю. Инструменты
вроде Plaso генерируют подобную структуру автоматически из десятков артефактов.

## Почему каждый артефакт частичен

Полезно понимать ограничения каждого источника, чтобы не ждать от него лишнего:

- **Реестр** знает о настройках и закреплении, но не о времени запуска процессов.
- **Журналы событий** знают о входах и службах, но не о содержимом файлов.
- **Файловая система** знает о созданных/изменённых файлах, но таймстемпы можно подделать.
- **Сеть** знает о соединениях, но не о том, что процесс делал локально.
- **Память** знает о живых процессах и соединениях, но только на момент снятия.

Отсюда вывод: **полнота достигается только совокупностью**. Пропуск любого слоя оставляет
дыру в картине, и её нужно честно отметить.

## Связь событий: пример с закреплением

Разберём, как корреляция вскрывает закрепление. Наблюдения из разных источников:

```
Реестр:    Run-ключ "Updater" -> C:\\Users\\Public\\u.exe
Файлы:     C:\\Users\\Public\\u.exe создан 11:02:10
Процессы:  u.exe запущен 11:05:00 (родитель explorer.exe)
Сеть:      u.exe -> 198.51.100.7:8443
```

По отдельности: ключ реестра (подозрительный), файл (неизвестный), процесс (запущен),
соединение (внешнее). Вместе — полная цепочка: закрепление создано, файл лежит, процесс
запущен, C2 установлен. Ключ корреляции — путь файла и PID процесса.

## Как отделять сигнал от шума

В супер-таймлайне миллионы событий, и большая часть — нормальная. Чтобы не утонуть:

- построй **базовую линию**: какие процессы, задачи, соединения типичны;
- фильтруй по **редкости**: редкое событие — кандидат;
- фильтруй по **времени**: окно вокруг подозрительного эпизода;
- фильтруй по **сущности**: конкретный пользователь, хост, процесс.

Хороший приём — начать с одного «якорного» события (подозрительный процесс) и раскручивать
связи вокруг него, а не просматривать всё подряд.

## Ограничения корреляции

Корреляция не всесильна. Она может:

- **объединить несвязанное** — если ключ совпал случайно (например, одинаковый PID в разное
  время);
- **пропустить связь** — если ключа нет (процесс завершился, следов не осталось);
- **ввести в заблуждение** — если таймстемпы подделаны.

Поэтому корреляцию всегда сопровождают **provenance** (откуда каждое событие) и оценкой
уверенности. Связь без обоснования — это гипотеза, а не факт.

## Мини-упражнение

Возьми два артефакта (например, историю команд и список процессов) и попробуй связать их
события по общему ключу. Определи, какие связи подтверждены, а какие — только по времени.
Отметь, где данных не хватает для уверенного вывода.
"""

ADD['tl-entity-resolution'] = """
## Источники идентификаторов

Разные системы хранят разные идентификаторы одного субъекта. Полезно знать, где что искать:

| Система | Идентификатор |
|---------|---------------|
| Windows | SID, `DOMAIN\\user`, RID |
| Linux | UID, логин, GECOS |
| Почта | адрес, display name |
| Сеть | IP, MAC, hostname |
| Приложения | логин в приложении, токен |

Задача — собрать эти идентификаторы и найти между ними мостики. Мостик — это артефакт, где
встречаются сразу два идентификатора: например, строка лога, где рядом стоят `DOMAIN\\user`
и `SID`.

## Мостики между идентификаторами

Мостик — ключевой инструмент. Примеры:

```
Security log:   CORP\\jsmith  (SID S-1-5-21-...-1001)
DNS-лог:        WS-22.corp.local -> 10.0.4.22
DHCP-лог:       10.0.4.22 -> MAC 00:1A:2B:...  (lease 09:00-17:00)
```

Здесь два мостика: логин↔SID и hostname↔IP↔MAC. Соединив их, получаем: `jsmith` работал
на `WS-22` с адресом `10.0.4.22` в окне 09:00–17:00. Каждый шаг подтверждён артефактом.

## Время как обязательный атрибут связи

Связь без времени неполна. IP `10.0.4.22` принадлежал `WS-22` только в окне аренды DHCP.
Если событие произошло вне этого окна — связка недействительна.

Поэтому при разрешении сущностей всегда фиксируют **интервал**, а не просто значение. Это
защищает от ложных объединений: адрес мог быть переиспользован.

## Сервисные и общие учётки

Особый случай — учётки, под которыми работают многие: `svc_backup`, `deploy`, `admin`.
Действие под такой учёткой **нельзя** приписать конкретному человеку без дополнительных
данных (например, источника входа).

Практический подход: помечать такие учётки как «общие» и не строить на них персональную
атрибуцию. Иначе легко обвинить не того сотрудника.

## Противоречия и как с ними быть

Иногда данные противоречат: один источник говорит, что IP принадлежал A, другой — что B.
Причины:

- разные окна времени;
- ошибка в одном из логов;
- смена аренды DHCP;
- NAT, за которым несколько хостов.

Правильная реакция — **показать противоречие**, а не выбрать удобную версию. Уверенность
такой связи понижается, и в отчёте это отражается.

## Мини-упражнение

Собери из трёх источников идентификаторы одного пользователя и построй цепочку мостиков от
логина к IP. Для каждого перехода укажи артефакт-обоснование и временное окно. Если хотя бы
один переход не подтверждён — отметь связь как предположительную.

## Резюме

Entity resolution — это не «угадать, что это один человек», а **доказать** это через мостики
между идентификаторами с учётом времени. Надёжность ключей различается, коллизии возможны,
а общие учётки ломают персональную атрибуцию. Каждая связь фиксируется с уровнем уверенности.
"""

for lid, add in ADD.items():
    path = os.path.join(C, lid + '.md')
    t = open(path, encoding='utf-8').read()
    m = re.search(r'^## Квиз\s*$', t, re.MULTILINE)
    t = t[:m.start()] + add.strip() + '\n\n' + t[m.start():]
    open(path, 'w', encoding='utf-8').write(t)
    print('deepened', lid)
