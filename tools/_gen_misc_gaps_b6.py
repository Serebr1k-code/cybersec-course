st = []
for i, c in enumerate(code):
    if c == '[': st.append(i)
    elif c == ']':
        j = st.pop(); br[i] = j; br[j] = i
i = 0
while i < len(code):
    c = code[i]
    if c == '>': p += 1
    elif c == '<': p -= 1
    elif c == '+': tape[p] = (tape[p] + 1) % 256
