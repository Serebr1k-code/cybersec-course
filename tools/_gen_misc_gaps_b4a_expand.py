#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Expand MIS-GAP-4a lessons to >=1200 real content words (append before ## Квиз)."""
import re

CONTENT = 'content/misc/'


def add(lesson, text, minutes=None):
    p = CONTENT + lesson + '.md'
    s = open(p, encoding='utf-8').read()
    add_txt = text.strip()
    if '## Квиз' in add_txt or '## Где пригодится' in add_txt:
        raise SystemExit('additions must not contain Квиз/Где пригодится')
    m = re.search(r'^## Квиз\s*$', s, re.MULTILINE)
    if not m:
        raise SystemExit('no quiz: ' + lesson)
    out = s[:m.start()] + add_txt + '\n\n' + s[m.start():]
    if minutes:
        out = re.sub(r'^estimated_minutes:.*$', f'estimated_minutes: {minutes}',
                     out, count=1, flags=re.MULTILINE)
    open(p, 'w', encoding='utf-8').write(out)
    print('expanded', lesson)


