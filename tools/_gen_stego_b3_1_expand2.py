"""Second expansion pass for stego B3-1 lessons (push each over 1200 real words)."""
import os

ROOT = "content/stego"

def expand(lid, extra):
    path = os.path.join(ROOT, lid + ".md")
    if not os.path.exists(path):
        print("MISSING", path); return
    t = open(path, encoding="utf-8").read()
    key = extra.strip().splitlines()[0]
    if key in t:
        print("SKIP(done)", lid); return
    marker = "## Что мы теперь знаем"
    t = t.replace(marker, extra.strip() + "\n\n" + marker, 1)
    open(path, "w", encoding="utf-8").write(t)
    print("EXPANDED", lid)

