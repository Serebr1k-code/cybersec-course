E['misc-llm-tokenizer'] = '''
## Шаг 8: byte-level BPE

Современные модели используют **byte-level BPE**: базовые единицы — байты, а не символы. Это решает проблему «неизвестного символа»: любое слово, любой язык и даже эмодзи представимы байтами. Поэтому модель «понимает» произвольный текст, но редкие последовательности режутся на много токенов — отсюда рост стоимости.

## Шаг 9: glitch tokens

**Glitch-токены** — редкие токены словаря, на которых модель ведёт себя странно (например, не может повторить слово). Они появляются из-за того, что словарь строится по корпусу, а некоторые токены почти не встречались в обучении. Их используют в задачах, где нужно «сломать» поведение модели необычным входом.

## Шаг 10: как измерить токены

Точное число токенов даёт сам токенизатор модели (в Python — библиотека `tiktoken` или `transformers`). Оценка «на глаз»: английский ≈ 4 символа/токен, кириллица ≈ 1–2 символа/токен, base64 — почти 1 токен на 1–2 символа. Это объясняет, почему русский запрос «дороже» английского.

## Шаг 11: обход фильтров на практике

Пусть фильтр запрещает слово `password`. Варианты обхода через представление:

- `pass word` (пробел) — если фильтр не нормализует пробелы;
- `pass\u200bword` (zero-width space) — визуально одно слово;
- `pаssword` с кириллической `а` — другая кодовая точка, тот же вид;
- `pass` + `word` как отдельные токены.

Проверка: восстанавливает ли потребитель смысл после нормализации.

## Шаг 12: многоязычность и стоимость

Словарь оптимизирован под язык корпуса: для английского часты целые слова-токены, для других языков — подслова. Отсюда практический вывод для CTF: длинные нелатинские строки быстро съедают контекст, а короткие ASCII-полезные нагрузки проходят «дешевле».

## Шаг 13: частые ошибки

- Думать, что модель видит символы (она видит токены).
- Считать, что пробел незначим (ведущий пробел меняет токен).
- Забывать про нормализацию юникода при сравнении строк.

## Шаг 14: чек-лист

1. Понять, что вход — токены.
2. Проверить, как режется опасное слово.
3. Найти расхождение фильтра и модели.
4. Построить обходное разбиение.
5. Проверить, что смысл восстановился.
'''

