E['misc-prompt-leak'] = '''
## Приоритет: не хранить секреты

Главный вывод аудита LLM-приложений: если данные не должны утечь, их не должно быть в промпте. Всё остальное — фильтры, мониторинг, ограничения вывода — лишь снижает вероятность, но не устраняет причину. Поэтому первая рекомендация всегда одна: вынести секреты из промпта.

## Как оформить находку

При аудите фиксируют: какой запрос привёл к утечке, что именно утекло, воспроизводимость (срабатывает ли повторно) и влияние (какие правила/данные раскрыты). В CTF достаточно метки; в отчёте — воспроизводимый запрос и оценка риска.

## Итог

Утечка промпта — не экзотика, а базовая техника. Она объединяет обход фильтров, смену задачи и побочные каналы. Понимая её, ты и решаешь задачи, и даёшь приложению правильную рекомендацию: держать секреты вне инструкции.
'''

def insert(path, extra):
    with open(path, encoding='utf-8') as f:
        t = f.read()
    for marker in ('\n## Что мы теперь знаем', '\n## Квиз'):
        i = t.find(marker)
        if i != -1:
            break
    assert i != -1, path
    with open(path, 'w', encoding='utf-8') as f:
        f.write(t[:i] + '\n' + extra.strip() + '\n' + t[i:])

for lid, ex in E.items():
    insert(os.path.join(CONTENT, lid + '.md'), ex)
    print('expanded', lid)
