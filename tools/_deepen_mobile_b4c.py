ATTEST3 = '''
## Шаг 13: как отличить настоящую аттестацию от витрины

Не всякое «мы используем App Attest» означает реальную защиту. Проверить это можно по
нескольким признакам. Настоящая аттестация отправляет объект на **сервер**, и сервер выполняет
все пять проверок (цепочка, rpId, challenge, счётчик, хеш сборки). Витрина же ограничивается
вызовом API на клиенте и локальной проверкой результата — такой флаг патчится одной строкой.

Практический способ убедиться: перехватить трафик (MITM) и посмотреть, уходит ли attestation
на сервер и приходит ли оттуда решение. Если приложение само решает «аттестация ок» и
продолжает работу, серверная защита отсутствует. Если же чувствительные операции выполняются
только после серверного подтверждения, и сервер проверяет challenge — это настоящая схема.

Этот приём — перехват и наблюдение — универсален для мобильного пентеста: он показывает не
то, что приложение *заявляет*, а то, что оно *делает*. И именно на стыке клиента и сервера чаще
всего находятся реальные слабости, даже когда на клиенте стоит самая современная защита.
'''

ENT3 = '''
## Шаг 14: entitlements и приватные API

Отдельная тема — использование приватных API. Некоторые возможности iOS доступны только через
непубличные методы, а часть из них дополнительно защищена entitlement вида
`com.apple.private.*`. Стороннее приложение не может заявить такое право, поэтому попытка
использовать приватный API без него обычно заканчивается отказом или крашем.

Однако в анализе это важно по двум причинам. Во-первых, если в стороннем приложении всё же
встречается приватный API, это признак либо переподписи с системным профилем (что подозрительно
само по себе), либо уязвимости, позволяющей обойти проверку. Во-вторых, понимание того, какие
возможности защищены entitlement, помогает оценить поверхность атаки: всё, что защищено
подписью, нельзя просто «включить» в рантайме.

```bash
$ codesign -d --entitlements :- example.app | grep -c 'com.apple.private'
0
$ strings example_binary | grep -i 'private_framework' | head
```

Если строки приватного фреймворка есть, а соответствующего entitlement нет — стоит разобраться,
как приложение рассчитывает его использовать. Часто это остатки отладочного кода, но иногда —
признак более глубокой проблемы. Такой сигнал полезно фиксировать в отчёте: он направляет
дальнейший анализ туда, где защита может не сработать.
'''

