def b64file(path, data):
    return {'path': path, 'b64': base64.b64encode(data).decode(), 'mode': '644'}


# --- synthetic save-state fixture: header + zlib body with flag -------------
def build_state():
    magic = b'SAVSTATE\x01'
    body = b'CPU: PC=0x8000 SP=0xFFFE\nSCORE=1337\nSECRET=nto{s4v3_st4t3_t4mp3r1ng}\n'
    comp = gzip.compress(body)
    # 8-byte magic + u32 length + compressed payload
    return magic + struct.pack('<I', len(comp)) + comp


