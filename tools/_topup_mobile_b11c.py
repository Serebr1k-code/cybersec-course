#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Third top-up: short 'а что если' edge-case section for the last thin lessons."""
import os

MARK = '## Что мы теперь знаем'

ADD = {}

ADD['mobile-android-odex-unpack'] = '''## А если код зашифрован

Бывает так, что ни в APK, ни в `.vdex` читаемого кода нет: приложение упаковано
защитным обфускатором, и настоящий dex собирается уже в памяти при запуске. Тогда
статический путь бессилен — сколько ни извлекай из `.vdex`, там будет только
загрузчик. Решение — динамическое: запустить приложение под отладчиком и снять дамп
памяти в тот момент, когда оно расшифровало свой код. После этого dex вытаскивают из
дампа по сигнатуре `dex\\n035` и открывают в декомпиляторе. Это отдельная тема, но
полезно знать: `.vdex` — источник байткода только тогда, когда код не расшифровывается
на лету.

'''

ADD['mobile-android-factory-reset'] = '''## А если устройство уже сброшено

Иногда аудит начинается с устройства, которое уже прошло сброс. Тогда проверять FRP
поздно: либо она уже сработала и устройство заблокировано, либо защита была выключена
и устройство чистое. В первом случае фиксируй факт привязки к аккаунту как работающую
защиту; во втором — как находку о том, что устройство было не защищено. Важно не
путать эти состояния: «не смог обойти» и «защиты не было» — противоположные выводы.
Если нужно понять, была ли FRP включена до сброса, смотри косвенные следы: журналы
сервиса, конфигурацию MDM, историю прошивок.

'''

ADD['mobile-android-instant-apps'] = '''## А если ссылка ведёт не туда

Отдельный сценарий — не перехват домена, а **подмена цели внутри легитимной ссылки**.
Приложение получает параметр с адресом и открывает его во встроенном WebView, не
проверяя хост. Тогда злоумышленнику не нужно регистрировать домен: достаточно
подсунуть пользователю ссылку, где внешний адрес спрятан в параметре. Проверять это
надо так же, как обычный open redirect: подставлять внешние хосты в каждый параметр и
смотреть, не откроется ли чужой сайт внутри доверенного приложения. Это особенно
опасно, когда WebView имеет JS-мост к нативному коду.

'''

ADD['mobile-android-odex-vdex'] = '''## А если приложение обновлялось

После обновления система пересобирает артефакты, но старые файлы могут какое-то время
оставаться на диске. Это значит, что в каталоге `oat` иногда лежат артефакты **двух**
версий приложения. Если взять `.vdex` от старой версии и APK от новой, классы не
совпадут, и анализ уведёт в сторону. Поэтому всегда сверяй имена каталогов установки
(`~~x`, `~~y` и подобные префиксы) и даты файлов. Самый свежий `.vdex` по времени
изменения, как правило, соответствует текущей версии. Если сомневаешься — удали
приложение, установи заново и работай с чистым набором артефактов.

'''

ADD['mobile-android-fbe-fde'] = '''## А если ключ всё-таки извлекли

Даже успешное извлечение ключа не всегда означает конец истории. Во-первых, ключ мог
относиться только к одной зоне: расшифровав CE, ты не получишь доступ к данным,
которые приложение дополнительно зашифровало своими ключами. Во-вторых, часть
приложений шифрует чувствительные поля отдельно, поверх системного шифрования. Это
называют **двойным шифрованием**, и оно встречается в банковских и корпоративных
приложениях. Поэтому после извлечения ключа следующий шаг — искать внутри уже
расшифрованных данных второй слой: зашифрованные файлы, базы с шифрованием на уровне
полей, ключи, выведенные из PIN приложения. Работа не заканчивается на системном
шифровании.

'''

ADD['mobile-android-lockscreen'] = '''## А если пользователь вернётся

Все техники выше предполагают, что устройство остаётся у тебя. В реальности это не
так: телефон может понадобиться владельцу, и любые изменения (установка приложения,
включение отладки, попытки перебора) оставят следы и вызовут тревогу. Поэтому аудит
физического доступа почти всегда ведут на **копии** данных, а не на живом устройстве.
Сначала снимают образ разделов, потом работают с ним офлайн: перебирают PIN, изучают
уведомления, восстанавливают удалённое. Так и владелец не мешает, и следов на
оригинале не остаётся. Планируй работу заранее: время на извлечение образа, время на
офлайн-анализ и обязательное возвращение устройства в исходное состояние.

'''

ADD['mobile-android-messenger-ipc'] = '''## А если сервис проверяет uid

Иногда защита есть, но обойти её всё равно можно — через **посредника**. Сервис
проверяет `Binder.getCallingUid()` и отказывает чужому процессу. Но если в том же
приложении есть экспортированная Activity, которая сама подключается к сервису и
передаёт сообщения, то атакующий обращается к Activity, а та — уже «от имени»
приложения. Проверка uid её пропустит. Поэтому, найдя проверку, не останавливайся:
ищи любой экспортированный компонент того же приложения, который умеет достучаться до
защищённого сервиса. Часто именно он оказывается настоящей дырой, а сам сервис —
всего лишь хорошо защищённой внутренностью.

'''

for lid, block in ADD.items():
    p = os.path.join('content', 'mobile', lid + '.md')
    t = open(p, encoding='utf-8').read()
    if '## А если' in t:
        print('already:', lid)
        continue
    t = t.replace(MARK, block + MARK, 1)
    open(p, 'w', encoding='utf-8').write(t)
    print('topped up:', lid)
print('done')
