"""Second expansion for stego B3-2 tool lessons."""
import os
ROOT = "content/stego"

def expand(lid, extra):
    p = os.path.join(ROOT, lid + ".md")
    t = open(p, encoding="utf-8").read()
    key = extra.strip().splitlines()[0]
    if key in t:
        print("SKIP(done)", lid); return
    m = "## Что мы теперь знаем"
    open(p, "w", encoding="utf-8").write(t.replace(m, extra.strip() + "\n\n" + m, 1))
    print("EXPANDED", lid)

expand("stego-tool-stegoveritas", r'''
## Шаг 15: пошаговый сценарий на незнакомом файле

Представь, что файл `mystery.png` попал к тебе впервые. Ты не знаешь ни формат
содержимого, ни метод сокрытия. Действуй так. Сначала `file mystery.png` — формат.
Потом `stegoveritas mystery.png` — полный автоматический прогон. Читай отчёт
сверху вниз: метаданные, LSB, палитра, добавленные данные. Если что-то найдено —
извлекай и записывай результат. Если пусто — переходи к ручным инструментам:
`pngcheck -v`, `zsteg`, `binwalk`, `xxd` хвоста. Такой порядок экономит время,
потому что автоматика закрывает типовые случаи за один прогон.

## Шаг 16: почему отчёт бывает шумным

Stegoveritas иногда выдаёт десятки строк «найдено», но настоящий флаг один.
Причина — детекторы LSB срабатывают на естественном шуме и на сжатии. Поэтому
отчёт надо фильтровать: искать строки в формате флага, проверять их длину и
осмысленность. Случайная строка из `strings` редко выглядит как `nto{...}`.

## Шаг 17: автоматизация в своих скриптах

Ты можешь вызвать Stegoveritas из своего скрипта и разобрать его вывод
программно: найти строку с `extracted data`, вырезать payload, сохранить. Это
полезно, когда файлов много. Но помни: автоматический разбор чужого вывода хрупок —
формат отчёта может меняться между версиями.

## Шаг 18: сравнение с конкурентами

Кроме Stegoveritas есть `Aperi'Solve` (веб-сервис), `Stegdetect`, `zsteg`. Веб-сервис
удобен, но требует загрузки файла (не всегда допустимо). `zsteg` силён в LSB для
PNG, `stegdetect` — в JPEG. Stegoveritas — «зонтик» над ними: удобно для первого
прохода, но специализированный инструмент иногда точнее.

## Шаг 19: что делать, если всё пусто

Если ни автоматика, ни ручные проверки ничего не нашли — гипотезы: данные
зашифрованы (нужен пароль), использован кастомный метод, или данные в неочевидном
месте (альфа-канал, палитра, метаданные EXIF). Тогда возвращайся к теории формата и
проверяй каждый канал отдельно. Отсутствие результата у инструмента — не
доказательство отсутствия данных.

## Шаг 20: итог по инструменту

Stegoveritas ценен скоростью: за один запуск ты получаешь карту всех типовых
проверок. Его правильное место — этап быстрого триажа. После него всегда идёт
ручная работа: понять, что нашлось, извлечь и проверить. Инструмент не думает за
тебя, но избавляет от рутины.
''')

expand("stego-tool-png-suite", r'''
## Шаг 14: пошаговый сценарий на незнакомом PNG

Открой неизвестный `image.png`. Шаг 1: `file image.png` — подтверди формат. Шаг 2:
`pngcheck -v image.png` — список чанков. Ищи нестандартные типы (`tEXt`, `zTXt`,
`iTXt`) и CRC-ошибки. Шаг 3: `exiftool image.png` — метаданные. Шаг 4: `zsteg -a
image.png` — LSB по всем комбинациям. Шаг 5: `binwalk image.png` — вложенные
сигнатуры. Шаг 6: `xxd image.png | tail` — данные после IEND. Такой порядок
закрывает почти все PNG-задачи.

## Шаг 15: что означают разные чанки

`IHDR` — обязательный заголовок. `PLTE` — палитра для индексированных
изображений. `tRNS` — прозрачность. `IDAT` — сжатые пиксели (может быть несколько
подряд). `IEND` — конец. Служебные: `gAMA`, `cHRM`, `sRGB`, `pHYs`, `tIME`, `tEXt`,
`zTXt`, `iTXt`. Данные прячут чаще всего в `tEXt`/`zTXt`/`iTXt` (текст), в порядке
`IDAT`, в палитре или после `IEND`.

## Шаг 16: сжатие IDAT и zlib

Пиксели PNG сжаты zlib (deflate). Иногда данные прячут **внутри** сжатого потока:
лишние байты после deflate-потока в `IDAT`. Инструмент `pngcheck` покажет размер
чанка, но не содержимое. Распаковать и посмотреть можно так:

```bash
python3 -c "import zlib,sys; d=open('image.png','rb').read(); print(len(d))"
```

Если длина `IDAT` аномально велика для размера изображения — внутри что-то есть.

## Шаг 17: частые ошибки новичков

Первая — смотреть только пиксели и забыть про чанки. Вторая — не проверять хвост
после `IEND`. Третья — игнорировать `PLTE`. Четвёртая — запускать оптимизатор на
оригинале. Пятая — считать, что `pngcheck` покажет всё: он не декодирует пиксели и
не смотрит после конца файла.

## Шаг 18: сравнение инструментов

| Инструмент | Роль |
|---|---|
| `file` | формат |
| `pngcheck` | структура и CRC |
| `exiftool` | метаданные |
| `zsteg` | LSB |
| `binwalk` | вложенные сигнатуры |
| `optipng`/`pngcrush` | пересборка (оракул) |

Вместе они дают полную картину. По отдельности каждый узок.

## Шаг 19: полный разбор с пересборкой

Продолжим историю: после `pngcheck -v` мы нашли `tEXt` с флагом. Теперь пересоберём
копию без метаданных: `pngcrush -rem allb test.png` (удалить все вспомогательные
чанки). Если флаг исчез — подтверждается, что он был именно в чанке. Это хороший
способ доказать гипотезу.
''')

expand("stego-tool-jpeg-suite", r'''
## Шаг 14: пошаговый сценарий на незнакомом JPEG

Шаг 1: `file image.jpg`. Шаг 2: `jpegtran -copy all -verbose image.jpg > /dev/null`
— маркеры. Шаг 3: `exiftool -a -u image.jpg` — метаданные. Шаг 4: `strings
image.jpg | grep -i nto` — быстрый поиск. Шаг 5: `binwalk image.jpg` — вложенные
файлы. Шаг 6: `xxd image.jpg | tail` — хвост после `FFD9`. Шаг 7: если пусто —
`steghide info image.jpg`, `outguess -r`, `stegdetect`. Так закрывается JPEG.

## Шаг 15: как выглядит структура в байтах

Откроем `xxd image.jpg` и посмотрим начало: `ffd8` — SOI, затем `ffe0` — APP0
(JFIF), затем `ffdb` — таблицы квантования, `ffc0` — кадр, `ffc4` — таблицы
Хаффмана, `ffda` — начало сканирования, потом сжатые данные, в конце `ffd9` — EOI.
Между маркерами может быть что угодно: комментарий (`fffe`), APPn (`ffe1..ffef`),
данные после EOI.

## Шаг 16: где прячут данные в JPEG

- **COM (`fffe`)** — простой текст/флаг.
- **APPn** — EXIF, XMP, «лишние» блоки.
- **После EOI** — произвольные байты (ZIP, второй файл).
- **DCT-коэффициенты** — F5, OutGuess, JSteg (нужны профильные инструменты).
- **Таблицы квантования** — редко, но возможно (изменённые значения).

Первые три находятся без спец-инструментов, последние два — только с ними.

## Шаг 17: lossless-трансформация на практике

`jpegtran` умеет поворачивать без пересжатия. Это не только удобно, но и
диагностично: если после поворота данные пропали, значит, они были в метаданных
(их можно было и не сохранять). Если остались — они в пикселях/DCT. Так трансформация
работает как проверка.

## Шаг 18: частые ошибки

Первая — пересжать файл. Вторая — искать только в EXIF. Третья — не проверить
хвост. Четвёртая — применить не тот инструмент (например, `zsteg` к JPEG). Пятая —
считать, что `jpegtran` покажет данные после EOI.

## Шаг 19: сравнение с PNG-подходом

Мышление одинаковое: сначала структура, потом метаданные, потом хвост, потом
пиксели/DCT. Разница в инструментах: для PNG — `pngcheck`, для JPEG — `jpegtran`.
Освоив оба, ты работаешь с любым изображением по одному плану.
''')

expand("stego-tool-foremost", r'''
## Шаг 16: пошаговый сценарий на сыром образе

Шаг 1: `file evidence.dd` — что это. Шаг 2: `binwalk evidence.dd` — карта сигнатур
и энтропия. Шаг 3: `foremost -i evidence.dd -o out -t png,jpg,pdf,zip` — карвинг
основных типов. Шаг 4: просмотр `out/` по каталогам. Шаг 5: `strings` по найденным
файлам. Шаг 6: ручной разбор подозрительных. Такой конвейер даёт максимум за один
проход.

## Шаг 17: энтропия как подсказка

Энтропия — мера «случайности» байтов. У сжатых/зашифрованных данных она близка к 8
бит/байт, у текста и кода — ниже. `binwalk -E` рисует карту энтропии: высокие
участки — сжатые/шифрованные блоки. Это подсказывает, где искать контейнеры, и
отличает настоящие данные от заполнителей.

## Шаг 18: карвинг без конфига

Иногда нужно вырезать формат, которого нет в конфиге. Тогда пишешь правило сам:
сигнатуру начала и конца. Например, для кастомного контейнера с маркером
`MYST` и концом `END!`. Добавляешь строку в `foremost.conf` и запускаешь. Это
продвинутый, но полезный приём для задач с авторским форматом.

## Шаг 19: ложные срабатывания

Карвер может «найти» файл там, где его нет: сигнатура случайно встретилась в
данных. Признаки ложного: файл не открывается, размер подозрительно мал, CRC не
сходится. Всегда проверяй найденное (`file`, открытие, проверка структуры).

## Шаг 20: производительность

На больших образах карвинг занимает время. Ускорить: ограничить типы (`-t`),
использовать `scalpel`, разбить образ на части и карвить параллельно. Но помни:
карвинг — I/O-зависимая задача, и упор в диск.

## Шаг 21: полный разбор со вложенностью

Продолжим историю: `foremost` нашёл PNG с флагом. Но что если внутри PNG был ещё
ZIP? Тогда карвер вырезал бы оба, и мы разобрали бы ZIP (`unzip`, `zip2john`).
Правило: после карвинга всегда проверяй найденное на вложенность — рекурсивно.

## Шаг 22: где карвинг не работает

В шифрованном или сжатом без заголовков потоке карвинг бессилен: сигнатур нет.
Также он плохо работает с форматами без чёткого конца (некоторые бинарные
контейнеры). Тогда помогает ручной анализ по смещениям и размерам.
''')

expand("stego-tool-audacity", r'''
## Шаг 16: пошаговый сценарий на незнакомом аудио

Шаг 1: `file hidden.wav` — формат и параметры. Шаг 2: открыть в Audacity,
включить спектрограмму, посмотреть весь диапазон. Шаг 3: если виден текст —
прочитать. Шаг 4: если нет — увеличить диапазон/сменить окно. Шаг 5: проверить
разницу каналов (стерео). Шаг 6: если пусто — `strings`, DeepSound/SilentEye, LSB
в сэмплах. Так покрывается большинство аудио-задач.

## Шаг 17: стерео и разница каналов

Иногда данные прячут в **разнице** левого и правого каналов: в моно они
компенсируются, а в разнице проступает сигнал. В Audacity: раздели стерео на две
дорожки (`Split Stereo Track`), затем `Effect → Invert` на одной и сведи — разница
станет слышимой/видимой. Это частый приём в CTF.

## Шаг 18: осциллограмма и зум

Кроме спектрограммы полезна **осциллограмма** (форма волны). На ней видно
аномалии: резкие скачки, периодические пики, «ступеньки» LSB. Сильный зум (по
сэмплам) показывает, меняется ли младший бит осмысленно. Иногда текст закодирован
именно в форме волны.

## Шаг 19: экспорт и внешние инструменты

Audacity умеет экспортировать выделение в WAV и картинку спектрограммы в PNG. Это
удобно: выделяешь участок, экспортируешь, обрабатываешь отдельно (например,
декодируешь морзе или QR). Sonic Visualiser экспортирует слои для дальнейшего
анализа.

## Шаг 20: частые ошибки

Первая — смотреть только слышимый диапазон. Вторая — слишком грубое окно FFT.
Третья — игнорировать стерео. Четвёртая — перекодировать файл. Пятая — не
проверить низкие частоты (иногда данные в 0–100 Гц как медленные колебания).

## Шаг 21: полный разбор с двумя слоями

Продолжим: на спектрограмме `hidden.wav` виден текст. Но что если бы он был
нечитаем? Тогда: экспорт спектрограммы в PNG, увеличение контраста, OCR, проверка
глазами. Если и это пусто — вернуться к LSB-анализу сэмплов. Слои проверяются по
очереди.

## Шаг 22: связь с восприятием

Главная идея аудио-стего: использовать разрыв между тем, что мы **слышим**, и тем,
что **видим** на представлении сигнала. Человек не замечает тихих высоких частот, но
инструмент показывает их как яркие линии. Понимание этого разрыва — ключ к
аудио-задачам.
''')

expand("stego-tool-deepsound", r'''
## Шаг 16: пошаговый сценарий на подозрительном WAV

Шаг 1: `file secret.wav` — формат, сэмплрейт, размер. Шаг 2: `strings secret.wav |
head -50` — заголовки/имена встроенных файлов. Шаг 3: `deepsound secret.wav` —
опознание контейнера. Шаг 4: извлечение (пароль из подсказки). Шаг 5: разбор
содержимого (`unzip`, чтение текста). Шаг 6: если пусто — SilentEye, спектрограмма,
LSB вручную.

## Шаг 17: как оценить размер контейнера

WAV без сжатия имеет предсказуемый размер: `сэмплрейт × каналы × 2 байта ×
секунды`. Если файл заметно больше — внутри данные. Быстрая оценка:

```bash
python3 -c "import os,wave; w=wave.open('secret.wav'); print(w.getnframes()*w.getnchannels()*2, os.path.getsize('secret.wav'))"
```

Разница между теоретическим и фактическим размером — объём скрытого.

## Шаг 18: контейнеры и шифрование

DeepSound/SilentEye часто шифруют содержимое. Признак: инструмент сообщает
`password-protected`, а `strings` не показывает осмысленного текста (только
заголовок). Тогда путь один — найти пароль. Если пароль есть, извлечение мгновенно.

## Шаг 19: частые ошибки

Первая — считать, что данные в спектре, когда они в LSB (или наоборот). Вторая —
перебирать пароли вместо поиска подсказки. Третья — перекодировать файл. Четвёртая —
не проверить размер файла. Пятая — забыть, что внутри может быть ZIP с паролем.

## Шаг 20: сравнение с mp3stego

`mp3stego` прячет данные в MP3, используя особенности сжатия. DeepSound работает с
WAV и LSB. Это разные носители и разные инструменты: `mp3stego` не откроет WAV, а
DeepSound — MP3. Всегда определяй формат, прежде чем выбирать инструмент.

## Шаг 21: полный разбор цепочки

Продолжим: `secret.wav` → `deepsound` опознал `secret.zip` → извлекли → `unzip` →
внутри `note.txt` с флагом. Цепочка: контейнер → архив → текст. Каждый шаг
проверяется отдельно. Так решаются многослойные аудио-задачи.

## Шаг 22: вывод по инструменту

DeepSound/SilentEye — специализированные инструменты под конкретный формат
контейнера. Их ценность в том, что они **опознают** и **извлекают** без ручного
разбора битов. Но они бессильны без пароля и не работают с чужими форматами.
Поэтому в арсенале держи оба плюс ручной LSB-скрипт.
''')

