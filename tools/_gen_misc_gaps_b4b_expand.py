#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Expansion for MIS-GAP-4b lessons (gameboy/nes) to >=1200 real words."""
import re

CONTENT = 'content/misc/'


def add(lesson, text):
    p = CONTENT + lesson + '.md'
    s = open(p, encoding='utf-8').read()
    add_txt = text.strip()
    m = re.search(r'^## Квиз\s*$', s, re.MULTILINE)
    out = s[:m.start()] + add_txt + '\n\n' + s[m.start():]
    open(p, 'w', encoding='utf-8').write(out)
    print('expanded', lesson)


add('misc-gameboy-rom', '''
## Разбор: зачем логотип и как его проверяют

Логотип Nintendo — не просто картинка. Загрузчик сравнивает 48 байт в ROM с эталоном, зашитым в самом устройстве. Если хоть один байт отличается, реальный Game Boy показывает пустой экран и не передаёт управление в ROM. Эмуляторы обычно эту проверку пропускают, поэтому в CTF повреждённый логотип встречается как «игра запускается в mgba, но не на железе». Для решения задачи это важно: не трать время на восстановление логотипа, если флаг всё равно лежит в данных.

## Полный разбор полей заголовка

Пройдёмся по всем полям, которые стоит проверять при разборе:

- `0x0100–0x0103` — инструкция перехода к коду инициализации (обычно `nop; jp`).
- `0x0104–0x0133` — логотип Nintendo (48 байт).
- `0x0134–0x0143` — название игры, 16 байт ASCII, дополненное нулями.
- `0x0143` — флаг CGB (поддержка Game Boy Color).
- `0x0144–0x0145` — ASCII-код издателя (новый формат).
- `0x0146` — версия ROM.
- `0x0147` — тип картриджа (маппер).
- `0x0148` — размер ROM в банках по 16 КБ.
- `0x0149` — размер внешней RAM.
- `0x014A` — код региона.
- `0x014B` — код лицензии.
- `0x014C` — версия маски ROM.
- `0x014D` — контрольная сумма заголовка.
- `0x014E–0x014F` — глобальная контрольная сумма.

Если название выглядит осмысленно (например, `FLAG`), это подсказка: автор задачи специально положил данные в заголовок.

## Как устроен процессор SM83

Game Boy использует 8-битный процессор SM83 (близкий к Z80, но не он). Программы для него ассемблируются инструментами `rgbds` (`rgbasm`, `rgblink`, `rgbfix`). `rgbfix` умеет пересчитывать контрольные суммы после патча:

```
$ rgbfix -v -p 0xFF game.gb
```

Флаг `-v` исправляет заголовок, `-p` задаёт padding. Это избавляет от ручного пересчёта checksum.

## Работа с эмулятором

Для отладки используют эмуляторы с встроенным отладчиком: `mgba` (открытый), `bgb` (Windows), `SameBoy`. В `mgba` есть консоль с командами для дампа памяти, точек останова и пошагового исполнения. Если флаг собирается кодом, именно отладчик покажет, в какой момент он формируется в памяти.

## Типичные ошибки при патчинге

- Патчить, не сохранив копию оригинала: после нескольких правок непонятно, что сломалось.
- Забывать про checksum: часть эмуляторов отказывается стартовать.
- Менять длину строки названия: поле фиксированной длины, лишние байты затирают соседние.
- Искать флаг только через `strings`: если он собран из частей, строка не найдётся.
- Путать банк: при маппере данные могут быть не в первом банке.
''')

add('misc-nes-rom', '''
## Разбор заголовка iNES построчно

Разберём каждый байт заголовка, потому что именно здесь чаще всего прячется причина «данные не там, где я думал»:

- Байт 0–3: `4E 45 53 1A` — сигнатура `NES` и символ `0x1A`. Если её нет, файл не iNES.
- Байт 4: число 16-килобайтных банков PRG-ROM (код).
- Байт 5: число 8-килобайтных банков CHR-ROM (графика). Ноль означает, что CHR-RAM.
- Байт 6: биты 0–3 — номер маппера (младшие), бит 2 — trainer, бит 3 — зеркалирование, биты 4–7 — старшие биты маппера.
- Байт 7: биты 4–7 — ещё старшие биты маппера, а также флаги VS/PlayChoice.
- Байты 8–15: размер PRG-RAM, тайминги, расширения.

Маппер собирается так: `mapper = (byte6 >> 4) | (byte7 & 0xF0)`. Это число определяет, как эмулятор переключает банки.

## PRG и CHR: что где лежит

PRG-ROM — это код игры и таблицы данных: здесь лежат уровни, тексты и часто флаг. CHR-ROM — тайлы 8×8 для фона и спрайтов. Смещение PRG всегда начинается сразу после заголовка (смещение 16), если нет trainer; иначе — со смещения 16 + 512.

```
$ xxd -s 16 -l 64 game.nes
```

Именно в PRG ищут строки: `strings -n 4 game.nes | grep nto`. Если флаг закодирован, его придётся декодировать, но обычно автор задачи кладёт читаемую строку.

## Мапперы подробнее

- **NROM (0)** — 32 КБ PRG без переключения, простейший.
- **MMC1 (1)** — банки переключаются через регистры, распространён в крупных играх.
- **UxROM (2)** — фиксированный последний банк, переключаемые остальные.
- **CNROM (3)** — переключается только графика.
- **MMC3 (4)** — сложный, с прерываниями по сканлайну.

Для чтения флага достаточно понимать, что банк 0 PRG всегда виден по адресам `0x8000–0xBFFF`, а последний банк — по `0xC000–0xFFFF`. В NROM они совпадают.

## Типичные ошибки

- Считать смещение PRG от нуля, забыв про 16 байт заголовка.
- Игнорировать trainer: при его наличии всё сдвинуто на 512 байт.
- Искать флаг в CHR: там графика, а не текст.
- Путать число банков с размером: `01` — это один банк 16 КБ, а не 1 КБ.
- Править код, не понимая, что делает инструкция: сначала дизассемблируй.

## Практические заметки

Для патчинга удобны `nesasm`/`cc65` (сборка) и `fceux`/`mesen` (отладка). У iNES нет общей контрольной суммы, поэтому патч применяется сразу — но некоторые мапперы имеют свои проверки. Если задача про «запусти и получи флаг», держи под рукой `strings` и `xxd`: чаще всего флаг находится именно ими.
''')

print('batch 4b expand done')
