def insert_before_quiz(path, extra):
    with open(path, encoding='utf-8') as f:
        t = f.read()
    marker = '\n## Квиз'
    i = t.find(marker)
    if i == -1:
        raise SystemExit('no quiz in ' + path)
    t = t[:i] + '\n' + extra.strip() + '\n' + t[i:]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(t)


