#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Second expansion pass for MOB-GAP-9a lessons — push each over 1250
real-content words."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')
MARK = '<!-- lab -->'

EXTRA = {
 'mobile-android-rat': '''
## Шаг 12: каналы доставки RAT

Чаще всего RAT приходит не из магазина, а сбоку: фишинговые ссылки, «взломанные» игры,
поддельные банковские приложения, сторонние магазины. Нередко используется социальная
инженерия: «установи приложение для защиты от мошенников» — и пользователь сам включает
Accessibility. Поэтому первый вопрос в разборе инцидента — как именно приложение попало на
устройство, а не только что оно делает.
''',
 'mobile-android-sms-stealer': '''
## Шаг 11: что делать пользователю

Самое действенное — не устанавливать приложения из мессенджеров и не выдавать доступ к
уведомлениям или спецвозможностям по чужой просьбе. Если банк предлагает перейти на
push-подтверждение вместо SMS-кода, стоит согласиться: такой канал не перехватывается так же
просто. Регулярный просмотр списка приложений с доступом к уведомлениям выявляет лишние.

## Шаг 12: как анализировать образец

При разборе стилера ищут: регистрацию ресивера SMS с высоким приоритетом, вызов
`abortBroadcast`, объявление NotificationListenerService, адреса C2 и шаблоны пересылки.
Динамически полезно перехватить исходящий трафик и посмотреть, какой текст уходит на сервер.
Итог — понимание, какие коды и от каких сервисов ворует образец.
''',
 'mobile-ios-spyware': '''
## Шаг 12: защита и гигиена

Базовая защита от шпионов класса Pegasus — своевременно обновлять iOS, не открывать подозрительные
ссылки, использовать аппаратные ключи вместо SMS-кодов, где это возможно, и включать
дополнительные режимы защиты для тех, кто в зоне риска. Ни одна мера не даёт абсолютной
гарантии, но вместе они резко поднимают стоимость атаки.

## Шаг 13: роль обновлений

Многие атаки эксплуатируют уже исправленные уязвимости. Поэтому устаревшая версия iOS —
главный фактор риска. Обновление не спасает от активного zero-day, но закрывает окно для
повторного использования старого эксплойта. В отчёте об инциденте обязательно фиксируют
версию iOS на момент заражения и дату последнего обновления.
''',
 'mobile-android-dropper': '''
## Шаг 13: как связать ступени

Дроппер и payload анализируют вместе: ключ расшифровки из дроппера открывает payload, а payload
объясняет смысл дроппера. Иногда обе ступени лежат в одном APK, иногда payload приходит с C2
позже. В первом случае достаточно статики и расшифровки, во втором нужен сетевой перехват.
Связка «кто кого доставил» — центральный вывод отчёта.
''',
}

for lid, extra in EXTRA.items():
    p = os.path.join(MOB, lid + '.md')
    s = open(p, encoding='utf-8').read()
    if MARK not in s:
        raise SystemExit('marker not found in ' + p)
    s = s.replace(MARK, extra.strip() + '\n\n' + MARK, 1)
    open(p, 'w', encoding='utf-8').write(s)
    print('expanded', lid)
