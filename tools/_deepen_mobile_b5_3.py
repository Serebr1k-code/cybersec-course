OBJC2 = '''
## Шаг 11: hooking против swizzling

Важно различать два подхода к перехвату. **Swizzling** меняет реализацию метода в рантайме
ObjC — это высокоуровневый приём, работающий через таблицы методов. **Hooking** (inline hooks)
меняет машинный код функции напрямую (перезаписывает первые инструкции прыжком). Swizzling
проще, но работает только для ObjC-методов; hooking работает для любой функции, включая
Swift и C, но требует прав на запись в код.

Для атакующего выбор зависит от цели: перехватить `-[Security isJailbroken]` проще swizzling'ом,
а перехватить C-функцию проверки — только hooking'ом. Для защищающегося это означает, что
проверки в ObjC-методах уязвимы к swizzling, а в C-функциях — к inline hooking; устойчивая
защита комбинирует оба типа и проверяет целостность и таблиц методов, и кода.

## Шаг 12: что запомнить про рантайм ObjC

Objective-C — динамический язык, и вся его сила (и слабость) в рантайме. Объект указывает на
класс через `isa`, класс — на метакласс; вызов метода (`objc_msgSend`) ищет реализацию во время
выполнения. Это даёт swizzling — подмену методов, которой пользуются и фреймворки, и атакующие.
Из-за динамики метаданные классов и методов остаются в бинарнике, что облегчает реверс
(`class-dump`), но и означает, что защита на одном методе обходится одной строкой. Устойчивая
защита не полагается на единственный метод, комбинирует проверки и использует статическую
диспетчеризацию там, где динамика не нужна.
'''

DYLD2 = '''
## Шаг 11: подпись и инъекция на современном iOS

На современном iOS инъекция ограничена подписью: приложение, подписанное Apple, игнорирует
переменные `DYLD_*`, а патч бинарника (добавление `LC_LOAD_DYLIB`) ломает подпись и не даёт
процессу запуститься. Поэтому «просто подложить библиотеку» на чистом устройстве нельзя.
Обойти это можно тремя путями: джейлбрейк (отключена проверка подписи), переподпись своим
сертификатом (но тогда приложение — уже не оригинал), или уязвимость в ядре (что выходит за
рамки обычной инъекции).

Отсюда практический вывод: если вы видите, что приложение уязвимо к инъекции dylib, но
устройство не джейлбрейкнуто, эксплуатируемость ограничена. И наоборот: на джейлбрейке
инъекция — обычный инструмент, и защиты, не проверяющие список образов, обходятся тривиально.
Понимание этого зазора важно и для пентеста, и для оценки реальной защищённости.

## Шаг 12: что запомнить про dyld

dyld — динамический загрузчик, который читает Mach-O load commands, рекурсивно грузит
библиотеки и выполняет инициализаторы **до** `main`. Отсюда — инъекция: добавив библиотеку в
список загрузки (`DYLD_INSERT_LIBRARIES` или `LC_LOAD_DYLIB`), можно выполнить свой код в
процессе. Системные библиотеки живут в dyld shared cache, поэтому их не найти отдельными
файлами. Пути поиска (`LC_RPATH`) определяют, откуда берутся библиотеки, и записываемые пути —
риск подмены. Защита строится на подписи и на проверке списка загруженных образов, а на
джейлбрейке эти ограничения снимаются. Понимание dyld — ключ и к реверсу, и к разработке
твиков, и к анализу инъекций.
'''

