EXTRA['reversing-bluetooth-l2cap'] = '''
## Разбор глубже: классический Bluetooth против BLE

Классический Bluetooth (BR/EDR) и BLE — разные стеки, хотя делят радио. BR/EDR использует L2CAP, RFCOMM, SDP; BLE — ATT/GATT. У них разные профили и разные атаки. Реверс BLE не переносится напрямую на классику.

При анализе сначала определи, какой стек используется: по рекламе и по типу соединения. Инструменты тоже разные (`bluetoothctl` для обоих, но профили отличаются).

## Разбор глубже: как документировать протокол

Результат BLE-реверса оформляют как карту: сервис → характеристика → направление (read/write/notify) → формат данных → смысл. Это «даташит» на устройство, которого нет у вендора.

С такой картой можно: автоматизировать управление, писать тесты, искать уязвимости. Она же — основа для отчёта и для защиты (какие данные не должны быть доступны без аутентификации).

## Разбор глубже: закрепление навыка

Навык BLE-реверса ставится практикой: возьми свой гаджет (фитнес-трекер, умную лампу), просканируй, перечисли сервисы, включи нотификации, поуправляй. Записывай, что меняется.

Так ты за несколько сессий пройдёшь весь цикл и научишься читать протоколы «с нуля», без документации. Это навык, применимый к любому IoT-устройству.
'''

