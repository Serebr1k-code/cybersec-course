def insert(path, extra):
    with io.open(path, encoding="utf-8") as f:
        text = f.read()
    if ANCHOR not in text:
        print("NO ANCHOR", path); return
    if extra.strip().splitlines()[0] in text:
        print("ALREADY", path); return
    text = text.replace(ANCHOR, "\n" + extra.strip() + ANCHOR, 1)
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("DEEPENED", path)


