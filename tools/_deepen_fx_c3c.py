#!/usr/bin/env python3
"""Batch C3c — third layer for forensics-cloud-serverless, spec-gps, doc-xps."""
from __future__ import annotations
import re, sys

ADDS = {}

ADDS["forensics-cloud-serverless"] = r"""## Ограничения serverless-форензики

У serverless есть жёсткие пределы для расследования. Нет диска и памяти — только логи,
которые платформа хранит ограниченное время (по умолчанию лог-группа может хранить
данные «вечно», но часто настроена ротация). Логи содержат лишь то, что функция сама
напечатала, плюс строки платформы. Если логирование не было настроено на уровне кода,
многое теряется. Кроме того, между вызовами экземпляр может переиспользоваться, из-за
чего следы одного вызова попадают в «чужой» поток. Поэтому выводы всегда сопровождай
оговоркой: «по доступным логам» и «при условии, что логирование было включено»."""

ADDS["spec-gps"] = r"""## Что писать в отчёте

По GPS-данным отчёт должен отвечать на три вопроса: **источник**, **точность**,
**время**. Источник — конкретный файл/БД и формат (GPX, NMEA, FIT). Точность — HDOP или
число спутников, с интерпретацией (метры). Время — приведённое к UTC, с оговоркой о
часовом поясе и leap seconds. Далее — маршрут, стоянки, аномалии и сопоставление с
другими артефактами. Каждое утверждение («был здесь в 03:20») подкрепляй точкой трека
и временем. Без этих трёх атрибутов координата недоказуема.

## Ограничения GPS-данных

GPS-трек не является абсолютным доказательством. Сигнал можно заглушить или подделать,
точность в помещении падает, часы устройства «уезжают», а трек может быть обрезан при
потере фикса. Некоторые приложения **сглаживают** трек или удаляют выбросы, скрывая
реальные аномалии. Наконец, наличие трека не доказывает, что устройство было у
человека (телефон мог быть у другого). Поэтому GPS всегда рассматривают в комплексе с
другими источниками и указывают границы применимости вывода."""

ADDS["doc-xps"] = r"""## Почему формат важен

XPS — формат фиксированного вида, где каждая страница описана XML. Для форензика это
удобно: текст, ресурсы и метаданные лежат в открытых частях пакета, и их можно извлечь
без тяжёлого рендера. В корпоративной среде XPS встречается в печати, сканировании и
внутренних документах. Понимание его структуры позволяет быстро находить автора,
скрытый текст, внедрённые изображения и статус подписи — то, что нужно при разборе
вложения или проверке подлинности документа.

## Инструменты разбора

- **`unzip`/`zipinfo`** — распаковка и листинг частей;
- **`grep`/`sed`** — извлечение текста из `*.fpage` (по `UnicodeString`);
- **`exiftool`** — метаданные изображений из `Resources/`;
- **`binwalk`/`foremost`** — карвинг встроенных объектов;
- **XPS Viewer / Okular** — визуальный просмотр (для сверки);
- **`xmllint`** — проверка и форматирование XML-частей.

Для повторяющихся задач пиши короткий скрипт: собрать все `UnicodeString` из страниц,
отсортировать по `OriginX`/`OriginY` и вывести читаемый текст. Это воспроизводимо и
быстрее ручного разбора."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
