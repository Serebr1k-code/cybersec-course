def main():
    for lid, text in ADD.items():
        path = 'content/cloud/%s.md' % lid
        lesson = open(path, encoding='utf-8').read()
        m = re.search(r"^## Квиз\s*$", lesson, re.MULTILINE)
        assert m, path
        add = text.strip('\n')
        assert '## Квиз' not in add and '## Где пригодится' not in add
        out = lesson[:m.start()] + add + '\n\n' + lesson[m.start():]
        open(path, 'w', encoding='utf-8').write(out)
        print('topped up', path, '+%d words' % len(add.split()))


if __name__ == '__main__':
    main()
