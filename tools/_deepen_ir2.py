ADD['ir-root-cause'] = """
## Как собирать данные для RCA

RCA не делается по памяти. Нужны артефакты, и их удобно разделить по вопросам.

**Что произошло и когда** — таймлайн: журналы аутентификации, изменения файлов, сетевые
события, история команд. Это костяк.

**Как это стало возможно** — конфигурации: открытые порты, настройки доступа, версии ПО,
политики паролей. Это причина.

**Почему не заметили** — детекты: какие правила существуют, какие сработали, какие нет.
Это пробел в видимости.

**Что усилило ущерб** — факторы распространения: отсутствие сегментации, доступность
бэкапов атакующему, избыточные права.

Собрав эти четыре группы, ты почти всегда видишь причину без гаданий.

## Отличаем причину от фактора

Не всё, что связано с инцидентом, — его причина. Различай:

- **причина** — без неё инцидент не случился бы (открытый порт, слабый пароль);
- **фактор** — усилил ущерб, но не был условием (нет сегментации, нет бэкапов);
- **симптом** — то, что заметили (зашифрованные файлы, алерт).

Пример: RDP был открыт наружу (причина), пароль был слабым (причина), не было MFA
(фактор), сработал алерт (симптом). Убрав только один пункт, инцидент не обязательно
исчезнет — поэтому рекомендации дают на все.

## Как проверить гипотезу о причине

Хороший тест — **контрфактический**: «если бы условия не было, произошло бы?». Если да —
это не причина. Если нет — причина.

Второй тест — **воспроизведение**: можно ли воспроизвести путь атаки в тестовой среде?
Если да, причина подтверждена, и закрытие условия проверяемо.

Третий — **независимость**: подтверждают ли причину минимум два источника? Один лог может
врать или быть неполным; перекрёстная проверка повышает уверенность.

## RCA — это процесс, а не отчёт

Итог RCA — не документ, а изменение состояния: закрытые порты, включённая MFA, новые
детекты. Отчёт лишь фиксирует это. Поэтому RCA считается завершённым не когда написан
документ, а когда рекомендации внедрены и проверены.
"""

