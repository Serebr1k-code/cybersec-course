def insert_before_quiz(path, extra):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    marker = '\n## Квиз'
    idx = text.find(marker)
    if idx < 0:
        raise SystemExit('no Квиз in ' + path)
    text = text[:idx] + '\n' + extra.strip() + '\n' + text[idx:]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)

