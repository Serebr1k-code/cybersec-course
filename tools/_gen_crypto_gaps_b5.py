A5 = [(19, [13, 16, 17, 18]), (22, [20, 21]), (23, [7, 20, 21, 22])]
CLK = [8, 10, 10]


def _clock_bit(r, i):
    return (r >> CLK[i]) & 1


def _a5_step(regs, clock_all=False):
    maj = (_clock_bit(regs[0], 0) + _clock_bit(regs[1], 1) + _clock_bit(regs[2], 2)) >= 2
    out = 0
    for i, (n, taps) in enumerate(A5):
        cb = _clock_bit(regs[i], i)
        if clock_all or cb == maj:
            fb = 0
            for t in taps:
                fb ^= (regs[i] >> t) & 1
            regs[i] = (regs[i] >> 1) | (fb << (n - 1))
            if i == 0:
                out ^= 0
    # keystream bit = XOR of all three outputs (LSB before shift)
    return regs


def a5_keystream(key, frame, k):
    regs = [0, 0, 0]
    for i in range(64):
        for j in range(3):
            regs[j] ^= (key >> i) & 1
        regs = _a5_step(regs, clock_all=True)
    for i in range(22):
        for j in range(3):
            regs[j] ^= (frame >> i) & 1
        regs = _a5_step(regs, clock_all=True)
    ks = []
    for _ in range(k):
        out = (regs[0] & 1) ^ (regs[1] & 1) ^ (regs[2] & 1)
        ks.append(out)
        regs = _a5_step(regs, clock_all=False)
    return ks


