# --- LFSR (Fibonacci) -------------------------------------------------------
def lfsr_step(state, n, taps):
    out = state & 1
    fb = 0
    for t in taps:
        fb ^= (state >> t) & 1
    state = (state >> 1) | (fb << (n - 1))
    return state, out


def lfsr_keystream(seed, n, taps, k):
    st = seed
    ks = []
    for _ in range(k):
        st, b = lfsr_step(st, n, taps)
        ks.append(b)
    return ks


def lfsr_recover(ks, n, taps):
    # coefficient vectors for the n state bits (over initial-state bits)
    M = [1 << i for i in range(n)]
    rows = []
    for j in range(n):
        # output = state bit 0
        rows.append(M[0])
        # advance one step
        newM = [M[i + 1] for i in range(n - 1)]
        fb = 0
        for t in taps:
            fb ^= M[t]
        newM.append(fb)
        M = newM
    # solve over GF(2): rows * x = ks[:n]
    # Gaussian elimination
    import copy
    A = [[(rows[i] >> j) & 1 for j in range(n)] + [ks[i]] for i in range(n)]
    r = 0
    for c in range(n):
        piv = None
        for i in range(r, n):
            if A[i][c]:
                piv = i
                break
        if piv is None:
            continue
        A[r], A[piv] = A[piv], A[r]
        for i in range(n):
            if i != r and A[i][c]:
                for j in range(c, n + 1):
                    A[i][j] ^= A[r][j]
        r += 1
    x = 0
    for i in range(n):
        if A[i][n]:
            x |= 1 << i
    return x


