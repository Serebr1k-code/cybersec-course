ADD["mobile-ios-backup"] = r'''
## Разбор ключевых баз в бэкапе

Манифест говорит, **где** лежит файл, но ценность — в содержимом. Вот главные цели и что в
них искать.

**`sms.db`** (HomeDomain `Library/SMS/`) — база сообщений. Таблица `message` содержит текст,
дату (`date`, в эпохе Apple), направление (входящее/исходящее) и идентификатор собеседника,
а `handle` — сами адреса/номера. Восстановив связи, ты получишь полную переписку с
таймстемпами.

**`CallHistory.storedata`** (HomeDomain `Library/CallHistoryDB/`) — история звонков: номер,
тип (входящий, исходящий, пропущенный), длительность, дата. Позволяет доказать контакт в
конкретное время.

**`History.db`** (AppDomain `com.apple.mobilesafari`) — история и закладки Safari. Таблицы
`history_items` (URL) и `history_visits` (посещения с временем). Дополняется `Cache.db`,
где могут остаться тела сетевых ответов.

**`AddressBook.sqlitedb`** (HomeDomain `Library/AddressBook/`) — контакты: имена, телефоны,
почта. Полезно для сопоставления номеров из SMS со людьми.

**Базы мессенджеров** (AppDomain `net.whatsapp.WhatsApp`, `ph.telegra.Telegraph` и т. п.) —
каждое приложение хранит свою историю. Их схемы различаются, но общий подход тот же:
открыть SQLite и найти таблицы сообщений и чатов.

## Геоданные и активность

Помимо переписки, бэкап содержит **геолокацию**: `Cache.sqlite` и `consolidated.db` хранят
записи о местоположении (соты Wi-Fi и GPS), а `routined`-артефакты — значимые места. Каждая
запись — точка с координатами и временем. Это позволяет строить карту перемещений
пользователя и сопоставлять её с событиями: где человек был в момент инцидента.

Отдельно стоит база **Health** (`HealthDomain`) — шаги, пульс, тренировки: косвенный
индикатор активности (спал ли пользователь, был ли на месте). И **фото** (`CameraRollDomain`)
с EXIF-геотегами и временем съёмки.

## Шифрование и классы защиты

iOS защищает данные **классами защиты**, привязанными к состоянию устройства. Даже если
бэкап зашифрован, важно понимать, что при разборе устройства часть файлов недоступна, пока
оно заблокировано (**BFU** — Before First Unlock), а часть — только после разблокировки
(**AFU** — After First Unlock). В бэкапе же всё, что попало в копию, уже расшифровано ключом
копии. Поэтому бэкап часто ценнее живого устройства: он снимает ограничения классов защиты,
если у тебя есть пароль.

## Практический сценарий: найти переписку

Требуется восстановить переписку в мессенджере. Шаги:

1. Открой `Manifest.db` и найди записи `AppDomain-<bundle>` с путями баз (`*.db`, `*.sqlite`).
2. Возьми `fileID` нужной записи и скопируй файл из подкаталога бэкапа.
3. Открой SQLite, найди таблицы с сообщениями (имена вида `message`, `ZWAMESSAGE`).
4. Выгрузи текст, время (переведи из эпохи Apple), отправителя и получателя.

В результате — упорядоченная по времени переписка с доказанными атрибутами.

## Ограничения и целостность

Бэкап — это **логическая** копия, а не образ диска. В неё попадают только файлы,
разрешённые системой; удалённые данные там, как правило, отсутствуют (в отличие от
физического образа, где можно восстановить удалённое). Кроме того, копия может быть
неполной (её прерывали) или старой. При работе фиксируй хеши файлов копии, чтобы доказать,
что ты не менял оригинал, и отмечай в отчёте дату и версию iOS — от них зависит набор
артефактов.
'''

ADD["mobile-android-backup"] = r'''
## Что можно и что нельзя извлечь

`adb backup` — это **логическая** копия. Она содержит данные приложений, разрешивших
бэкап, а также (при флагах `-shared` и `-apk`) разделяемое хранилище и сами APK. Чего в
ней нет:

- данных приложений с `android:allowBackup=false`;
- удалённых файлов (это не образ диска);
- системных разделов и метаданных ФС;
- содержимого защищённых хранилищ (KeyStore, некоторое шифрованное).

Поэтому `.ab` — быстрый, но неполный источник. Если нужен максимум, делают **физический
образ** через root или chip-off, а `.ab` используют как дополнение.

## Логическая копия против физического образа

| Критерий | `.ab` (логическая) | Физический образ |
|----------|--------------------|------------------|
| Права root | не нужны | нужны (или exploit) |
| Удалённые данные | нет | да |
| Данные всех приложений | только разрешившие | да |
| Сложность | низкая | высокая |
| Шифрование | может быть AES | зависит от FBE |

В отчёте важно указать, какой именно тип извлечения использован: выводы о полноте данных
зависят от этого.

## Разбор tar вручную

Если инструмент недоступен, `.ab` разбирают вручную. Сначала читают строки заголовка до
пустой строки — это метаданные. Затем оставшиеся байты (если флаг сжатия 1) прогоняют через
zlib, получая tar. Tar распаковывают стандартным `tar xf`. Понимание этого позволяет
работать даже с «нестандартными» копиями и объясняет, почему некоторые инструменты требуют
указывать версию формата.

## Шифрование AES и пароль

При `AES-256` payload зашифрован. Ключ выводится из пароля функцией вывода ключа (PBKDF2 с
солью из заголовка). Инструменты просят пароль и расшифровывают. Важно: слабый пароль
подбирается офлайн, поэтому в CTF-задачах пароль часто подбирают по словарю — это законный
сценарий, но в реальном расследовании пароль обычно известен от владельца или из другого
источника. Без пароля остаётся только анализ заголовка и метаданных.

## Практический сценарий

Задача: найти базу заметок. Шаги: прочитать заголовок (`ANDROID BACKUP`, версия, сжатие,
шифрование); если `none` и сжатие 1 — распаковать zlib и получить tar; найти в tar
`apps/com.example.notes/db/notes.db`; открыть SQLite и выгрузить записи. Если копия
зашифрована — сначала расшифровать с известным паролем. В отчёте зафиксируй пакет, файл и
время — это доказывает источник данных.
'''


def expand(lid, add):
    path = f"{C}/{lid}.md"
    t = open(path, encoding="utf-8").read()
    marker = "\n## Квиз"
    assert marker in t, lid
    t = t.replace(marker, "\n" + add.strip() + "\n" + marker, 1)
    open(path, "w", encoding="utf-8").write(t.rstrip() + "\n")


for lid, add in ADD.items():
    expand(lid, add)
print("B10-B mobile expanded")
