ADDS["mobile-screen-lock"] = """## Модель защиты: пароль устройства и Secure Enclave

Экранная блокировка — это не «замок на интерфейсе», а криптографический барьер.
Пароль (passcode) не хранится нигде: из него и аппаратного UID, зашитого в Secure
Enclave, выводится ключ, которым шифруются классово-производные ключи. Отсюда
следуют важные свойства. Во-первых, пароль нельзя «вытащить» из устройства — можно
только перебирать. Во-первых, смена пароля меняет всю ключевую иерархию, поэтому
старые ключи становятся бесполезны. В-третьих, сложность пароля напрямую определяет
стойкость: 4-значный PIN — это 10 000 комбинаций, 6-значный — миллион, а
буквенно-цифровой — миллиарды, и именно поэтому полицейские инструменты часто
работают только с короткими PIN.

## Состояния BFU и AFU

Для мобильной форензики критично различать два состояния:

| Состояние | Расшифровка | Что доступно |
|---|---|---|
| BFU | Before First Unlock | почти всё зашифровано, ключи не выведены |
| AFU | After First Unlock | классово-производные ключи в памяти, часть данных читается |

После перезагрузки устройство в BFU: даже имея дамп памяти, ты не получишь файлы,
защищённые классом `WhenUnlocked`. Как только пользователь один раз ввёл пароль и
устройство дошло до AFU, ключи класса `AfterFirstUnlock` оказываются доступны, и
часть данных (логи, базы фоновых сервисов) можно извлечь без пароля. Поэтому
извлечение почти всегда делают в AFU — это резко повышает шансы.

## Классы защиты данных

iOS размечает каждый файл классом защиты (`NSFileProtection*`): `Complete`,
`CompleteUnlessOpen`, `CompleteUntilFirstUserAuthentication`, `None`. Класс
определяет, при каком состоянии файл доступен. Практический вывод: один и тот же
образ даёт разные результаты в BFU и AFU, и это не ошибка инструмента, а ожидаемое
поведение. В отчёте всегда указывай состояние устройства на момент извлечения.

## Android: FDE, FBE и gatekeeper

На Android исторически было полное шифрование диска (FBE — File-Based Encryption
пришло на смену FDE). Пароль/графический ключ обрабатывает служба `gatekeeper`:
она хранит в `/data/system/gatekeeper.*.key` данные для проверки, а число неудачных
попыток — в `/data/system/locksettings.db`. Графический ключ — это не пароль, а
последовательность узлов; его «хеш» тоже перебираем, но пространство меньше.

## Брутфорс и его пределы

Устройства намеренно замедляют перебор: задержки растут с числом попыток, а после
заданного порога (обычно 10) срабатывает стирание данных. Инструменты обходят это,
либо аппаратно перехватывая обмен с SEP, либо используя уязвимости загрузчика
(`checkm8` на старых SoC). Для современных устройств с A12+ и новее надёжного
программного обхода нет — это принципиальное ограничение, а не «недостаток
инструмента». В отчёте различай «пароль неизвестен» и «пароль невосстановим».

## Справочная таблица

| Артефакт | Платформа | Смысл |
|---|---|---|
| keybags | iOS | связка пароль-ключи |
| `/private/var/keybags/` | iOS | классовые ключи |
| gatekeeper.*.key | Android | проверка пароля |
| locksettings.db | Android | настройки блокировки |
| attempt counters | обе | счётчик неудач |

## Тонкие места

- BFU/AFU — самое частое упущение: из BFU-образа делают вывод «данных нет».
- Отключение пароля (swipe) убирает шифрование части данных — это меняет картину.
- Биометрика не заменяет пароль: она лишь разблокирует уже выведенные ключи.
- Рабочий профиль Android имеет собственный gatekeeper и счётчик.
- Время извлечения и версия ОС обязательны: от них зависит применимость методов."""

ADDS["forensics-ios-backup"] = """## Структура бэкапа

Бэкап iPhone (iTunes/Finder) — это не дерево файлов с понятными именами, а набор
файлов, разложенных по подкаталогам, имена которых совпадают с первыми двумя
символами SHA-1. В корне лежат четыре метафайла:

| Файл | Что содержит |
|---|---|
| `Manifest.plist` | метаданные бэкапа: устройство, версия iOS, шифрование, ключи |
| `Manifest.db` | карта: логический путь → имя файла на диске |
| `Info.plist` | сводка: имя, телефон, версия ОС |
| `Status.plist` | состояние бэкапа (полный/инкрементальный) |

Именно `Manifest.db` превращает безымянные файлы в осмысленную структуру: в таблице
`Files` есть столбцы `fileID`, `domain`, `relativePath` и `flags`. Зная домен и
путь, можно вычислить, где лежит файл.

## Домены и как найти файл

`fileID` — это SHA-1 от строки `домен-относительный_путь`. Значит, найти файл можно
без базы:

```
$ echo -n 'HomeDomain-Library/SMS/sms.db' | shasum -a 1
```

Полученный хеш `abcd...` означает, что файл лежит в `ab/cd...`. Домены отражают
происхождение данных: `HomeDomain` — данные пользователя, `CameraRollDomain` —
медиа, `AppDomain-com.example` — приложение, `RootDomain` — системное, а
`WirelessDomain` — настройки Wi-Fi. Понимание доменов сразу подсказывает, где искать
переписку, фото или пароли.

## Шифрованный и нешифрованный бэкап

Нешифрованный бэкап не содержит keychain и части чувствительных данных. Шифрованный
(с паролем) включает их, но требует пароля для расшифровки. `Manifest.plist`
содержит признак `IsEncrypted`, а также обёрнутые ключи. Без пароля содержимое
остаётся недоступным — это не «битый архив».

## Инструменты извлечения

```
$ idevicebackup2 backup --full Backup/
$ iphone_backup_decrypt -i Backup/<UDID> -o out -p <password>
$ ileapp -i out -o report/          # iLEAPP: разбор артефактов
```

Для старта достаточно распаковать файлы по `Manifest.db` и применить парсеры
артефактов. Ручной поиск по хешу полезен, когда нужен конкретный файл.

## Что искать

- SMS/iMessage (`HomeDomain-Library/SMS/sms.db`);
- контакты, календарь, заметки;
- медиа с геотегами (`CameraRollDomain`);
- keychain (только в шифрованном бэкапе);
- базы приложений (`AppDomain-*`) — переписка мессенджеров;
- настройки Wi-Fi (`WirelessDomain`).

## Тонкие места

- `Manifest.db` — карта; без неё файлы безымянные, но восстановимы по SHA-1.
- Инкрементальный бэкап содержит не все файлы — сверяй `Status.plist`.
- Пароль бэкапа — не пароль устройства; они независимы.
- `fileID` считается от нормализованного пути — регистр и разделители важны.
- Локальный бэкап может быть усечён — проверяй целостность до анализа."""

ADDS["tool-grr"] = """## Архитектура подробнее

GRR состоит из нескольких компонентов. **Frontend** — точка входа, к которой
подключаются агенты. **Workers** — процессы, выполняющие задачи. **Datastore** —
хранилище результатов (часто MySQL). **Агенты** устанавливаются на хосты и
поддерживают постоянное соединение, забирая задачи. Когда аналитик запускает
действие, сервер ставит задачу агенту, агент выполняет её на хосте и возвращает
результат, который сохраняется в datastore и доступен через веб-интерфейс. Такая
архитектура позволяет осматривать тысячи машин одновременно, не выезжая к каждой.

## Flows и артефакты

Работа в GRR описывается потоком (flow) — графом шагов. Базовые потоки:
`ListProcesses`, `ListDirectory`, `GetFile`, `FileFinder`, `MemoryDump`,
`Timeline`. Из них собираются более сложные: например, `FileFinder` с маской
`/var/log/*.log` плюс `GetFile` дают сбор всех логов с сохранением структуры. Есть
потоки, собирающие готовые артефакты (registry, браузерные базы), — их называют
ArtifactCollectorFlow. Всё, что собрано, попадает в **Virtual File System** (VFS) —
единое дерево результатов, по которому можно ходить как по файловой системе.

## Client-side search и hunts

Ключевая сила GRR — выполнение поиска **на хосте**, а не перекачивание всего диска.
Client-side search позволяет искать файлы по условиям (имя, размер, содержимое,
время) и забирать только совпадения. Hunts — это широкомасштабные кампании: одна
hunt-задача запускается на десятках тысяч хостов, результаты агрегируются, и видно,
где найден индикатор. Это основной инструмент «охоты» по IOC: задал строку или
YARA-правило — получил список хостов, где оно сработало.

## YARA и автоматизация

GRR умеет запускать YARA прямо на хосте, не перекачивая файлы: агент применяет
правило и возвращает только совпадения. Автоматизация идёт через API и Python-клиент
(`grr_api_client`), что позволяет встраивать GRR в конвейеры реагирования: по
инциденту автоматически запускаются нужные flows на всех подозрительных хостах.

## GRR и Velociraptor

GRR — классика удалённого live-ответа, сильна в масштабе и client-side search.
Velociraptor — более новый инструмент с языком запросов VQL и агрессивным
«сбор-на-хосте». На практике их часто используют вместе: GRR для широких hunts,
Velociraptor для точечных глубоких запросов. Выбор зависит от инфраструктуры, но
принцип один — минимизировать перекачивание данных.

## Тонкие места

- Агент offline → flows не выполняются; проверяй статус клиента.
- Client-side search требует аккуратных условий, иначе получишь шум.
- Права агента ограничивают то, что можно собрать (обычно SYSTEM/root).
- Hunts надо ограничивать по времени и области, чтобы не перегрузить сеть.
- Результаты в VFS — это копии; для юридической значимости фиксируй хеши."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("deepened", lid, "+", len(add.split()), "tokens")
    return 0

if __name__ == "__main__":
    sys.exit(main())
