"""Deepen MOBILE batch 2 — second pass to clear 1200."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')
ANCHORS = ('\n## Что мы теперь знаем', '\n## Квиз')


def add(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already):', lid)
        return
    idx = next((t.find(a) for a in ANCHORS if t.find(a) != -1), None)
    t = t[:idx] + '\n' + extra.strip() + '\n' + t[idx:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


