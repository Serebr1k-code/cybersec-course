# --- lagged-Fibonacci (glibc TYPE_3-like) -----------------------------------
def lf_outputs(seed, n):
    r = [0] * 34
    r[0] = seed
    for i in range(1, 31):
        r[i] = (16807 * r[i - 1]) % 2147483647
    for i in range(31, 34):
        r[i] = r[i - 31]
    # discard 310 outputs (glibc does this)
    vals = []
    for i in range(34, 34 + 310 + n):
        r.append((r[i - 31] + r[i - 3]) & 0xffffffff)
        if i >= 34 + 310:
            vals.append(r[-1])
    return vals


def lf_predict(outs):
    # outs: 31 consecutive outputs; next = outs[0] + outs[28] (mod 2^32)
    return (outs[0] + outs[28]) & 0xffffffff


