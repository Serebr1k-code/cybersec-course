#!/usr/bin/env python3
"""Batch C3b — second layer for forensics-cloud-serverless, spec-gps, doc-xps."""
from __future__ import annotations
import re, sys

ADDS = {}

ADDS["forensics-cloud-serverless"] = r"""## Serverless против контейнеров и VM: что где остаётся

| Аспект            | VM               | Контейнер         | Serverless (FaaS)     |
|-------------------|------------------|-------------------|-----------------------|
| Диск              | образ/снимок     | слои образа       | нет (только код)      |
| Память            | дамп возможен    | дамп через хост   | недоступна            |
| Логи              | в системе        | stdout/движок     | платформенные         |
| Время жизни       | долгое           | часы/дни          | секунды               |
| Что остаётся      | много            | средне            | логи, метрики, конфиг |

Вывод: чем «тоньше» среда, тем меньше артефактов и тем важнее **логирование до
инцидента**. В serverless нет ни диска, ни памяти для анализа — только то, что
успело попасть в логи и API-аудит.

## Другие платформы: GCP и Azure

- **Google Cloud Functions** — логи в Cloud Logging (`resource.type=cloud_function`),
  идентичность через service account; аудит — Cloud Audit Logs (Admin Activity/Data
  Access).
- **Azure Functions** — логи в Application Insights и Log Analytics; управление — через
  Activity Log; идентичность — managed identity.
- **Cloudflare Workers** — логи через Tail/Logpush; изоляты вместо контейнеров.

Логика едина: **логи выполнения + аудит изменений + конфигурация роли**. Различаются
лишь имена сервисов и способ включения. Всегда уточняй, что было включено на момент
инцидента.

## Логи и трассировки: практические запросы

- CloudWatch Logs Insights:

```
fields @timestamp, @message
| filter @message like /http/
| sort @timestamp desc
| limit 50
```

- поиск по конкретному вызову: `aws logs filter-log-events --log-group-name /aws/lambda/fn
  --filter-pattern "RequestId"`;
- трассировки X-Ray: `aws xray get-trace-summaries --start-time ... --end-time ...`;
- аудит: `aws cloudtrail lookup-events --lookup-attributes AttributeKey=EventName,AttributeValue=UpdateFunctionCode`.

Комбинируя эти запросы, восстанавливают и «что делала функция», и «кто её менял».

## Мини-чек-лист расследования

1. Собери логи функции за период (CloudWatch/GCP/Azure).
2. Найди в stdout URL/IP/команды — аномальные обращения.
3. Проверь `START`/`REPORT`: длительность и частота (майнинг/ожидание C2).
4. Посмотри конфигурацию: роль, env, слои, таймаут.
5. Сравни версии функции — что изменилось.
6. Проверь CloudTrail на `UpdateFunctionCode`/`AddPermission`.
7. Смотри трассировки X-Ray на внешние вызовы.
8. Задокументируй каждый вывод со ссылкой на лог/событие.

Этого достаточно, чтобы восстановить serverless-инцидент без диска и памяти."""

ADDS["spec-gps"] = r"""## GPS против других источников геолокации

GPS — не единственный источник координат. В деле часто есть:

- **сотовая сеть** — привязка к вышкам (Cell ID/TAC), точность от сотен метров;
- **Wi-Fi** — по базе точек доступа, точность десятки метров в городе;
- **IP-геолокация** — грубо, до города;
- **фото/видео EXIF** — координаты с камеры;
- **облачные сервисы** — «Хронология» Google/Apple, грубее, но с историей.

Каждый источник имеет свою точность и надёжность. Сильнее всего — когда они
**совпадают**. GPS точен, но пропадает в помещении; соты всегда есть, но грубы; Wi-Fi
заполняет пробелы. В отчёте указывай источник и точность каждой точки — иначе
координата «висит в воздухе».

## Геозоны и определение мест

Часто нужно не точное место, а ответ «был ли там». Приёмы:

- **кластеризация точек** — группы близких координат = стоянка/пребывание;
- **геозона (geofence)** — заданный периметр (адрес, здание); проверяем, попадают ли
  точки внутрь;
- **время в зоне** — сколько минут/часов устройство провело внутри;
- **пересечения** — точки, общие для нескольких треков/устройств.

Кластеризация устойчива к шуму GPS: даже если отдельные точки «уехали», группа в целом
показывает, где человек был.

## Хранение треков: устройства и приложения

Треки живут в разных местах:

- **навигаторы** — GPX/FIT на карте памяти;
- **телефоны** — базы приложений (Карты, фитнес, мессенджеры), часто SQLite;
- **автомобили** — телематика, «чёрные ящики», мультимедиа;
- **трекеры** — отдельные устройства с SIM;
- **облако** — синхронизированная история.

Форензик-путь: сначала найти источник (файл/БД), затем извлечь точки с временем, затем
нормализовать формат (всё в UTC) и свести в единый трек.

## Мини-чек-лист разбора трека

1. Определи формат (GPX/NMEA/FIT/KML) и источник.
2. Нормализуй время в UTC (проверь leap seconds и сбросы).
3. Проверь точность (HDOP/спутники) каждой точки.
4. Построй маршрут на карте.
5. Найди стоянки (кластеры) и аномалии (прыжки, прямые линии).
6. Сопоставь с событиями и другими источниками по времени.
7. Оцени физическую проходимость маршрута (скорость).
8. Зафиксируй выводы с оговоркой о точности.

Этот порядок отделяет реальный маршрут от артефактов и подделок."""

ADDS["doc-xps"] = r"""## XPS против PDF и OOXML

| Аспект           | XPS (OXPS)             | PDF                | OOXML (docx)          |
|------------------|------------------------|--------------------|-----------------------|
| Основа           | ZIP + XML (OPC)        | бинарный/структуры | ZIP + XML             |
| Страницы         | `*.fpage` (XML)        | объекты PDF        | `word/document.xml`   |
| Текст            | `Glyphs`/`UnicodeString`| поток контента    | `w:t`                 |
| Метаданные       | `Metadata/`            | `/Info`, XMP        | `docProps/`           |
| Подпись          | встроенная             | встроенная          | редко                 |
| Разбор           | распаковка ZIP         | парсер PDF          | распаковка ZIP        |

XPS — «ZIP-брат» OOXML с фиксированной вёрсткой страниц. Для форензика удобен тем, что
текст лежит в открытых XML-атрибутах: не нужен тяжёлый парсер PDF, достаточно
`unzip` + `grep`.

## Извлечение изображений и шрифтов

Внедрённые ресурсы вытаскиваются распаковкой:

```
$ unzip -o doc.xps -d xps_out
$ file xps_out/Documents/1/Resources/Images/*.png
$ exiftool xps_out/Documents/1/Resources/Images/*.png | head
```

Изображения могут содержать **EXIF** (камера, дата, геолокация) и стеганографию — их
стоит проверить отдельно. Внедрённые шрифты (`FontUri`) иногда раскрывают ПО-источник
или содержат встроенные метаданные. Кисти (`ImageBrush`) ссылаются на изображения —
по ним видно, какая картинка где использована.

## Мини-чек-лист разбора XPS

1. `unzip -l` — состав пакета.
2. Прочитай `Metadata/` — автор, заголовок, свойства.
3. Извлеки текст из `*.fpage` (`UnicodeString`), отсортируй по координатам.
4. Вытащи ресурсы (`Resources/`) и проверь изображения (EXIF/стего).
5. Проверь наличие цифровой подписи.
6. Проверь внешние ссылки (`xlink:href`).
7. Собери всё в отчёт со ссылками на части пакета.

XPS хорошо разбирается даже в CTF: обычно достаточно `unzip` и `grep` по XML.

## Правовые и процедурные аспекты

XPS — обычный документ, но с встроенной подписью он может быть **юридически значимым**.
Поэтому:

- не редактируй оригинал; работай с копией;
- фиксируй хеш файла;
- если есть подпись — проверь её и опиши результат (валидна/невалидна/отсутствует);
- в отчёте различай извлечённый текст и его интерпретацию.

Подпись XPS связывает содержимое с сертификатом; её проверка — часть экспертизы, а не
формальность."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
