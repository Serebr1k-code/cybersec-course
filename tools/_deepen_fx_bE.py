from __future__ import annotations
import re, sys

ADDS = {}

ADDS["tool-dfir-orc"] = """## Расширенный разбор: от конфигурации к артефакту

Пусть нужно собрать с рабочей станции базовый набор для триажа. Конфигурация может
выглядеть так:

```xml
<config>
  <modules>
    <module name="Registry"/>
    <module name="EventLogs"/>
    <module name="NTFSInfo"/>
    <module name="SystemInfo"/>
    <module name="FileInfo">
      <path>C:\\Users\\*\\AppData\\Roaming\\Microsoft\\Windows\\Start Menu\\Programs\\Startup</path>
      <path>C:\\Windows\\Temp</path>
    </module>
  </modules>
</config>
```

Запуск:

```
$ orc.exe /config triage.xml /out C:\\case\\host01.7z /temp C:\\Windows\\Temp
$ dir C:\\case\\host01.7z
```

После сбора архив разбирается по частям. Реестр — `RegRipper` или `hivexsh`;
журналы — `EvtxECmd`; USN journal — `MFTECmd`; списки файлов — обычным разбором
CSV. Логи ORC (`orc.log`) показывают, какие модули отработали и где возникли
ошибки доступа. Типовой провал — сбор `SAM`/`SECURITY` без прав администратора:
модуль отработает, но кусты будут пустыми.

Проверить целостность архива и зафиксировать хеш — обязательный шаг:

```
$ sha256sum host01.7z > host01.7z.sha256
```

## Что реально доказывает собранное

ORC даёт «срез состояния»: что было в автозагрузке, какие журналы есть, какие файлы
лежали в подозрительных каталогах. По USN journal видно историю создания и удаления
файлов — это часто ценнее, чем сами файлы. По реестру восстанавливается история
USB-подключений, список служб, настройки безопасности. Каждый модуль отвечает на
свой вопрос, и вместе они образуют основу таймлайна. ORC не читает содержимое
удалённых файлов — для этого нужен образ; он фиксирует метаданные и состояние.

## Ограничения и сравнение

ORC — коллектор, а не анализатор. Он не строит таймлайн и не интерпретирует данные.
Его сила — стандартизация и скорость на большом парке; слабость — зависимость от
конфигурации: забыл модуль, не собрал нужное. По сравнению с KAPE у ORC меньше
готовых «таргетов», но конфигурация прозрачнее и воспроизводимее. По сравнению с
Velociraptor ORC не требует агента и постоянного присутствия, но и не даёт запросов
«на лету». Выбор зависит от задачи: массовый однократный сбор — ORC; длительное
наблюдение — агентные платформы."""

ADDS["tool-magnet-axiom"] = """## Расширенный разбор: дело от сбора до отчёта

Разберём типовой поток в AXIOM. Допустим, изъят ноутбук и телефон.

1. **Импорт источников.** В AXIOM Process добавляешь образ диска ноутбука и
   мобильное устройство (или его бэкап). Инструмент сам определяет тип и
   предлагает набор артефактных модулей.
2. **Выбор модулей.** Для ноутбука — браузеры, реестр, USB, почта; для телефона —
   коммуникации, геолокация, приложения. Лишние модули отключаешь, чтобы не
   раздувать обработку.
3. **Обработка.** AXIOM прогоняет модули и складывает находки в «дело». Время
   обработки зависит от объёма: большой образ может считаться часами.
4. **Анализ.** В AXIOM Examine фильтруешь по времени, типу артефакта, источнику.
   Например, ищешь все USB-подключения за интересующую дату.
5. **Связывание.** Находки из разных источников (ноутбук и телефон) объединяются в
   общий таймлайн — это ключевая ценность AXIOM.
6. **Отчёт.** Помечаешь релевантные находки и экспортируешь отчёт (PDF/Excel/CSV).

Так один инструмент покрывает и компьютер, и мобильное устройство, и (при
необходимости) облако.

## Работа с мобильными и облаком

Для мобильных AXIOM умеет как прямое извлечение, так и импорт бэкапов и образов. Он
разбирает коммуникации (SMS, мессенджеры), геолокацию, установленные приложения,
историю браузера. Для облачных источников нужны учётные данные и правовое
основание; AXIOM подключит аккаунт и соберёт доступные данные, объединив их с
локальными. Это позволяет, например, сопоставить переписку на телефоне с
активностью в облачном хранилище.

## Ограничения

- Глубина по отдельному артефакту иногда меньше, чем у специализированной утилиты.
- Magnet.AI — эвристика: обязательна ручная проверка срабатываний.
- Обработка больших образов требует времени и ресурсов.
- Облачные источники зависят от прав доступа и юридических ограничений.
- Для воспроизводимости фиксируй версию AXIOM и точные настройки обработки.

## Что писать в отчёте

Перечисли источники, модули и версию инструмента. Для каждой ключевой находки
укажи источник и модуль. Приведи хеши исходных данных и момент извлечения. Отдельно
отметь, что не обрабатывалось или было недоступно, — так отчёт показывает границы
анализа и не создаёт ложного впечатления полного охвата."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("layer2", lid, "+", len(add.split()), "tokens")
    return 0

if __name__ == "__main__":
    sys.exit(main())
