"""Third expansion for MIS-GAP-4a lessons — cross-links and practical notes."""
import re

CONTENT = 'content/misc/'


def add(lesson, text):
    p = CONTENT + lesson + '.md'
    s = open(p, encoding='utf-8').read()
    add_txt = text.strip()
    m = re.search(r'^## Квиз\s*$', s, re.MULTILINE)
    out = s[:m.start()] + add_txt + '\n\n' + s[m.start():]
    open(p, 'w', encoding='utf-8').write(out)
    print('expanded3', lesson)


