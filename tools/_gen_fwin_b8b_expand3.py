#!/usr/bin/env python3
"""Third top-up for batch B (three lessons still under 1200)."""
import re

ADD = {}

ADD["win-amcache-deep"] = r'''
## Практический чек-лист по AmCache

Держи короткий порядок работы. Сначала определи версию Windows, чтобы выбрать подходящий
парсер. Затем разбери `Amcache.hve` и выгрузи записи в CSV, чтобы дальше работать с ними как
с таблицей. Отфильтруй системные пути и оставь пользовательские каталоги — именно там чаще
прячется маскировка. Для каждой подозрительной записи выпиши путь, SHA-1 и время. После этого
проверь хеши в базе ВПО и сопоставь с локальными IOC. В конце сверь с Prefetch, чтобы
разделить «присутствовал» и «запускался», и зафиксируй вывод в отчёте с указанием источника и
даты проверки хеша. Такой чек-лист переносится на любой хост и занимает считанные минуты.
'''

ADD["win-srum-deep"] = r'''
## Практический чек-лист по SRUM

Порядок работы прост и воспроизводим. Первое — определи, что перед тобой ESE-база, и выбери
инструмент (`esedbexport`/`SRUMDump`). Второе — выгрузи таблицу `NetworkUsages`. Третье —
обязательно свяжи `AppId` с именами через `SruDbIdMapTable`; без этого шага цифры
бессмысленны. Четвёртое — построй топ приложений по `BytesSent` и `BytesRecv` за интересующий
период. Пятое — для аномалий найди подтверждения в Prefetch, AmCache и журналах. Шестое —
зафиксируй период данных и ограничение агрегации. В конце сохрани выгрузку в CSV как
приложение к отчёту. Каждый шаг опирается на один источник и легко проверяется повторно.
'''

ADD["win-appcompat-deep"] = r'''
## Итоговый вывод по ShimCache

ShimCache — это артефакт **присутствия**, и его главная ценность в том, что он переживает
удаление файла. Он не заменяет Prefetch и не доказывает запуск, но даёт то, чего у Prefetch
нет: список путей, включая давно исчезнувшие. Используй его как отправную точку: найди
интересные пути, отфильтруй системные, а затем ищи идентичность (хеш) в AmCache и запуск в
Prefetch. В отчёте формулируй строго: «по данным ShimCache файл присутствовал на хосте».
Соблюдая эту дисциплину, ты не позволишь себе превратить «видел» в «запускал» и не дашь
защите оспорить вывод на терминологии. Именно точность формулировок отличает корректный
форензик-вывод от поспешного.
'''

for lid, add in ADD.items():
    p = f"content/forensics/{lid}.md"
    t = open(p, encoding="utf-8").read()
    m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
    out = t[:m.start()] + add.strip() + "\n\n" + t[m.start():]
    open(p, "w", encoding="utf-8").write(out)
    print("topup", lid)
