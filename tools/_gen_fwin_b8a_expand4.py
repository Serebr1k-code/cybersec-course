#!/usr/bin/env python3
"""Fourth top-up pass for batch A (notification-db, cortana)."""
import re

ADD = {}

ADD["win-notification-db"] = r'''
## Разбор payload уведомления шаг за шагом

Разберём, как из «сырой» записи получить человекочитаемый текст. В базе payload хранится
как blob, часто в виде XML или сжатой структуры. Первый приём — выгрузить конкретную
запись в файл и посмотреть её тип:

```
$ sqlite3 wpndatabase.db "SELECT Payload FROM Notification ORDER BY ExpiryTime DESC LIMIT 1;" > payload.bin
$ file payload.bin
payload.bin: XML 1.0 document, UTF-8 text
```

Если `file` говорит, что это XML, — форматируем и читаем текст напрямую. Если это
«data» или «zlib compressed data» — распаковываем (`zlib-flate -uncompress` или короткий
скрипт на Python) и повторяем опознание. Такой пошаговый подход спасает, когда приложение
шлёт уведомления в нестандартной упаковке. Второй приём — если payload разбит на несколько
полей (заголовок и тело отдельно), собери их вместе: только в паре они дают полный смысл
уведомления. Третий приём — ищи привязку к действию: тосты с кнопками содержат идентификатор
действия, который иногда указывает на конкретную ссылку или объект в приложении.

## Что делать, когда база почти пуста

Бывает, что в текущей `wpndatabase.db` всего пара уведомлений — пользователь чистил историю
или система давно её ротировала. Не спеши делать вывод «уведомлений не было». Проверь три
вещи. Первое — соседние профили: у каждой учётной записи своя база, и на машине их может
быть несколько. Второе — теневые копии тома: исторический снимок профиля часто содержит
более полную базу. Третье — кэш уведомлений: вложения и картинки из тостов могут лежать
отдельно от самой базы, и по ним восстанавливается контекст. Только собрав все три слоя,
можно утверждать, что истории уведомлений действительно нет.
'''

ADD["win-cortana-search"] = r'''
## Разбор истории поиска: от файла к таблице

Покажем полный путь от обнаружения файла до готовой таблицы запросов. Сначала находим
кандидатов в профиле — базы и кэш поиска:

```
$ find . -iname '*.db' | grep -iE 'search|cortana|history' | head
```

Затем для каждого файла проверяем, что это SQLite, и смотрим таблицы:

```
$ file query.db
query.db: SQLite 3.x database
$ sqlite3 query.db ".tables"
SearchHistory  Suggestions  ...
```

Дальше выгружаем запросы с временем и сохраняем в CSV, чтобы дальше работать с ними как с
данными:

```
$ sqlite3 -csv query.db "SELECT datetime(TimeStamp,'unixepoch'), QueryText FROM SearchHistory ORDER BY TimeStamp;" > queries.csv
$ column -s, -t queries.csv | head
```

Такой прогон даёт воспроизводимый артефакт: таблицу, которую можно приложить к отчёту и
которую другой аналитик получит из того же файла теми же командами. Это важная черта
хорошей форензики — **воспроизводимость**: вывод должен опираться на команды, а не на
«я посмотрел глазами».

## Сводная картина по намерениям

Когда таблица запросов готова, полезно свести её в короткую сводку по времени и темам.
Раздели запросы на до и после ключевого события инцидента — это покажет подготовку и
реакцию. Отметь запросы, напрямую связанные с инструментами или антифорензикой, и для
каждого найди подтверждение в других артефактах. В итоге получается не список строк, а
связная линия поведения пользователя, где каждый запрос подкреплён фактом. Именно такая
сводка идёт в отчёт, а сырые запросы — в приложение как исходные данные.
'''

for lid, add in ADD.items():
    p = f"content/forensics/{lid}.md"
    t = open(p, encoding="utf-8").read()
    m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
    out = t[:m.start()] + add.strip() + "\n\n" + t[m.start():]
    open(p, "w", encoding="utf-8").write(out)
    print("topup4", lid)
