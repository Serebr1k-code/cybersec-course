"""Deepen MOBILE batch 1 — fourth pass to clear 1200."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')
ANCHORS = ('\n## Что мы теперь знаем', '\n## Квиз')


def add(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already):', lid)
        return
    idx = next((t.find(a) for a in ANCHORS if t.find(a) != -1), None)
    t = t[:idx] + '\n' + extra.strip() + '\n' + t[idx:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


OLLVM = '''
## Почему деобфускация — это про стоимость, а не про «взлом»

Важно понимать цель обфускации: она не делает реверс невозможным, она повышает его цену. Пока
стоимость анализа выше ценности результата, защита работает. Для пентеста это означает, что не
всегда нужно вскрывать функцию целиком: часто достаточно понять один проверяемый факт —
принимает ли `check()` конкретный вход. Тогда вместо полной деобфускации используют динамику:
подставляют вход и наблюдают результат, обходя статический разбор вовсе. Такой «чёрный ящик» на
защищённой функции экономит часы и даёт тот же ответ.
'''

REFLECTION = '''
## Reflection в нативном коде

Reflection бывает и на уровне JNI: нативный код вызывает `CallObjectMethod` по имени, полученному
из C-строки. Java-хуки здесь не видят вызов. Тогда перехватывают JNI-таблицу: `FindClass`,
`GetMethodID`, `CallObjectMethod`. Через Frida это делается по адресам из `JNIEnv`, а через
статику — поиском `GetMethodID` в декомпиляции `.so`. Результат тот же: мы видим имя метода и
класс, к которому он относится, и дальше работаем с ними напрямую. Так закрывается последний
пробел, когда часть логики уехала в нативный слой ради сокрытия от анализа DEX.
'''

UNICORN = '''
## Эмуляция как инструмент массовой расшифровки

Главная сила эмуляции — повторяемость. Если приложение расшифровывает сотни строк одной функцией,
не нужно запускать приложение сто раз: достаточно один раз подготовить окружение и прогнать
функцию в цикле по всем входам. Так за секунды получают таблицу «шифртекст → открытый текст»,
которая затем используется офлайн. Именно поэтому эмуляция — стандартный первый шаг при разборе
защищённых приложений: она превращает медленный ручной реверс в автоматический процесс, а
результат можно проверить и переиспользовать.
'''

NDKDEBUG = '''
## Что даёт отладчик там, где бессилен статический анализ

Статический анализ показывает код, но не данные. Отладчик показывает и то, и другое: в какой
ветви пошло исполнение, какие значения пришли в функцию, что записалось в память. Для проверок,
построенных на рантайм-значениях (хеш устройства, время, ответ сервера), это единственный способ
увидеть «правильный» вход. Поэтому нативная отладка — не просто удобство, а метод: она превращает
непрозрачную проверку в наблюдаемый процесс, который можно воспроизвести и обойти.
'''

for lid, txt in [
    ('mobile-android-ollvm', OLLVM),
    ('mobile-android-reflection', REFLECTION),
    ('mobile-android-unicorn-emu', UNICORN),
    ('mobile-android-ndk-debug', NDKDEBUG),
]:
    add(lid, txt)
