#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Deepen MOBILE batch 1 — fifth pass to clear 1200."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')
ANCHORS = ('\n## Что мы теперь знаем', '\n## Квиз')


def add(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already):', lid)
        return
    idx = next((t.find(a) for a in ANCHORS if t.find(a) != -1), None)
    t = t[:idx] + '\n' + extra.strip() + '\n' + t[idx:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


OLLVM = '''
## Практический вывод по OLLVM

Соберём всё в один рабочий подход. Сначала классифицируем защиту: flattening выдаёт себя большим
диспетчером, bogus flow — невыполняемыми ветвями, substitution — странной арифметикой. Затем
запускаем приложение под Stalker и записываем реальный порядок блоков; это самый быстрый способ
получить «скелет» логики, потому что трасса автоматически исключает мусорные ветви. После этого
упрощаем оставшиеся выражения и сверяем результат с поведением функции на устройстве. Если трасса
недоступна, включается символьное исполнение: angr проходит путь и решает предикаты. И только
когда ни трассировка, ни символика не помогают — например, при вложенном flattening — переходим к
кропотливому ручному разбору небольшого участка. Такой порядок экономит время и не даёт утонуть в
деталях, которые не влияют на итоговый ответ.
'''

REFLECTION = '''
## Практический вывод по reflection

Reflection — это способ спрятать логику, но не способ её удалить. В рантайме все имена становятся
известны, и именно на этом строится вся работа. Начинаем с поиска точек reflection в smali и
декомпиляции; затем выясняем, как формируется имя — константами, ресурсами или функцией-расшифровщиком.
Для простых случаев хватает скрипта, складывающего части; для сложных — перехват `Class.forName`
и `Method.invoke` через Frida. Полученные имена сопоставляем с кодом и читаем его уже статически.
Если часть логики ушла в нативный слой, перехватываем JNI-таблицу. В итоге «растворённая» логика
снова становится набором обычных методов, которые можно анализировать привычными инструментами.
'''

UNICORN = '''
## Практический вывод по эмуляции

Эмуляция хороша там, где нужно изолированно исполнить функцию и получить результат, не поднимая
устройство. Порядок работы: найти смещение и размер функции, вырезать байты, замапить код, данные
и стек, положить аргументы в регистры и запустить. Ключевые детали — правильный регистр `LR`
(чтобы функция «вернулась» в заглушку) и обработка внешних вызовов, которых в эмуляции нет.
Результат читаем из памяти после остановки. Если функция тянет за собой JNI и системные вызовы,
выгоднее перейти на Frida или Qiling. Но для «чистых» крипто-функций эмуляция даёт максимальную
скорость и повторяемость: один раз настроив окружение, вы расшифровываете сотни входов в цикле и
получаете готовые таблицы для офлайн-анализа.
'''

NDKDEBUG = '''
## Практический вывод по нативной отладке

Нативная отладка отвечает на вопрос «что происходит в рантайме», на который статический анализ
ответить не может. Порядок: получить root и ptrace, поднять `gdbserver`, пробросить порт, найти
базу библиотеки, поставить точку останова по имени или по смещению, прочитать регистры и память.
Для защит, зависящих от рантайм-значений, это единственный способ увидеть корректный вход. Важно
работать с относительными смещениями, а не абсолютными адресами: ASLR меняет базу при каждом
запуске, и только смещение воспроизводимо. Если anti-debug мешает, комбинируйте отладчик с Frida:
инструментация снимает защиту и подменяет значения, а отладчик даёт пошаговый разбор. Так два
инструмента дополняют друг друга — один обходит препятствия, другой показывает глубину.
'''

for lid, txt in [
    ('mobile-android-ollvm', OLLVM),
    ('mobile-android-reflection', REFLECTION),
    ('mobile-android-unicorn-emu', UNICORN),
    ('mobile-android-ndk-debug', NDKDEBUG),
]:
    add(lid, txt)
