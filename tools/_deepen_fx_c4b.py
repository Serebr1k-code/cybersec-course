ADDS = {}

ADDS["media-deepfake"] = r"""## Виды подделок медиа

Deepfake — зонтичный термин. Различают:

- **face swap** — подмена лица одного человека на другого (автоэнкодеры/GAN);
- **face reenactment** — перенос мимики, сохраняя личность;
- **lip sync** — синхронизация губ с чужим аудио;
- **voice cloning / TTS** — синтез речи по образцу голоса;
- **полностью синтетическое видео** — сгенерированные люди и сцены (диффузия);
- **cheapfake** — грубые правки (замедление, вырезание, перемонтаж) без ИИ.

Для каждого типа — свои артефакты. Cheapfake ловится по монтажным склейкам и
несоответствию звука; ИИ-подделки — по швам генерации. Понимание типа подделки
подсказывает, где искать.

## Инструменты форензики медиа

- **`ffprobe`/`ffmpeg`** — контейнер, кодеки, покадровое извлечение, фильтры;
- **`sox`** — спектрограммы и анализ аудио;
- **`exiftool`** — метаданные, EXIF;
- **`c2patool`** — проверка Content Credentials (C2PA);
- **`inVID`/`WeVerify`** — плагины для проверки видео;
- **`FotoForensics`** — ELA (error level analysis) для изображений;
- **OpenCV/NumPy** — собственный частотный анализ и детекция.

Комбинация «метаданные + визуальные артефакты + спектр + провенанс» даёт наиболее
устойчивый вывод.

## Мини-чек-лист анализа медиа

1. `ffprobe`/`exiftool` — контейнер и метаданные.
2. Покадровый просмотр — границы лица, волосы, зубы, освещение.
3. Аудио — спектрограмма, дыхание, паузы, фон.
4. Частотный анализ ключевых кадров (FFT).
5. Проверка C2PA/провенанса.
6. Сопоставление с известными записями/оригиналами.
7. Оценка уверенности и перечисление непроверенного.

Такой чек-лист систематизирует экспертизу и делает вывод воспроизводимым.

## Почему это важно

Синтетические медиа используются для мошенничества (фейковые «звонки от директора»),
дезинформации и дискредитации. Умение отличить подделку — навык не только
форензик-аналитика, но и журналиста, юриста и службы безопасности. При этом «серебряной
пули» нет: результат — это вероятность, подкреплённая набором признаков и контекстом.
Честная оценка уверенности важнее громкого «это фейк»."""

ADDS["tool-xways"] = r"""## Работа с реестром: практика

X-Ways открывает кусты реестра как «виртуальные» файлы и показывает их структуру.
Практические задачи:

- **USB-история** — `SYSTEM\CurrentControlSet\Enum\USBSTOR` (какие устройства
  подключались) + `NTUSER.DAT\...\MountPoints2`;
- **автозагрузка** — `Run`/`RunOnce` в `SOFTWARE`/`NTUSER.DAT`;
- **сеть** — `SOFTWARE\Microsoft\Windows NT\CurrentVersion\NetworkList`;
- **последние программы** — `NTUSER.DAT\...\Explorer\UserAssist`;
- **учётные записи** — `SAM` (пользователи), `SECURITY` (политики).

Времена ключей (`LastWrite`) дают момент изменения — ценно для таймлайна. X-Ways
показывает их прямо в интерфейсе, без `reglookup`/`RegRipper`.

## Таймлайн и сортировка

X-Ways умеет строить «объединённый таймлайн» событий файловой системы и реестра.
Сортировка по времени позволяет увидеть последовательность:

- создание файла → запуск (prefetch) → удаление (`$UsnJrnl`);
- подключение USB → копирование файла → отключение;
- изменение ключа реестра → перезагрузка.

Таймлайн — ядро расследования: он превращает разрозненные артефакты в историю. X-Ways
даёт его «из коробки», объединяя ФС, реестр и журналы.

## Мини-чек-лист работы в X-Ways

1. Добавить образ, выбрать раздел, построить индекс.
2. Отфильтровать по окну инцидента.
3. Просмотреть категории типов и галерею.
4. Восстановить удалённое (метаданные, затем карвинг).
5. Разобрать реестр (USB, автозагрузка, сеть).
6. Построить таймлайн.
7. Сформировать отчёт с временами и хешами.
8. Экспортировать найденные файлы.

## Ограничения и подводные камни

- **Индекс не мгновенный.** На больших образах построение индекса занимает время —
  планируй.
- **Карвинг медленный и «шумный».** Результаты нужно валидировать (`file`).
- **Шифрование.** Зашифрованные разделы/файлы X-Ways не «сломает»; нужен ключ.
- **Времена подделываются.** `$MFT` можно «затереть»; сверяй с `$UsnJrnl`.
- **Не путай «найдено» и «доказано».** Найденный файл — факт; его роль — вывод.

X-Ways — инструмент, а не эксперт: интерпретация остаётся за аналитиком."""

ADDS["web-mongodb-redis"] = r"""## Redis: разбор конфигурации и следов

Redis-конфиг (`redis.conf`) определяет, куда пишутся данные и как включается защита.
Форензик-значимые параметры:

- `bind` — на каких интерфейсах слушает (0.0.0.0 = наружу);
- `protected-mode` — защита от внешнего доступа без пароля;
- `requirepass` — пароль (отсутствие = открытый доступ);
- `dir`/`dbfilename` — путь и имя RDB-файла (атакующий меняет для записи файлов);
- `appendonly`/`appendfilename` — AOF-журнал;
- `rename-command` — переименование опасных команд (редкая защита).

```
$ redis-cli -h target CONFIG GET dir
$ redis-cli -h target CONFIG GET requirepass
$ redis-cli -h target INFO server
```

Если `CONFIG GET` работает без `AUTH` — инстанс открыт. Изменение `dir` в логах —
сильный признак попытки записи файла на хост.

## MongoDB: структура и восстановление

MongoDB хранит данные в каталоге `dbPath` (по умолчанию `/var/lib/mongodb`). Ключевые
файлы:

- `collection-*.wt` / `index-*.wt` — данные и индексы (WiredTiger);
- `WiredTiger`, `WiredTigerLog*` — движок и журнал;
- `diagnostic.data/*` — метрики;
- `local/oplog.rs` — журнал операций (в репликации).

Восстановление: остановить сервер, скопировать каталог, поднять на отдельном хосте (не
на «боевом»). Удалённые коллекции иногда можно восстановить из журнала WiredTiger или
из oplog. `mongodump`/`mongorestore` — штатные средства, но для удалённого нужен
журнал.

## Мини-чек-лист расследования БД

1. Проверь доступ без аутентификации.
2. Зафиксируй версию (`INFO server`, `db.version()`).
3. Проверь конфиг (`dir`, `bind`, `requirepass`; `dbPath`).
4. Ищи опасные команды в логах (CONFIG/SAVE/MODULE/SLAVEOF; drop/delete).
5. Изучи AOF (Redis) и oplog (Mongo) как историю.
6. Проверь профилировщик/аудит.
7. Собери сетевые подключения.
8. Задокументируй каждый вывод.

## Ограничения и подводные камни

- **Логи могут быть отключены.** Тогда работаешь по AOF/oplog и сетевому аудиту.
- **AOF/RDB перезаписываются.** Сразу копируй файлы, пока не зациклились.
- **oplog ограничен размером.** Старые операции вытесняются — успей прочитать.
- **Профилировщик замедляет БД.** Его часто выключают, поэтому данных нет.
- **RCE через Redis не всегда оставляет явный след.** Ищи косвенные: изменённый `dir`,
  новые файлы в `~/.ssh`/cron.

БД — это хост: после доступа к ней переходи к анализу ОС (пользователи, cron, ключи),
потому что компромисс сервиса часто означает компромисс машины."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
