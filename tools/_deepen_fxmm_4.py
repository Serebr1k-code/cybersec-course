ADD['mobile-fraud'] = r"""
## Разбор: почему важна метрика false positive

Антифрод — это баланс. Слишком строгие правила ловят мошенников, но блокируют честных;
слишком мягкие — пропускают фрод. Ключевая метрика — **false positive rate** (доля
ошибочно заблокированных честных). Аудитор смотрит:

- измеряется ли FPR вообще;
- есть ли канал апелляции для заблокированных;
- не зависит ли порог от одного подделываемого сигнала.

Для пентеста это отдельный вектор: если защита строится на подделываемом сигнале
(отпечаток, геолокация), злоумышленник может **вызвать блокировку честных** — то есть
DoS на легитимных пользователей. Находка «правило блокирует честных по подделываемому
сигналу» не менее важна, чем «правило обходится», и её тоже нужно подтвердить
сценарием с числами.
"""


def find_file(lid):
    for cat in ("misc", "mobile"):
        p = os.path.join(ROOT, "content", cat, lid + ".md")
        if os.path.exists(p):
            return p
    return None


def main() -> int:
    n = 0
    for lid, add in ADD.items():
        path = find_file(lid)
        if not path:
            print("MISSING", lid, file=sys.stderr)
            continue
        t = open(path, encoding="utf-8").read()
        if MARK in t:
            print("skip (already)", lid)
            continue
        m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
        if not m:
            m = re.search(r"^## Что мы теперь знаем\s*$", t, re.MULTILINE)
        if not m:
            print("NO ANCHOR", lid, file=sys.stderr)
            continue
        block = MARK + "\n" + add.strip() + "\n\n"
        t = t[:m.start()] + block + t[m.start():]
        open(path, "w", encoding="utf-8").write(t)
        print("deepened4", lid)
        n += 1
    print("done:", n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
