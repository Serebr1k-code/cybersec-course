ADD["win-prefetch-deep"] = r'''
## Сквозной пример: доказательство запуска утилиты с флешки

Разберём историю целиком. Задача: доказать, что на хосте запускали `psexec.exe` и делали это
с внешнего USB-накопителя.

Шаг первый — находим файл Prefetch и читаем метаданные. Имя `PSEXEC.EXE-1A2B3C4D.pf` уже
говорит о программе, а внутри лежат счётчик и серийник тома. Выписываем серийник, скажем
`0x7a1c9e42`. Шаг второй — ищем этот серийник в реестре. В `HKLM\SYSTEM\MountedDevices`
серийники сопоставлены буквам дисков; смотрим, какой букве соответствует наш номер. Если он
привязан к съёмному устройству — половина дела сделана. Шаг третий — открываем
`HKLM\SYSTEM\CurrentControlSet\Enum\USBSTOR`, где хранятся серийные номера подключённых
USB-устройств и их имена. Находим совпадение — значит, носитель действительно подключался.
Шаг четвёртый — сверяем с `Setupapi.dev.log`, где фиксируется время подключения устройства.

В итоге получаем связную цепочку: программа запускалась, запускалась с конкретного
USB-накопителя, и носитель подключался к машине. Это уже не «подозрение», а обоснованный
вывод, подкреплённый несколькими независимыми источниками. Именно такой ход — **от одного
артефакта к связке** — отличает профессиональный разбор от «нашёл строку».

## Практика: читаем Prefetch вручную и парсером

Полезно один раз разобрать `.pf` и вручную, чтобы понимать, откуда берутся данные. Файл
начинается с сигнатуры и версии; дальше — заголовок с размерами секций и таблица метаданных.
В секции с информацией о томах лежат серийные номера, в секции со строками — имена файлов,
к которым обращался процесс. На Windows 10+ содержимое строк сжато алгоритмом XPRESS
Huffman, поэтому «руками» через `strings` ты увидишь лишь часть.

Парсер делает всё это автоматически. Разница между ручным и автоматическим разбором в том,
что парсер знает смещения полей для каждой версии формата и сам распаковывает строки.
Практический совет: используй парсер для скорости, но понимай структуру, чтобы замечать,
когда результат выглядит подозрительно (например, пустой список файлов при ненулевом счётчике
запусков — признак повреждения или частичной перезаписи файла).

## Полный прогон по всем источникам

Хороший разбор запуска программы — это всегда несколько источников. Собери их в один
порядок. Сначала Prefetch: факт запуска, счётчик, время, тома. Затем ShimCache: присутствие
файла и его путь. Затем AmCache: хеш и время изменения. Затем SRUM: была ли у программы
сетевая активность и какая. Затем журналы событий: входы пользователя, создание процессов
(если аудит включён). Каждый источник отвечает на свой вопрос, и вместе они дают полную
картину: «кто, когда, откуда, с какими данными и с какой сетевой активностью». Если один
источник противоречит другому, не прячь противоречие — опиши его, это тоже часть вывода.

## Что фиксировать в отчёте

В отчёте укажи: путь к каталогу Prefetch, конкретный `.pf`-файл, версию формата, счётчик
запусков, время первого и последнего запуска, серийный номер тома и результат его
сопоставления с `MountedDevices`/`USBSTOR`. Отдельно оговори, что времена Prefetch — это
метки запуска, а не создания файла. Такая детализация делает вывод проверяемым: другой
аналитик повторит команды и получит то же самое.
'''

ADD["win-appcompat-deep"] = r'''
## Сквозной пример: от пути в ShimCache к хешу в AmCache

Соберём историю целиком. Дано: файла нет, Prefetch пуст, но есть hive SYSTEM. Задача —
доказать присутствие подозрительного файла и по возможности получить его хеш.

Шаг первый — разбираем ShimCache из hive SYSTEM и находим путь
`C:\Users\jdoe\Downloads\mimikatz.exe` с временем последнего изменения. Уже это доказывает,
что файл существовал: каталог `Downloads` и подозрительное имя — сильный сигнал. Шаг второй —
открываем hive `SOFTWARE`, точнее `Amcache.hve`, и ищем тот же путь. В AmCache рядом с путём
лежит SHA-1. Шаг третий — берём хеш и проверяем его в базе ВПО; детект подтверждает
вредоносность. Шаг четвёртый — ищем тот же хеш в локальном списке IOC и в отчётах с других
хостов: возможно, программа запускалась не только здесь.

Итог: один путь из ShimCache вырос в доказательство присутствия вредоносного файла с
подтверждённым хешем и потенциальными связями с другими машинами. Обрати внимание на порядок:
ShimCache дал **зацепку**, AmCache — **идентичность**, threat-intel — **оценку**.

## Разница между «видел», «устанавливал» и «запускал»

Три глагола описывают три разных артефакта, и путать их — типичная ошибка.

- **ShimCache** — «видел»: загрузчик проверял файл на совместимость. Файл существовал.
- **AmCache** — «устанавливал/присутствовал»: программа была на хосте, есть хеш.
- **Prefetch** — «запускал»: процесс стартовал, есть счётчик и время.

В отчёте формулируй вывод строго по источнику: «по данным ShimCache файл присутствовал», «по
данным Prefetch файл запускался». Такая точность не даёт защите развалить вывод на одном
неверном глаголе.

## Полный прогон: связка трёх артефактов

Практический порядок такой. Начни с самого «дешёвого» источника — ShimCache: он быстро даёт
список путей. Отфильтруй интересные (не системные, из пользовательских каталогов). Для
каждого пути поищи запись в AmCache и выпиши хеш. Для подтверждения запуска поищи
соответствующий `.pf` в Prefetch. Если все три совпали, вывод прочный. Если AmCache есть, а
Prefetch нет — возможно, программу не запускали (или Prefetch очищен). Такой прогон занимает
минуты, но даёт трёхуровневое подтверждение вместо одной догадки.

## Что фиксировать в отчёте

Опиши источники (пути к hive), инструменты и их версии, найденные пути, хеши и времена.
Явно разведи «присутствие» и «запуск», укажи, какой артефакт что подтверждает. Если хеш
проверялся во внешней базе, приведи результат проверки и дату — базы меняются, и дата важна
для воспроизводимости вывода.
'''

ADD["win-amcache-deep"] = r'''
## Сквозной пример: от подозрительного пути к подтверждённому хешу

Разберём историю целиком. Дано: есть hive `Amcache.hve`, подозрение на запуск вредоносной
программы. Задача — получить путь, хеш и время, а затем связать с другими хостами.

Шаг первый — разбираем AmCache инструментом и находим запись с путём в пользовательском
каталоге, например `C:\Users\jdoe\AppData\Local\Temp\svchost.exe`. Обрати внимание на
маскировку: легитимный `svchost.exe` живёт в `System32`, а копия в `Temp` — классический
признак малвари. Шаг второй — выписываем SHA-1 и время последнего изменения. Шаг третий —
проверяем хеш в базе ВПО: детект подтверждает вредоносность. Шаг четвёртый — ищем тот же
хеш в списке IOC и в выгрузках с других хостов; совпадение означает распространение образца
по сети.

Итог: AmCache дал не просто «файл был», а **идентичность файла** (хеш), по которой можно
связать события на разных машинах и обосновать блокировку.

## Как отличить легитимную программу от маскировки

Путь — первый фильтр. Вредоносные образцы часто маскируются под системные имена в
нестандартных каталогах: `svchost.exe` в `Temp`, `lsass.exe` в `Downloads`, `explorer.exe` в
`Public`. AmCache даёт и путь, и хеш, поэтому подозрение проверяется объективно: сравни
хеш с эталонным для системного файла (в системе есть оригинал — можно посчитать его хеш).
Если хеши не совпадают, значит, под именем системного процесса работает чужой файл. Это
сильный и легко проверяемый вывод.

## Полный прогон: AmCache + ShimCache + Prefetch + SRUM

Собери четыре источника в одну картину. AmCache: путь и хеш. ShimCache: подтверждение
присутствия. Prefetch: подтверждение запуска и счётчик. SRUM: сетевая активность — например,
утилита много передавала наружу. Сложив их, ты отвечаешь сразу на четыре вопроса: что за
файл, был ли он на диске, запускался ли, и что он делал в сети. Именно такая полнота нужна
в отчёте по инциденту, где одного источника недостаточно.

## Что фиксировать в отчёте

Приведи путь к `Amcache.hve`, инструмент, найденный путь, SHA-1 и время. Укажи результат
проверки хеша в базе ВПО и дату проверки. Отдельно оговори ограничение: AmCache описывает
присутствие/установку, а факт запуска подтверждается Prefetch. Если хеш совпал с образцом из
threat-intel, приведи название семейства и источник — это связывает техническую находку с
контекстом угрозы.
'''

ADD["win-srum-deep"] = r'''
## Сквозной пример: выявление эксфильтрации через SRUM

Разберём инцидент целиком. Дано: подозрение на утечку данных, сетевые логи неполные. Задача —
по базе SRUM понять, какое приложение и сколько передало наружу.

Шаг первый — разбираем `SRUDB.dat` и выгружаем таблицу `NetworkUsages`. Шаг второй — через
`SruDbIdMapTable` связываем числовые `AppId` с именами процессов. Шаг третий — сортируем по
`BytesSent` за интересующий период. Видим аномалию: неизвестный процесс передал сотни
мегабайт, тогда как обычные приложения — килобайты. Шаг четвёртый — для подозрительного
процесса ищем подтверждения: Prefetch (запускался), AmCache (путь и хеш), журналы (вход
пользователя). Шаг пятый — сопоставляем с сетевыми логами, если они есть, чтобы узнать
назначение (адрес/домен).

Итог: SRUM дал **объём и направление** передачи по приложению, а связка с другими
артефактами — контекст: какая программа, кем запущена и когда. Это стандартный путь
расследования утечки, когда прокси-логи неполны.

## Агрегация по интервалам: как читать временные метки

SRUM хранит данные не по отдельным пакетам, а **агрегированно по интервалам** (обычно час).
Это значит, что ты не увидишь точное время каждого соединения — только «в этот интервал
приложение передало столько байт». Для расследования это нормально: цель SRUM — выявить
**факт и объём** передачи, а точное время уточняется по другим логам. Помни об этом, чтобы не
делать ложных выводов: всплеск в интервале не означает, что передача шла всю минуту — она
могла произойти за секунды внутри часа.

## Полный прогон: от байтов к атрибуции

Хороший разбор утечки строится так. Сначала SRUM: топ приложений по `BytesSent`. Затем для
подозрительного приложения — путь и хеш через AmCache и Prefetch. Затем пользователь,
от имени которого шла передача, — из `UserId` и журналов входа. Затем сетевые логи (прокси,
файрвол) — куда именно шла передача. В конце — вывод: какая программа, от чьего имени и куда
передала данные. Каждый шаг опирается на отдельный источник, и вместе они дают атрибуцию, а
не просто «была сетевая активность».

## Что фиксировать в отчёте

Укажи путь к `SRUDB.dat`, инструмент разбора, период данных, таблицу `NetworkUsages`, имена
процессов и объёмы (`BytesSent`/`BytesRecv`). Оговори агрегацию по интервалам и срок хранения
базы. Если удалось связать передачу с конкретным адресом, приведи и его, но с пометкой об
источнике. Так отчёт показывает и технический факт, и его ограничения.
'''

