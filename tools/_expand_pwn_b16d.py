EXTRA['pwn-windows-cfg-cet'] = r"""
## Частые вопросы

**CFG мешает любому ROP?** Нет. CFG проверяет **косвенные** вызовы/переходы.
ROP, построенный на `ret`, CFG не трогает — его ловит **CET/shadow stack**.
Поэтому важно понимать, какая именно защита включена.

**Можно ли обойти CFG перезаписью bitmap?** Теоретически да, но bitmap лежит в
памяти, доступной только для чтения (для обычного кода), и правка требует
примитива записи. На практике чаще используют valid-target reuse или data-only.

**CET уже везде включён?** Аппаратно — только на новых CPU, и поддержка зависит
от ОС и сборки. Проверяй флаг `CET_COMPAT` и поддержку процессора.

**Что выбрать при CFG+CET?** Data-only и COOP. Классический ROP на возврате
уступает место изменению данных, которые исполняет доверенный код.

"""

EXTRA['pwn-windows-driver'] = r"""
## Частые вопросы

**Обязательно ли писать свой драйвер?** Нет. Эксплуатируют уже установленный
уязвимый драйвер. Если своего нет — используют BYOVD: загружают подписанный, но
уязвимый драйвер.

**Почему METHOD_NEITHER так часто уязвим?** Потому что ядро не проверяет и не
копирует буфер: драйвер получает сырые указатели пользователя и должен сам
валидировать их. Ошибка в валидации = произвольная запись.

**Что если устройство требует прав администратора?** Тогда нужен хотя бы
ограниченный доступ; некоторые драйверы дают `FILE_ANY_ACCESS` и открываются
обычным пользователем — это и делает их опасными.

**Как не уронить систему?** Пиши только в проверенные цели (токен), не трогай
критичные структуры, следи за PatchGuard, тестируй на снапшоте.

"""

EXTRA['pwn-windows-pool'] = r"""
## Частые вопросы

**Чем kernel pool отличается от userland heap?** Идея похожа (аллокатор,
заголовки, регионы), но ошибка роняет **всю систему**, а митигации
(PatchGuard, Segment Heap) строже.

**Зачем вообще тег пула?** Тег говорит, **кто** аллоцировал блок. Это помогает
подобрать жертву: зная тег соседа, понимаешь, какой объект там лежит и какие
поля можно перезаписать.

**Что такое Big Pool?** Аллокации крупнее страницы, обслуживаемые иначе. Их
раскладка отличается от мелких блоков, поэтому техники grooming для них другие.

**Почему grooming обязателен?** Без него уязвимый блок и жертва окажутся в
разных местах, и переполнение уйдёт «в пустоту». Grooming делает раскладку
предсказуемой.

"""

EXTRA['pwn-windows-token-stealing'] = r"""
## Частые вопросы

**Достаточно ли подменить токен, чтобы получить ring 0?** Нет — ты получаешь
права **SYSTEM** в userland. Для ring 0 из SYSTEM можно загрузить драйвер или
использовать другой примитив. Но для большинства задач SYSTEM достаточно.

**Почему не перехватить код ядра вместо токена?** Перехват ловят PatchGuard и
HVCI: правка SSDT/callback/кода ведёт к BSOD. Подмена токена — data-only и
стабильна.

**Как узнать смещение Token?** Из символов `ntoskrnl.exe` целевой сборки
(WinDbg, публичные карты смещений). Смещения меняются между сборками.

**Работает ли это при Credential Guard?** Да: token stealing не зависит от
защиты учётных данных, он меняет токен процесса напрямую.

**Что если нет примитива чтения?** Иногда токен находят по фиксированному
смещению от утечки или через `ActiveProcessLinks`, если известна база ядра.

"""

EXTRA['pwn-windows-iop'] = r"""
## Частые вопросы

**IoRing — это уязвимость?** Нет, это **механизм**. Уязвимости могут быть в его
реализации или в драйверах, использующих ring. Для эксплойта ring ценен как
источник примитивов и доступа к структурам.

**Почему недокументированные API вообще существуют?** Их используют внутренние
компоненты Windows; они не входят в публичный контракт и могут меняться.
Для эксплойт-разработчика это и хорошо (слабые проверки), и плохо
(версионность).

**Как выбрать между ring и обычным API?** Обычный API проще и стабильнее, но
проверяется строже. Ring/недокументированные API дают больше свободы ценой
нестабильности. Выбор — по задаче.

**Что важнее для отчётности — примитив или стабильность?** Стабильность. В
kernelCTF и bug bounty нестабильный эксплойт, роняющий хост, не засчитывают.

"""

EXTRA['pwn-hyperv-escape'] = r"""
## Частые вопросы

**Можно ли атаковать гипервизор из гостя?** Да, через интерфейсы, которые хост
обязан обрабатывать: VMBus, синтетические устройства, интеграционные сервисы.
Это и есть поверхность VM-escape.

**Почему так мало публичных эксплойтов?** Сложность отладки, узкая поверхность,
специфичность сборок и высокая ценность находок (bug bounty). Многие баги
остаются DoS, а не полноценным escape.

**С чего начать исследование?** С инвентаризации интерфейсов, доступных гостю,
и с разбора формата сообщений VMBus. Затем — аудит/фаззинг хост-парсеров.

**Чем VM-escape отличается от kernel-эксплойта?** Границей: в kernel-эксплойте
цель — своя ОС, в VM-escape — **гипервизор и другие ВМ**. Уровень риска
принципиально выше.

"""

EXTRA['pwn-vbs-hvci'] = r"""
## Частые вопросы

**VBS и HVCI — это одно и то же?** Нет. VBS — общий механизм изоляции через
гипервизор; HVCI — одна из его функций (целостность кода ядра). Вместе они
защищают и код, и (через Credential Guard) учётные данные.

**Можно ли вообще обойти HVCI?** Напрямую исполнить неподписанный код — нет.
Но обходят **не HVCI, а его предположения**: используют подписанные уязвимые
драйверы (BYOVD) и data-only примитивы.

**Почему data-only работает при HVCI?** HVCI защищает **код**, а не **данные**.
Меняя данные (токен, флаги), которые исполняет доверенный код, мы не нарушаем
целостность кода.

**Включён ли VBS на моей цели?** Проверь `Win32_DeviceGuard` и реестр
`DeviceGuard`. На новых Windows и в облаке — обычно да.

**Что делать с Credential Guard?** Пересмотреть тактику: вместо дампа LSASS
использовать существующие сессии, делегирование и DPAPI-материалы.

"""


def main():
    for lid, extra in EXTRA.items():
        path = os.path.join(PWNDIR, lid + '.md')
        with open(path, encoding='utf-8') as f:
            txt = f.read()
        if SENT in txt:
            print('SKIP (already):', lid)
            continue
        if MARKER not in txt:
            print('SKIP (no marker):', lid)
            continue
        txt = txt.replace(MARKER, extra.strip() + '\n\n' + SENT + '\n\n' + MARKER, 1)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(txt)
        print('expanded:', lid)


if __name__ == '__main__':
    main()
