EXTRA['pwn-windows-aslr-bypass'] = r"""
## Совмещение утечки и частичной перезаписи

На практике техники комбинируют. Сначала добывают **любую** утечку, чтобы узнать
базу, а затем используют **частичную перезапись** для точечного изменения
указателя без полного знания адреса. Это даёт устойчивость: даже если утечка
нестабильна, частичная перезапись младших байт сработает, потому что старшие
байты известны из базы.

Порядок: утечка → база → вычисление целевого адреса → перезапись нужного
числа младших байт. Такой подход переносим между запусками и не зависит от
точного значения слайда, если он затрагивает только старшие байты.

Ещё один приём — **двухэтапная утечка**: сначала утекает указатель на структуру
с указателями (например, vtable или список модулей), затем по нему читается
адрес нужной функции. Это позволяет строить цепочки, где один баг даёт
«многоступенчатый» доступ к адресам.

"""

EXTRA['pwn-windows-cfg-cet'] = r"""
## XFG и типы функций

XFG (eXtended Flow Guard) добавляет к проверке CFG **хэш типа** вызываемой
функции. Компилятор помечает каждую функцию её сигнатурой, и косвенный вызов
разрешён, только если хэш типа совпадает. Это закрывает трюк «вызвать другую
функцию с той же сигнатурой»: мало быть в bitmap, нужно ещё совпасть по типу.

Практическое следствие: при XFG список «полезных» целей резко сужается. Часто
приходится искать **ровно тот** класс/метод с нужным типом, что делает
valid-target reuse намного сложнее. Поэтому при XFG чаще уходят в **data-only**
и **COOP**, где код не подменяется вовсе.

Стоит проверять наличие XFG-сигнатур (`__guard_xfg_*`) и флага в PE: включённый
XFG меняет всю стратегию эксплойта и должен быть выявлен **до** сборки цепочки.

"""

EXTRA['pwn-windows-driver'] = r"""
## IOCTL-практика: буферы и длины

При работе с драйвером важно передать буфер **правильного размера** и **типа**.
Для `METHOD_BUFFERED` ядро само копирует данные, и длины проверяются. Для
`METHOD_NEITHER` драйвер получает сырые указатели, и если он не вызывает
`ProbeForRead`/`ProbeForWrite`, можно передать любой адрес — включая адрес ядра.

Частая ошибка — неверная длина входного буфера: драйвер прочитает больше, чем
мы передали, и получит мусор (или упадёт). Поэтому сначала сверяют ожидаемый
размер структуры с тем, что принимает обработчик (по дизассемблеру видно,
сколько байт копируется и по каким смещениям).

Ещё нюанс — **права доступа** к устройству. Некоторые драйверы требуют
`GENERIC_WRITE` или определённый `FILE_*_ACCESS`; без него `CreateFile` вернёт
отказ, хотя устройство существует. Проверяй это до построения эксплойта.

"""

EXTRA['pwn-windows-pool'] = r"""
## Проверка раскладки в отладчике

Перед финальным запуском убедись, что раскладка такая, как задумано. В WinDbg
посмотри, что лежит рядом с уязвимым блоком:

```
kd> !pool <адрес_уязвимого_блока>
kd> !pool <адрес_жертвы>
```

Если между ними «мусор» или блоки из разных субаллокаторов — grooming не
сработал, и переполнение не попадёт в поля жертвы. Итеративно подбирай число и
порядок аллокаций, пока `!pool` не покажет нужное соседство.

Полезно также смотреть `!poolused`, чтобы понять, какие теги доминируют в
регионе: это подсказывает, какие объекты доступны для заполнения. Так
эксплойт становится **предсказуемым**, а не «иногда работающим».

"""

EXTRA['pwn-windows-token-stealing'] = r"""
## Как работает проверка прав

Когда процесс обращается к объекту (файлу, ключу реестра, процессу), ядро
вызывает подсистему безопасности (`SeAccessCheck`), которая сравнивает
**access token** процесса с **security descriptor** объекта. Токен содержит
SID пользователя, группы и привилегии. Если токен — SYSTEM (`S-1-5-18`), все
проверки проходят.

Именно поэтому подмена токена так эффективна: мы не обходим проверки — мы
**становимся** тем, кому всё разрешено. Никакие права не «взламываются», просто
у процесса теперь правильная личность.

## Разница между userland и kernel привилегиями

Важно понимать, что token stealing даёт **не** ring 0 сам по себе, а
**привилегии** в userland-контексте (SYSTEM). Для большинства задач (чтение
`SAM`, загрузка драйверов, доступ к защищённым объектам) этого достаточно.
Если же нужен именно ring 0, уже из SYSTEM можно загрузить драйвер или
использовать другой примитив.

Связка «произвольная запись в ядро → token stealing» — стандартный финал
Windows kernel-эксплойта, потому что превращает примитив памяти в конкретные
права.

## Почему это надёжнее, чем перехват кода

Перехват потока управления в ядре ловят PatchGuard и HVCI: правка SSDT,
callback-таблиц или кода ядра приводит к BSOD или отказу. Подмена токена —
**data-only** и не трогает защищённые структуры, поэтому стабильна и
безопасна для хоста. Это ключевое преимущество для отчётности и bug bounty.

"""

EXTRA['pwn-windows-iop'] = r"""
## Зачем ring нужен ядру

I/O ring снижает **накладные расходы** на системные вызовы: вместо перехода
user↔kernel на каждую операцию приложение пишет запросы в общую очередь, а ядро
обрабатывает их пакетно. Для высоконагруженных серверов это ускорение.

Но «общая память» — это и **поверхность атаки**. Часть структур видна обеим
сторонам, и неверная синхронизация/проверка открывает примитивы. Именно поэтому
ring используют в эксплойтах: он даёт доступ к внутренностям ядра через
полулегальный интерфейс.

## Сравнение с io_uring

| Аспект | Windows IoRing | Linux io_uring |
|---|---|---|
| Очереди | SQ/CQ в общей памяти | SQ/CQ + mmap |
| Регистрация | файлы, буферы | файлы, буферы, флаги |
| Статус | недокументирован | частично документирован |
| Эксплуатация | data-only, доступ к структурам | частые CVE (гонки/UAF) |

Оба механизма ценны для исследователя: Linux io_uring дал серию CVE, Windows
IoRing — недокументированные примитивы. Понимание одного помогает в другом.

## Вывод

Недокументированные механизмы вроде I/O ring — «серая зона» между API и
внутренностями ядра. Они дают сильные примитивы, но требуют аккуратности:
версионность, стабильность и митигации (HVCI/PatchGuard) диктуют, как их
применять.

"""

EXTRA['pwn-hyperv-escape'] = r"""
## Синтетические устройства

Гость Hyper-V «видит» не физические, а **синтетические** устройства: сетевой
адаптер, контроллер хранилища, видео, шину интеграции. За каждым стоит пара
VSC (в госте) / VSP (в хосте), общающаяся через VMBus. Поскольку запросы идут
от недоверенного гостя, **весь парсинг на хост-стороне** — потенциальная
поверхность атаки.

Наиболее «богаты» на баги сетевой стек (`vmswitch`), хранилище (`storvsp`) и
шина интеграции: они принимают сложные структуры с длинами и индексами, где
легко ошибиться в проверках.

## Сложность триажа

VM-escape-баг сложно **подтвердить**:

- сбой роняет **весь хост**, а не процесс;
- воспроизведение требует стабильного стенда;
- отладка гипервизора специфична;
- цепочка до контроля хоста длинная.

Поэтому найденный баг часто «застревает» на стадии DoS, а полноценный escape —
редкость. Тем ценнее каждый подтверждённый случай для облачной безопасности.

## Почему это высшая категория

Компрометация гипервизора ломает **фундаментальную границу** между
арендаторами: один гость получает доступ к другим ВМ и хосту. Для облачных
провайдеров это максимальный риск, поэтому VM-escape входит в топ программ
bug bounty с самыми высокими выплатами.

"""

EXTRA['pwn-vbs-hvci'] = r"""
## Почему VBS включён по умолчанию

На новых Windows (и в облаке) VBS/HVCI включаются **по умолчанию**: Microsoft
считает, что изоляция критичных компонентов гипервизором стоит небольшой потери
производительности. Это значит, что современный эксплойт-разработчик почти
всегда имеет дело с VBS и должен планировать **data-only** цепочку с самого
начала, а не как «запасной вариант».

Дополнительно VBS защищает учётные данные (Credential Guard), ломая классические
приёмы кражи хэшей. Red team вынужден переходить на использование существующих
сессий и делегирования вместо дампа LSASS.

## Практический вывод

Если на цели включены VBS/HVCI:

1. **Не планируй shellcode** в ядре — его не будет.
2. **Ищи data-only** цель (токен, флаги, указатели на подписанные функции).
3. **Рассмотри BYOVD** как быстрый путь к примитиву записи.
4. **Проверь Credential Guard** и пересмотри тактику сбора учётных данных.
5. **Проверяй конфиг** на каждом стенде: без VBS эксплойт может вести себя
   иначе.

VBS/HVCI — не «непреодолимая стена», а **смена парадигмы**: эксплуатируют
данные, которые исполняет доверенный код, а не сам код.

"""


def main():
    for lid, extra in EXTRA.items():
        path = os.path.join(PWNDIR, lid + '.md')
        with open(path, encoding='utf-8') as f:
            txt = f.read()
        if SENT in txt:
            print('SKIP (already):', lid)
            continue
        if MARKER not in txt:
            print('SKIP (no marker):', lid)
            continue
        txt = txt.replace(MARKER, extra.strip() + '\n\n' + SENT + '\n\n' + MARKER, 1)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(txt)
        print('expanded:', lid)


if __name__ == '__main__':
    main()
