# --- Vigenere breaker -------------------------------------------------------
def vigenere_enc(pt, key):
    pt = ''.join(c for c in pt.upper() if c.isalpha())
    key = key.upper()
    return ''.join(AL[(ord(pt[i]) - 65 + ord(key[i % len(key)]) - 65) % 26]
                   for i in range(len(pt)))


def ic(text):
    n = len(text)
    if n < 2:
        return 0.0
    return sum(text.count(c) * (text.count(c) - 1) for c in set(text)) / (n * (n - 1))


def best_shift(col):
    best, bk = -1, 0
    for k in range(26):
        s = sum(ENG[(ord(c) - 65 - k) % 26] for c in col)
        if s > best:
            best, bk = s, k
    return bk


def vigenere_break(ct):
    n = len(ct)
    best_len, best_ic = 1, -1
    # smallest length whose columns look like natural language (IC > 0.055);
    # multiples of the true key length also score high, so take the smallest.
    chosen = None
    for L in range(2, 14):
        cols = [ct[i::L] for i in range(L)]
        avg = sum(ic(c) for c in cols) / L
        if avg > best_ic:
            best_ic, best_len = avg, L
        if avg > 0.055 and chosen is None:
            chosen = L
    L = chosen if chosen else best_len
    key = ''.join(AL[best_shift(ct[i::L])] for i in range(L))
    pt = ''.join(AL[(ord(ct[i]) - ord(key[i % L])) % 26] for i in range(n))
    return L, key, pt


# --- Solitaire (Pontifex) ---------------------------------------------------
def solitaire_step(deck):
    d = deck[:]
    i = d.index(53); d.pop(i); d.insert((i + 1) % (len(d) + 1), 53)
    i = d.index(54); d.pop(i); d.insert((i + 2) % (len(d) + 1), 54)
    a, b = d.index(53), d.index(54)
    if a > b:
        a, b = b, a
    d = d[b + 1:] + d[a:b + 1] + d[:a]
    last = d[-1]
    v = 53 if last == 54 else last
    d = d[v:-1] + d[:v] + d[-1:]
    top = d[0]
    out = 53 if top == 54 else top
    return d, d[out]


def solitaire_keystream(deck, n):
    d = deck[:]
    ks = []
    for _ in range(n):
        d, v = solitaire_step(d)
        ks.append((v - 1) % 26)
    return ks


def solitaire_encrypt(pt, deck):
    pt = ''.join(c for c in pt.upper() if c.isalpha())
    ks = solitaire_keystream(deck, len(pt))
    return ''.join(AL[(ord(pt[i]) - 65 + ks[i]) % 26] for i in range(len(pt)))


# --- Enigma I (simplified: 3 rotors, reflector B, no plugboard) -------------
ROTORS = {
    'I': ('EKMFLGDQVZNTOWYHXUSPAIBRCJ', 16),
    'II': ('AJDKSIRUXBLHWTMCQGZNPYFVOE', 4),
    'III': ('BDFHJLCPRTXVZNYEIWGAKMUSQO', 21),
}
REFL = 'YRUHQSLDPXNGOKMIEBFZCWVJAT'


def enigma(text, order, pos, rings=(0, 0, 0)):
    text = ''.join(c for c in text.upper() if c.isalpha())
    wires = [ROTORS[r][0] for r in order]
    notches = [ROTORS[r][1] for r in order]
    p = list(pos)
    out = []
    for ch in text:
        # step (odometer + double step)
        if p[2] == notches[2]:
            if p[1] == notches[1]:
                p[0] = (p[0] + 1) % 26
            p[1] = (p[1] + 1) % 26
        p[2] = (p[2] + 1) % 26
        c = ord(ch) - 65
        # forward right->left
        for idx in (2, 1, 0):
            w = [ord(x) - 65 for x in wires[idx]]
            o = (c + p[idx] - rings[idx]) % 26
            c = (w[o] - p[idx] + rings[idx]) % 26
        c = ord(REFL[c]) - 65
        # backward left->right
        for idx in (0, 1, 2):
            w = [ord(x) - 65 for x in wires[idx]]
            o = (c + p[idx] - rings[idx]) % 26
            c = (w.index(o) - p[idx] + rings[idx]) % 26
        out.append(chr(c + 65))
    return ''.join(out)


