import os

ROOT = '/home/Serebr1k/learning_tree'


def insert_before_quiz(path, extra):
    with open(path, encoding='utf-8') as f:
        t = f.read()
    marker = '\n## Квиз'
    i = t.find(marker)
    if i == -1:
        raise SystemExit('no quiz in ' + path)
    t = t[:i] + '\n' + extra.strip() + '\n' + t[i:]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(t)


B = {}

B['mobile-sanitizers'] = '''
И отдельно про дисциплину: фиксируйте в отчёте, с какими флагами собрана библиотека и какая
версия компилятора использовалась. Отчёт санитайзера без этих данных сложно воспроизвести, а
значит и исправить.
'''

B['mobile-afl-native'] = '''
Ещё одна деталь: AFL умеет сохранять не только падения, но и «зависания» (hangs) — входы, на
которых программа не завершается за таймаут. Их тоже стоит проверять: зависание часто
означает бесконечный цикл, а это отказ в обслуживании.
'''

B['mobile-valgrind'] = '''
И наконец, не путайте два вопроса: «есть ли утечка» и «опасна ли она». Утечка нескольких
байт в редком пути — это низкий риск, утечка буфера на каждый запрос — высокий. Оценивайте
влияние, а не только факт.
'''

B['mobile-android-nnapi'] = '''
Ещё стоит проверить, не логируется ли содержимое модели при включённом отладчике: иногда
разработчики оставляют подробные логи, и они попадают в общий системный журнал. Это утечка
данных, о которой легко забыть.
'''

B['mobile-android-onnx'] = '''
И ещё практическая мелочь: если приложение использует несколько моделей, проверьте каждую.
Разработчики часто защищают основную модель и забывают про вспомогательную, а она тоже может
содержать чувствительные данные или кастомные операторы.
'''

B['mobile-android-tflite'] = '''
И последнее: если в модели есть кастомные операции, посмотрите, где именно лежит их код.
Если это отдельная библиотека внутри APK — её можно проанализировать отдельно; если она
загружается извне — это потенциальная точка подмены и отдельная находка.
'''

for lid, extra in B.items():
    insert_before_quiz(os.path.join(ROOT, 'content/mobile', lid + '.md'), extra)
print('OK ninth expansion')
