ADDS["tool-bulk-extractor"] = """## Как устроен движок: сканеры и feature-файлы

Bulk Extractor — это не один анализатор, а конвейер независимых **сканеров**, каждый из
которых ищет свой класс структур. Основные сканеры и то, что они дают:

| Сканер | Что извлекает | Файл вывода |
|---|---|---|
| `email` | адреса вида `user@host` | `email.txt` |
| `url` | URL, `http(s)://`, `ftp://` | `url.txt` |
| `domain` | доменные имена (FQDN) | `domain.txt` |
| `net` | IPv4-адреса и MAC | `ip.txt` |
| `telephone` | номера телефонов | `telephone.txt` |
| `ccn` | номера кредитных карт (Luhn) | `ccn.txt` |
| `exif` | EXIF-поля JPEG/TIFF | `exif.txt` |
| `rfc822` | заголовки писем, границы сообщений | `rfc822.txt` |
| `wordlist` | слова по заданному словарю | `wordlist.txt` |
| `zip` | локальные заголовки ZIP | `zip.txt` |

Каждый сканер пишет свой **feature-файл** — построчный список найденного. Формат строки
универсален: `<offset>\t<feature>\t<context>`. Первое поле — смещение в байтах от начала
потока, второе — само значение, третье — необязательный контекст (например, имя файла или
родительская структура). Именно offset позволяет вернуться к месту находки и понять
контекст.

## Практический разбор: домен C2 в образе

Допустим, в задаче нужно найти домен, куда «звонил» вредонос. Быстрый путь:

```
$ bulk_extractor -o out -e domain,url /evidence/disk.img
$ cat out/domain.txt | head
178392145\tev1l-c2.example\t<domain>
182004912\tsync.example.org\t<domain>
```

Затем фильтруем подозрительные и сверяем со стоп-листом популярных доменов:

```
$ cut -f2 out/domain.txt | sort -u | grep -viE 'windows|microsoft|gstatic' | head
ev1l-c2.example
```

Дальше берём offset и вырезаем контекст вокруг находки:

```
$ dd if=/evidence/disk.img bs=1 skip=$((178392145-64)) count=256 2>/dev/null | strings
```

Так в одном окне видно и домен, и URL запроса, и, возможно, HTTP-заголовок `Host`.

## Работа с feature-файлами повторно

Сканирование 2-ТБ образа занимает часы, но результат (`out/`) можно переиспользовать:

```
$ bulk_extractor -f out -o out2 /evidence/disk.img   # быстрый повтор по фичам
$ bulk_extractor -R -o out -e wordlist:custom.txt /evidence/disk.img
```

Ключ `-R` добавляет сканер к уже существующему набору, не пересканируя всё заново, а `-f`
вообще позволяет собрать вывод без повторного прогона тяжёлых сканеров. Это критично,
когда нужно быстро добавить новый словарь.

## Словари, стоп-листы и контекст

- `-w custom.txt` — свой словарь для сканера `wordlist` (поиск паролей, имён проектов);
- `-s stop.txt` — стоп-лист, чтобы не засорять вывод системными строками;
- `-E ccn:12` — включить конкретный сканер с параметром (для `ccn` — порог длины);
- `-S scan_name` — повторно запустить один сканер;
- `-C` — отключить запись контекста (экономит место на огромных образах).

Стоп-лист почти всегда нужен: без него `domain.txt` заполнится сотнями доменов из
системных библиотек, и настоящий индикатор утонет в шуме.

## Извлечение из памяти и сетевых дампов

Bulk Extractor одинаково хорошо работает не только с дисками, но и с другими потоками:

```
$ bulk_extractor -o mem_out /evidence/memory.raw        # дамп RAM
$ bulk_extractor -o pcap_out /evidence/capture.pcap     # сетевой дамп
```

В дампе памяти он находит URL, ключи и артефакты из кэшей браузеров, которых уже нет на
диске. В pcap — заголовки HTTP, `Host`, пользовательские агенты, домены, даже если
содержимое TLS не читается. Это делает его универсальным первым шагом триажа.

## Ограничения и типичные ошибки

- **Нет файловой системы.** Инструмент не понимает ФС, поэтому не скажет, какому файлу
  принадлежит находка, — только offset. Имя файла появляется лишь там, где сканер
  встретил структуру, где оно рядом (например, в ZIP-заголовке).
- **Пропуск при сжатии/шифровании.** Данные внутри архива, зашифрованного тома или
  сжатого потока не видны, пока их не распакуешь.
- **Ложные срабатывания.** `domain.txt` ловит и мусор; `ccn.txt` иногда даёт случайные
  числа, прошедшие Luhn. Всегда подтверждай контекстом.
- **Не заменяет экспертизу ФС.** Для привязки к файлам и удалённым записям нужны
  `sleuthkit`/`Autopsy`, а не Bulk Extractor.

## Если сработало / не сработало

Если сканер молчит, проверь, что он включён (`-e` без него отключает лишнее), и что ты
сканируешь нужный поток. Если находок слишком много — добавь стоп-лист и словарь. Если
нужен контекст — используй offset с `dd`/`strings`. Если данные сжаты — сначала распакуй
контейнер."""

ADDS["spec-dvr-camera"] = """## Внутреннее устройство NVR: чанки и индекс

Большинство сетевых регистраторов (NVR) пишут видео не как «файлы по дням», а как поток
**чанков** (сегментов) фиксированной длительности — обычно 30–60 минут. Каждый чанк
получает запись в индексной базе, где указаны: время начала и конца, камера, тип события
(непрерывная запись, движение, тревога) и физическое расположение чанка на диске. Именно
поэтому для расследования индекс важнее самого видео: даже если чанк перезаписан, строка в
индексе может сохранить **время и факт** события.

Типичная структура на диске:

```
$ ls /mnt/nvr/
  ├─ index/        # БД сегментов (часто SQLite или проприетарная)
  ├─ data/         # сами чанки (raw H.264/H.265 или контейнеры)
  ├─ log/          # журнал событий и тревог
  └─ snapshot/     # кадры-превью по событиям
```

## Вендорные форматы: что монтируется, а что нет

| Вендор | Формат на диске | Чем снять |
|---|---|---|
| Hikvision | проприетарный, чанки + индекс | iVMS-4200, `binwalk`, карвинг |
| Dahua | `.dav` контейнеры | Smart Player, конвертер `.dav`→`.mp4` |
| Xiongmai (XM) | «.h264» в каталогах по дням | прямая конкатенация + `ffmpeg` |
| Китайские OEM | часто ext4/xfs | монтирование только для чтения |
| Axis | open-стандарт, RTSP/ONVIF | штатный экспорт |

Для Dahua `.dav` — это контейнер с заголовками, поэтому простое переименование в `.mp4`
не работает; нужен `dahua-dav-converter` или `Smart Player`. Для Xiongmai сырые `.h264`
файлы склеиваются в один поток.

## Работа с индексной базой

Если индекс — SQLite, его можно прочитать напрямую:

```
$ file index/*.db
index/record.db: SQLite 3.x database
$ sqlite3 index/record.db '.tables'
records  events  cameras
$ sqlite3 index/record.db 'SELECT start,end,camera,status FROM records ORDER BY start DESC LIMIT 5;'
```

Поле `status` часто содержит `deleted` для перезаписанных интервалов — это и есть
«удалённые» записи, которые нужны в расследовании. Для проприетарных БД используй
`strings` + `grep` по времени или вендорную утилиту.

## Практический разбор CTF

В задачах на DVR обычно дан либо образ диска, либо выгрузка индекса. Порядок действий:

```
$ binwalk -e dvr.img                     # вытащить вложенные структуры
$ grep -a 'deleted' index_dump.txt       # найти удалённые интервалы
$ foremost -t mp4,h264 -i dvr.img -o carved/   # карвинг видео
$ ffprobe carved/*.h264                  # проверить, что поток валиден
```

Если в задаче спрятан флаг, он часто в метаданных кадра (`snapshot`) или в поле
`camera name` индексной БД, а не в самом видео.

## Часовые пояса и дрейф времени

Самая частая ошибка — принять время камеры за истину. Камеры:

- хранят время в локальном поясе без зоны;
- дрейфуют, если нет NTP;
- сбрасываются при потере питания на «эпоху»;
- показывают разное время в разных интерфейсах (web vs. OSD).

Всегда сверяй время камеры с независимым событием: срабатыванием датчика, логом
мобильного телефона рядом, сетевым трафиком NVR. Сдвиг в час — это почти наверняка
переход на летнее время или неверная зона, а не подделка.

## Извлечение из IP-камеры (а не с диска)

Если запись велась на карту SD внутри камеры, а не на NVR:

```
$ rtsp://admin:pass@10.0.0.9:554/Streaming/Channels/101   # живой поток
$ curl -s 'http://10.0.0.9/ISAPI/ContentMgmt/record/...'  # Hikvision ISAPI
```

Прошивку и список учётных записей достают через ONVIF или веб-интерфейс. Часто именно в
конфиге камеры (а не в видео) лежат учётные данные к другим системам.

## Ограничения

- Проприетарная ФС без документации — нужна вендорная утилита.
- Шифрование диска (некоторые модели) — нужен ключ устройства.
- Циклическая перезапись затирает старые чанки физически — восстановишь не всё.
- Время не верифицировано — таймлайн может «съехать» на часы.

## Если сработало / не сработало

Если карвинг даёт битые потоки — добавь `-t h264,h265` и проверь выравнивание по
стартовым кодам (`00 00 00 01`). Если индекс не читается — используй вендорную утилиту
или `strings`. Если видео пустое — проверь, не включено ли шифрование на устройстве."""

ADDS["af-detection-methodology"] = """## Строим эталон: какие артефакты ДОЛЖНЫ быть

Обнаружение анти-форензики — это сравнение с ожидаемым. Поэтому первый шаг — построить
**эталонный профиль** (baseline) системы: набор артефактов, которые обязаны существовать
на исправной машине за тот же период. Источники эталона:

- другая машина той же сборки ОС (лучший вариант);
- официальная документация по журналам и их ротации;
- «здоровый» образ той же версии ОС из лаборатории;
- сравнение нескольких пользовательских профилей на одном хосте.

Чем конкретнее эталон, тем точнее ловится аномалия. Например, на Windows Server всегда
есть `Security.evtx` с записями 4624/4634; их отсутствие за рабочий период — аномалия.

## Расхождения между источниками: где искать

Ключевой приём — сопоставление **независимых** источников, которые описывают одни и те
же события. Если один молчит, а другие активны — его подчистили.

| Событие | Источник A | Источник B | Источник C |
|---|---|---|---|
| Запуск программы | Prefetch | UserAssist (реестр) | Amcache |
| Создание файла | MFT (`$MFT`) | `$UsnJrnl` | журнал событий |
| Вход в систему | Security.evtx | SAM/LOGON | профиль NTUSER |
| Обращение к файлу | `$LogFile` | `$UsnJrnl` | LNK-файлы |
| Сетевые соединения | `SRUM` | журнал DNS | pcap |

Атака обычно чистит один-два источника и забывает про остальные. Именно «забытые»
источники и выдают подчистку.

## Следы конкретных инструментов очистки

Утилиты анти-форензики сами оставляют артефакты:

```
$ grep -ai 'ccleaner\\|sdelete\\|eraser' /evidence/MFT_dump.txt
$ grep -ai 'wevtutil' /evidence/Prefetch/*.txt
```

- **CCleaner / BleachBit** — записи о запуске, пути установки, `.lnk` в недавних;
- **sdelete** (`-z` / `-p`) — аномальные шаблоны записи, «пустые» сектора с `0x00`;
- **wevtutil cl** — обрыв журнала + отсутствие записи о завершении сессии;
- **timestomper** — расхождение `$STANDARD_INFORMATION` и `$FILE_NAME` на NTFS.

На Linux аналогично: `shred`, `dd if=/dev/zero`, `journalctl --vacuum-time`, ручная
правка `utmp`/`wtmp` (`last`, `lastlog`) — всё оставляет следы в `syslog`, `auditd`,
`bash_history` и в ctime самих файлов журналов.

## Практический разбор: «слишком чистая» система

Сценарий: инцидент зафиксирован в 03:00, но `auth.log` пуст, а `wtmp` за ту ночь
отсутствует. Проверяем:

```
$ stat /var/log/auth.log /var/log/wtmp
Modify: 2026-01-14 03:02   <-- момент очистки
$ ls -la /var/log/auth.log.1
-rw-r--r-- 1 root root 0 Jan 14 03:02 /var/log/auth.log.1
```

Нулевой размер ротации + свежий mtime = ручная очистка. Дальше ищем, чем чистили:

```
$ grep -aiE 'rm .*log|truncate|shred|: > ' /root/.bash_history /home/*/.bash_history
$ ausearch -ts recent -m 'execve' | grep -iE 'rm|shred|truncate'
```

Совпадение времени правки журнала с моментом сессии — сильная корреляция.

## Ложные срабатывания — не спеши с выводом

Аномалия ≠ атака. Регулярные причины «пропажи» артефактов:

- штатная ротация и `logrotate` (журнал ушёл в `.gz`);
- обновление ОС, которое пересоздаёт журналы;
- сбой питания — обрыв записи;
- антивирус/EDR, удаляющий «подозрительные» файлы сам;
- пользователь, удаливший профиль.

Поэтому вывод строится на **совокупности**: несколько независимых аномалий, совпадение по
времени и следы конкретных инструментов. Одна пропавшая запись — не приговор.

## Документирование находок

Каждую аномалию фиксируй по схеме «ожидалось / обнаружено / чем подтверждается /
альтернативное объяснение». Это защищает от ошибки и делает вывод воспроизводимым:
эксперт, читающий отчёт, должен сам убедиться, что «недостача» — не результат ротации.
Хэшируй артефакты до анализа и веди цепочку хранения (chain of custody).

## Ограничения методологии

- Нет эталона — сравнение субъективно; используй максимум внешних источников.
- Артефакт может отсутствовать по легитимной причине — проверяй альтернативы.
- Некоторые rootkits скрывают и сами расхождения — тогда нужен низкоуровневый анализ ФС
  и памяти, а не только «поверхностные» артефакты."""

