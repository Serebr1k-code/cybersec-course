#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Fourth top-up pass for reversing b15 gap lessons (target >=1200 real words)."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content', 'reversing')
MARK = '<!-- b15-deep4 -->'

ADD = {}

ADD['reversing-android-smali-dex-edit'] = """
## Что делать, если правка не помогает

Бывает, что приложение всё равно детектит модификацию. Причины: несколько независимых проверок,
проверка целостности DEX, нативная проверка, отложенный детект. Тогда действуй системно: найди
все проверки (grep по строкам и вызовам), отключи их по очереди, проверяя эффект. Не
останавливайся на первой найденной — их обычно больше одной. Веди список: что нашёл, где, чем
обошёл. Это экономит время при повторных сборках.
"""

ADD['reversing-android-dynamic-instrumentation'] = """
## Как писать надёжные хуки

Хук должен быть устойчивым: не падать при неожиданных типах, не блокировать поток, корректно
вызывать оригинал. Используй `try/catch` внутри реализации, проверяй аргументы на null, а для
перегруженных методов указывай `overload`. Если хук нужен только для наблюдения, не меняй
возврат — логируй и вызывай оригинал. Если меняешь — убедись, что подменённый тип совпадает с
ожидаемым, иначе приложение упадёт с `ClassCastException`. Эти мелочи отличают рабочий
инструмент от одноразового скрипта.
"""

ADD['reversing-android-native-symbols'] = """
## Итоговая стратегия

Порядок действий для обрезанного `.so`: сначала `nm -D` и `strings` (часто хватает), затем
поиск `RegisterNatives` и разбор таблицы, затем восстановление helper-функций по строкам и
кросс-ссылкам, и наконец — динамика через Frida. Держи в голове, что JNI-имена и сигнатуры
часто переживают strip, поэтому начинай именно с них. А anti-hook проверяй всегда — иначе хук
«не сработает» там, где приложение его уже обнаружило.
"""

ADD['reversing-oat-art'] = """
## Что делать, если APK утерян

Если у тебя только артефакты с устройства (`base.vdex`, `base.oat`, `base.art`), порядок такой:
извлеки DEX из vdex, деквикни его, открой в jadx. Машинный код в oat анализируй отдельно, если
нужны оптимизированные версии методов. Профиль подскажет, какие методы важны. Этот набор
инструментов (`vdexExtractor`, `oatdump`, `jadx`) покрывает большинство задач мобильной
форензики, когда исходный APK недоступен.
"""

ADD['reversing-apk-structure'] = """
## Итоговый порядок анализа

Инвентаризация APK — это не «подготовка», а самостоятельный этап, дающий находки. Начни с
`unzip -l`, затем манифест (`aapt dump xmltree`), затем ресурсы (`aapt dump resources`), затем
собери все split-APK с устройства и проверь подпись (`apksigner verify`). Только после этого
переходи к декомпиляции. Такой порядок ловит экспортированные компоненты, отладочные флаги и
встроенные строки до того, как ты утонешь в коде. Записывай находки по ходу — они пригодятся в
отчёте.
"""

ADD['reversing-win-com-rpc'] = """
## Итоговая стратегия анализа

Порядок: `strings` (UUID и имена), поиск `RpcServerRegisterIf`, разбор `MIDL_SERVER_INFO` и
`DispatchTable`, дизассемблирование обработчиков, проверка доверия к входу, проверка
достижимости (endpoint + права). Если есть IDL — компилируй его и сопоставляй стабы. Если нет —
восстанавливай по таблице методов. Для эксплуатации используй `impacket` (DCOM) или свой клиент
по IDL. Держи в голове, что поверхность RPC шире одного бинарника: интерфейсы могут
регистрироваться динамически.
"""

ADD['reversing-win-drivers-irp'] = """
## Итоговая стратегия анализа драйвера

Порядок: `strings` (имена функций, IOCTL), поиск `DriverEntry` и `MajorFunction`, определение
обработчика `IRP_MJ_DEVICE_CONTROL`, разбор `switch` по IOCTL-кодам, анализ метода доступа к
буферу (buffered/direct/neither), проверка доверия к длине и адресу, проверка прав устройства.
Подозрительные IOCTL фаззят на изолированной ВМ. Найденный примитив (например, произвольная
запись) документируют и используют для privesc. Никогда не фаззи на рабочей машине — BSOD реален
и может повредить файловую систему.
"""


def main():
    missing = [k for k in ADD if not os.path.exists(os.path.join(C, k + '.md'))]
    if missing:
        print('missing lessons:', missing)
        return 1
    done = 0
    for lid, extra in ADD.items():
        p = os.path.join(C, lid + '.md')
        with open(p, encoding='utf-8') as f:
            text = f.read()
        if MARK in text:
            continue
        idx = text.find('\n## Квиз')
        if idx == -1:
            print('no quiz heading:', lid)
            continue
        block = '\n' + extra.strip() + '\n\n' + MARK + '\n'
        text = text[:idx] + block + text[idx:]
        with open(p, 'w', encoding='utf-8') as f:
            f.write(text)
        done += 1
    print('topped-up %d lessons' % done)
    return 0


if __name__ == '__main__':
    sys.exit(main())
