ADD['ir-tabletop'] = """
## Частые ошибки при проведении

Учения легко превратить в бесполезное мероприятие. Типичные ошибки:

- **слишком много участников** — обсуждение тонет в шуме;
- **сценарий нереалистичен** — участники играют в фантастику;
- **нет фасилитатора** — разговор уходит в сторону;
- **подсказки** — фасилитатор сам называет решения;
- **нет разбора** — учение закончилось, выводы не сделаны;
- **нет последствий** — находки не превратились в задачи.

Хорошее учение — это **управляемая дискуссия с конкретным результатом**, а не встреча ради
галочки.

## Что считать успехом

Успех учения измеряется не тем, «справилась ли команда», а тем, сколько реальных пробелов
нашли. Учение, на котором всё прошло гладко, скорее всего, было слишком простым или
нереалистичным. Настоящая польза — в неудобных находках: устаревшие контакты, неясные
полномочия, отсутствующие бэкапы.

Поэтому к «мы справились без замечаний» стоит относиться настороженно: возможно, сценарий
не проверил ничего сложного.

## Итог

Tabletop — самый дешёвый способ узнать, работает ли ваш план реагирования. Проведённый
регулярно, он превращает план из документа в навык, а находки — в конкретные улучшения.
"""

