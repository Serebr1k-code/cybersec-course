EXTRA["stego-cmyk"] = r'''
## Шаг 19: как отличить «данные» от «естественного шума»

Младшие биты любого изображения выглядят случайными. Как понять, что там спрятан
текст, а не шум? Критерии:

- **Осмысленность**: собранные байты печатаемы и образуют слова.
- **Сигнатура**: `nto{`, `PK\x03\x04`, `\x89PNG` — узнаваемые начала.
- **Регулярность**: у данных есть структура (заголовок, длина), у шума — нет.

Простой скрипт печатает долю печатаемых символов и ищет сигнатуры. Это надёжнее
глазной оценки.

## Шаг 20: сколько бит реально доступно

Не все младшие биты «свободны». У гладких областей (небо, фон) соседние пиксели
почти равны, и LSB предсказуем — там данные заметны. У текстурных областей LSB
шумнее — там прятать безопаснее. Поэтому ёмкость CMYK-файла зависит от содержимого,
а не только от размера. В задачах данные обычно кладут в «шумную» область.

## Шаг 21: практический итог по CMYK

Соберём всё воедино. CMYK-носитель — это:

1. Четыре канала, из которых K часто самый «тихий».
2. Печатный формат, который инструменты стего не читают.
3. Байты, которые надо смотреть **до** конверсии в RGB.
4. Файл, где planar/chunky и разрядность критичны.

Запомни главное: **CMYK — это RGB плюс лишний канал, но платить приходится
несовместимостью с автоматикой**.
'''

EXTRA["stego-multispectral"] = r'''
## Шаг 18: практический сценарий от начала до конца

Представь задачу: дан `scene.img` и `scene.hdr`. Порядок действий:

1. Читаем `.hdr`: `samples = 8`, `lines = 64`, `interleave = bsq`, `data type = 1`.
2. Понимаем: 8 полос, 64 строки, байты, полосы подряд.
3. Открываем `.img` как массив `(8, 64, W)`.
4. Прогоняем LSB по каждой полосе, ищем сигнатуру.
5. Находим полосу-носитель, извлекаем сообщение.

Так выглядит реальный разбор гиперспектрального носителя — не «магическим
инструментом», а чтением заголовка и перебором.

## Шаг 19: почему нельзя просто открыть куб как картинку

Обычный просмотрщик возьмёт первые три полосы и покажет RGB-превью. Скрытое в
четвёртой полосе не появится. Хуже: некоторые просмотрщики нормализуют значения
(растягивают диапазон), и тогда даже первые полосы меняются. Вывод: **работай с
кубом как с числами**, а не как с картинкой.

## Шаг 20: мост к другим многоканальным носителям

Тот же принцип — «канал, которого нет у RGB» — встречается в:

- **DICOM** (медицина): десятки «фреймов» и служебные теги.
- **тайловых TIFF** с несколькими страницами;
- **многоканальном аудио** (5.1/7.1);
- **видео** (YUV-плоскости).

Освоив спектральный куб, ты умеешь смотреть на любой многоканальный контейнер как
на набор независимых носителей.

## Шаг 21: итог по мультиспектру

Гипер- и мультиспектральные изображения — это:

1. Десятки полос вместо трёх.
2. Естественное место для данных в «лишних» полосах.
3. Формат с заголовком, который обязательно надо прочитать.
4. Носитель, где перебор полос дешевле интуиции.

Запомни: **в кубе данных любая полоса может быть носителем**.
'''

EXTRA["stego-thermal-ir"] = r'''
## Шаг 18: практический сценарий разбора

Задача: дан `ir.bin` неизвестной разрядности. Порядок:

1. `ls -l` — размер; кратен ли 2 (16 бит) или 4 (float)?
2. Открыть hexdump первых байт — увидеть закономерность/заголовок.
3. Прочитать как uint16 little-endian, собрать LSB.
4. Если мусор — повторить big-endian.
5. Если и это мусор — попробовать float32 (бит мантиссы).
6. Искать сигнатуру `nto{`.

Такой системный перебор экономит время: разрядность и endianness — всего 4
комбинации, их можно проверить за минуту.

## Шаг 19: заголовки реальных ИК-форматов

Настоящие тепловизоры пишут не «голый» RAW, а формат с заголовком:

- **FLIR SEQ/FCF** — последовательности с калибровкой.
- **R-JPEG** — JPEG с радиометрическим блоком.
- **TIFF с тегом 339** — FLIR-specific.
- **PGM P5** — простой 16-битный grayscale с текстовым заголовком.

Заголовок сдвигает данные — LSB надо читать **после** него. Если не учесть
смещение, все биты «съедут» на байт.

## Шаг 20: почему это важно в форензике

В реальной форензике ИК-кадры используют для детектирования скрытых объектов и
подделок. Данные, встроенные в ИК-кадр, могут нести метку времени, идентификатор
камеры или «отпечаток» сцены. Понимание 16-битной структуры — базовый навык
сенсорной форензики.

## Шаг 21: итог по ИК-кадру

Тепловизионный кадр — это:

1. Один канал, но 16 бит (часто больше).
2. Носитель, где «младший бит» — бит значения, а не байта.
3. Формат, чувствительный к endianness и разрядности.
4. Данные, которые легко уничтожить нормализацией.

Запомни: **высокая разрядность = больше места + сильнее маскировка шумом**.
'''

EXTRA["stego-fractal"] = r'''
## Шаг 18: практический сценарий

Задача: дан файл с фракталом. Порядок:

1. Понять, что носитель — параметры, а не пиксели.
2. Найти, где хранятся параметры (код, JSON, заголовок).
3. Распаковать каждый параметр в битовое представление.
4. Взять младшие биты и собрать байты.
5. Искать сигнатуру.

Если параметры «слишком точные» (много знаков после запятой) — это подсказка:
обычные генераторы не хранят лишнюю точность, а стего — да.

## Шаг 19: почему точность — это подсказка

Хороший фрактал описывается небольшим числом коэффициентов с обычной точностью
(float32 хватает). Если ты видишь float64 с «набитыми» младшими битами — почти
наверняка там данные. Это структурный признак, по которому стего ловится без
знания алгоритма.

## Шаг 20: связь с квантованием и хаосом

Фрактальные схемы близки к **хаос-стего** (`stego-chaos`): там данные прячут в
начальных условиях хаотической карты. Общее: чувствительность к начальному
состоянию делает изменения непредсказуемыми, а значит — труднообнаружимыми. Разница
лишь в том, что фрактал порождает изображение, а хаос — поток.

## Шаг 21: итог по фракталам

Фрактальная стеганография — это:

1. Носитель-код, а не носитель-данные.
2. Данные в младших битах параметров (IFS/коэффициенты).
3. Устойчивость к масштабированию, но не к смене параметров.
4. Обнаружение через аномальную точность параметров.

Запомни: **если изображение генерируется, прячь в генераторе**.
'''

def insert(path, extra):
    with io.open(path, encoding="utf-8") as f:
        text = f.read()
    if extra.strip().splitlines()[0] in text:
        print("ALREADY", path); return
    text = text.replace(ANCHOR, "\n" + extra.strip() + ANCHOR, 1)
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("DEEPENED", path)

for lid, extra in EXTRA.items():
    insert(ROOT + "/" + lid + ".md", extra)
print("deepen img2 done")
