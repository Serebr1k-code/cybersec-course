#!/usr/bin/env python3
"""Third top-up for batch D."""
import re

ADD = {}

ADD["win-scheduled-tasks-deep"] = r'''
## Итоговый вывод по планировщику

Планировщик задач — самый распространённый механизм персистентности в Windows, и его проверяют
первым. Его сила в гибкости: триггер по входу, по времени или по событию, действие в виде
любой программы, запуск от SYSTEM через `HighestAvailable`. Читая задание, всегда разбирай
четыре элемента: автор, триггер, действие и уровень прав. Аномалия хотя бы в одном из них
(действие в `Public`/`Temp`, автор-пользователь, скрытое имя, обфусцированная команда) —
повод для глубокой проверки. Дополняй разбор журналом `TaskScheduler` и сверкой реестра с
каталогом `Tasks`. Тогда вывод покажет не только «задание есть», но и как оно появилось и что
запускает.
'''

ADD["win-service-artifacts"] = r'''
## Итоговый вывод по службам

Службы — второй по частоте механизм закрепления после планировщика. Их сила в правах и
автозапуске: служба может стартовать при загрузке и работать от SYSTEM. Различай три способа
использования: создание новой службы, модификация существующей (подмена `ImagePath` или
`ServiceDll`) и ослабление прав доступа к службе. Для каждого нужен свой признак: нестандартный
путь, изменение знакомой службы, слабый дескриптор. Подтверждай вывод журналом System
(событие 7045) и проверкой подписи файла. В отчёте свяжи службу с найденным образцом и
объясни, почему она переживает перезагрузку и с какими правами работает.
'''

ADD["win-wmi-persistence"] = r'''
## Итоговый вывод по WMI

WMI-персистентность — самый скрытный из распространённых механизмов: она не создаёт ни служб,
ни заданий, ни записей в `Run`. Обнаруживается только целенаправленным запросом к
`root\subscription` или офлайн-разбором репозитория. Всегда проверяй три компонента — фильтр,
консьюмер и связку; без связки подписка не работает. Особое внимание уделяй консьюмерам
`CommandLineEventConsumer` и `ActiveScriptEventConsumer` и раскодируй их содержимое. В отчёте
приведи все компоненты и их действие целиком, а также способ обнаружения. Если код явно
выполняется, а механизм не найден, WMI — первый подозреваемый.
'''

ADD["win-boot-config"] = r'''
## Итоговый вывод по загрузке

Загрузочная конфигурация — редко проверяемый, но критичный уровень. Здесь ищут две вещи:
ослабление защиты (`testsigning`, отключённый Secure Boot) и подмену загрузочного кода
(буткит). Проверяй согласованность трёх слоёв — BCD, файлов на EFI-разделе и переменных
прошивки: в норме они совпадают, а расхождение указывает на ручную правку. Сравнивай хеши
загрузчиков с эталонными из установочного носителя. Всегда снимай копию BCD и загрузчиков как
улики до восстановления. В отчёте опиши все слои и найденные аномалии: внимание к загрузке
отличает глубокое расследование от поверхностного.
'''

for lid, add in ADD.items():
    p = f"content/forensics/{lid}.md"
    t = open(p, encoding="utf-8").read()
    m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
    open(p, "w", encoding="utf-8").write(t[:m.start()] + add.strip() + "\n\n" + t[m.start():])
    print("topup", lid)
