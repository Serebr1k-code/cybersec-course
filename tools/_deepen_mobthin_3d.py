#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Deepen MOBILE batch 3 — final pass to clear 1200."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')
ANCHORS = ('\n## Что мы теперь знаем', '\n## Квиз')


def add(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already):', lid)
        return
    idx = next((t.find(a) for a in ANCHORS if t.find(a) != -1), None)
    t = t[:idx] + '\n' + extra.strip() + '\n' + t[idx:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


MOBSF = '''
## Итог по MobSF

Автоматический сканер ценен там, где нужен масштаб: двадцать приложений за вечер вместо недели
ручной работы. Он не заменяет аналитика, но расставляет приоритеты и избавляет от рутины.
Правильное использование — прогнать, распарсить, взять топ находок и проверить их руками.
Встроенный в CI, MobSF становится фильтром, не пропускающим типовые проблемы в релиз.
'''

ANGR = '''
## Итог по angr

Символьное исполнение — это автоматический подбор входа для формульных проверок. Оно не
универсально: там, где нужен реальный контекст, оно уступает динамике. Но для «чистых» проверок
(сравнение, хеш, XOR) angr даёт результат за минуты, которые вручную ушли бы на часы чтения
ассемблера. Умение сузить задачу и вовремя переключиться на другой инструмент — вот что делает
его по-настоящему полезным.
'''

SIDELOAD = '''
## Итог по sideloading

Sideloading — это мост между разработкой и устройством, без которого мобильный пентест
невозможен. Его ограничения (срок подписи, доверие сертификату, отзыв) — не недостатки, а
свойства системы, которые нужно учитывать в планировании. Освоив подпись и установку, вы
получаете базу для всего остального: инструментации, динамического анализа и подготовки
инструментов на устройстве.
'''

TEE = '''
## Итог по атакам на TEE

Атаки на TEE — это редкий, research-уровневый сценарий, но понимание устройства доверенной
среды необходимо каждому мобильному пентестеру: оно определяет, чему можно доверять, а чему нет.
Практический вывод прост: аппаратная защита сильна, но приложение должно правильно ей
пользоваться — требовать аутентификацию, проверять аттестацию на сервере и учитывать модель
угроз с root-устройством.
'''

for lid, txt in [
    ('mobile-android-mobsf-deep', MOBSF),
    ('mobile-android-angr', ANGR),
    ('mobile-ios-sideload', SIDELOAD),
    ('mobile-android-tee-attacks', TEE),
]:
    add(lid, txt)
