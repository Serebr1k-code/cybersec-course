import os

ROOT = '/home/Serebr1k/learning_tree'


def insert_before_quiz(path, extra):
    with open(path, encoding='utf-8') as f:
        t = f.read()
    marker = '\n## Квиз'
    i = t.find(marker)
    if i == -1:
        raise SystemExit('no quiz in ' + path)
    t = t[:i] + '\n' + extra.strip() + '\n' + t[i:]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(t)


B = {}

B['mobile-android-tflite'] = '''
Стоит добавить, что разбор модели — это только первый шаг. Дальше важно понять, как
приложение её использует: что подаёт на вход, что делает с выходом, есть ли постобработка.
Именно постобработка часто содержит логику, которую хочется обойти, а значит она — самая
интересная цель для анализа. Модель без постобработки бесполезна, и защищать надо всю цепочку.
'''

B['mobile-android-onnx'] = '''
Добавим важное про доверие: если модель и её операторы приходят из одного источника с
приложением, их целостность обеспечивается подписью APK. Как только появляется сеть или
внешнее хранилище, эту гарантию надо восстанавливать вручную — подписью модели или
контрольной суммой. Без этого вся цепочка доверия рушится в одном месте.
'''

B['mobile-android-nnapi'] = '''
В завершение отметим: NNAPI постоянно развивается, появляются новые операции и версии HAL.
Это значит, что старые выводы о «безопасности драйвера» устаревают вместе с обновлениями.
Проверяйте актуальную версию на целевом устройстве и не переносите результаты с одной
модели телефона на другую без перепроверки.
'''

B['mobile-valgrind'] = '''
И ещё: сохраняйте вывод Valgrind целиком, а не только строку с утечкой. Полный отчёт
позволяет увидеть контекст: сколько всего выделений, сколько освобождений, есть ли ещё
проблемы рядом. Часто одна утечка тянет за собой вторую, и обе видны только в полном логе.
'''

for lid, extra in B.items():
    insert_before_quiz(os.path.join(ROOT, 'content/mobile', lid + '.md'), extra)
print('OK tenth expansion')
