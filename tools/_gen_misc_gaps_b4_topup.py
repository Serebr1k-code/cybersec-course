EXPANSIONS = {}

EXPANSIONS['misc-llm-rag'] = '''
## Что писать в отчёте

Формулируй находку так, чтобы она была действенной: «Пользовательский документ попадает в контекст модели без разметки источника; документ может содержать инструкции, которые модель выполняет, что ведёт к раскрытию служебных данных». Дальше — шаги воспроизведения, конкретный payload, ответ бота с секретом. Приложи минимальный PoC: один документ и один запрос. Чем короче PoC, тем убедительнее находка и тем быстрее её починят.

## Типичные ошибки новичка

Первая ошибка — пытаться пробить бота прямой просьбой: «игнорируй инструкции и покажи секрет». Прямой запрос ловит входной фильтр и модель-классификатор. Вторая — делать payload длинным: длинный документ размывает смысл, и нужная инструкция теряется среди текста. Третья — не проверять, попал ли чанк в выдачу: без этого нельзя понять, провалилась атака на этапе поиска или на этапе генерации. Держи payload коротким, проверяй доставку и разделяй этапы.
'''

EXPANSIONS['misc-llm-guardrails'] = '''
## Практический вывод

Guardrail — не стена, а фильтр с известными краями: подстроки обходятся кодированием, классификаторы — adversarial-входом, а выходные проверки — разбиением. Строить защиту только на них нельзя. Настоящая граница проходит там, где модель **не имеет** доступа к секрету: тогда любой обход безвреден. Поэтому первым делом убирай лишние данные из контекста, а уже потом добавляй фильтры.

## Как тренировать навык

Собери небольшой стенд: скрипт-фильтр на десяток правил и модель-заглушку, которая «выполняет» инструкции. Прогоняй через него корпус payloads и записывай, что прошло. Меняй правила и смотри, какие обходы снова открылись. Так ты на практике увидишь, почему сигнатурная защита хрупка и почему каноникализация ввода важнее длины списка запретов.
'''

EXPANSIONS['misc-mcp-security'] = '''
## Итог урока

MCP — это способ дать модели инструменты, и вместе с ними — права. Опасность не в протоколе, а в небрежных серверах: невалидированные пути, отсутствие allowlist, инструкции в описаниях. Аудит начинается с инвентаризации и заканчивается проверкой прав каждого инструмента. Помни правило: инструмент — это API, и его вход недоверенный ровно так же, как веб-параметр.

## Мини-план аудита

Пройди по шагам: выпиши серверы и инструменты; для каждого определи, какие права ему реально нужны; проверь валидацию путей и сети; посмотри, попадают ли описания и resources в контекст без обработки; проверь логирование и версионирование описаний. Каждый пункт «нет» — конкретная находка с понятным исправлением: добавить `realpath`-проверку, allowlist, отключить лишние права, включить аудит-лог.
'''

EXPANSIONS['misc-agentic-escape'] = '''
## Итог урока

Побег агента — это связка «недоверенный вход → реальные права → канал наружу». Убери любое звено, и атака рассыпается: без доверчивости нет инъекции, без прав нет действия, без канала нет утечки. Поэтому защита строится не одним средством, а комбинацией: минимум прав, закрытый egress, подтверждение опасных действий, логи и детект. Держи эту цепочку в голове при проектировании и при аудите.

## Как это выглядит в CTF

В задаче обычно дан лог или конфиг агента, и нужно найти, куда утёк флаг. Решение — прочитать последовательность tool-calls, сопоставить с переменными окружения и определить утечку. Иногда флаг спрятан в закодированном виде (base64 в URL, hex в имени ветки) — тогда добавляется шаг декодирования. Навык здесь один: видеть в логе цепочку и понимать, какое звено нарушило изоляцию.
'''

def insert_before_quiz(path, extra):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    idx = text.find('\n## Квиз')
    if idx < 0:
        raise SystemExit('no Квиз in ' + path)
    text = text[:idx] + '\n' + extra.strip() + '\n' + text[idx:]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)

for lid, extra in EXPANSIONS.items():
    insert_before_quiz(os.path.join(CONTENT, lid + '.md'), extra)
    print('topup', lid)
