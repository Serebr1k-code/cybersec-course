ADD["linux-auditd-deep"] = r'''
## Расширенный разбор: восстановление атаки по аудиту

Соберём полный сценарий из разрозненных записей. Начни с поиска всех `execve` от
веб-пользователя за период инцидента:

```
$ ausearch -ua 33 -m EXECVE -ts recent -i
```

Ты получишь список команд, запущенных веб-процессом. В норме их мало (скрипты сайта,
обработчики). Если среди них `bash`, `sh`, `python`, `nc` — это уже подозрительно. Далее
для найденного `pid` запроси все события с этим `pid`:

```
$ ausearch -p 2212 -i
```

Так собирается вся активность процесса: какие файлы открывал, какие соединения открывал,
какие команды порождал. Это и есть реконструкция атаки на уровне ядра — от первичного
выполнения до закрепления. Заверши сопоставлением с journald (контекст входа) и с сетевыми
логами (куда ушли данные), и у тебя будет доказательная цепочка, а не догадка.
'''

ADD["linux-journald-binary"] = r'''
## Расширенный разбор: аномалии под нагрузкой

На реальном сервере журнал огромен, и «прочитать его глазами» нельзя. Работай от гипотез.
Первая гипотеза — компромисс сервиса: ищи запуск shell из сетевого демона по
`_SYSTEMD_UNIT`. Вторая — вход: фильтруй `sshd` по неуспешным и успешным попыткам и ищи
аномальные IP. Третья — закрепление: ищи сообщения systemd о запуске **новых** юнитов и
таймеров.

```
$ journalctl -D /mnt/img/var/log/journal -u sshd --since "2025-05-01" | grep -i 'Accepted\|Failed'
$ journalctl -D /mnt/img/var/log/journal | grep -i 'Started\|Stopped' | sort | uniq -c | sort -rn
```

Первый запрос выделяет вход по SSH, второй — частоту стартов и остановок сервисов. Сервис,
который стартовал сотни раз или появился впервые в день инцидента, заслуживает внимания.
Заверши построением таймлайна из полей `__REALTIME_TIMESTAMP` и сопоставлением с auditd.
'''


def expand(lid, add):
    path = f"{C}/{lid}.md"
    t = open(path, encoding="utf-8").read()
    marker = "\n## Квиз"
    assert marker in t, f"no quiz marker in {lid}"
    t = t.replace(marker, "\n" + add.strip() + "\n" + marker, 1)
    open(path, "w", encoding="utf-8").write(t.rstrip() + "\n")


