SCREENSHOT = '''
## Как устроен порог различий

Порог — это число или доля, ниже которой различия считаются шумом. Есть два способа его
задать. Первый — **абсолютный**: «не больше 500 отличающихся пикселей». Второй —
**относительный**: «не больше 0,5% площади экрана». Относительный удобнее: он не зависит от
разрешения устройства. Но у обоих есть подвох: маленькая, но важная деталь (иконка
предупреждения) может занимать меньше порога и остаться незамеченной. Поэтому порог —
компромисс между чувствительностью и стабильностью.

## Метрики сравнения

Инструменты визуального сравнения дают разные числа:

| Метрика | Что считает | Когда полезна |
|---------|-------------|---------------|
| AE | число отличающихся пикселей | грубая оценка объёма изменений |
| RMSE | среднеквадратичное отклонение яркости | оценка силы изменений |
| PSNR | отношение сигнал/шум | сравнение качества картинок |

Для регрессионных тестов чаще берут AE: он интуитивен («столько пикселей поменялось») и
легко превращается в порог.

## Обновление эталона

Эталон — не вечная истина. Когда интерфейс меняется намеренно, эталон надо обновить, иначе
тест будет вечно красным. Но обновление — опасная операция: если обновить «на автомате», можно
зафиксировать и настоящую поломку. Правило: эталон обновляет человек, посмотрев на карту
различий и убедившись, что изменение ожидаемое. Обновление фиксируется в репозитории, чтобы
было видно, кто и когда его сделал.

## Ложные срабатывания и как их гасить

Основные источники шума: системные часы, индикатор батареи, анимации, курсор, реклама,
шрифтовые подстановки. Способы борьбы: маски (игнорируемые области), фиксированное время в
тестовом окружении, отключение анимаций на эмуляторе, ожидание стабильного состояния перед
снимком. Хорошая практика — «прогревать» экран: сделать снимок дважды с паузой и сравнивать
второй, когда анимации уже завершились.

## Реальный случай: пропавшая кнопка

Приложение прошло все проверки, но пользователи жаловались, что кнопка «Оплатить» не
нажимается. Оказалось, она перекрыта невидимым слоем. Скриншотный тест это поймал бы: карта
различий показала бы изменение в области кнопки. Но порог был выставлен слишком высоким —
различия «съел» шум от рекламного баннера. Мораль: порог надо калибровать по конкретному
экрану, а не брать «на глаз».

## Чек-лист

- эталон лежит в репозитории и обновляется вручную;
- порог подобран под экран;
- шумные области закрыты масками;
- перед снимком дождались стабильного состояния;
- карта различий сохраняется как артефакт.
'''

DETOX = '''
## Жизненный цикл теста

Detox проходит несколько фаз. Сначала `beforeAll` поднимает приложение и ждёт его готовности;
затем каждый `it` выполняет шаги; в `afterAll` приложение закрывается. Важная деталь — между
тестами Detox обычно перезапускает приложение (`reloadReactNative`), чтобы состояние не
перетекало из одного сценария в другой. Если этого не делать, тест может «протекать»: логин
из прошлого теста делает следующий сценарий невалидным.

## Устройство и сборка

Detox различает **конфигурацию устройства** и **конфигурацию приложения**. Устройство — это
эмулятор или реальный телефон; приложение — APK/IPA и способ его установки. Для CI обычно
готовят снапшот эмулятора: один раз запускают, настраивают, сохраняют образ, а в конвейере
поднимают из него. Это экономит минуты на каждой сборке и, что важнее, убирает разницу между
прогонами.

## Стабилизация и ожидания

Даже с автосинхронизацией бывают моменты, которые Detox не отслеживает: анимация, запущенная
вне UI-потока, или сетевой запрос, идущий через нативный код. Тогда используют `waitFor`:
тест ждёт появления элемента с таймаутом. Важно не злоупотреблять этим: `waitFor` с большим
таймаутом маскирует настоящие проблемы производительности. Хороший тест ждёт конкретное
условие, а не «просто время».

## Отладка упавших тестов

Когда тест падает, Detox сохраняет скриншот и видео. Порядок разбора: сначала видео — оно
показывает, на каком шаге всё сломалось; затем скриншот — видно состояние экрана; затем лог
приложения — видно исключение. Частая причина падения — изменение `testID`: разработчик
переименовал идентификатор, и тест перестал находить элемент. Это не баг приложения, а
рассинхронизация теста.

## Что даёт пентестеру

Detox-тесты — это карта пользовательских путей. Читая их, вы видите, какие экраны существуют,
какие кнопки нажимаются и какие запросы уходят. Иногда в комментариях остаются реальные
эндпоинты и тестовые учётки. Это законная разведка: тесты лежат в репозитории, а иногда и
попадают в сборку. Отдельно стоит проверить, не включён ли debug-режим Detox в релизной
сборке — это открывает отладочный мост.

## Реальный случай: тест зелёный, баг есть

Сценарий «сохранить профиль» проходил, но в реальности данные не сохранялись при плохой сети.
Тест не ловил это, потому что эмулятор всегда был онлайн. Урок: e2e-тест проверяет только те
условия, которые в нём воспроизведены. Хорошая практика — добавить сценарии с обрывом сети и
медленным откликом.

## Чек-лист

- приложение перезапускается между тестами;
- образ эмулятора зафиксирован в CI;
- ожидания привязаны к условию, а не к времени;
- падения разбираются по видео, скриншоту и логу;
- проверены сценарии с плохой сетью.
'''

REPORT = '''
## Шаблон карточки находки

Чтобы отчёт был единообразным, каждая находка оформляется по одному шаблону:

- **Заголовок** — коротко и по делу: «Сессионный токен хранится в открытом виде».
- **Класс** — привязка к MASVS (например, STORAGE) и MASTG-тест.
- **Серьёзность** — High/Medium/Low с обоснованием.
- **Описание** — что не так и почему это плохо.
- **Воспроизведение** — окружение, шаги, команды.
- **Доказательство** — сырой вывод или скриншот.
- **Рекомендация** — конкретный механизм исправления.

Такой шаблон позволяет читать отчёт «по диагонали»: руководитель смотрит заголовки и
серьёзность, разработчик — воспроизведение и рекомендацию.

## Оценка серьёзности на мобильных

На десктопе и вебе есть привычные метрики вроде CVSS, но на мобильных у них есть
особенность: многое зависит от модели угроз. Токен в открытом виде на устройстве без root
прочитать сложно, а на устройстве с root — элементарно. Поэтому в обосновании всегда
указывают **предполагаемого атакующего**: «пользователь с root», «вредоносное приложение без
специальных прав», «физический доступ к разблокированному устройству». Без этого оценка
висит в воздухе.

## Приоритизация

Находки сортируют по двум осям: серьёзность и стоимость исправления. Быстрые и важные
исправления идут первыми. Иногда дешёвая находка с высокой серьёзностью (например, забытый
debug-флаг) важнее сложной архитектурной проблемы. Отдельно отмечают находки, которые
блокируют релиз: секреты в коде, обход аутентификации, утечка персональных данных.

## Реальный случай: спор о серьёзности

Пентестер отметил экспортированный компонент как Medium. Заказчик возразил: «это только
внутренний экран». В доказательстве пентестер показал, что компонент вызывается из другого
приложения без прав и открывает экран с токеном. Спор закончился: серьёзность подняли до
High. Мораль: доказательство снимает разногласия лучше любых формулировок.

## Что делать с ложными срабатываниями

Не каждая подозрительная строка — находка. Если приложение хранит в `SharedPreferences`
не секрет, а, например, настройку темы, это не уязвимость. Включать такое в отчёт вредно:
шум обесценивает серьёзные пункты. Правило — каждая находка должна иметь **последствие**:
что конкретно теряет пользователь или компания, если её не исправить.

## Чек-лист

- каждая находка привязана к MASVS/MASTG;
- серьёзность обоснована через модель угроз;
- доказательство воспроизводимо;
- рекомендация называет механизм;
- есть приоритизация и список блокеров релиза.
'''

