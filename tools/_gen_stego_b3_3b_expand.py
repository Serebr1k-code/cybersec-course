# -*- coding: utf-8 -*-
"""Expansion for stego B3-3b lessons (grayscale/raw-bayer/ntp/ipv4-options)."""
import os
ROOT = "content/stego"

def expand(lid, extra):
    p = os.path.join(ROOT, lid + ".md")
    t = open(p, encoding="utf-8").read()
    key = extra.strip().splitlines()[0]
    if key in t:
        print("SKIP(done)", lid); return
    m = "## Что мы теперь знаем"
    open(p, "w", encoding="utf-8").write(t.replace(m, extra.strip() + "\n\n" + m, 1))
    print("EXPANDED", lid)

expand("stego-grayscale", r'''
## Шаг 8: подробный разбор структуры PNG

Разберём, как устроен PNG изнутри, чтобы чтение LSB было осознанным. После 8-байтной
сигнатуры идут чанки. Первый — `IHDR`: 13 байт данных, где ширина (4 байта), высота
(4), bit depth (1), color type (1), compression (1), filter (1), interlace (1).
Именно здесь мы узнаём, что изображение grayscale (color type 0) с глубиной 8.

Затем идёт `IDAT` — сжатые zlib данные. Их может быть несколько чанков подряд; перед
распаковкой их надо объединить. После `zlib.decompress` получаем **сырой поток
пикселей**: для grayscale 8 бит это просто байты яркости, но с фильтр-байтом в
начале каждой строки. Длина строки = ширина + 1 (фильтр-байт).

## Шаг 9: что такое фильтр-байт и зачем он

PNG применяет фильтрацию перед сжатием, чтобы улучшить сжатие: каждая строка
начинается с байта, задающего тип фильтра (None, Sub, Up, Average, Paeth). Этот
байт — не пиксель. Если его не пропустить, все последующие пиксели сдвигаются на
один, и LSB-сообщение читается как мусор. Поэтому в скрипте мы делаем
`raw[y*(w+1)+1:(y+1)*(w+1)]` — берём строку без первого байта.

## Шаг 10: битовые плоскости

Кроме LSB, в grayscale можно смотреть любую битовую плоскость. Младший бит (bit 0)
— самый популярный, но данные могут быть в бите 1, 2 и т. д. Разложение на битовые
плоскости превращает изображение в 8 чёрно-белых картинок; на одной из них может
быть видно сообщение или картинку. Это делают в GIMP (`Colors → Decompose`) или
скриптом.

## Шаг 11: grayscale из цветного

Иногда grayscale получают из RGB через формулу яркости (например, `0.299R + 0.587G
+ 0.114B`). Если автор прятал данные в цветном изображении, а потом сконвертировал в
grayscale, часть информации потеряется — LSB-канал может разрушиться. Поэтому в
задачах grayscale обычно создают «с нуля».

## Шаг 12: частые ошибки

Первая — не пропустить фильтр-байт. Вторая — перепутать bit depth (1/2/4/8).
Третья — не учесть интерлейс (Adam7), который меняет порядок строк. Четвёртая —
читать LSB в палитровом изображении, где канал не яркость. Пятая — забыть, что
`IDAT` может быть несколько.

## Шаг 13: полный разбор примера

История: `gray.png` → `file` говорит `8-bit grayscale` → скрипт распаковывает
`IDAT`, пропускает фильтр-байты, читает младшие биты яркости → собирает байты →
получает `nto{gr4ysc4l3_lsb}` → записывает в `found.txt`. Мы прошли путь от формата
до флага, понимая каждый шаг.

## Шаг 14: практика на разных типах

Попробуй один и тот же скрипт на разных файлах: grayscale 8-бит, палитровый,
монохром. Для каждого результат будет разным. Так ты научишься быстро определять
тип по `IHDR` и выбирать правильную стратегию, а не запускать вслепую.
''')

expand("stego-raw-bayer", r'''
## Шаг 8: разбор RAW-форматов

RAW — общее название, но конкретных форматов много: CR2 (Canon), NEF (Nikon), ARW
(Sony), DNG (Adobe) и «сырой» `.raw` без заголовка. У каждого своя структура:
метаданные камеры, сжатие (иногда lossless), порядок сэмплов. В CTF чаще дают
«голый» поток сэмплов без заголовка, как в нашем примере.

Первый вопрос: 8, 10, 12, 14 или 16 бит на сэмпл? Это определяет и размер, и
распаковку. Второй: какой Bayer-паттерн (RGGB, BGGR, GRBG, GBRG)? Третий: порядок
строк и endianness. Без этих параметров чтение битов даёт мусор.

## Шаг 9: определение размеров

Если файл — «голый» поток 8-битных сэмплов, размер = ширина × высота. Для нашего
файла 512 байт → например, 16×32 или 22×23 (не круглые числа — значит, параметры
задают в задаче или подсказке). Для 16-битных сэмплов размер = ширина × высота × 2.
Умение быстро оценить размеры помогает понять формат.

## Шаг 10: LSB и старшие биты

В RAW прячут не только в LSB. Старшие биты сэмпла тоже можно использовать, но это
заметнее (меняет яркость сильнее). Чаще берут LSB — изменение на 1 из 1024 (для
10-бит) незаметно. Также используют **разницу** между соседними сэмплами одного
цвета: она мала, и в неё удобно встраивать.

## Шаг 11: демозаика и потеря данных

Почему RAW-стего не выживает демозаику? Демозаика интерполирует каждый пиксель из
соседей: значение RGB в точке — комбинация сэмплов разных цветов. Если в сэмплах
были младшие биты сообщения, интерполяция их «размазывает» и уничтожает. Поэтому
RAW-задачи всегда дают сырой файл, а не RGB.

## Шаг 12: частые ошибки

Первая — читать 10-битный RAW как 8-битный (сдвиг). Вторая — не учесть endianness
для 16-битных сэмплов. Третья — перепутать порядок строк. Четвёртая — ожидать, что
`zsteg`/`binwalk` найдут данные (не найдут). Пятая — забыть про Bayer-паттерн при
интерпретации цветов.

## Шаг 13: полный разбор примера

История: `sensor.raw` → `file` не распознаёт (нет сигнатуры) → скрипт читает LSB
всех байтов, собирает в байты → получает `nto{b4y3r_r4w_s3ns0r}` → записывает в
`found.txt`. Мы работали с RAW как с потоком байтов, потому что знали, что сжатия
нет.

## Шаг 14: связь с реальной форензикой

RAW-анализ — часть sensor forensics: по шуму сенсора определяют камеру, по паттерну
— модель, по артефактам — манипуляции. Стего в RAW — обратная задача: спрятать
данные в шуме так, чтобы их не заметили. Понимание RAW нужно и там, и там.

## Шаг 15: практика на разных глубинах

Попробуй написать распаковщик для 10-битного RAW (упаковка 4 сэмпла в 5 байт) и
прочитать из него LSB. Это упражнение закрепляет понимание битовой упаковки, которое
пригодится и в других форматах (например, 12-битных DICOM или 16-битных TIFF).
''')

expand("stego-ntp", r'''
## Шаг 8: полный формат NTP-пакета

Разберём пакет по полям. Первый байт: LI (2 бита, leap indicator), VN (3 бита,
version), Mode (3 бита). Второй байт: Stratum. Третий: Poll. Четвёртый: Precision
(signed). Затем Root Delay (32 бита, 16.16 fixed-point), Root Dispersion (32),
Reference ID (32). Далее четыре таймстемпа по 64 бита: Reference, Originate,
Receive, Transmit. Каждый — секунды с 1900 года (32 бита) + дробная часть (32 бита).

Именно дробная часть даёт наносекундное разрешение — избыточное для реальных часов.
Младшие биты этой части и используют как канал.

## Шаг 9: почему избыточность — ключ

Точность часов NTP ограничена сетью и кварцем: реально синхронизация идёт с
точностью микро- или миллисекунд. Значит, последние ~10–20 бит дробной части — шум.
Протокол их не проверяет, получатель использует таймстемп как приблизительное
время. Это «бесплатное» место для данных. Тот же принцип работает в любом протоколе
с избыточной точностью.

## Шаг 10: как читать канал правильно

Ключевая тонкость: биты могут быть в разных полях и в разных позициях. Сначала
определи, какое поле «дрожит» неслучайно. Затем возьми младший бит (или несколько)
и собери. Порядок битов (LSB-first/MSB-first) тоже может варьироваться. Начни с
самого вероятного — transmit_ts, LSB-first.

## Шаг 11: альтернативы — тайминг-канал

Кроме полей, канал может быть в **интервалах** между пакетами. Например, короткий
интервал = 0, длинный = 1. Это медленнее, но устойчивее к фильтрации полей. В CTF
иногда дают времена прихода пакетов и просят декодировать. Принцип тот же:
неслучайность там, где ожидается шум.

## Шаг 12: частые ошибки

Первая — читать не то поле (например, reference вместо transmit). Вторая — путать
секунды и дробную часть. Третья — не учесть, что биты могут быть MSB-first.
Четвёртая — забыть про padding. Пятая — не проверить, что полученный текст осмыслен
(проверка формата флага).

## Шаг 13: полный разбор примера

История: `ntp.txt` → скрипт берёт дробную часть `transmit_ts` каждого пакета → берёт
младший бит → собирает по 8 → получает `nto{ntp_t1m3st4mp_ch4nn3l}` → записывает в
`found.txt`. Мы использовали структуру протокола, а не перебор.

## Шаг 14: перенос на другие протоколы

Тот же подход работает для DNS (ID, TTL, порядок ответов), ICMP (payload,
идентификатор), TCP (ISN, timestamps), HTTP (заголовки). Общий рецепт: найди поле,
которое не проверяется строго, и используй его как носитель. NTP — просто самый
наглядный пример.

## Шаг 15: как это ловят в реальности

Системы обнаружения covert channels анализируют статистику полей: если младшие биты
таймстемпов не выглядят как равномерный шум, а имеют структуру (например, много
нулей), это подозрительно. Также смотрят на интервалы пакетов. Поэтому в реальных
атаках канал делают «шумоподобным», а в CTF — простым и читаемым.
''')

expand("stego-ipv4-options", r'''
## Шаг 8: полный формат IPv4-заголовка

Разберём заголовок. Первый байт: Version (4 бита) + IHL (4 бита). Второй: DSCP/ECN.
Затем Total Length (16), Identification (16), Flags (3) + Fragment Offset (13), TTL
(8), Protocol (8), Header Checksum (16), Source Address (32), Destination Address
(32). Это 20 байт при IHL=5. Если IHL>5, после адресов идут options длиной
`(IHL−5)×4` байт.

Options выровнены по 4 байта, поэтому часто заканчиваются опцией EOL (0) и
padding'ом (0). Именно это выравнивание иногда выдаёт канал: слишком много нулей
после осмысленных байтов.

## Шаг 9: почему options почти всегда пусты

В современном интернете options практически не используются: маршрутизация от
источника запрещена, record-route не нужен. Поэтому IHL почти всегда 5. Это делает
любой пакет с IHL>5 аномалией — хороший признак канала для аналитика и хорошую
заметность для атакующего.

## Шаг 10: record-route подробнее

Опция RR (type=7) заставляет каждый маршрутизатор записать свой адрес в поле data.
Формат: type, length, pointer, затем список адресов. Атакующий может заполнить
список «адресами», которые на самом деле — закодированные байты. Снаружи выглядит
как легитимная опция. Обнаружить сложнее, чем сырой канал.

## Шаг 11: timestamp-опция

Опция TS (type=68) несёт 32-битные метки времени маршрутизаторов. Младшие биты
метки — снова избыточная точность, как в NTP. Это показывает общий принцип:
**избыточность = носитель**, независимо от протокола.

## Шаг 12: частые ошибки

Первая — читать options без учёта выравнивания по 4 байта. Вторая — путать байты
опций с padding'ом. Третья — не проверить IHL (может быть 6, 7, ...). Четвёртая —
забыть, что пакет может быть фрагментирован. Пятая — не проверить формат флага.

## Шаг 13: полный разбор примера

История: `headers.txt` → каждый пакет с `IHL=6` → скрипт берёт байты `options=`,
склеивает по всем пакетам → декодирует как latin-1 → получает
`nto{1pv4_0pt10ns_c0v3rt}` → записывает в `found.txt`. Мы использовали поле,
которого в обычном трафике не бывает.

## Шаг 14: обнаружение в реальной сети

Правило фильтрации: дропать пакеты с IHL>5 (если options не нужны). Инструменты:
`tshark -Y 'ip.hdr_len > 20'`. В CTF достаточно посмотреть IHL и байты опций. В
форензике — построить статистику по IHL и options, найти аномалии.

## Шаг 15: общий принцип модуля

NTP и IPv4-options — два примера одного принципа: **любое необязательное или
избыточное поле протокола можно использовать как носитель**. Освоив этот принцип,
ты найдёшь канал в DNS, ICMP, TCP, HTTP и других протоколах. Меняются поля, идея
остаётся.
''')

