ADD['win-app-compat'] = r'''
## AppCompatCache и вопрос «был ли файл на диске»

Отдельная ценность ShimCache — он фиксирует **существование** файла, даже если сейчас
его нет. Сценарий: атакующий положил инструмент в `C:\Temp\tool.exe`, запустил и удалил.
Prefetch мог очиститься, но путь `C:\Temp\tool.exe` остался в AppCompatCache. Значит,
файл на диске был — это уже факт, опровергающий «ничего не было».

Комбинируем с другими источниками:

- **MFT/USN journal** — запись о создании/удалении файла с временем;
- **ShimCache** — путь файла (что он существовал);
- **AmCache** — хеш (что за файл);
- **Prefetch/WER** — запуск (если был).

Пересечение даёт полную цепочку «создан → существовал → запускался → удалён». Каждый
шаг подкреплён отдельным артефактом, и вместе они образуют защищаемый вывод о том, что
программа действительно была и работала, несмотря на попытку замести следы.

## Где AppCompatCache бессилен

ShimCache не покажет **время запуска** и **число запусков** — за это отвечает Prefetch.
Он не покажет **командную строку** — это Sysmon/4688. И он не покажет **сеть** — это
журналы соединений. Поэтому ShimCache — кирпич, а не стена: он закрывает вопрос
«существовал/мог запускаться», но остальные вопросы закрывают другие артефакты. Так и
строится корректный форензик-вывод — из нескольких независимых кирпичей.
'''

