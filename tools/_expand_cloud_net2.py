def main():
    for lid, extra in EXTRA.items():
        p = os.path.join(ROOT, 'content', 'cloud', lid + '.md')
        t = open(p, encoding='utf-8').read()
        m = re.search(r'^## Квиз\s*$', t, re.MULTILINE)
