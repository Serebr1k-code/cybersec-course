#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Deepen MOB-GAP-6 (il2cpp, third-party-sdk) to >=1200 real content words."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')


def add_before_quiz(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already deepened):', lid)
        return
    i = t.index('\n## Квиз')
    t = t[:i] + '\n' + extra.strip() + '\n' + t[i:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


IL2 = '''
## Шаг 7: версии метаданных и совместимость

`global-metadata.dat` начинается с магического числа и номера версии. Версия привязана к
версии Unity, и именно поэтому Il2CppDumper спрашивает её при запуске — от версии зависит
раскладка полей структуры. Если указать неверную версию, дамп получится мусорным.

```bash
$ xxd -l 16 global-metadata.dat
00000000: af1b b1fa 1f00 0000 ...     # magic + version 0x1f (31)
```

Если инструмент не поддерживает версию напрямую, можно указать ближайшую и проверить
результат. Иногда версию метаданных подменяют (модифицированная Unity), и тогда нужен
кастомный парсер — но магическое число и структура обычно сохраняются, потому что движку
нужна совместимость.

## Шаг 8: работа с обфусцированными именами

Многие игры включают обфускацию: имена классов превращаются в `a`, `b`, `c`. `dump.cs`
всё равно даёт структуру (какие методы есть, сколько аргументов), но без осмысленных имён.
Восстановить смысл помогают: строковые литералы (в `stringliteral.json`), которые
обфускатор не всегда прячет; порядок вызовов; сигнатуры методов.

```bash
$ grep -i 'purchase\\|premium\\|unlock' out/stringliteral.json | head
"premium_unlocked"
```

Строки часто остаются читаемыми даже при обфускации имён — и именно по ним находят нужный
метод. Так, найдя строку `premium_unlocked`, вы ищете метод, который её использует.

## Шаг 9: практический разбор — проверка покупки

Разберём типичную задачу: игра проверяет, куплен ли премиум. В `dump.cs` находим метод
`Shop__IsPremium` и переходим к его адресу в дизассемблере. Часто оказывается, что метод
читает флаг из локального хранилища или делает запрос к серверу. Если проверка только
локальная, её легко обойти хуком:

```javascript
Interceptor.attach(ptr("0x00A1B4D0"), {
  onLeave: function (retval) { retval.replace(1); }  // всегда premium
});
```

Если проверка серверная, обход сложнее: нужно либо подделать ответ сервера, либо найти, как
игра кэширует результат. Разница между локальной и серверной проверкой — ключевая при реверсе
игр, и она видна из того, есть ли в методе сетевой вызов.

## Шаг 10: чек-лист реверса IL2CPP

1. Извлечь `libil2cpp.so` и `global-metadata.dat` из APK.
2. Определить версию Unity/метаданных.
3. Прогнать Il2CppDumper и получить `dump.cs` + скрипты.
4. Найти целевые методы по строкам и именам.
5. Разобрать их в IDA/Ghidra по восстановленным символам.
6. Понять, локальная проверка или серверная.
7. При необходимости — хукнуть через Frida и проверить гипотезу.

Этот порядок экономит время: сначала карта (метаданные), потом цель (строки), потом код.

## Шаг 11: почему IL2CPP всё ещё реверсится

Иногда считают, что IL2CPP «защищает» C#-код. На практике он усложняет реверс, но не
скрывает структуру: метаданные нужны движку, а строки нужны логике. Поэтому IL2CPP — это
повышение порога, а не стена. Настоящая защита добавляется поверх: шифрование метаданных,
анти-отладка, проверка целостности. И даже тогда расшифрованные метаданные в итоге появляются
в памяти, потому что движок должен их прочитать, — и их можно снять дампом. Понимание этого
помогает реалистично оценивать трудозатраты на реверс конкретной игры.
'''

SDK = '''
## Шаг 7: юридические и приватностные аспекты

Сторонние SDK — не только техническая, но и юридическая тема. Регламенты (GDPR, CCPA) требуют,
чтобы разработчик знал, какие данные собираются и кому передаются. SDK, который отправляет
идентификатор устройства на сторонний сервер, делает разработчика ответственным за эту
передачу — даже если он не писал этот код. Поэтому инвентаризация SDK нужна не только
безопасникам, но и юристам.

Практический вывод: при аудите фиксируйте не только «какие SDK есть», но и «какие данные
каждый из них отправляет и куда». Это превращает технический отчёт в документ, пригодный для
оценки соответствия.

## Шаг 8: как SDK обходят ограничения

Интересная категория — SDK, которые ведут себя агрессивнее, чем ожидает разработчик. Некоторые
динамически загружают код, чтобы обойти статические проверки магазина; некоторые собирают
данные, не заявленные в политике; некоторые регистрируют свои компоненты (сервисы, ресиверы)
и работают в фоне. Всё это видно при анализе манифеста: сторонние `service`, `receiver`,
`provider` — частый признак «тяжёлого» SDK.

```bash
$ aapt dump xmltree app.apk AndroidManifest.xml | grep -iE 'service|receiver' | head
```

Если компонент принадлежит чужому пакету, стоит понять, зачем он и что делает. Иногда это
легитимная аналитика, иногда — избыточный сбор данных.

## Шаг 9: практический чек-лист инвентаризации

1. Список нативных библиотек (`lib/*.so`) и их назначение.
2. Список Java-пакетов сторонних вендоров (по именам классов).
3. Список сетевых доменов, к которым обращается приложение.
4. Версии SDK и известные CVE для них.
5. Компоненты манифеста, принадлежащие SDK.
6. Наличие динамической загрузки кода.

Пройдясь по этим пунктам, вы получите полную картину присутствующих SDK и их влияния на
безопасность и приватность приложения.

## Шаг 10: связь с supply-chain

Риски SDK — часть общей проблемы supply-chain. Атака на популярный SDK (или на его обновление)
компрометирует сразу тысячи приложений. Поэтому зрелые команды: фиксируют версии SDK, проверяют
их происхождение, следят за уведомлениями безопасности и минимизируют зависимости. Для
пентеста это означает, что находка «в приложении устаревший SDK с известной CVE» — не мелочь,
а реальный риск, который нужно зафиксировать с указанием версии и CVE. Так технический аудит
смыкается с управлением зависимостями, и обе стороны выигрывают от одной и той же
инвентаризации.
'''

add_before_quiz('mobile-il2cpp', IL2)
add_before_quiz('mobile-third-party-sdk', SDK)
print('done deepen b6-1')
