A['hardware-iso-tp'] = '''## Полный прогон: читаем длинный ответ целиком

Покажем весь путь на конкретном примере.

**Шаг 1. Запрос.** Отправляем UDS-запрос `22 F1 90` (ReadDataByIdentifier, DID F190) на адрес `0x7E0`.

**Шаг 2. First Frame.** ECU отвечает FF: первый байт `0x10`, длина `0x014` = 20 байт, затем 6 байт данных.

**Шаг 3. Flow Control.** Мы отвечаем `30 00 00` — «продолжай, без ограничения блока».

**Шаг 4. Consecutive Frames.** ECU шлёт CF с номерами 1, 2, 3. Каждый несёт 7 байт данных.

**Шаг 5. Сборка.** Берём 6 байт из FF и 7+7+7 из CF (минус первые байты-номера), получаем ровно 20 байт.

**Шаг 6. Интерпретация.** Первый байт `0x62` — положительный ответ на сервис `0x22`. Остальное — данные DID F190 (например, VIN или калибровка).

Если хотя бы один CF потерялся, сборка даст мусор — поэтому всегда проверяем номера последовательности. При ручном разборе удобно выписать байты в столбик и вычеркнуть служебные.

## Как это связано с другими уроками

ISO-TP — мост между «коротким» CAN и «длинной» диагностикой. Всё, что вы знаете про UDS-сервисы, работает поверх него. А сам ISO-TP — частный случай более общей задачи: сегментация и сборка. Ровно та же идея встретится в 6LoWPAN (фрагментация) и в TCP (сегменты). Увидев её здесь, вы узнаете в других протоколах.

## Врезка: а что если...

**...ответ ровно 8 байт?** Тогда это Single Frame `0x0N`, без FF/CF. Проверяйте первый байт: если он `0x0X`, всё в одном кадре.

**...ECU не отвечает?** Возможно, нужен `TesterPresent` (сервис `0x3E`), чтобы сессия не сбросилась, или не выполнены условия доступа.

**...нужно писать, а не читать?** Те же типы фреймов, но в обратную сторону: тестер шлёт FF/CF, ECU — FC.
'''

A['hardware-flexray'] = '''## Полный прогон: восстанавливаем расписание

Покажем методику целиком.

**Шаг 1. Разметка циклов.** Находим в дампе повторяющийся индикатор начала цикла. Все кадры между двумя такими индикаторами — один цикл.

**Шаг 2. Static-слоты.** В статическом сегменте кадры идут строго по порядку. Нумеруем их 1..N. Для каждого записываем ID и длину payload.

**Шаг 3. Владение.** Смотрим, какой ID повторяется в каком слоте от цикла к циклу. Так строится таблица «слот → узел».

**Шаг 4. Dynamic-сегмент.** Отмечаем, где начинается динамическая часть. Здесь порядок кадров зависит от загрузки; для анализа нужны minislot-и и приоритеты.

**Шаг 5. Данные.** Внутри payload ищем закономерности: счётчики, флаги, значения датчиков. Часто один слот — одно логическое сообщение.

**Шаг 6. Проверка гипотез.** Меняем входные данные (в симуляторе) и смотрим, какой слот изменился. Так подтверждается назначение.

Главное — не интерпретировать кадр в отрыве от цикла. Сначала сетка времени, потом смысл.

## Как это связано с другими уроками

FlexRay — противоположность LIN и CAN по философии: там среда достаётся «по случаю», здесь — по расписанию. Поняв TDMA, вы легче разберёте и промышленные сети (EtherCAT, PROFINET IRT), где та же идея жёсткого времени. А CRC-защита и sync-кадры вернутся в разговоре о TSN (Time-Sensitive Networking).

## Врезка: а что если...

**...слот пуст?** Узел молчит, выпал из сети или не сконфигурирован. Пустой слот — тоже информация.

**...кадр есть, но CRC неверный?** Помеха или вмешательство. Не толкуйте такой кадр как данные.

**...нужно понять, кто в сети?** Смотрите, какие слоты заполнены, и сопоставляйте ID с известными узлами из конфигурации.
'''

A['hardware-automotive-ethernet'] = '''## Полный прогон: от кабеля до команды

**Шаг 1. Физика.** Подключаем конвертер 100BASE-T1 ↔ 100BASE-TX. Проверяем линк: скорость 100 Мбит/с, master/slave определены.

**Шаг 2. Слой 2.** Снимаем дамп и смотрим VLAN-теги. Определяем, в каком домене мы оказались.

**Шаг 3. Слой 3/4.** Находим IP-адреса и порты. SOME/IP SD живёт на UDP 30490.

**Шаг 4. Discovery.** Собираем multicast-сообщения offer service. Строим карту сервисов: service ID, instance ID, версии.

**Шаг 5. Вызов метода.** Формируем SOME/IP-запрос с нужным service/method ID и полезной нагрузкой. Отправляем по UDP/TCP.

**Шаг 6. Проверка.** Если метод не защищён, действие выполняется. Если защищён — смотрим, где именно (SecOC, TLS) и можно ли это обойти.

Это полный цикл от провода до управления сервисом.

## Как это связано с другими уроками

Automotive Ethernet переносит автомобиль в мир IP. Отсюда прямой мост к DoIP (диагностика по IP) и AUTOSAR SecOC (защита сообщений). А привычные инструменты — tcpdump, Wireshark, nmap — снова работают, потому что под капотом обычные IP-пакеты. Это редкий случай, когда автомобильный навык пересекается с сетевым.

## Врезка: а что если...

**...нет линка?** Проверьте полярность пары и тип физики (100BASE-T1 vs 1000BASE-T1), а также, включено ли питание узла.

**...не видно SD?** Возможно, multicast не проходит через ваш конвертер. Попробуйте зеркалирование порта или пассивный TAP.

**...сервис защищён?** Смотрите на SecOC/TLS: иногда защита есть, но включена частично, и остаются незащищённые методы.
'''

