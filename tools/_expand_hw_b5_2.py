ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def append_before_quiz(lesson_id, add):
    path = os.path.join(ROOT, 'content', 'hardware', lesson_id + '.md')
    t = open(path, encoding='utf-8').read()
    m = re.search(r'^## Квиз\s*$', t, re.MULTILINE)
    if not m:
        raise SystemExit('no quiz in ' + lesson_id)
    out = t[:m.start()] + add.rstrip() + '\n\n' + t[m.start():]
    open(path, 'w', encoding='utf-8').write(out)
    print('expanded', lesson_id, '+', len(add.split()))


