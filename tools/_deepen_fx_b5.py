ADDS["mobile-ios-keychain-deep"] = """## Связка с бэкапом и облаком

Ключевой практический вопрос: где искать keychain. Есть три источника, и они дают
разные подмножества. Шифрованный бэкап содержит элементы, не помеченные
`ThisDeviceOnly`, и для их чтения нужен пароль бэкапа. Живое разблокированное
устройство с jailbreak даёт доступ к `keychain-2.db` целиком, но значения всё равно
зашифрованы классовыми ключами. iCloud Keychain синхронизирует часть элементов в
облако под отдельным ключом. Практический вывод: отсутствие элемента в одном
источнике ничего не доказывает. Если пароля бэкапа нет, проверь живое устройство;
если и его нет — проверь, не помечен ли элемент как `ThisDeviceOnly`, и не
синхронизируется ли он через iCloud. В отчёте всегда указывай, из какого источника
получен элемент и почему другие источники его не содержат: это снимает вопрос
«почему у вас нет пароля Wi-Fi», когда он просто не покидает устройство."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("layer5", lid, "+", len(add.split()), "tokens")
    return 0

if __name__ == "__main__":
    sys.exit(main())
