import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = os.path.join(ROOT, 'content', 'web')

def expand(fname, extra):
    p = os.path.join(W, fname)
    t = open(p, encoding='utf-8').read()
    t = t.replace('\n## Квиз', '\n' + extra.strip() + '\n\n## Квиз', 1)
    open(p, 'w', encoding='utf-8').write(t)

expand('web-f5-bigip.md', r"""
## Практический чек-лист по BIG-IP

Собираем всё в порядок действий. Сначала обнаружение: `nmap -p443,8443,8080 <ip>`, затем `curl -I https://<ip>/tmui/login.jsp` — заголовок `Server: BIG-IP` подтверждает продукт. Дальше версия: `/mgmt/tm/sys/version`, а если закрыт — статика `/tmui/` и `nuclei -tags f5`. Затем выбор CVE: для свежих сборок — CVE-2022-1388, для старых — CVE-2020-5902, для AJP — CVE-2023-46747. Проверка: запрос к `/mgmt/tm/util/bash` с заголовками обхода и пустым телом — ждём `200` вместо `401`. Доказательство: `{"command":"run","utilCmdArgs":"-c id"}` и фиксация `uid=0`. Пост-эксплуатация: `/config/bigip.conf`, ключи TLS, креды бэкендов. Отчёт: версия, CVE, запрос, ответ, импакт на ключи.

Такой порядок универсален для любого appliance — меняется только продукт и эндпоинты.

## Сравнение двух главных CVE F5

| CVE | Тип | Механизм | Pre-auth |
|---|---|---|---|
| CVE-2022-1388 | Auth bypass → RCE | header trust (`Connection`/`X-F5-Auth-Token`) | да |
| CVE-2020-5902 | RCE | path traversal в TMUI (`..%2f`) | да |
| CVE-2023-46747 | Auth bypass → RCE | AJP-конфузия | да |
| CVE-2021-22986 | RCE | iControl REST | да |

Обе главные уязвимости pre-auth, обе ведут к root. Поэтому F5 BIG-IP — одно из самых опасных устройств на периметре: незакрытый management-интерфейс означает полный контроль над балансировщиком, а через ключи TLS — и над трафиком.
""")

expand('web-fortinet-ssl-vpn.md', r"""
## Практический чек-лист по FortiGate

Порядок. Обнаружение: `curl -I https://<ip>/remote/login` — скрытый `Server`-заголовок и страница FortiGate. Версия: через traversal `lang=/../../../../../../etc/fortios_version` или по статике. Выбор CVE: для 5.x/6.0 — CVE-2018-13379 (traversal), для 6.0–7.2 — CVE-2022-40684 (auth bypass), для 7.x — CVE-2024-21762 (OOB write). Проверка traversal: чтение `/etc/passwd`. Доказательство: чтение нескольких строк `sslvpn_websession` с логинами. Пост-эксплуатация: конфиги с кредами к AD, сертификаты. Отчёт: версия, CVE, доказательство утечки, импакт, рекомендация сбросить пароли.

## Почему Fortinet — частый герой новостей

FortiGate — один из самых массовых firewall'ов в мире, и его VPN-портал открыт в интернет у сотен тысяч организаций. Это идеальные условия для pre-auth уязвимостей: одна CVE сканируется по всему интернету за дни. История CVE-2018-13379 и CVE-2022-40684 показала: если у периметрового устройства есть баг без аутентификации, он становится массовым почти мгновенно. Вывод для пентестера: версия FortiOS — одна из первых вещей, которую надо снять на периметре.
""")

