#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""_topup_cloud_d1b.py — second top-up pass for the D1 Azure lessons."""
import re

ADD = {
    'cloud-azure-synapse': """
## Связь с локальными и внешними данными

Synapse умеет читать не только озеро, но и внешние источники через linked services: другие базы, Key Vault, сторонние хранилища. Если linked service настроен на локальную базу через self-hosted integration runtime, то workspace получает путь во внутреннюю сеть. Для атакующего это расширяет радиус: компромисс workspace может дать не только облачные данные, но и доступ к корпоративным системам. Перечисляя linked services, отдельно отмечай, какие из них ходят за пределы облака, — именно они превращают облачный сервис в мост во внутреннюю инфраструктуру. И проверяй, какими правами эти подключения обладают: часто это не «только чтение», а полноценный доступ к источнику.
""",
    'cloud-azure-data-factory': """
## Параметры и динамическое содержимое

Конвейеры ADF поддерживают параметры и динамические выражения: имена источников, пути, запросы могут подставляться во время запуска. Это удобно и опасно одновременно. Если атакующий может передать значение параметра при запуске, он влияет на то, какие данные читаются и куда пишутся, — без изменения самого определения конвейера. Динамические выражения, собирающие пути или запросы из пользовательского ввода, дают инъекцию в конвейер: подставленное значение меняет цель операции. Проверяй, какие параметры конвейера можно задать извне и попадают ли они в пути хранилища или в тексты запросов без проверки. Это тот же принцип, что инъекция в SQL, только на уровне оркестратора данных.
""",
    'cloud-azure-ai-services': """
## Развёртывания моделей и версии

У ресурса Azure [OI] модели не «включены» сами по себе: их разворачивают как deployments с именем и версией модели. Ключ открывает все deployments, а значит, даёт доступ к разным моделям, включая дорогие и мощные. Разные версии модели ведут себя по-разному, и то, что заблокировано на одной, может пройти на другой. Если приложение ходит к конкретному deployment, атакующий с ключом может обратиться к тому же ресурсу напрямую и выбрать модель без guardrails приложения. Проверяй список deployments, их модели и версии: это карта возможностей ресурса. Иногда за одним ресурсом стоит несколько приложений, и ключ открывает их все сразу.
""",
    'cloud-azure-sql-mi': """
## Гибридный сценарий и Entra-only

Если база настроена на Entra-only аутентификацию, SQL-логины отключены, и пароль из конфига бесполезен. Тогда путь один — токен Entra: пользователя, приложения или managed identity. Это важно для приоритезации: сначала определи, какой режим аутентификации включён, и не трать время на перебор паролей, если логины выключены. В гибридных сценариях Managed Instance участвует в домене и может доверять локальному AD через Entra — тогда компромисс гибридной identity открывает и облачные базы. Смотри на связку «кто входит» и «откуда входит»: режим аутентификации и сетевые правила вместе определяют, возможен ли доступ вообще.
""",
}


def main():
    for lid, text in ADD.items():
        path = 'content/cloud/%s.md' % lid
        lesson = open(path, encoding='utf-8').read()
        m = re.search(r"^## Квиз\s*$", lesson, re.MULTILINE)
        assert m, path
        add = text.strip('\n')
        assert '## Квиз' not in add and '## Где пригодится' not in add
        out = lesson[:m.start()] + add + '\n\n' + lesson[m.start():]
        open(path, 'w', encoding='utf-8').write(out)
        print('topped up', path, '+%d words' % len(add.split()))


if __name__ == '__main__':
    main()
