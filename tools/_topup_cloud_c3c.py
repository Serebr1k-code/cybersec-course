def topup(lid, extra):
    p = os.path.join(CONTENT, lid + '.md')
    t = open(p, encoding='utf-8').read()
    marker = '## ' + extra[0][0].lstrip('# ')
    if marker in t:
        print('already', lid); return
    block = '\n\n'.join(h + '\n\n' + x.strip() for h, x in extra)
    t = t.replace('## Что мы теперь знаем', block + '\n\n## Что мы теперь знаем', 1)
    open(p, 'w', encoding='utf-8').write(t)
    print('topped up', lid)
for lid, extra in EXTRA.items():
    topup(lid, extra)
