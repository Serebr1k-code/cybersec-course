"""Expansion for stego B3-2 tool lessons (push each over 1200 real words)."""
import os
ROOT = "content/stego"

def expand(lid, extra):
    p = os.path.join(ROOT, lid + ".md")
    t = open(p, encoding="utf-8").read()
    key = extra.strip().splitlines()[0]
    if key in t:
        print("SKIP(done)", lid); return
    m = "## Что мы теперь знаем"
    open(p, "w", encoding="utf-8").write(t.replace(m, extra.strip() + "\n\n" + m, 1))
    print("EXPANDED", lid)

expand("stego-tool-stegoveritas", r'''
## Шаг 9: справочник флагов и режимов

Stegoveritas запускается как `stegoveritas [опции] файл`. Полезные режимы:

| Опция | Что делает |
|---|---|
| `-meta` | только метаданные (быстро) |
| `-l` / `--lsb` | только LSB-проверки |
| `-out dir` | куда складывать результаты |
| `-brute` | перебор паролей steghide по словарю |
| `-image` | полный прогон изображения |

В CTF чаще всего запускают полный режим без опций: инструмент сам решит, что
проверять. Если задача под таймером — начни с `-meta`, это секунды, а потом уже
полный прогон фоном.

## Шаг 10: как читать каталог results

После прогона Stegoveritas складывает артефакты в `results/`. Там могут быть:

- `metadata.txt` — вывод exiftool;
- `lsb/` — извлечённые LSB-потоки по каналам;
- `trailing/` — данные после EOF;
- `strings.txt` — все строки файла.

Именование помогает понять, **откуда** пришли данные. Если флаг нашёлся в
`trailing/`, не нужно смотреть LSB — гипотеза закрыта.

## Шаг 11: сравнение с ручным подходом

Может показаться, что Stegoveritas — «серебряная пуля». Но сравни:

| Подход | Плюс | Минус |
|---|---|---|
| Stegoveritas | быстро, всё сразу | шумно, медленно на больших файлах |
| Ручной | точно, под задачу | нужно знать, что искать |

Опытные игроки часто делают так: `file`, `exiftool`, `strings`, `binwalk` вручную,
и только если пусто — запускают Stegoveritas. Это быстрее на типовых задачах.

## Шаг 12: частые ошибки при использовании

Первая — запускать на огромных изображениях без таймаута (инструмент «висит»).
Вторая — доверять строке, похожей на флаг: проверяй формат (`nto{...}`) и контекст.
Третья — забыть, что `nothing` — это результат, а не сбой. Четвёртая — не сохранять
вывод: если флаг найден, запиши его в файл, иначе потеряешь.

## Шаг 13: расширение своими проверками

Stegoveritas — открытый Python-проект. Ты можешь дописать свою проверку (например,
для кастомного формата) и встроить её в конвейер. Это полезно в задачах, где автор
использовал нестандартный приём: автоматика его не знает, но твоя проверка — знает.

## Шаг 14: полный разбор примера

Соберём историю целиком. На входе `image.png`. Шаг 1: `stegoveritas image.png`
печатает список проверок. Шаг 2: видим `appended-data ... FOUND`. Шаг 3: читаем
смещение `0x4a2`. Шаг 4: `dd` достаёт байты. Шаг 5: получаем флаг
`nto{st3g0v3r1t4s_4ut0}`. Шаг 6: записываем в `found.txt`. Так автоматика
превращается в конкретный результат.
''')

