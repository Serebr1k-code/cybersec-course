def topup(lesson_id, extra):
    path = os.path.join(CONTENT, lesson_id + '.md')
    with open(path, encoding='utf-8') as f:
        text = f.read()
    marker = '## ' + extra[0][0].lstrip('# ')
    if marker in text:
        print('already topped up', lesson_id)
        return
    anchor = '## Что мы теперь знаем'
    block = '\n\n'.join(h + '\n\n' + t.strip() for h, t in extra)
    text = text.replace(anchor, block + '\n\n' + anchor, 1)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    print('topped up', lesson_id)


for lid, extra in EXTRA.items():
    topup(lid, extra)
