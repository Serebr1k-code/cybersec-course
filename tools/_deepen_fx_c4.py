ADDS = {}

ADDS["media-deepfake"] = r"""## Как работают генераторы: GAN и diffusion

Синтетические медиа создаются двумя основными классами моделей:

- **GAN** (генеративно-состязательные сети) — генератор создаёт изображение, дискриминатор
  пытается отличить его от настоящего. Так делают **подмену лица** (face swap): берут
  лицо-источник и «накладывают» на видео-цель.
- **Диффузионные модели** — изображение получается из шума за много шагов; дают более
  высокое качество, но оставляют свои артефакты.
- **Нейросетевые вокодеры/TTS** — клонирование голоса по нескольким секундам записи.

Каждая модель оставляет **отпечаток** (fingerprint) в пикселях, частотном спектре или
аудио-спектре. Именно эти отпечатки и ищет форензика. Полностью «идеального» deepfake
практически не бывает: где-то остаются швы — на границах лица, в текстуре кожи, в
синхронизации губ или в фоновом шуме.

## Частотный анализ и следы GAN

Свёрточные генераторы работают с **upsampling**, который оставляет периодические
паттерны в частотной области. Приём — построить спектр (FFT) и поискать характерные
«пики» или решётку:

```
$ python3 - <<'EOF'
import numpy as np, imageio.v2 as iio
img = iio.imread("frame.png", as_gray=True)
f = np.fft.fftshift(np.abs(np.fft.fft2(img)))
iio.imwrite("spectrum.png", np.log1p(f) / np.log1p(f).max() * 255)
EOF
```

У настоящих фото спектр спадает плавно; у синтетики появляются аномальные кольца/пики.
Дополнительно смотрят **PRNU** (photo-response non-uniformity) — «шум-отпечаток»
конкретной камеры: у сгенерированного кадра его нет или он не совпадает с камерой,
указанной в метаданных.

## Аудио: форманты и спектр

Клонированная речь выдаёт себя на нескольких уровнях:

- **спектрограмма** — у синтеза ровная «полоса» без естественных вариаций;
- **отсутствие дыхания и микропауз** — человек дышит между фразами;
- **форманты** (резонансные частоты гласных) — могут «плыть» или быть усреднёнными;
- **несоответствие фонового шума** между словами (склейки);
- **артефакты на границах** — щелчки, обрывы, изменение тембра.

```
$ sox voice.wav -n spectrogram -o spec.png
```

Сравнение спектрограмм подлинной и подозрительной записи часто сразу показывает
разницу. Аудио-форензика всегда комбинируется с анализом содержания и контекста.

## Метаданные, C2PA и происхождение

Современный подход — **провенанс** (provenance): подписанная история происхождения
контента. **C2PA / Content Credentials** прикрепляет к файлу манифест с указанием, кто
и чем создал контент, и подписывает его. Проверка:

```
$ c2patool clip.mp4
$ exiftool clip.mp4 | grep -iE 'make|model|software|encoder|create'
```

Признаки подозрительности: отсутствие «камерных» EXIF при заявленной съёмке на телефон,
несоответствие кодеков/encoder, несовпадение даты создания и метаданных, разрыв
провенанс-цепочки. Наличие валидных Content Credentials от доверенного источника —
сильный аргумент подлинности; их отсутствие — не приговор, но повод копать глубже.

## Практический разбор видео

Пришло видео с «признанием». Ход:

1. `ffprobe clip.mp4` — контейнер, кодеки, длительность, метаданные.
2. `ffmpeg -i clip.mp4 -vf fps=5 frame_%04d.png` — покадрово.
3. Просмотр кадров: границы лица, волосы, зубы, уши, освещение, «плавание» контуров.
4. Аудио: `sox`/спектрограмма — дыхание, паузы, фон.
5. Частотный анализ ключевых кадров (FFT-спектр).
6. Метаданные и C2PA.
7. Сопоставление с известными записями того же человека (если есть).

Итог — не «это точно фейк», а «есть N признаков синтетики, уверенность средняя».

## Частые ошибки

- **Искать «100% детектор».** Надёжного универсального детектора нет; вывод — всегда
  вероятность.
- **Игнорировать аудио.** Подделка часто скрыта в звуке, а не в картинке.
- **Верить метаданным на слово.** Их легко подделать; важна согласованность.
- **Судить по одному кадру.** Артефакты видны в динамике (дрожание между кадрами).
- **Забывать про контекст.** Кто, когда, откуда получил файл — часть доказательства.

## Что писать в отчёте

Опиши методы (покадровый просмотр, спектр, метаданные, C2PA), найденные артефакты с
указанием кадров/времени, результат проверки провенанса и итоговую оценку уверенности
(низкая/средняя/высокая). Не выдавай вероятность за приговор. Отметь, что осталось
непроверенным (например, нет оригинала для сравнения).

## Ограничения детекторов

Модели-детекторы обучаются на известных генераторах и плохо работают против новых;
к тому же их можно **обмануть** (adversarial-примеры). Высокое качество генерации
снижает число артефактов. Поэтому детектор — лишь один сигнал, а не вердикт. Настоящая
экспертиза — это комбинация инструментов, метаданных, контекста и, при необходимости,
заключения специалиста."""

ADDS["tool-xways"] = r"""## Рабочий процесс: от образа к отчёту

Типовой поток в X-Ways:

1. **Добавить образ** — `File → Open` или через «Add image»; выбрать раздел, если
   несколько (`Partition`).
2. **Индекс** — дать программе построить индекс (быстрее фильтры и поиск).
3. **Фильтры** — по типу, времени, размеру, сигнатуре.
4. **Восстановление** — отметить удалённые файлы, восстановить.
5. **Артефакты** — реестр, `$MFT`, `$UsnJrnl`, prefetch, LNK, почта.
6. **Отчёт** — сформировать таблицу найденного с метаданными.
7. **Экспорт** — выгрузить выбранные файлы и отчёт.

Ключевое преимущество — скорость и гибкость фильтров: из миллиона файлов остаются
десятки релевантных.

## Карвинг и восстановление удалённого

X-Ways предлагает несколько режимов:

- **Recover deleted** — восстановление по метаданным (`$MFT`), если запись цела;
- **Simultaneous search** — параллельный поиск по сигнатурам (карвинг);
- **File type signature search** — поиск файлов по «магическим» байтам, когда записи
  уничтожены.

Порядок: сначала метаданные (быстро и с именами), затем карвинг (медленно, без имён).
Восстановленные файлы помечаются как «deleted» — важно для отчёта: имя может быть
неверным, а содержимое обрезанным. Всегда проверяй восстановленные файлы на валидность
(`file`, открытие).

## Фильтры и галерея

Фильтры — главный инструмент сокращения объёма:

- **по категории типа** — показать только изображения/документы/исполняемые;
- **по времени** — окно инцидента (диапазон `Created`/`Modified`);
- **по размеру** — например, файлы > 1 МБ (утечки);
- **по пути** — `Temp`, `Downloads`, `Startup`;
- **по сигнатуре** — карвинг конкретного типа.

Галерея отображает превью изображений/видео — быстро видно контент. Комбинация фильтров
и галереи даёт возможность за минуты просмотреть релевантный срез диска.

## Реестр и системные артефакты

X-Ways парсит артефакты Windows **сам**, без сторонних утилит:

- **hives** реестра — `SAM`, `SYSTEM`, `SOFTWARE`, `NTUSER.DAT` (USB, службы, сети);
- **`$MFT`** — записи файлов, времена;
- **`$UsnJrnl`** — история создания/удаления/переименования;
- **prefetch** — запускавшиеся программы;
- **LNK** — недавние файлы и устройства;
- **почта и браузеры** — история, вложения, загрузки.

Это экономит время: вместо цепочки внешних парсеров — один интерфейс с общим индексом.

## Практический разбор

Изъят образ диска подозреваемого. Ход:

1. Добавляем образ, выбираем раздел Windows.
2. Фильтруем по времени — окно инцидента.
3. Смотрим категорию «исполняемые» и путь `Temp`/`Downloads`.
4. Восстанавливаем удалённые `.exe`/`.ps1`.
5. Проверяем `$UsnJrnl` на создание/удаление этих файлов.
6. Смотрим prefetch — запускались ли они.
7. Проверяем реестр — автозагрузка, USB.
8. Формируем отчёт с временами и хешами.

Так из образа извлекается история активности, включая попытки замести следы.

## Частые ошибки

- **Работать по оригиналу.** X-Ways читает образ read-only; не подключай оригинал на
  запись.
- **Игнорировать времена.** Файлы без фильтра по времени — это шум.
- **Верить именам восстановленных файлов.** После карвинга имена могут отсутствовать
  или быть неверными.
- **Забывать про `$UsnJrnl`.** Он показывает то, чего нет в `$MFT` (удалённые записи).
- **Не фиксировать версию.** Отчёты и хеши должны быть воспроизводимы.

## Сравнение с Autopsy и FTK

- **X-Ways** — лёгкий, быстрый, гибкие фильтры, хорош для больших образов и точечного
  анализа; интерфейс плотный, порог входа выше.
- **Autopsy** — бесплатный, GUI поверх Sleuth Kit, дружелюбнее, есть модули; медленнее.
- **FTK** — коммерческий, мощный, ориентирован на лабораторную экспертизу; дороже.

Выбор зависит от задачи и бюджета. Навык работы с X-Ways переносится: принципы (образ
read-only, фильтры, карвинг, парсинг артефактов) одинаковы во всех инструментах."""

ADDS["web-mongodb-redis"] = r"""## Redis: больше, чем RCE

Redis — не только хранилище. Атакующие используют его возможности:

- **запись файлов** — `CONFIG SET dir` + `SET`/`SAVE` позволяет писать в произвольный
  путь: SSH-ключ в `~/.ssh/authorized_keys`, cron-файл, webshell;
- **загрузка модулей** — `MODULE LOAD` исполняет произвольный `.so` на хосте (RCE);
- **репликация** — `SLAVEOF`/`REPLICAOF` на контролируемый «мастер» позволяет вытащить
  данные или подсунуть модуль;
- **Lua-скрипты** — `EVAL` исполняет Lua с доступом к `redis.call`;
- **открытые ключи** — `KEYS *` показывает всё содержимое.

Форензик-вывод: в логах Redis ищи `CONFIG`, `SAVE`, `BGSAVE`, `MODULE`, `SLAVEOF`,
`EVAL` — это действия, которых не должно быть при нормальной работе.

## Redis-форензика: RDB и AOF

Redis персистит данные двумя способами:

- **RDB** — бинарные снапшоты (точки во времени); имя по умолчанию `dump.rdb`;
- **AOF** — журнал команд (append-only file), где записана каждая операция.

```
$ redis-check-rdb /var/lib/redis/dump.rdb
$ head -c 200 /var/lib/redis/appendonly.aof
```

RDB даёт снимок состояния, AOF — историю команд (то, что нужно для таймлайна). Если
данные «пропали», их можно восстановить из RDB или прокрутить AOF. Место хранения
определяется `dir`/`dbfilename` в конфиге — проверь, не менял ли их атакующий.

## MongoDB: следы в файлах

MongoDB (движок WiredTiger) хранит данные в файлах `collection-*.wt` и журнале
`WiredTigerLog`/`journal`. Полезные артефакты:

- **`oplog.rs`** (коллекция в `local`) — журнал операций репликации: история
  вставок/обновлений/удалений;
- **`diagnostic.data`** — метрики и события сервера;
- **профилировщик** — `system.profile` пишет медленные/все операции (если включён);
- **audit log** — если включён, фиксирует аутентификацию и команды.

```
$ mongosh --host target
> use local; db.oplog.rs.find().sort({$natural:-1}).limit(5)
> use appdb; db.system.profile.find().limit(5)
```

По oplog видно, кто и когда менял данные; по профилировщику — подозрительные запросы.

## Аудит и профилирование

- **Redis** — `redis-cli MONITOR` (в реальном времени), лог-файл (`redis-server.log`),
  `INFO` (версия, конфиг, клиенты);
- **MongoDB** — audit log (Enterprise) и profiler (Community), `db.currentOp()`;
- **сетевой уровень** — кто подключался (netstat/логи ОС).

Если логи выключены, единственный путь — сетевой аудит ОС и RDB/AOF/oplog как «слепки»
истории. Поэтому в отчёте всегда указывай, какие источники были доступны.

## Практический разбор

Из приложения пропали данные, БД Redis/Mongo торчит наружу. Ход:

1. Проверяем открытость: `redis-cli -h target INFO` без `AUTH`; `mongosh` без логина.
2. Redis: ищем в логах `CONFIG`/`SAVE`/`MODULE` — признак записи файлов/RCE.
3. Смотрим `dir`/`dbfilename` — не изменены ли.
4. Mongo: `oplog.rs` — история операций; ищем `drop`/`delete` (anti-forensics).
5. Проверяем `system.profile` на подозрительные запросы.
6. Сетевой аудит: внешние IP, время.
7. Фиксируем найденное со ссылками на логи/файлы.

Так восстанавливается, что и кто делал с БД.

## Частые ошибки

- **Считать отсутствие пароля «нормой».** Открытый Redis/Mongo — уязвимость, а не
  настройка по умолчанию.
- **Игнорировать AOF/oplog.** Это главный источник истории.
- **Путать RDB и AOF.** RDB — снимок, AOF — журнал команд.
- **Забыть про `dir`/`dbfilename`.** Атакующий меняет их для записи файлов.
- **Не проверять сетевой доступ.** Внешние подключения — ключевой признак.

## Что писать в отчёте

Версии Redis/MongoDB, факт отсутствия/наличия аутентификации, изменённые параметры
(`dir`, `dbfilename`), найденные опасные команды (CONFIG/SAVE/MODULE/SLAVEOF),
историю из AOF/oplog, результаты профилирования и сетевые подключения. Каждый вывод —
со ссылкой на лог/файл. Отметь, какие логи были выключены и что осталось вне охвата."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
