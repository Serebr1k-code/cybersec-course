"""Expansion for MIS-GAP-4c lessons to >=1200 real words."""
import re

CONTENT = 'content/misc/'


def add(lesson, text):
    p = CONTENT + lesson + '.md'
    s = open(p, encoding='utf-8').read()
    add_txt = text.strip()
    m = re.search(r'^## Квиз\s*$', s, re.MULTILINE)
    out = s[:m.start()] + add_txt + '\n\n' + s[m.start():]
    open(p, 'w', encoding='utf-8').write(out)
    print('expanded', lesson)


add('misc-emulator-dev', '''
## Разбор реального примера: OOB в загрузчике ROM

Представим конкретную уязвимость, чтобы увидеть теорию в действии. Эмулятор читает из ROM число банков и вычисляет размер:

```c
uint16_t banks = rom[4];
uint32_t size = banks * 16384;
uint8_t *buf = malloc(size);
memcpy(buf, rom + 16, size);   // читает size байт из rom
```

Если `rom` меньше, чем `size`, `memcpy` прочитает за границей входного буфера — утечка памяти хоста в буфер гостя. Атакующий управляет полем `banks` (байт 4 ROM), поэтому может запросить огромный размер. Это классический «trust the header» баг: эмулятор доверяет данным картриджа.

Починка проста — проверять, что `size` не превышает длину файла:

```c
if (size > rom_len - 16) { fprintf(stderr, "bad ROM size\\n"); exit(1); }
```

Но в реальных проектах такие проверки часто забывают, и именно они становятся CVE.

## Как устроен PPU и почему тайминги важны

Кроме процессора эмулятор содержит PPU (picture processing unit) — графический чип. Он рисует сканлайн за сканлайном и генерирует прерывания. Точные тайминги критичны: игры синхронизируются с PPU. Ошибки в счётчике циклов приводят к рассинхронизации, зависаниям и, что важнее для безопасности, к гонкам в состоянии — если два «потока» эмуляции (CPU и PPU) обращаются к памяти без согласования, возможен use-after-free. Поэтому качественные эмуляторы либо исполняют всё в одном потоке, либо используют точную синхронизацию.

## Практические заметки по фаззингу

- Начинай с функций, принимающих недоверенные данные: загрузчик ROM, обработчики MMIO, загрузчик save state.
- Сохраняй вход, который привёл к падению, и минимизируй его (`afl-tmin`).
- Классифицируй падение в отладчике: OOB чтение, OOB запись, UAF, переполнение.
- Для эмулятора консоли полезно фаззить сам ROM-формат: заголовок, размеры банков, trainer.
- Если эмулятор на Rust/Go — ищи `unsafe`/cgo и фаззь именно эти места.

## Итоговый разбор по шагам

Разбор эмулятора всегда начинается с формата входа: как он читает ROM и состояние. Затем ищем арифметику по адресам и размерам — там живут OOB. После этого фаззим загрузчик и обработчики устройств. Найденное падение классифицируем и превращаем в примитив: утечку, запись или исполнение. Правильный вывод — не «я уронил эмулятор», а «вот конкретная проверка, которой не хватает, и вот как её активировать».
''')

