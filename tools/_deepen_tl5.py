ADD['tl-entity-resolution'] = """
## Практические сценарии

Разберём два частых сценария, где разрешение сущностей решает исход разбора.

**Сценарий 1: утёкший ключ.** В репозитории найден приватный SSH-ключ с комментарием
`jsmith@corp.local`. Нужно понять, чей это ключ и где использовался. Мостики: комментарий
ключа → почта → логин → SID → хосты, куда этот ключ давал доступ. Цепочка длинная, но каждый
шаг подтверждается артефактом: `authorized_keys` на серверах, лог входов с этим ключом,
учётная запись в AD.

**Сценарий 2: общий NAT.** Внешний адрес `203.0.113.5` фигурирует в логах, но за ним —
корпоративный NAT, а значит, десятки внутренних хостов. Приписать адрес одному человеку
нельзя. Нужны логи NAT (какой внутренний IP использовал внешний в это время) и DHCP-логи
(какому хосту принадлежал внутренний IP). Только тогда связка становится доказательной.

## Инструменты разрешения сущностей

Хотя entity resolution — во многом ручная работа, есть помощники:

- **графовые базы** (Neo4j) — хранят сущности и связи, позволяют искать пути;
- **таблицы соответствий** — простой CSV/SQL со связками идентификаторов;
- **SIEM-корреляция** — автосвязывание по общим полям;
- **AD-утилиты** — разрешение SID, групп, членства.

Для небольших инцидентов достаточно аккуратной таблицы: колонки — идентификатор, тип,
источник, окно времени. Главное — не терять обоснование каждой связки.

## Чек-лист разрешения сущностей

Перед тем как приписать действие конкретному субъекту, проверь:

- собран ли **SID/UID** (сильный ключ), а не только логин;
- есть ли **мостик** между разными идентификаторами;
- учтено ли **время** (окно аренды IP, сессия);
- не является ли учётка **общей/сервисной**;
- подтверждена ли связка **не одним** источником;
- зафиксирован ли **уровень уверенности**.

Если хотя бы один пункт не выполнен — атрибуция преждевременна, и её нужно смягчить в отчёте.

## Почему это защищает от ошибок

История знает немало случаев, когда действия приписывались не тому человеку из-за поспешной
связки по слабому ключу. Цена ошибки — испорченная репутация, неверные кадровые решения,
проигранное дело. Дисциплина разрешения сущностей — это не бюрократия, а защита от именно
таких ошибок.

Практическое правило: **сомневаешься — понижай уверенность**. Лучше честное «предположительно»,
чем уверенное «это был он», которое рассыплется при первой проверке.

## Связь с таймлайном и provenance

Entity resolution не существует в вакууме. Она опирается на таймлайн (когда субъект был где)
и питает provenance (на чём основана связка). Вместе эти три вещи — время, сущности и
происхождение — превращают набор разрозненных артефактов в доказуемую картину инцидента.

Без разрешения сущностей таймлайн знает «что» и «когда», но не «кто». Без provenance он не
знает, насколько этому можно верить. Только все три вместе дают вывод, который выдержит
проверку.

## Резюме

Разрешение сущностей — это дисциплина доказательной атрибуции: сильные ключи, мостики между
идентификаторами, учёт времени, осторожность с общими учётками и явный уровень уверенности.
Она защищает от ложных объединений и превращает технические следы в ответ на вопрос «кто».
"""

ADD['tl-visualization'] = """
## Дашборды и совместная работа

В командном расследовании визуализация — это ещё и средство совместной работы. Хороший
дашборд позволяет нескольким аналитикам смотреть на одну картину:

- **общая гистограмма** — все видят одно окно событий;
- **заметки и теги** — аналитики помечают находки для коллег;
- **сохранённые представления** — часто используемые фильтры под рукой;
- **ссылки на события** — можно переслать конкретное событие, а не описывать словами.

Timesketch и подобные платформы дают это «из коробки». Ценность в том, что выводы не
дублируются, а накапливаются: один аналитик помечает подозрительный процесс, другой — его
сетевую активность, и картина собирается сообща.

## Типичные ошибки визуализации

- **Слишком много данных на одном графике.** Пять источников на одной гистограмме дают шум,
  а не инсайт. Разделяй по источникам.
- **Неправильный масштаб.** На недельном графике секундный всплеск не виден. Масштаб должен
  соответствовать вопросу.
- **Игнорирование базовой линии.** Без неё нормальный cron выглядит как атака.
- **Отсутствие подписей.** График без осей и единиц бесполезен для читателя.
- **Красота вместо смысла.** Наглядность должна служить вопросу, а не украшению отчёта.

## От графика к выводу

График — не вывод, а его подспорье. Порядок такой: график → подозрительное окно → фильтр →
события → проверка → вывод. Пропуск шагов приводит к поспешным заключениям по «страшному
всплеску», который на деле оказался плановым бэкапом.

Хороший аналитик всегда перепроверяет то, что подсказала картинка: открывает события,
смотрит контекст, сопоставляет с базовой линией. Визуализация направляет, но не решает.

## Визуализация для разных аудиторий

Одна и та же находка подаётся по-разному:

| Аудитория | Что показать |
|-----------|--------------|
| Технический аналитик | полный таймлайн, фильтры, граф |
| Руководство | короткая лента ключевых событий |
| Юрист | события с источниками и временем |
| Клиент | обезличенная хронология |

Умение переключать уровень детализации — часть мастерства. Полный таймлайн для руководства
так же бесполезен, как краткая выжимка для технического разбора.

## Резюме

Визуализация таймлайна — это инструмент сужения внимания, совместной работы и объяснения.
Она опирается на подготовленные данные и базовую линию, а её результат всегда перепроверяется
по событиям. Правильно выбранное представление под нужную аудиторию превращает миллион строк
в понятную и убедительную историю.
"""

ADD['tl-provenance'] = """
## Provenance и воспроизводимость

Ключевое свойство хорошего разбора — **воспроизводимость**: другой специалист по описанию
может повторить путь и получить тот же результат. Provenance делает это возможным. Если в
отчёте указано «событие взято из auth.log хоста 10.0.0.5 методом grep Accepted», проверка
займёт минуты.

Воспроизводимость ценна и внутри команды: когда разбор передают от смены к смене, коллега не
начинает с нуля, а проверяет и продолжает. Без provenance каждая передача — это пересказ
памяти, где детали теряются и искажаются.

## Стоимость улики и её вес

Не все доказательства равноценны. Условный «вес» зависит от:

- **надёжности источника** (системный лог весомее показаний);
- **независимости** (внешний дамп весомее внутреннего лога);
- **сохранности** (с хешем весомее, чем без);
- **подтверждения** (несколько источников весомее одного).

Этот вес и выражается уровнем уверенности. В отчёте сильные утверждения опирают на тяжёлые
улики, а слабые — помечают как предположения. Так читатель видит, где твёрдая почва, а где
песок.

## Как не завысить уверенность

Самая частая ошибка — выдать желаемое за доказанное. Противоядия:

- формулируй утверждение **ровно настолько сильно, насколько позволяют данные**;
- отделяй «файл создан» от «файл — вредонос»;
- если вывод держится на интерпретации — называй это интерпретацией;
- перед отправкой отчёта перечитай сильные утверждения и спроси: «чем это доказано?».

Привычка задавать себе этот вопрос отличает аккуратного аналитика от самоуверенного.

## Резюме

Provenance — это то, что делает форензик наукой, а не мнением: у каждого факта есть
происхождение, метод и оценка надёжности; наблюдение отделено от интерпретации; противоречия
показаны; уверенность соответствует весу улик. Вместе с таймлайном и разрешением сущностей
provenance замыкает триаду, на которой стоит доказуемый вывод.
"""

