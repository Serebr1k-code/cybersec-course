EXPANSIONS['misc-font-parsing'] = '''
## Как устроен разбор таблиц в парсере

Парсер шрифта читает заголовок, затем Table Directory, затем каждую таблицу по её смещению. Ошибка в одном смещении сдвигает разбор и может привести к чтению за границами — отсюда исторические уязвимости. Для задач полезно знать порядок: сначала `head` (масштаб и формат `loca`), потом `maxp` (число глифов), потом `loca`, потом `glyf`. Только с этими четырьмя таблицами можно обойти все контуры.

## Шрифт как носитель кастомного формата

Иногда в шрифте прячут не текст, а целую структуру: набор глифов кодирует байты по их контурам, или порядок глифов задаёт сообщение. Тогда задача — восстановить кодировку и декодировать. Подход: извлечь все глифы (`fontTools`), сравнить их, найти нестандартные, сопоставить с ASCII. Это смесь форензики и реверса формата.

## Валидация шрифта

Перед разбором полезно проверить целостность: совпадают ли смещения таблиц, нет ли выхода за пределы файла, корректен ли `loca`. `fontTools` при загрузке делает часть проверок и бросает исключение на битом шрифте. Если файл «не открывается» — это тоже сигнал: возможно, структура подделана намеренно, и данные лежат в нестандартном месте.

## Итог

Разбор шрифтов учит главному приёму форензики контейнеров: найди оглавление (Table Directory), пройди по элементам, проверь границы, посмотри на «щели» и хвост. Этот приём работает со шрифтами, архивами, медиа-контейнерами и прошивками. Один раз поняв принцип, ты разбираешь любой табличный формат.
'''

def insert_before_quiz(path, extra):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    idx = text.find('\n## Квиз')
    if idx < 0:
        raise SystemExit('no Квиз in ' + path)
    text = text[:idx] + '\n' + extra.strip() + '\n' + text[idx:]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)

for lid, extra in EXPANSIONS.items():
    insert_before_quiz(os.path.join(CONTENT, lid + '.md'), extra)
    print('final', lid)
print('b5 final done')
