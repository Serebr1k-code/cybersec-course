ADDS["mobile-ios-keychain-deep"] = """## Итог: что реально можно извлечь

Из keychain извлекается ровно то, что разрешено моделью защиты. Из шифрованного
бэкапа доступны элементы, не помеченные `ThisDeviceOnly`, — включая пароли Wi-Fi и
часть токенов приложений. С живого разблокированного устройства с jailbreak
доступно больше, но SEP-привязанные ключи всё равно неэкспортируемы. Метаданные
(`svce`, `acct`, `agrp`) читаются всегда и часто дают ответ и без расшифровки
значения. В отчёте различай три состояния: «значение извлечено», «известен только
сервис и аккаунт» и «недоступно из-за SEP/iCloud». Такая честная градация важнее,
чем громкое «взломали keychain», за которым на деле стоит лишь список служб."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("layer4", lid, "+", len(add.split()), "tokens")
    return 0

if __name__ == "__main__":
    sys.exit(main())
