#!/usr/bin/env python3
"""Batch C1c — third layer for tool-fiwalk, mem-macos, doc-odf."""
from __future__ import annotations
import re, sys

ADDS = {}

ADDS["tool-fiwalk"] = """## NTFS-специфика: потоки и журнал изменений

На NTFS у файла может быть несколько **потоков** (Alternate Data Streams, ADS). Классика
малвари — спрятать данные в `file.txt:hidden`. fiwalk показывает потоки отдельными
записями с именем вида `file.txt:stream`. Если видишь двоеточие в имени — это ADS.

Второй важный артефакт NTFS — журнал `$UsnJrnl` (Update Sequence Number). Он хранит
историю **создания, переименования и удаления** файлов, даже если запись MFT уже
переиспользована. fiwalk его не разбирает; для этого нужен `MFTECmd`/`usnparser`:

```
$ MFTECmd.exe -f '$UsnJrnl:$J' --csv out --csvf usn.csv
```

Связка «инвентарь fiwalk + история $UsnJrnl» даёт почти полный таймлайн файловых
операций, включая следы anti-forensics (быстрое создание и удаление файла).

## Типичные вопросы и ответы

- **Можно ли fiwalk на живой системе?** Нет, он работает по образу; для живой системы
  есть другие средства (например, `tsk` по `\\\\.\\C:` с осторожностью).
- **Даёт ли fiwalk содержимое файлов?** Нет, только метаданные и byte_runs; контент —
  через `icat` или `dd` по `img_offset`.
- **Почему файл есть в XML, но не открывается?** Он удалён (`meta_type=0`) или
  фрагментирован; восстанавливай через `tsk_recover`/карвинг.
- **Где времена в локальной зоне?** fiwalk всегда UTC; переводи сам.
"""

ADDS["mem-macos"] = """## Быстрый триаж: чек-лист

Когда времени мало, а дамп большой, иди по чек-листу:

1. Зафиксируй хеш и версию ОС.
2. Прогони `strings` по C2-индикаторам (IP, домены, URL).
3. Найди подозрительные процессы и их родителей.
4. Проверь persist-точки (`LaunchDaemons`/`LaunchAgents`).
5. Выпиши сетевые соединения.
6. Сопоставь всё в таймлайн.

Этот порядок отсекает 90% шума и оставляет релевантные артефакты. Дальше — углублённый
разбор конкретных находок.

## Ограничения метода

Память macOS даёт **снимок момента**, а не историю: что было до снятия — неизвестно.
Сжатые страницы и зашифрованный swap скрывают часть данных. Отсутствие символов
ограничивает плагины. Поэтому память всегда дополняют артефактами с диска
(`unified log`, plist, кэши) и сетевыми логами. В отчёте честно перечисли пробелы —
это повышает доверие к остальным выводам.
"""

ADDS["doc-odf"] = """## Разбор таблиц, формул и графиков

ODF-таблицы лежат в `content.xml` как `table:table` с ячейками `table:table-cell`:

```xml
<table:table table:name="Лист1">
  <table:table-row>
    <table:table-cell office:value-type="float" office:value="40817">
      <text:p>40 817</text:p>
    </table:table-cell>
  </table:table-row>
</table:table>
```

Значение хранится и как текст, и как атрибут `office:value` — это позволяет извлекать
числа без парсинга форматирования. Формулы хранятся в `table:formula` (синтаксис
`of:=SUM([.A1:.A9])`). Диаграммы — в `Object N/` как внедрённые объекты со своими
данными в `content.xml` (элемент `chart:chart`).

Для анализа финансовых документов удобно выгрузить все `office:value`:

```
$ unzip -p book.ods content.xml | grep -o 'office:value="[^"]*"' | head
```

## Частые вопросы и ошибки

- **Путают ODF и OOXML.** `.odt` — это ODF (ISO), `.docx` — OOXML (ECMA). Метаданные
  лежат в разных частях; не ищи `docProps/` в `.odt`.
- **Забывают про `manifest.xml`.** Именно там указано, какие части зашифрованы и какие
  есть на самом деле. Если части нет в манифесте — она «лишняя» и подозрительна.
- **Считают, что ZIP-структура всегда одна.** Порядок частей и сжатие могут
  отличаться; полагайся на манифест и имена, а не на порядок.
- **Не проверяют внешние ссылки.** `xlink:href` может указывать на удалённый ресурс —
  это и след, и потенциальная утечка (при открытии документ «дёргает» URL).
- **Игнорируют `settings.xml`.** Там бывает информация о последнем пользователе и
  позиции курсора — косвенный признак, кто и где работал с файлом.
"""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
