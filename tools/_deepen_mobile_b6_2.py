"""Deepen MOB-GAP-6 (android-forensics-tools) to >=1200 real content words."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')


def add_before_quiz(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already deepened):', lid)
        return
    i = t.index('\n## Квиз')
    t = t[:i] + '\n' + extra.strip() + '\n' + t[i:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


FOR = '''
## Шаг 7: где живут самые ценные артефакты

Чтобы не тонуть в файлах, полезно знать, где искать. Основные места в `userdata`:

| Путь | Что там |
|---|---|
| `/data/data/<pkg>/databases/` | SQLite-базы приложения |
| `/data/data/<pkg>/shared_prefs/` | XML-настройки |
| `/data/media/0/` | пользовательские файлы (фото, загрузки) |
| `/data/system/` | системные БД (учётки, настройки) |
| `/data/misc/` | Wi-Fi, VPN, keystore-метаданные |

Самое ценное для «что происходило» — базы приложений (сообщения, звонки, браузер) и
`/data/system`, где лежат системные события. Именно оттуда строится таймлайн.

## Шаг 8: разбор SQLite и удалённых записей

Базы SQLite — основной источник. Важно помнить, что `DELETE` в SQLite не всегда стирает данные:
записи остаются в свободных страницах файла, и их можно восстановить. Инструменты вроде
`sqlite3` с `.recover` или специализированные парсеры извлекают удалённое.

```bash
$ sqlite3 -readonly msg.db '.recover' | grep -i 'delete' | head
```

Это важно для форензики: удалённое сообщение часто можно восстановить из свободных страниц,
и это меняет выводы расследования.

## Шаг 9: работа с образами и хешами

Дисциплина работы с образами критична. Правильный порядок:

1. Снять образ (`dd`, EDL, `adb backup`).
2. Посчитать хеш и записать его.
3. Работать только с копией образа.
4. Для каждого извлечённого артефакта фиксировать источник.

Хеш образа доказывает, что копия не изменялась, — это требование любого форензического
заключения. Без него результаты могут быть оспорены.

## Шаг 10: анализ памяти устройства

Помимо диска, ценна оперативная память: в ней живут расшифрованные данные, ключи, активные
соединения. На Android дамп памяти делается через root (`/proc/<pid>/mem`) или специальные
инструменты (LiME-подобные). Volatility и его Android-профили помогают разобрать дамп: найти
процессы, сокеты, строки.

Дамп памяти особенно полезен против приложений с шифрованием: на диске данные зашифрованы, а в
памяти — открыты. Поэтому при реагировании на инцидент память снимают **до** выключения
устройства, иначе она теряется.

## Шаг 11: чек-лист форензики Android

1. Зафиксировать состояние (скриншоты, режим, версия).
2. Снять образ диска и дамп памяти, посчитать хеши.
3. Разобрать ФС (sleuthkit/Autopsy), извлечь артефакты.
4. Парсить базы приложений и системные БД.
5. Попробовать восстановить удалённое.
6. Проверить компрометацию (MVT).
7. Свести всё в таймлайн.

Такой порядок гарантирует, что анализ воспроизводим и доказателен, а не «мы посмотрели пару
файлов».

## Шаг 12: почему это важно для пентеста

Мобильная форензика — обратная сторона пентеста. Там, где пентестер ищет, как получить данные,
форензик ищет, что уже произошло. Навыки общие: понимание, где приложение хранит данные, как
оно их шифрует и как общается. Поэтому специалисты часто совмещают обе роли. Для практики
полезно уметь пройти путь от образа устройства до таймлайна: это закрепляет понимание
мобильных артефактов, которое пригодится и в атаке, и в защите.
'''

add_before_quiz('mobile-android-forensics-tools', FOR)
