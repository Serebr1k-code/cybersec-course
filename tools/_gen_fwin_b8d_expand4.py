#!/usr/bin/env python3
"""Fourth top-up for batch D."""
import re

ADD = {}

ADD["win-wmi-persistence"] = r'''
## Практический совет по обнаружению

Простейший способ не пропустить WMI-персистентность — включить её проверку в стандартный
чек-лист расследования наравне с задачами и службами. Достаточно одной команды, перечисляющей
консьюмеры в `root\subscription`, чтобы отсеять большинство случаев: если консьюмеров нет
вообще, вопрос закрыт. Если есть — разбирай каждую связку. Такой подход дёшев по времени и
даёт высокую отдачу, потому что WMI-закрепление встречается редко, но именно оно чаще всего
остаётся незамеченным. Держи эту проверку в привычке, и ты не пропустишь самый скрытный
механизм автозапуска.
'''

ADD["win-service-artifacts"] = r'''
## Практический совет по приоритизации

Служб на типичной машине сотни, и проверять все подряд неэффективно. Приоритизируй так:
сначала службы с `ImagePath` вне `System32` (явная аномалия), затем службы, изменённые
незадолго до инцидента (по `LastWrite` ключа), затем службы с нестандартным `ServiceDll`,
затем службы с ослабленными дескрипторами. Такой порядок быстро выделяет подозрительное,
даже когда служб много. Дополнительно сверь список с эталоном «чистой» установки: всё, что
отличается, — на проверку. В отчёте объясни, почему та или иная служба попала в приоритет, —
это показывает методичность анализа.
'''

ADD["win-boot-config"] = r'''
## Практический совет по сбору артефактов загрузки

Загрузочные артефакты хрупки: неправильные действия (например, `bootrec /rebuildbcd`) затирают
улики. Поэтому строй работу так. Первым делом сними копии BCD, загрузчиков и, если возможно,
переменных прошивки. Только после этого анализируй. Если нужно восстановить систему, делай это
на копии или после полного документирования состояния. В отчёте укажи, что копии сняты до
восстановления, — это подтверждает сохранность доказательств. Такой порядок отличает
аккуратное расследование от действий, уничтожающих улики.
'''

for lid, add in ADD.items():
    p = f"content/forensics/{lid}.md"
    t = open(p, encoding="utf-8").read()
    m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
    open(p, "w", encoding="utf-8").write(t[:m.start()] + add.strip() + "\n\n" + t[m.start():])
    print("topup2", lid)
