#!/usr/bin/env python3
"""Batch C2d — final top-off for cloud-storage, container-runtime, mal-script-js."""
from __future__ import annotations
import re, sys

ADDS = {}

ADDS["cloud-storage"] = r"""## Почему это важно

Объектные хранилища — это «свалка» корпоративных данных: бэкапы, дампы БД, документы,
ключи. Именно поэтому они первая цель атакующих и частая причина утечек. Умение
читать логи доступа, проверять публичность и восстанавливать версии превращает
облачное хранилище из чёрного ящика в источник доказательств. Без логов инцидент
остаётся «что-то утекло»; с логами — становится «кто, когда, чем и сколько»."""

ADDS["forensics-cloud-container-runtime"] = r"""## Почему это сложно

Контейнеры разделяют ядро хоста, поэтому граница между «внутри» и «снаружи» тоньше,
чем у виртуальных машин. Побег может произойти через уязвимость рантайма, через
небезопасную конфигурацию или через ошибку в самом приложении, получившем доступ к
сокету. Из-за этого расследование всегда идёт на **двух уровнях** — контейнер и хост —
и требует сопоставления версий, конфигураций и логов. Хорошая новость: почти все
следы побега видны на хосте, если знать, куда смотреть: бинарники рантайма, процессы
вне namespace, монтирования и аудит exec."""

ADDS["mal-script-js"] = r"""## Почему это распространено

Скриптовая малварь не требует компиляции, легко обфусцируется и часто проходит
мимо антивирусов, которые ищут сигнатуры бинарников. Windows Script Host, PowerShell
и shell есть на любой системе, поэтому атакующему достаточно одной строки, чтобы
загрузить второй этап. Именно поэтому фишинговые вложения всё чаще — `.js`, `.hta`,
`.ps1` и `.lnk`. Понимание приёмов обфускации и умение декодировать без запуска —
базовый навык форензик-аналитика."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
