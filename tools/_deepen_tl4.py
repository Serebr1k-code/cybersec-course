"""Deepen timeline lessons — batch 4 (top-ups)."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content', 'forensics')
ADD = {}

ADD['tl-timezone-dst'] = """
## Один момент — много представлений

Полезная мысль напоследок: один и тот же момент времени существует объективно, а его
представлений — бесконечно много. `11:02 UTC`, `14:02 Москва`, `03:02 Лос-Анджелес` — это
один и тот же миг, записанный по-разному. Ошибка аналитика — принять разные представления за
разные события. Правило простое: сначала приведи к единой шкале, потом сравнивай.
"""

ADD['tl-clock-skew'] = """
## Порядок работы с временем

Итоговая последовательность для любого таймлайна: определи пояс каждого хоста, приведи всё
к UTC, измерь и скорректируй дрейф, и только затем сравнивай события. Пропуск любого шага
делает последующие выводы ненадёжными — а исправлять ошибку времени задним числом почти
невозможно.
"""

ADD['tl-cross-artifact'] = """
## Ключи корреляции: подробнее

Выбор ключа определяет, какие связи ты найдёшь. Разберём типовые ключи и что они связывают:

| Ключ | Связывает |
|------|-----------|
| PID | процесс ↔ файлы ↔ сокеты |
| путь | файл ↔ процесс ↔ реестр |
| SID/UID | действия ↔ учётная запись |
| IP:port | процесс ↔ внешний адрес |
| hostname | хост ↔ DNS ↔ логи |
| hash | файл ↔ база IOC |

Важно: ключ действует **в пределах времени жизни**. PID переиспользуется после завершения
процесса, IP выдаётся на время аренды. Поэтому связку всегда проверяют на пересечение
интервалов: если окна не пересекаются — ключ совпал случайно.

## Ручная корреляция: пример

Иногда инструментов под рукой нет, и связать события приходится вручную. Порядок:

```
$ grep -n "1842" proc.txt        # найти PID во всех артефактах
$ grep -n "/dev/shm/.index" *    # найти путь во всех артефактах
$ grep -n "203.0.113.9" *        # найти внешний адрес
```

Каждый `grep` вытаскивает строки, где встречается ключ. Собрав их вместе и отсортировав по
времени, ты получаешь ручной супер-таймлайн. Это медленнее автоматизации, но на маленьком
эпизоде часто быстрее, чем настраивать платформу.

## Почему совпадение по времени — не связь

Соблазн велик: два события в одну секунду «наверняка связаны». Но совпадение по времени без
общего ключа ничего не доказывает. В системе одновременно происходят тысячи событий, и часть
из них совпадёт случайно.

Правило: **связь обосновывается ключом**, а время лишь упорядочивает уже связанные события.
Если ключа нет, событие может быть «рядом», но не «вместе».

## Как проверять корреляцию

После сборки супер-таймлайна прогони проверки:

- у каждого ребра связи есть источник (provenance);
- временные окна пересекаются;
- нет «невозможных» последовательностей;
- ключ не переиспользовался между разными сущностями.

Эти проверки отсеивают ложные связи и делают вывод защищаемым. Без них красивый граф может
оказаться набором совпадений.
"""

for lid, add in ADD.items():
    path = os.path.join(C, lid + '.md')
    t = open(path, encoding='utf-8').read()
    m = re.search(r'^## Квиз\s*$', t, re.MULTILINE)
    t = t[:m.start()] + add.strip() + '\n\n' + t[m.start():]
    open(path, 'w', encoding='utf-8').write(t)
    print('deepened', lid)
