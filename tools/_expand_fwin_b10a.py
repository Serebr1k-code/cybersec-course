ADD["linux-auditd-deep"] = r'''
## Как писать правила аудита

Аудит бесполезен без правил — по умолчанию он почти ничего не пишет. Базовые правила задают,
**что** перехватывать:

```
-w /etc/passwd -p wa -k passwd_changes
-a always,exit -F ar -S execve -k exec
-a always,exit -F ar -S openat -F exit=-EACCES -k access_denied
```

Первое правило следит за записью (`w`) и изменением атрибутов (`a`) файла `/etc/passwd` с
ключом `passwd_changes`. Второе логирует каждый `execve` (запуск программы) с ключом `exec`.
Третье — неуспешные `openat` (отказы в доступе). Загруженные правила можно посмотреть через
`auditctl -l`. Если правил не было — детального следа не будет, и это ограничение нужно
учитывать при оценке полноты картины.

## Разбор случая: компромисс веб-сервера

Полный сценарий по нашим строкам: `uid=33` (`www-data`) запускает `curl` с ключом `recon` —
это веб-процесс скачивает скрипт. Через несколько секунд `bash /tmp/p.sh` уже от `uid=0` —
скрипт выполнился с повышением прав. Следом `nc` с ключом `reverse` от root — установка
реверс-шелла. Цепочка восстанавливается **только** потому, что правило `exec` писал каждый
`execve`. Без аудита остались бы разрозненные куски.

## Интеграция с SIEM

auditd пишет в `/var/log/audit/audit.log`, откуда его забирают в SIEM (например, через
`audisp`-плагин). На стороне SIEM строят корреляции: цепочка `execve` от веб-пользователя к
shell — алерт. Но при переносе важно сохранять **все** поля (ключ, uid, exe, путь), иначе
теряется контекст. Для офлайн-анализа удобно `ausearch -i --raw | ...` и последующая
обработка скриптом.

## Мини-практика: найти аномалию

```
$ aureport -x --summary
$ ausearch -ua 33 --start today -i
```

Первый отчёт даёт сводку исполненных программ — ищи редкие бинарники. Второй фильтрует
события по uid веб-пользователя за сегодня. Если веб-процесс запускал `nc`, `curl` или
`bash` — это то, что нужно расследовать. В норме веб-сервер не должен запускать shell.
'''

