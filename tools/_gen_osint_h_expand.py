"""Expand Batch H osint lessons to 1200+ real content words by inserting
extra teaching sections before '## Квиз'."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, 'content', 'osint')

def add(lesson_id, text):
    path = os.path.join(CONTENT, lesson_id + '.md')
    lesson = open(path, encoding='utf-8').read()
    if text.strip()[:40] in lesson:
        print('already expanded:', lesson_id); return
    m = re.search(r"^## Квиз\s*$", lesson, re.MULTILINE)
    if not m:
        raise SystemExit('no quiz heading in ' + lesson_id)
    lesson = lesson[:m.start()] + text.strip() + "\n\n" + lesson[m.start():]
    open(path, 'w', encoding='utf-8').write(lesson)
    print('expanded', lesson_id)

