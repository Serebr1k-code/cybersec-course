#!/usr/bin/env python3
"""Top-up web gap lessons (batch S5b) — second pass to 1200+."""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def insert(lid, additions, minutes=None):
    path = os.path.join(ROOT, "content", "web", lid + ".md")
    lesson = open(path, encoding="utf-8").read()
    add = additions.strip("\n")
    if "## Квиз" in add or "## Где пригодится" in add:
        raise SystemExit("bad additions: " + lid)
    m = re.search(r"^## Квиз\s*$", lesson, re.MULTILINE)
    out = lesson[:m.start()] + add + "\n\n" + lesson[m.start():]
    if minutes:
        out = re.sub(r"^estimated_minutes:.*$", f"estimated_minutes: {minutes}",
                     out, count=1, flags=re.MULTILINE)
    open(path, "w", encoding="utf-8").write(out)
    print("topup", lid)

insert("web-sqli-dbms-exotic", r"""
## Определение диалекта: расширенный набор проб

Разберём определение диалекта подробнее, потому что от него зависит всё дальнейшее. Есть несколько категорий проб, и их стоит применять по порядку.

Первая категория — **функция версии**. Разные СУБД отвечают по-разному: `version()` (MySQL, PostgreSQL, ClickHouse), `@@version` (MSSQL, MySQL), `sqlite_version()` (SQLite), `H2VERSION()` (H2), `dbmsinfo('version')` (Sybase), `rdb$get_context('SYSTEM','ENGINE_VERSION')` (Firebird). Отправляя их по очереди, ты быстро сужаешь список.

Вторая категория — **dummy-таблица**. Некоторым СУБД нужна таблица для `SELECT` без `FROM`. У Oracle и ClickHouse это `dual`/`system.one`, у DB2 — `sysibm.sysdummy1`. Если `SELECT 1` без `FROM` работает, это тоже подсказка: MySQL, PostgreSQL и SQLite позволяют `SELECT 1` напрямую.

Третья категория — **функции работы со строками и датами**. `SUBSTRING` vs `SUBSTR`, `LENGTH` vs `LEN`, `NOW()` vs `SYSDATE` vs `GETDATE()`. Совпадение функций уточняет диалект, если версия не сработала.

Четвёртая категория — **поведение ошибок**. Текст ошибки почти всегда называет продукт: `MySQLSyntaxErrorException`, `org.postgresql.util.PSQLException`, `ORA-01756`, `Dynamic SQL Error` (Firebird), `SQLCODE` (DB2). Читать ошибки — самый быстрый способ определить диалект.

Применяя эти категории по очереди, ты почти всегда за несколько запросов понимаешь, с какой СУБД работаешь.

## Почему это важно для эксплуатации

Диалект определяет не только синтаксис, но и доступные примитивы. В одних СУБД легко читать файлы, в других — сложно. В одних есть `CREATE ALIAS` для RCE, в других — нет. В одних удобна слепая time-based инъекция, в других её приходится заменять булевой.

Например, ClickHouse даёт функции `file()`, `url()`, `s3()`, которые превращают SQLi в чтение файлов и SSRF. H2 даёт `CREATE ALIAS` и RCE. DB2 и Firebird чаще ограничиваются чтением данных, но при избыточных правах читают файлы. Понимая это, ты планируешь эксплуатацию под конкретную СУБД, а не действуешь наугад.

## Как снимать схему в разных СУБД

Метаданные — второй шаг после определения диалекта. В стандартных СУБД это `information_schema.tables` и `information_schema.columns`. Но не все её поддерживают одинаково: DB2 использует `sysibm`/`syscat`, Firebird — `rdb$`, ClickHouse — `system.tables`, H2 — `INFORMATION_SCHEMA`.

Общий подход: сначала найти представление, где перечислены таблицы, потом — где колонки. В большинстве СУБД есть и то, и другое, просто под разными именами. Если не помнишь точное имя, попробуй стандартное `information_schema` — многие СУБД его поддерживают хотя бы частично.

После снятия схемы дампишь интересующие таблицы. Если вывод обрезается, используешь `SUBSTR`/`SUBSTRING` и извлекаешь по частям. Если инъекция слепая — перебираешь символы булевыми условиями.

## Что делать, если СУБД неизвестна

Иногда определить диалект не удаётся: приложение прячет ошибки, а пробы не срабатывают. Тогда действуешь по признакам. Во-первых, смотри на технологии: `JSESSIONID` и `X-Powered-By: Java` намекают на Java и встраиваемые СУБД (H2, HSQLDB) или на enterprise-СУБД. Во-вторых, анализируй формат данных в ответах: даты, числа, строки иногда выдают стиль СУБД. В-третьих, используй слепые пробы с разными функциями и смотри, какая не даёт ошибку.

Если ничего не помогло, эксплуатируй то, что работает: возможно, приложение возвращает данные, и можно дампить их через стандартный `UNION` с `information_schema`. Не обязательно знать точное имя продукта, чтобы извлечь данные.

## Итог ветки

Экзотические СУБД — это та же SQL-инъекция, но с другим диалектом и другими примитивами. Ключевой навык — быстро определить диалект по пробам и ошибкам, затем снять схему и найти путь к файлам или коду. Далее ветка разбирает DB2, Firebird, ClickHouse и H2 отдельно, потому что у каждой есть свои особенности, которые нужно знать наизусть.
""", minutes=30)

