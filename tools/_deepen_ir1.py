ADD['ir-containment-eradication'] = """
## Уровни изоляции

Изоляция — это спектр, а не одно действие. Уровни от мягкого к жёсткому:

| Уровень | Что делаем | Улики | Риск распространения |
|---------|------------|-------|----------------------|
| Блокировка адреса | режем трафик к C2 | сохраняются | средний |
| Сегментация сети | хост в изолированный VLAN | сохраняются | низкий |
| Отключение сервиса | гасим конкретный процесс | частично теряются | низкий |
| Выключение хоста | питание/reboot | память теряется | нулевой |

Правило: **выбирай самый мягкий уровень, который реально останавливает распространение**.
Жёстче — не значит лучше: выключение хоста лишает тебя памяти, а память часто содержит
расшифрованный вредонос и ключи.

## Заманивание атакующего

Иногда полезно не обрывать связь с C2, а **наблюдать** за ней. Хост оставляют в
контролируемой изоляции, трафик к атакующему перенаправляют в honeypot, и аналитики
собирают поведение: какие команды отдаёт оператор, какие инструменты подгружает.

Выгода — разведка: ты узнаёшь тактику группы. Риск — атакующий может использовать
канал для новых действий. Поэтому заманивание применяют только когда изоляция надёжна,
а выгода оправдана.

## Проверка после устранения

Прежде чем вернуть хост в работу, прогони контрольный чек-лист:

```
$ find / -newermt '2026-10-01' -type f -perm -u+x 2>/dev/null   # свежие бинарники
$ crontab -l; systemctl list-timers                              # задачи
$ grep -r . /etc/cron.* 2>/dev/null                              # cron
$ last -a | head                                                 # входы
$ ss -tunap                                                      # соединения
```

Если хотя бы один пункт даёт неизвестный результат — устранение неполное, и возврат в
работу преждевременен. Лучше потратить час на проверку, чем повторить инцидент.
"""

ADD['ir-root-cause'] = """
## Дерево причин (fishbone)

Когда «пяти почему» мало, помогает **диаграмма Исикавы** (рыбий скелет): событие справа,
а причины раскладываются по категориям-«косточкам». Для ИБ удобны категории:

- **Люди** — обучение, фишинг, ошибки;
- **Процессы** — ревью, изменение, доступ;
- **Технологии** — конфигурация, патчи, архитектура;
- **Внешние** — третьи стороны, поставщики.

Пример: файлы зашифрованы (следствие). Косточка «Технологии» даёт «открытый RDP», «Люди» —
«слабый пароль», «Процессы» — «нет MFA-политики». Уже видно, что причина не одна.

## Причина и совпадение

Не всё, что произошло до инцидента, — его причина. Классические ловушки:

- **Корреляция ≠ причинность.** Атака случилась после установки патча — но не из-за него.
- **Один свидетель.** Один лог говорит одно, но остальные данные не подтверждают.
- **Ретроспектива.** «Мы всегда так делали» — не аргумент, если именно это и сломали.

Проверяй причину вопросом: **если бы этого условия не было, инцидент бы не произошёл?**
Если ответ «нет» или «не знаю» — причина не найдена.

## RCA в отчёте

Отчёт о первопричине — это не только «почему», но и «что теперь». Хорошая структура:

1. Краткое описание события.
2. Причинная цепочка по таймлайну.
3. Первопричина (или несколько).
4. Вклад факторов (что усилило ущерб).
5. Рекомендации с владельцами и сроками.
6. Как проверим, что помогло.

Последний пункт отличает разбор от формальности: у каждой рекомендации есть метрика,
по которой через месяц видно, закрыта проблема или нет.
"""

ADD['ir-forensic-readiness'] = """
## Матрица источников логирования

Готовность удобно описывать матрицей «что × где × как долго». Пример для типовой сети:

| Источник | Где собираем | Хранение |
|----------|--------------|----------|
| Вход в ОС (SSH/RDP) | SIEM | 12 мес |
| Создание процессов | EDR/SIEM | 6 мес |
| DNS-запросы | DNS-логгер | 3 мес |
| Сетевые потоки | NetFlow | 1 мес |
| Изменения файлов | SIEM | 6 мес |
| Почтовый шлюз | шлюз | 6 мес |

Матрица сразу показывает пробелы: если DNS не логируется, туннелирование не увидеть,
каким бы хорошим ни был SIEM.

## Тестирование готовности

Готовность проверяют **упражнением**: запусти безобидную «атаку» и посмотри, что
зафиксировалось. Например, создай тестовую задачу по расписанию и проверь, попала ли она
в журнал и увидел ли её детект.

Простой тест на Linux:

```
$ logger "readiness-test $(date)"
$ grep readiness-test /var/log/syslog
```

Если сообщение появилось локально, но не на SIEM — централизация сломана. Такие тесты
прогоняют регулярно, а не один раз при внедрении.

## Готовность в облаке и контейнерах

Классическая готовность про хосты уже неполна: нагрузка живёт в контейнерах и облаке.

- **Cloud audit logs** (CloudTrail, Activity Log, Cloud Audit Logs) должны быть включены
  и выгружены в отдельное хранилище с защитой от удаления;
- **container runtime** события (запуск контейнера, exec, монтирование) — в SIEM;
- **IaC-репозитории** — история изменений инфраструктуры как источник «кто что поменял»;
- **identity-логи** (SSO, IdP) — кто и когда входил в облако.

Без этого инцидент в облаке расследовать почти нечем: локальных артефактов там нет, а
логи живут ровно столько, сколько задала политика.
"""

ADD['ir-legal-regulatory'] = """
## Согласие и внутренняя политика

Даже внутри своей компании сбор данных требует основания. Обычно его дают:

- **трудовой договор** и внутренние политики (например, «использование корпоративных
  ресурсов допускается только в рабочих целях»);
- **согласие** сотрудника, где оно необходимо;
- **законный интерес** компании в защите инфраструктуры.

Важно: основание должно существовать **до** инцидента. Если политики нет, сбор личных
файлов сотрудника легко оспорить. Поэтому юридическая проработка политик — часть
форензик-готовности, а не бюрократия.

## Третьи стороны

Современная инфраструктура почти всегда включает поставщиков: облако, SaaS, MSSP. Это
значит, что часть доказательств лежит **не у вас**.

- проверь, какие логи поставщик хранит и как долго;
- зафиксируй в договоре право на доступ к логам при инциденте;
- знай сроки и форму запроса к поставщику;
- учитывай, что трансграничная передача данных может регулироваться отдельно.

Если это не прописано заранее, в момент инцидента ты обнаружишь, что нужные логи
недоступны или удалены по политике провайдера.

## Хранение и удаление доказательств

Доказательства нельзя хранить вечно: после завершения разбирательства их пора удалять.
Но и удалять раньше времени нельзя — они могут понадобиться для апелляции или аудита.

Разумная политика:

| Тип данных | Срок хранения |
|------------|---------------|
| Сырые образы | до закрытия дела + срок исковой давности |
| Отчёты и выводы | по внутренней политике (обычно годы) |
| Персональные данные в уликах | минимум, необходимый для дела |
| Обезличенные метрики | долго (для статистики) |

Удаление тоже документируется: что, когда и на каком основании стёрто. Это часть
цепочки сохранности — доказательство, которое исчезло бесследно, вызывает вопросы.
"""

