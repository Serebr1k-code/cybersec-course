ADD["win-prefetch-deep"] = r'''
## Продвинутый разбор: счётчики, устройства и контекст запуска

За пределами базовых полей Prefetch хранит ещё несколько полезных вещей. Во-первых, для
некоторых версий есть **список устройств и файлов**, которые читал процесс: по нему можно
понять, с какими данными работала программа (конфиги, DLL, документы). Во-вторых, есть
**временные метки файла `.pf`** (создание/изменение) — их полезно сверять с временами
запуска: расхождение бывает признаком того, что файл копировали или подделывали. В-третьих,
для программ с одинаковым именем, но разными путями, разные хеши в имени файла позволяют
различить запуски из `System32` и из пользовательского каталога — это прямой способ поймать
маскировку под системный процесс.

Отдельно стоит сказать про **только чтение**: Prefetch не содержит аргументов командной
строки, поэтому он не скажет, с какими параметрами запускали программу. Для аргументов нужны
журналы создания процессов (если аудит включён) или артефакты вроде PowerShell-логов. Prefetch
отвечает на «что и когда», но не на «с какими ключами».

## Как выявлять очистку Prefetch и что делать

Антифорензика часто бьёт именно по Prefetch: утилиты «чистки» удаляют `.pf`-файлы, чтобы
скрыть запуски. Признаки очистки: каталог `Prefetch` пуст или содержит только самые свежие
системные файлы; в реестре есть следы запуска чистильщика; времена создания оставшихся
файлов «сбиты» в один момент. Если видишь такую картину, не делай вывод «ничего не
запускалось» — переходи к резервным источникам: ShimCache, AmCache, SRUM, журналы. Часто
именно они сохраняют след, который чистильщик не тронул. И зафиксируй сам факт очистки: это
само по себе улика намеренного сокрытия следов.
'''

ADD["win-appcompat-deep"] = r'''
## Продвинутый разбор: формат, версии и типичные ловушки

ShimCache — один из самых «капризных» артефактов, потому что его формат менялся почти в
каждой крупной версии Windows. В одних версиях запись состоит только из пути и времени, в
других добавляются флаги (например, признак исполнения), в третьих меняется порядок полей.
Поэтому главное правило: **сначала определи версию ОС**, затем выбирай парсер, который её
поддерживает. Если парсер не знает версию, он может «прочитать» мусор и выдать ложные пути —
это хуже, чем честное «формат не поддержан».

Вторая ловушка — **смешение с AmCache**. Пользователи часто ищут «AmCache в hive SYSTEM» или
наоборот; на самом деле ShimCache лежит в SYSTEM, а AmCache — в отдельном hive
`Amcache.hve`. Третья ловушка — интерпретация времени: время в ShimCache относится к
**изменению файла** (из его метаданных), а не к моменту попадания записи в кэш. Не выдавай
его за время запуска.

## Что делать, если ShimCache пуст или повреждён

Бывает, что значение `AppCompatCache` отсутствует или нечитаемо. Это не тупик. Проверь
следующее: возможно, hive снят некорректно (файл залочен) — попробуй копию из теневой копии
тома; возможно, механизм совместимости отключён групповой политикой — тогда записей просто
нет по конфигурации, и это надо оговорить. Резервные источники те же: AmCache, Prefetch,
журналы. И помни: пустой ShimCache при непустом AmCache — это не противоречие, а разные
механизмы. В отчёте опиши оба и не делай вывод об отсутствии файла только по одному
источнику.
'''

ADD["win-amcache-deep"] = r'''
## Продвинутый разбор: хеши, версии и корреляция

AmCache ценен именно хешами, но у него есть нюансы. Во-первых, типичный хеш — **SHA-1**;
если тебе нужен SHA-256 для конкретной базы, его придётся считать отдельно, если файл ещё
есть, или сопоставлять через внешние сервисы. Во-вторых, записи бывают в нескольких местах:
`Root\File` для файлов, `Root\Programs`/`InventoryApplication` для приложений; не ограничивай
поиск одной таблицей. В-третьих, время в AmCache чаще всего — **время последнего изменения
файла**, а не установки или запуска; формулируй вывод соответственно.

Корреляция — главная сила AmCache. Один хеш, найденный на нескольких хостах, связывает
инциденты в кампанию. Путь из нестандартного каталога (`Temp`, `Public`, `Downloads`) в паре
с детектом по хешу — почти готовое доказательство вредоносной активности. А если хеш
совпадает с известным семейством ВПО, ты получаешь и название, и типовое поведение, что
помогает предсказать дальнейшие шаги злоумышленника.

## Как строить вывод по AmCache

Хороший вывод по AmCache звучит так: «На хосте присутствовал файл `<путь>` с хешем SHA-1
`<хеш>`, время последнего изменения `<время>`; хеш совпадает с образцом `<семейство>` по
данным `<источник>`, проверено `<дата>`». Обрати внимание: здесь нет утверждения о запуске —
только о присутствии и идентичности. Если запуск подтверждён Prefetch, добавь отдельное
предложение: «факт запуска подтверждён записью Prefetch со счётчиком N». Такая дисциплина
формулировок делает отчёт устойчивым к проверке.
'''

ADD["win-srum-deep"] = r'''
## Продвинутый разбор: пользователи, приложения и аномалии

SRUM полезен не только объёмами. Он привязывает активность к **пользователю** (`UserId`) и
**приложению** (`AppId`), поэтому отвечает на вопрос «кто именно» и «чем именно». Это важно,
когда на машине несколько учётных записей: всплеск трафика может принадлежать не тому
пользователю, которого вы подозреваете. Отдельно смотри системные и служебные процессы: у
них часто есть фоновый трафик (обновления, телеметрия), и его надо уметь отличать от
аномалий, чтобы не поднять ложную тревогу.

Как искать аномалии: построй топ приложений по `BytesSent` и сравни с обычным профилем
машины. Неизвестный процесс в топе, скриптовый интерпретатор с большим исходящим объёмом,
клиент облачного хранилища там, где его не должно быть, — всё это сигналы. Дальше ищи
подтверждение в других артефактах и в сетевых логах. И не забывай про **входящий** трафик
(`BytesRecv`): большая загрузка тоже бывает признаком — например, доставки инструмента.

## Ограничения и что делать при ротации базы

SRUM хранит данные ограниченное время и ротирует их. Если интересующий период уже вытеснен,
текущая `SRUDB.dat` бесполезна — ищи **теневые копии тома**, где сохранилась более ранняя
версия базы. Сравнение двух снимков (старой и новой базы) позволяет восстановить активность,
которая уже исчезла. Это стандартный приём: когда «живые» данные вычищены ротацией или
чистильщиком, работай с историческим снимком. В отчёте укажи, из какого снимка взяты данные и
за какой период, — иначе вывод будет выглядеть произвольным.
'''

