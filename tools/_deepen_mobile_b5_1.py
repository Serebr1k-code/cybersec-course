def add_before_quiz(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already deepened):', lid)
        return
    i = t.index('\n## Квиз')
    t = t[:i] + '\n' + extra.strip() + '\n' + t[i:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


MACH = '''
## Шаг 8: audit token — как сервер узнаёт клиента

Когда процесс подключается к Mach-сервису, сервер может узнать о нём больше, чем просто
«кто-то пришёл». Ядро прикладывает **audit token** — структуру с идентификаторами процесса и,
главное, с информацией о его **подписи**. По audit token сервер проверяет, какой это бандл,
какой командой подписан и какие entitlements имеет.

```text
audit_token_t token = connection.auditToken;
pid_t pid = audit_token_to_pid(token);
// далее: получить SecCode клиента и проверить подпись/права
```

Это принципиальный момент: **идентификатор процесса (PID) не является удостоверением**. PID
можно переиспользовать, а процесс с тем же именем может быть подделан. Единственное надёжное
доказательство — проверка подписи через audit token. Сервер, который доверяет PID или имени
бандла, уязвим к подмене.

## Шаг 9: как выглядит эксплуатация Mach IPC

Разберём типичный сценарий по шагам, чтобы связать теорию с практикой. Есть привилегированный
демон, регистрирующий Mach-сервис. Атакующий (вредоносное приложение с нужным entitlement или
через цепочку) находит имя сервиса в bootstrap, получает его send-право и отправляет
сообщение с особым телом.

```text
// 1. найти порт сервиса
bootstrap_look_up(bootstrap_port, "com.vendor.helper", &service_port);
// 2. собрать сообщение
mach_msg(&msg, MACH_SEND_MSG, sizeof(msg), 0, service_port, ...);
// 3. сервер разбирает тело и выполняет операцию без проверки размера/типа
```

Если сервер не проверил ни отправителя, ни тело сообщения, шаг 3 даёт привилегированное
действие: запись файла, смену настройки, чтение защищённых данных. Именно так выглядит
большинство повышений привилегий на iOS «снизу вверх» — не магия, а доверчивый IPC-сервер.

## Шаг 10: чему учат реальные уязвимости

История iOS знает много случаев, когда уязвимость была именно в IPC. Общие уроки повторяются.
Во-первых, привилегированный сервис — самая ценная цель, потому что ошибка в нём даёт сразу
высокий уровень прав. Во-вторых, самые распространённые ошибки — отсутствие проверки клиента
и недоверие к размеру входных данных. В-третьих, наличие entitlements, разрешающих обращаться
к системным сервисам, расширяет поверхность атаки: чем шире `mach-lookup` исключения, тем
больше целей.

Практический вывод для аудита: не нужно искать сложную логическую ошибку — достаточно найти
сервис, который принимает сообщения и выполняет действия, не проверяя, кто и что прислал. Это
и есть типичная находка высокого уровня. Поэтому при оценке iOS-приложения с привилегированным
компонентом первым делом проверяйте: есть ли проверка audit token и валидация тела сообщения.
'''

XPC = '''
## Шаг 8: сериализация и NSSecureCoding

XPC передаёт между процессами не только простые значения, но и объекты — через сериализацию.
Классическая ошибка: сервер принимает объект без проверки его класса. В Objective-C для этого
используется `NSSecureCoding`, который требует явно перечислить допустимые классы. Если сервер
доверяет десериализованному объекту, атакующий может подсунуть объект другого класса и вызвать
неожиданное поведение (type confusion).

```text
// небезопасно: доверяем любому классу
id obj = [coder decodeObjectForKey:@"payload"];
// безопасно: ограничиваем классы
id obj = [coder decodeObjectOfClasses:allowedClasses forKey:@"payload"];
```

Правило простое: любой объект, пришедший из другого процесса, — недоверенный, и его класс
нужно ограничивать явно.

## Шаг 9: как искать уязвимый XPC-сервис

Практический план поиска:

1. Собрать список Mach-сервисов из `LaunchDaemons`/`LaunchAgents` и из plist приложения.
2. Для каждого найти реализацию `shouldAcceptNewConnection` и посмотреть, есть ли проверка.
3. Найти методы протокола XPC и понять, какие операции они выполняют.
4. Оценить привилегии сервиса: запущен ли он с повышенными правами.
5. Проверить, валидируются ли аргументы (особенно пути к файлам и команды).

Шаги 1–2 часто дают ответ сразу: если `shouldAcceptNewConnection` возвращает `true` без
проверки, сервис открыт любому, кто дотянулся до порта. Дальше остаётся оценить, насколько
опасны его операции — и это уже даёт серьёзную находку.

## Шаг 10: реальные кейсы и уроки

XPC-уязвимости регулярно встречаются в системных сервисах и в приложениях с привилегированными
helper-процессами. Общий сценарий: helper выполняет привилегированную операцию (например,
установку профиля или запись в защищённую директорию) и либо не проверяет клиента, либо
проверяет только bundle id. Атакующее приложение с тем же bundle id (после переподписи) или
вовсе без проверки получает возможность выполнить операцию от имени helper.

Уроки для защищающегося: проверяйте подпись клиента через audit token, ограничивайте
допустимые классы при десериализации, валидируйте пути и команды, а самому helper-процессу
давайте минимум привилегий. Уроки для атакующего: ищите сервисы, к которым можно подключиться,
и операции, которые они выполняют — самая простая цепочка «подключился → вызвал метод →
получил привилегированное действие» и есть классический XPC-баг.
'''

add_before_quiz('mobile-ios-mach-ports', MACH)
add_before_quiz('mobile-ios-xpc', XPC)
