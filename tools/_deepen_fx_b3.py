ADDS["mobile-ios-keychain-deep"] = """## Разбор: токен приложения

Пусть нужно понять, к какому сервису обращается приложение. Токен лежит в
`genp`-элементе:

```
$ sqlite3 /var/Keychains/keychain-2.db "SELECT svce,acct,agrp FROM genp WHERE agrp LIKE '%example%';"
```

`svce` и `acct` читаемы без расшифровки: они дают имя сервиса и аккаунт. `agrp`
(access group) показывает, какие приложения разделяют элемент. Даже без
расшифровки `data` этих метаданных часто достаточно, чтобы понять, каким сервисом
пользовался человек и с каким аккаунтом.

## Ограничения метода

- Значения (`data`) зашифрованы; без ключа класса их не прочитать.
- SEP-привязанные ключи неэкспортируемы в принципе.
- `ThisDeviceOnly` элементы отсутствуют в бэкапе — это не повреждение.
- Часть элементов синхронизирована в iCloud.
- Смена пароля устройства делает старые классовые ключи недоступными.

## Как усилить вывод

Сопоставь `svce`/`acct` с сетевыми артефактами и с установленными приложениями:
имя сервиса из keychain, встреченное в трафике, подтверждает реальное
использование. Для расшифровки нужен либо пароль бэкапа, либо живое
разблокированное устройство."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("layer3", lid, "+", len(add.split()), "tokens")
    return 0

if __name__ == "__main__":
    sys.exit(main())
