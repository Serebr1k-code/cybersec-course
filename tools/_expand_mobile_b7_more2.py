B['mobile-libfuzzer'] = '''
## Дизайн harness: что важно

Harness — это не «вызвать функцию», а аккуратно подготовить окружение. Фаззер запускает
harness **в одном процессе** миллионы раз, поэтому любое глобальное состояние накапливается.
Если harness выделяет память и не освобождает, через минуту процесс съест всю память и
упадёт — а это ложный краш, не баг библиотеки. Поэтому в конце harness освобождают всё, что
создал, и сбрасывают глобальные переменные к исходному состоянию.

Второе — **структура входа**. Случайные байты редко проходят проверки формата. Если формат
известен, вход удобно разбирать через `FuzzedDataProvider`: он берёт из случайных байтов
целые числа, строки и буферы нужного размера. Так фаззер быстрее доходит до глубокой логики.

```c
#include <FuzzedDataProvider.h>
extern int parse_record(const uint8_t *buf, size_t len);

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
    FuzzedDataProvider p(data, size);
    auto len = p.ConsumeIntegralInRange<size_t>(0, 64);
    auto buf = p.ConsumeBytes<uint8_t>(len);
    if (buf.size() == len) parse_record(buf.data(), buf.size());
    return 0;
}
```

## Частые ошибки

Первая — **утечка в harness**: память не освобождается, фаззер падает по OOM. Вторая —
**общее состояние**: статический буфер не сбрасывается, и каждый следующий запуск видит
«хвост» предыдущего. Третья — **медленный harness**: если он пишет на диск или ждёт сеть,
скорость падает в сотни раз. Четвёртая — **отсутствие словаря** для форматов с магическими
байтами. Пятая — **игнорирование отчёта**: ASan показывает первую ошибку и останавливается;
после исправления прогон надо повторить, чтобы найти следующую.

## Практика: воспроизведение краша

libFuzzer сохраняет вход, вызвавший падение, в файл `crash-*`. Его можно прогнать ещё раз:

```bash
$ adb shell /data/local/tmp/fuzz_parser crash-abc123
==3110==ERROR: AddressSanitizer: heap-buffer-overflow ...
```

Так баг превращается в воспроизводимый тест-кейс: файл можно приложить к задаче на
исправление. Хорошая практика — добавить этот файл в регрессионный корпус, чтобы будущие
прогоны проверяли и его.

## Что ещё посмотреть

Для больших проектов есть OSS-Fuzz — облачный сервис, который гоняет фаззеры непрерывно.
Дополнительно включают **value profile** (подсказки по сравнению значений) и
`-use_value_profile=1`: это помогает проходить проверки вроде «эта строка равна магической».
'''

B['mobile-afl-native'] = '''
## Режимы и производительность

AFL умеет работать быстрее за счёт **persistent mode**: программа не завершается после
каждого входа, а остаётся в цикле и принимает новые данные. Для этого код собирают с
`afl-clang-fast` и вставляют макрос `__AFL_LOOP`:

```c
while (__AFL_LOOP(1000)) {
    read_input();   // читает stdin или @@-файл
    process();
}
```

Число 1000 — сколько раз повторить цикл в одном процессе. Это ускоряет фаззинг в разы,
потому что исчезает стоимость запуска процесса.

Ещё один приём — **параллельный фаззинг**: один экземпляр запускают как `-M master`, а
остальные как `-S slave`. Они делят найденный корпус между собой, и суммарная скорость
растёт линейно числу ядер.

## Частые ошибки

Первая — **пустой или однообразный корпус**: AFL не с чего начать мутировать. Вторая —
**прогон без `@@`**: программа не получает входной файл и фаззит вхолостую. Третья —
**слишком долгий запуск программы**: если один запуск занимает секунды, AFL почти не успевает
мутировать; такие программы сначала упрощают. Четвёртая — **фаззинг на устройстве с данными**:
падение может испортить хранилище, поэтому только изолированный эмулятор. Пятая — **доверие
к числу crashes без проверки**: уникальность считается по отпечатку и может ошибаться.

## Практика: подготовка корпуса

Хороший корпус — залог успеха. Кладите не один файл, а несколько **разных** валидных входов:
минимальный, максимальный, с разными опциями формата. AFL «склеивает» их и порождает новые
варианты. Уменьшить корпус помогает `afl-cmin`: он оставляет только входы, дающие уникальное
покрытие, и убирает дубликаты.

## Что ещё посмотреть

Дополнительно к AFL есть **AFL++** — активно развиваемый форк с улучшенными мутациями и
поддержкой нескольких режимов инструментирования. Для Android есть готовые сборки под
эмулятор. Если программа читает не файл, а сеть или IPC, пишут «сетевой» harness: AFL
поддерживает фаззинг через сокет.
'''

