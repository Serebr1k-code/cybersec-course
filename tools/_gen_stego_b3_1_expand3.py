"""Third expansion pass — finish pushing stego B3-1 lessons over 1200 real words."""
import os

ROOT = "content/stego"

def expand(lid, extra):
    path = os.path.join(ROOT, lid + ".md")
    if not os.path.exists(path):
        print("MISSING", path); return
    t = open(path, encoding="utf-8").read()
    key = extra.strip().splitlines()[0]
    if key in t:
        print("SKIP(done)", lid); return
    marker = "## Что мы теперь знаем"
    t = t.replace(marker, extra.strip() + "\n\n" + marker, 1)
    open(path, "w", encoding="utf-8").write(t)
    print("EXPANDED", lid)

expand("stegoanalysis-quantitative", r'''
## Шаг 18: как проверять оценщик

Чтобы доверять оценке, её проверяют на «контрольном» изображении с известной
долей встраивания. Если оценщик на файле с α = 0.5 даёт 0.49, а на чистом — 0.01,
он работает. Если на чистом он выдаёт 0.2, у него смещение — вероятно, из-за
текстуры или сжатия. Практический тест: возьми заведомо чистое изображение того же
типа и прогони оценщик. Ненулевой результат на чистом файле — повод не доверять
абсолютным числам, а смотреть лишь на относительные различия между файлами.
''')

expand("stegoanalysis-steg-expose", r'''
## Шаг 17: почему пороги не универсальны

Порог зависит от типа изображений. На гладких картинках (небо, фон) детекторы
ведут себя иначе, чем на текстурных. Поэтому «порог 0.5» — лишь стартовая точка.
В пакетном режиме полезно разбить файлы по типу (пейзаж/портрет/скриншот) и
подбирать порог отдельно. Это удлиняет настройку, но резко снижает FP.

## Шаг 18: практическая ценность

Главная польза StegExpose в CTF — **скорость триажа**. Вместо того чтобы вручную
прогонять три теста на каждый файл, ты получаешь короткий список подозрительных.
Дальше работает ручная часть: определить метод и извлечь. Пайплайн не заменяет
аналитика, а расчищает ему фронт работы.
''')

expand("stegoanalysis-targeted-f5", r'''
## Шаг 17: как оценить устойчивость

Целевую атаку проверяют на устойчивость к постобработке. Если файл после
встраивания пересжали (даже с тем же качеством), shrinkage частично сглаживается,
и оценка длины падает. Поэтому при анализе важно знать, проходил ли файл повторное
сжатие. Если да — сначала попробуй восстановить «оригинальное» качество или
используй калибровку, иначе структурный след будет размыт.
''')

expand("stegoanalysis-cover-source-mismatch", r'''
## Шаг 18: mismatch и watermarking

Та же проблема бьёт по водяным знакам (watermarking). Если знак встроен с расчётом
на один источник, при пересжатии он может «сломаться» или стать нечитаемым. Поэтому
робастные схемы watermarking проектируют с учётом возможных преобразований
(сжатие, кроп, ресайз). В стегоанализе это зеркальная задача: чем устойчивее знак,
тем заметнее след — и наоборот.

## Шаг 19: как объяснить это на собеседовании

Формулировка на одну фразу: «Стегоанализ различает два очень похожих распределения,
и если тестовое изображение из другого домена, разница между доменами перекрывает
разницу между классами». Этого достаточно, чтобы показать понимание. Дальше —
пример: обучение на BOSSbase, тест на соцсети, падение PE с 0.1 до 0.4.
''')

