#!/usr/bin/env python3
"""Top-up web gap lessons (batch S1b) — second pass to 1200+."""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def insert(lid, additions, minutes=None):
    path = os.path.join(ROOT, "content", "web", lid + ".md")
    lesson = open(path, encoding="utf-8").read()
    add = additions.strip("\n")
    if "## Квиз" in add or "## Где пригодится" in add:
        raise SystemExit("bad additions: " + lid)
    m = re.search(r"^## Квиз\s*$", lesson, re.MULTILINE)
    out = lesson[:m.start()] + add + "\n\n" + lesson[m.start():]
    if minutes:
        out = re.sub(r"^estimated_minutes:.*$", f"estimated_minutes: {minutes}",
                     out, count=1, flags=re.MULTILINE)
    open(path, "w", encoding="utf-8").write(out)
    print("topup", lid)

insert("web-dependency-confusion", r"""
## Как резолвер принимает решение: разбор по шагам

Разберём, что именно происходит в момент `npm install`, когда у пакета два источника. Резолвер идёт по дереву зависимостей и для каждого имени спрашивает у источников: «какие версии у тебя есть?» Ответы складываются в один пул, после чего выбирается версия, удовлетворяющая диапазону и наибольшая среди подходящих.

Возьмём диапазон `^1.0.0`. Символ `^` означает «совместимое обновление»: разрешены версии от `1.0.0` до `2.0.0` не включая. Публичная `99.0.0` в этот диапазон не попадает, поэтому подмена не сработает. А вот диапазон `*` или `latest` подмену примет сразу. Отсюда практический вывод: чем жёстче диапазоны и чем полнее lock-файл, тем уже окно для атаки.

Есть и вторая тонкость — **порядок источников**. В одних конфигурациях приватный реестр стоит первым и ответ из него считается окончательным. В других источники объединяются, и тогда решение зависит только от номера версии. Именно вторая конфигурация и называется «уязвимой к dependency confusion»: она не различает, откуда пришло имя.

Проверить конфигурацию можно так:

```
$ npm config get registry
https://registry.npmjs.org/
$ npm config get @corp:registry
https://npm.corp.internal/
```

Если обе строки заданы, а fallback не запрещён явно, стоит посмотреть, как ведёт себя резолвер при конфликте версий. Самый надёжный способ — воспроизвести установку в изолированном окружении на тестовом пакете, не затрагивая реальные сборки.

## Почему это трудно заметить

Dependency confusion почти невидим для код-ревью. В `package.json` всё выглядит правильно: то же имя, тот же диапазон. Отличие проявляется только в момент установки, на машине сборки, и только если публичный пакет с тем же именем существует и его версия старше. В логах установки нет предупреждения «вы взяли публичный пакет вместо приватного» — резолвер считает, что всё в порядке.

Именно поэтому защита должна быть декларативной: конфиг, где приватное имя **не может** быть разрешено публично, а не бдительность разработчика. Полагаться на то, что кто-то «посмотрит внимательно», — не мера безопасности.

## Мини-кейс: что произошло бы у нас

Вернёмся к нашему `.npmrc` со scope `@corp`. Диапазон `*` в `package.json` означает, что резолвер возьмёт наибольшую доступную версию. Публичный `@corp/internal-utils@99.0.0` существует, значит выигрывает он. Его `postinstall` исполняется на машине сборки и читает переменные окружения. В нашем примере флаг лежит прямо в README публичного пакета — это метафора того, что атакующий полностью контролирует содержимое. В реальности там был бы код, а не строка с флагом.
""", minutes=45)

