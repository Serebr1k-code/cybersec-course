#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Final top-up for anti-forensics lessons."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content', 'forensics')
ADD = {
'af-secure-delete': """
## Итог

Разница между «удалил» и «стёр» — центральная для этой темы. Пока данные не перезаписаны, они
твои; как только перезаписаны — исчезли. Умение распознать, какой из двух сценариев имел
место, определяет, стоит ли тратить время на восстановление или искать копии в другом месте.
""",
'af-metadata-scrubbing': """
## Почему это важно для выводов

Метаданные — это мост между файлом и реальностью: человеком, устройством, местом и временем.
Когда мост разрушен или подделан, рушится и атрибуция. Поэтому работа с метаданными — не
факультатив, а обязательный шаг: сначала извлечь всё, что есть, затем проверить на
непротиворечивость, и лишь потом делать выводы о происхождении файла.
""",
'af-timestomping-deep': """
## Итог

Подделка времени — прямой удар по таймлайну, а значит, по всему расследованию. Защита от неё
строится на принципе независимых источников: чем больше артефактов подтверждают одно время,
тем труднее подделать их все. Обнаружив расхождение, не отбрасывай подделанную метку — она
сама становится уликой, свидетельствующей о намеренном сокрытии.
""",
'af-vm-detection': """
## Итог

Виртуальная среда и уклонение от неё — две стороны одной темы. Уметь определить VM нужно,
чтобы правильно интерпретировать артефакты; уметь распознать VM-detection код нужно, чтобы
не обмануться «тихим» поведением образца. В обоих случаях работает один принцип: смотри на
совокупность признаков, а не на отдельный маркер.
""",
}
for lid, add in ADD.items():
    path = os.path.join(C, lid + '.md')
    t = open(path, encoding='utf-8').read()
    m = re.search(r'^## Квиз\s*$', t, re.MULTILINE)
    t = t[:m.start()] + add.strip() + '\n\n' + t[m.start():]
    open(path, 'w', encoding='utf-8').write(t)
    print('deepened', lid)
