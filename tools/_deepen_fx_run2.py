ADDS["tool-bulk-extractor"] = """## Сравнение с альтернативами

Bulk Extractor — не единственный инструмент для массового извлечения. Полезно понимать,
когда он лучше, а когда нужен другой:

| Инструмент | Что делает | Когда выбирать |
|---|---|---|
| `bulk_extractor` | структуры по сигнатурам, offset | огромные образы, триаж IOC |
| `foremost` / `scalpel` | карвинг файлов по заголовкам | восстановить сами файлы |
| `photorec` | карвинг по сигнатурам + эвристика | картинки/медиа |
| `strings` | печатаемые строки | быстрый ручной поиск |
| `sleuthkit` (`fls`, `icat`) | разбор ФС | привязка к файлам и inode |
| `Autopsy` | GUI-надстройка над TSK | отчёт и визуальный анализ |

Ключевое отличие: Bulk Extractor **не** восстанавливает файлы и **не** знает ФС. Он даёт
карту находок с offset. Карвинг даёт сами файлы. Разбор ФС даёт имена и удалённые записи.
В реальном расследовании их комбинируют: сначала Bulk Extractor для карты, затем
карвинг/TSK для восстановления.

## Скорость, ресурсы и интеграция в пайплайн

Bulk Extractor оптимизирован под потоковую обработку и умеет параллелить сканеры:

```
$ bulk_extractor -j 4 -o out /evidence/disk.img   # 4 потока
$ time bulk_extractor -o out -e url,domain /evidence/disk.img
```

Что важно на практике:

- **Диск читается один раз** — все сканеры работают на одном проходе, поэтому включение
  дополнительных сканеров почти не увеличивает время чтения.
- **Многопоточность** (`-j`) ускоряет на многоядерных машинах.
- **Память** — вычитывает образ блоками, но `wordlist`-сканер на огромных словарях может
  потреблять заметно больше.
- **Воспроизводимость** — фиксируй версию и параметры запуска; разные версии дают разный
  набор сканеров по умолчанию.

В DFIR-пайплайне его обычно ставят сразу после снятия образа, параллельно с хэшированием:
пока считается хэш, Bulk Extractor уже выдаёт первые зацепки.

## Чек-лист быстрого запуска

1. Снять/принять образ, зафиксировать хэш (`sha256sum`).
2. Запустить `bulk_extractor -o out <образ>` (можно `-e` нужных сканеров).
3. Просмотреть `out/report.xml` — там перечень сканеров и статистика.
4. Отфильтровать ключевые файлы (`url.txt`, `domain.txt`, `email.txt`).
5. Подтвердить находки контекстом через offset + `dd`/`strings`.
6. Сохранить `out/` как артефакт — повторный анализ по фичам занимает секунды."""

ADDS["spec-dvr-camera"] = """## Событийный слой: тревоги и детекция движения

Видео — не единственный источник. Регистраторы ведут **журнал событий**, и он часто
информативнее самой картинки: кто, когда и по какому каналу сработал.

```
$ ls log/
motion.log  alarm.log  system.log  access.log
$ cat log/alarm.log | tail -5
2026-01-14 03:07:11 CH3 motion start
2026-01-14 03:07:44 CH3 motion stop
2026-01-14 03:09:02 CH3 door forced (alarm)
```

- `motion.log` — интервалы детекции движения по каналам;
- `alarm.log` — тревоги (вскрытие, потеря видео, датчики);
- `system.log` — перезагрузки, изменение настроек, смена времени;
- `access.log` — кто подключался к веб-интерфейсу и с какого IP.

`system.log` особенно ценен: смена времени на камере оставляет запись, и это объясняет
«съехавший» таймлайн. `access.log` показывает, что злоумышленник мог подключиться к
регистратору и стереть/выгрузить записи.

## Восстановление из «мусора» и типичные ошибки

Когда штатный экспорт невозможен, а индекс повреждён, работают с сырыми секторами:

```
$ ddrescue -f -n /dev/sdb dvr.img dvr.map     # сначала быстрый проход
$ ddrescue -d -r3 /dev/sdb dvr.img dvr.map    # добить «плохие» сектора
$ grep -abo $'\\x00\\x00\\x00\\x01' dvr.img | head   # стартовые коды H.264
```

Типичные ошибки:

- **Монтирование проприетарной ФС как ext4** — «пустой» диск, хотя данные есть.
- **Игнорирование часового пояса** — таймлайн смещён на несколько часов.
- **Поиск видео там, где оно сжато/зашифровано** — нужен ключ устройства.
- **Опора только на видео** — журнал событий и индекс дают больше, чем картинка.

## Чек-лист

1. Определить вендора (`banner`, `strings`, веб-интерфейс).
2. Снять диск через `ddrescue`, зафиксировать хэш.
3. `file -s` по разделам, попытка `binwalk -e`.
4. Найти и прочитать индекс (`sqlite3`/вендорная утилита) → интервалы и статусы.
5. Сопоставить `log/` (события) с индексом и видео.
6. Верифицировать время по независимому источнику.
7. Восстановить удалённое карвингом по сигнатурам H.264/H.265."""

ADDS["af-detection-methodology"] = """## Таймлайнинг как инструмент обнаружения

Анти-форензика ломает **согласованность** таймлайна, поэтому именно таймлайн — главный
детектор. Построй события из всех источников и наложи их:

```
$ log2timeline.py --storage-file case.plaso /evidence/
$ psort.py -o l2tcsv -w timeline.csv case.plaso
$ psort.py -o l2tcsv case.plaso 'date > "2026-01-14 02:00:00"' > window.csv
```

Признаки подчистки на таймлайне:

- **Разрыв** — плотный поток событий внезапно обрывается на несколько минут;
- **Скачок** — время прыгает назад/вперёд (смена часов или timestomping);
- **Дубликат** — одно событие есть в одном источнике и отсутствует в другом;
- **«Будущее»** — метка времени позже даты анализа;
- **Порядок** — файл изменён раньше, чем создан.

Наложив три-четыре источника на одну ось времени, аномалии видны как «дыры» и
несоответствия, даже если каждый источник по отдельности выглядит нормально.

## Специфика Linux и Windows

| Аспект | Linux | Windows |
|---|---|---|
| Очистка логов | `journalctl --vacuum`, `> /var/log/x` | `wevtutil cl`, Clear-EventLog |
| Метки времени | atime/mtime/ctime (+birth) | SI vs FN, MFT, USN |
| Следы в истории | `.bash_history`, `auth.log` | PowerShell log, Prefetch |
| Подделка времени | `touch -d` (меняет mtime/atime) | timestomper (SI, не FN) |
| Артефакт-свидетел | `auditd`, `wtmp`/`btmp` | SRUM, Amcache, ShimCache |

На Linux `ctime` подделать сложно (его меняет любое изменение inode), поэтому расхождение
`mtime` в прошлом и свежего `ctime` — сильный признак. На NTFS `$FILE_NAME`-времена почти
не поддаются подделке обычными тулами — расхождение с `$STANDARD_INFORMATION` выдаёт
timestomping.

## Быстрый чек-лист обнаружения

1. Определить ожидаемый набор артефактов (эталон).
2. Построить таймлайн из всех доступных источников.
3. Найти разрывы, скачки и дубликаты.
4. Проверить времена на согласованность (mtime vs ctime, SI vs FN).
5. Поискать следы инструментов очистки в истории и prefetch.
6. Проверить `system.log`/журналы на смену времени и обрыв.
7. Задокументировать каждую аномалию с альтернативным объяснением."""

ADDS["net-cloud-vpcflow"] = """## Приватные эндпоинты и NAT: почему источник обманчив

В flow logs «источник» — это адрес на сетевом интерфейсе, а не обязательно настоящий
клиент. Это важно при анализе:

- **NAT Gateway** — записи показывают приватный IP NAT-инстанса, а не хоста за ним;
- **VPC Endpoints** — трафик к сервисам AWS идёт на приватные IP (например, S3/DynamoDB
  через `pl-...`), и выглядит как «внутренний», хотя это выход в сервис;
- **Load Balancer** — dstaddr может быть адресом балансировщика, а не бэкенда;
- **Elastic IP** — смена EIP меняет картину, старые записи остаются на прежнем адресе.

Поэтому прежде чем делать вывод «инстанс X выгружал данные на Y», сопоставь ENI с
владельцем (`interface-id` → `describe-network-interfaces`) и проверь, не стоит ли между
ними NAT/балансировщик. Иначе можно обвинить не тот инстанс.

## Чек-лист и шаблон вывода

Практический порядок анализа flow logs:

1. Определить версию формата (v2–v5) и поля — иначе `awk` сместится.
2. Отфильтровать `NODATA`/`SKIPDATA` — это не события.
3. Найти `REJECT` — источник сканирования/брутфорса.
4. Сгруппировать `ACCEPT` по dstaddr и сумме `bytes` — искать эксфильтрацию.
5. Выделить нестандартные порты (`dstport NOT IN (80,443,53,...)`).
6. Сопоставить по времени с CloudTrail (API) и DNS-логами (домены).
7. Проверить владельцев ENI, чтобы не ошибиться с источником.

Шаблон записи в отчёт: `время | src (ENI→владелец) | dst | порт | байты | действие |
коррелирующий источник`. Такая строка воспроизводима и проверяема.

## Что искать при эксфильтрации

- **Большой исходящий объём** на один адрес — классика вывода данных.
- **Регулярный beacon** — соединения с примерно равным интервалом (C2 keep-alive).
- **DNS-туннель** — много коротких UDP/53-потоков к одному резолверу.
- **Нетипичные порты** — 4444, 8080, 8443, 53/TCP, 123/UDP как транспорт C2.
- **Прямые соединения к внешним IP** в обход балансировщика.

Эти признаки работают только в сочетании: один крупный поток может быть обычным бэкапом,
а регулярный beacon — штатным мониторингом. Контекст и корреляция решают."""

ADDS["net-vpn"] = """## Сопоставление с поведением и учётными данными

Туннель сам по себе — не приговор. Чтобы понять, был ли он легитимным, сопоставь его с
поведением пользователя и хоста:

```
$ last -F | head            # кто входил и когда
$ grep -i 'vpn\\|tunnel' /var/log/syslog | tail
$ ss -tunp | grep -E '51820|1194|500|4500'
```

Признаки «нештатного» VPN:

- туннель поднят вне рабочих часов и без записи в корпоративной системе VPN;
- `AllowedIPs = 0.0.0.0/0` при том, что корпоративный VPN настроен на split-tunnel;
- endpoint — не корпоративный адрес, а VPS/хостинг;
- конфиг создан недавно, а владелец не помнит установки.

Сопоставление времени поднятия туннеля с временем инцидента часто и есть недостающее
звено между «внешним трафиком» и «конкретным пользователем».

## Быстрый чек-лист по VPN в расследовании

1. Есть дамп? Определи протокол по сигнатуре заголовка, не по порту.
2. WireGuard/OpenVPN без ключей → ограничься фактом и метаданными.
3. Есть ключи/PSK/сертификаты → попробуй расшифровать (OpenVPN, IPsec с известным PSK).
4. Нет дампа → работай по конфигам (`/etc/wireguard`, `/etc/openvpn`, реестр) и логам.
5. Проверь `AllowedIPs`/`redirect-gateway` — full или split tunnel.
6. Проверь DNS-утечки и маршруты (`ip route`, `resolvectl`).
7. Сопоставь время туннеля с сессиями пользователя и инцидентом.

## Что останется на диске после VPN

Даже если трафик не пойман, следы конфигурации и установки остаются:

- установочные пакеты (`wireguard-tools`, `openvpn`) в логах менеджера пакетов;
- ключи и сертификаты в `~/.config`, `/etc/wireguard`, хранилище сертификатов;
- `.ovpn`-профили в «Загрузках» и недавних документах;
- записи в `bash_history` о `wg-quick up`, `openvpn --config`;
- записи DNS/маршрутов, оставшиеся после отключения.

Эти артефакты переживают сам туннель и часто именно в них лежит ответ на вопрос «кто и
зачем»."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("deepened", lid, "+", len(add.split()), "tokens")
    return 0

