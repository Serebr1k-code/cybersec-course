ADDS["forensics-ios-backup"] = """## Ручное восстановление по хешу

Иногда `Manifest.db` повреждён или отсутствует, но сами файлы на диске есть. Тогда
работают «от содержимого»: определяют тип файлов по магии и связывают их с
логическими путями вручную. Полезные команды:

```
$ find Backup/<UDID> -type f -name '????????????????????????????????????????' | head
$ for f in Backup/<UDID>/*/*; do file "$f"; done | grep -i sqlite | head
$ sqlite3 <файл> '.tables'
```

Файлы-базы SQLite опознаются по заголовку `SQLite format 3`. Найдя, например, базу с
таблицей `message`, ты понимаешь, что это `sms.db`, и можешь сопоставить её
логический путь. Такой «археологический» подход медленнее, но спасает повреждённые
бэкапы.

## Сравнение с Android-бэкапом

Android-бэкап (`adb backup` или AB-формат) устроен иначе: это архив с `apps/` и
`shared/`, без хешированных имён, но и без полного набора системных данных. iOS-бэкап
богаче по артефактам (keychain, домены приложений), но сложнее в навигации из-за
хеш-имён. Общий принцип один: есть карта (в iOS — `Manifest.db`), которая связывает
логические пути с физическими файлами; без неё остаётся ручное опознание.

## Практические заметки

Перед разбором сделай рабочую копию бэкапа и не трогай оригинал. Зафиксируй хеши
всех метафайлов. Проверь `IsEncrypted` в `Manifest.plist` — от этого зависит
маршрут. Если бэкап шифрован, пароль храни отдельно от выводов. Для каждого
извлечённого артефакта сохраняй исходный файл и логический путь, чтобы вывод был
воспроизводим. И помни про Apple epoch в каждом временном поле — это самая частая
ошибка при анализе iOS-бэкапов."""

