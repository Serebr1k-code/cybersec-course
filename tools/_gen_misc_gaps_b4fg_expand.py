"""Expansion for MIS-GAP-4f/4g (gvisor, firecracker, qemu) to >=1200 words."""
import re

CONTENT = 'content/misc/'


def add(lesson, text):
    p = CONTENT + lesson + '.md'
    s = open(p, encoding='utf-8').read()
    m = re.search(r'^## Квиз\s*$', s, re.MULTILINE)
    out = s[:m.start()] + text.strip() + '\n\n' + s[m.start():]
    open(p, 'w', encoding='utf-8').write(out)
    print('expanded', lesson)


add('misc-gvisor', '''
## История побегов и типовые баги

gVisor писали с оглядкой на безопасность, но и в нём находили уязвимости. Типовые категории: ошибки в сетевом стеке (netstack) при разборе пакетов от гостя; гонки в файловой подсистеме; ошибки в платформе systrap, где гость и Sentry делят память и общаются через сигналы. Каждая такая ошибка — потенциальный побег, потому что Sentry работает в user space и имеет доступ к хосту. Важно понимать: gVisor не использует ядро хоста для syscalls, поэтому классические приёмы «атаки на ядро» здесь не работают — атаковать нужно Go-код.

## Как устроен netstack

Сетевая подсистема gVisor реализует TCP/IP в user space. Пакеты от гостя попадают в Sentry, который их разбирает и решает, что делать. Это очень сложный код: разбор заголовков, сегментация, пересборка, состояния соединений. Ошибка в разборе длины или смещения даёт OOB. Поэтому netstack — популярная цель: гость может отправлять произвольные пакеты через виртуальный интерфейс, а Sentry их разбирает.

## Практические заметки по анализу

- Идентифицируй версию gVisor: от неё зависят известные CVE.
- Изучи, какие syscalls реализованы, и найди редкие (`io_uring`, `netlink`, `splice`).
- Фаззь из гостя: подавай необычные аргументы и смотри на падения Sentry.
- Читай диффы патчей на GitHub — они показывают исправленные проверки.
- Помни, что Gofer общается с хостом: ошибки в протоколе тоже ведут к побегу.

## Сравнение gVisor с другими песочницами

| Песочница | Ядро | Поверхность |
|---|---|---|
| Docker | ядро хоста | syscalls ядра |
| gVisor | user-space ядро | Go-код Sentry |
| Firecracker | отдельная ВМ | virtio/VMM |
| Kata | ВМ + ядро | гипервизор |

gVisor занимает нишу между контейнером и ВМ: дешевле ВМ, безопаснее контейнера. В CTF это означает специфическую поверхность атаки — user-space код, а не ядро.
''')

add('misc-firecracker', '''
## API-сокет подробнее

Firecracker полностью управляется через REST API на Unix-сокете. Через него создают микровиртуал, добавляют диски, настраивают сеть и запускают её. Если сокет доступен недоверенному коду, атакующий может: добавить диск с собственным образом, изменить параметры загрузки, добавить сетевое устройство. Это прямой путь к контролю над гостем и, при багах в разборе запросов, — к хосту. Поэтому в продакшене сокет закрывают правами доступа и удаляют после настройки.

## Как устроен jailer

jailer — это обёртка, которая запускает Firecracker в изолированном окружении. Она создаёт отдельные namespaces (mount, pid, net), делает chroot в пустой каталог, понижает привилегии до отдельного пользователя, ограничивает ресурсы (cgroups) и закрывает лишние файловые дескрипторы. Идея: даже если VMM скомпрометирован, он заперт в узком окружении и не видит хост. Обход jailer — отдельная задача, требующая бага в ядре или в самой jailer.

## Практические заметки

- Определи, запущен ли jailer: если нет, побег из VMM даёт больше.
- Проверь доступность API-сокета: иногда он смонтирован внутрь гостя.
- Изучи доступные virtio-устройства: сеть и блок — основные цели.
- Ищи известные CVE по версии Firecracker.
- Для отладки используй gdb на процессе Firecracker на хосте.

## Итоговый разбор

Порядок: идентифицируй Firecracker, изучи устройства и API, найди баг в разборе virtqueue или запросов, собери PoC из гостя, оцени ограничения jailer, получи доступ к хосту. Минимализм Firecracker сужает поверхность, но не убирает её: где есть разбор недоверенных данных, там есть баги.
''')

