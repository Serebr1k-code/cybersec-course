import re

ADD = {}

ADD["win-windows-search"] = r'''
## Индексируемые свойства и поиск по содержимому

Индексатор хранит не только путь, но и **свойства документа**: автора, название, ключевые
слова, а для текстовых форматов — фрагменты содержимого. Это значит, что по `Windows.edb`
иногда можно найти файл по слову, которое было **внутри** него, даже если сам файл удалён.
Свойства лежат в отдельных колонках таблицы индекса; ищи их по именам вида `System.*`
(`System.Title`, `System.Author`, `System.Keywords`). Такой поиск полезен в eDiscovery:
«найди все документы, где упоминается кодовое слово», — и индекс отвечает без доступа к
исходным файлам.

## Ограничения индексатора, о которых надо помнить

Индекс — это **производная** структура, а не первичное доказательство. Он зависит от
настроек: пользователь может исключить каталог из индексации, отключить службу или
пересоздать индекс. Отсюда два практических правила. Первое: отсутствие файла в индексе не
доказывает, что файла не было. Второе: наличие файла в индексе доказывает, что индексатор
его «видел», но не доказывает, что пользователь его открывал. Эти оговорки стоит прямо
писать в отчёте — они отделяют корректный вывод от поспешного.
'''

ADD["win-activity-timeline"] = r'''
## Таблица ActivityOperation и удалённые активности

В `ActivitiesCache.db` есть не только `Activity`, но и `ActivityOperation` — журнал
**операций** над активностями (создание, изменение, удаление). Когда пользователь чистит
историю, запись может исчезнуть из `Activity`, но след операции остаётся в
`ActivityOperation`. Для аналитика это второй шанс: иногда именно здесь находится активность,
которую пытались удалить. Смотри колонки с типом операции и временем — они образуют
мини-журнал изменений самой истории.

## Как читать JSON-объект активности вручную

Поле `ContentInfo` — это JSON-строка, и её удобно разобрать по шагам. Выгружаем одну
запись в файл и смотрим форматированно:

```
$ sqlite3 ActivitiesCache.db "SELECT ContentInfo FROM Activity WHERE AppId LIKE '%EXCEL%';" > ci.json
$ python3 -m json.tool ci.json
{
  "displayText": "payroll_q1.xlsx",
  "contentUri": "file:///C:/Users/jdoe/Documents/payroll_q1.xlsx",
  "appId": "EXCEL.EXE"
}
```

Если `json.tool` падает — значит строка не чистый JSON (иногда впереди мусор из SQLite-
страницы). Тогда вырезаем фрагмент между первой `{` и последней `}` и парсим снова. Этот
приём спасает и при разборе других «JSON-в-поле» артефактов.

## Сверка с JumpLists и Prefetch

Timeline говорит «работал с документом», но не всегда даёт **точное число** открытий. Чтобы
усилить вывод, сверяй с JumpLists (недавние документы приложения) и Prefetch (факт запуска
приложения). Если все три источника согласны — вывод прочный. Если Timeline показывает
сессию, а Prefetch не содержит запуска приложения, возможно, данные синхронизированы с
другого устройства, и это надо оговорить.
'''

ADD["win-notification-db"] = r'''
## Практика: извлечение ссылок и вложений из тостов

Многие тосты содержат **ссылку** или имя вложения. Их можно достать, не поднимая полный
парсер:

```
$ strings -el wpndatabase.db | grep -iE 'https?://|\.pdf|\.xlsx|\.docx' | head
https://files.example.com/invoice_4471.pdf
```

Ссылки ценны двумя вещами: домен показывает, с каким сервисом работал пользователь, а имя
файла связывает уведомление с конкретным документом. Дальше эту ссылку можно сопоставить с
браузерной историей и сетевыми логами — получится цепочка «пришло уведомление → открыл
ссылку → скачал файл».

## Сравнение уведомлений с журналами событий

База уведомлений и журнал событий смотрят на разные вещи. EVTX фиксирует **системные**
события (входы, службы, ошибки), а `wpndatabase.db` — то, что **видел пользователь**. В
расследовании они дополняют друг друга: журнал скажет, что служба запустилась, а база
уведомлений — что пользователю прилетел тост об этом. Держи оба источника под рукой: иногда
именно текст уведомления даёт контекст, которого нет в формальном журнале.

## Полный прогон от начала до конца

Соберём всю практику вместе. Дано: образ диска, задача — доказать получение конкретного
сообщения. Шаг первый: находим базу в профиле и опознаём формат (`file wpndatabase.db`).
Шаг второй: ищем читаемые строки (`strings -el ... | grep -i <слово>`). Шаг третий: если
нужен контекст, выгружаем payload и смотрим приложение-источник по `HandlerId`. Шаг
четвёртый: сопоставляем время с журналом событий и Timeline. На выходе — восстановленный
текст, источник, время и связь с другими действиями. Вся цепочка занимает несколько команд
и не требует запуска Windows: всё делается над копией файла.
'''

ADD["win-cortana-search"] = r'''
## Полный прогон: от запроса к выводу об антифорензике

Пройдём сценарий целиком. Дано: подозрение, что пользователь пытался скрыть следы.
Шаг первый — извлекаем запросы с временем и сортируем. Шаг второй — категоризируем:
запросы про очистку журналов и «wipe» попадают в антифорензику. Шаг третий — ищем
**последствия**: в Timeline — сессии `cmd.exe`/`powershell.exe`, в Prefetch — запуск
утилит, в журнале — событие очистки (`wevtutil`). Шаг четвёртый — формулируем вывод:
«пользователь искал способ очистить журналы и вскоре выполнил соответствующую команду».
Именно связка «запрос + последующее действие» превращает догадку в обоснованный вывод.

## Где ещё хранятся поисковые данные

Кроме основной базы, следы поиска встречаются в нескольких местах профиля: кэш пакета
`Microsoft.Windows.Search`, файлы подсказок, а иногда — в истории браузера, если поиск
уходил в веб. Полезно сделать общий проход по профилю:

```
$ find . -iname '*.db' -o -iname '*history*' | head -20
```

Не ограничивайся одним файлом: цель — собрать **все** источники и свести их в один
таймлайн. Тогда даже если часть истории очищена, оставшиеся следы позволят восстановить
картину.

## Настройки и реестр

Поведение поиска и Cortana регулируется настройками приватности (ключи в реестре и
политики). Для аналитика это важно по двум причинам. Во-первых, по настройкам видно,
**собирал ли** хост историю вообще: если сбор отключён, пустая история — ожидаема, а не
подозрительна. Во-вторых, изменения этих настроек перед инцидентом сами могут быть уликой.
Проверяй ветки политик поиска, но не переоценивай их: настройки говорят о конфигурации, а
не о конкретных действиях.
'''

for lid, add in ADD.items():
    p = f"content/forensics/{lid}.md"
    t = open(p, encoding="utf-8").read()
    m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
    assert m, lid
    out = t[:m.start()] + add.strip() + "\n\n" + t[m.start():]
    open(p, "w", encoding="utf-8").write(out)
    print("expanded2", lid)
