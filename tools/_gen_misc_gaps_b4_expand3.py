import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, 'content', 'misc')

EXPANSIONS = {}

EXPANSIONS['misc-llm-rag'] = '''
## Как выбрать вопрос-приманку

Чтобы чанк с инъекцией достали, нужен запрос, близкий к нему. Практика: сначала найди популярные вопросы бота (по логам, по FAQ), затем подгони документ под них. Если логов нет, используй общие темы: возврат, оплата, доставка, пароль, тариф. Чем чаще тему спрашивают, тем выше шанс, что именно твой чанк попадёт в топ. Это разведка перед атакой, и она часто важнее самого payload.

## Гибридный поиск и почему он усложняет жизнь

Многие базы используют гибрид: векторную близость плюс полнотекстовый BM25. Тогда документ с точными ключевыми словами поднимается выше. Для атакующего это удобно: добавь редкое слово из вопроса пользователя — и BM25 вытянет чанк. Для защищающегося это дополнительная сложность: нужно фильтровать и семантику, и ключевые слова.
'''

EXPANSIONS['misc-llm-guardrails'] = '''
## Тестирование фильтра как чёрного ящика

У тебя нет исходников guardrail — только ответы. Строй эксперимент: бинарный поиск по формулировкам, чтобы понять, что именно триггерит фильтр (слово, фраза, тема). Пробуй минимальные пары: меняешь одно слово — смотришь, изменился ли вердикт. Так восстанавливается «граница» фильтра, а значит, и обход. Это тот же подход, что при фаззинге валидатора.

## Ложные срабатывания как вектор

Слишком строгий guardrail — тоже проблема. Если он блокирует безобидные запросы, продукт ломается, и команда ослабляет правила. Ослабленное правило открывает старый обход. Поэтому при аудите полезно искать не только «что фильтр пропускает», но и «на что он ругается зря»: найденные ложные срабатывания показывают, где защита тонкая и, вероятно, будет ослаблена.
'''

EXPANSIONS['misc-mcp-security'] = '''
## Согласие пользователя и его пределы

Клиент обычно показывает список инструментов и просит подтверждения. Но пользователь не читает описания — он жмёт «разрешить». Поэтому согласие почти ничего не защищает: отравленное описание проходит вместе с разрешением. Правильнее — не полагаться на «прочитал и согласился», а ограничивать права технически: что инструмент может, а не что пользователь подтвердил.

## Инвентаризация как первый шаг аудита

Начни с карты: какие серверы подключены, какие инструменты объявлены, какие права у процесса. Часто обнаруживается, что у «файлового» сервера есть сетевой доступ, а у «поискового» — запись на диск. Инвентаризация выявляет лишние права ещё до атак. Дальше — для каждого инструмента проверь валидацию входа и логирование.
'''

EXPANSIONS['misc-agentic-escape'] = '''
## Роль наблюдаемости в защите

Защита агента — это на треть архитектура, на треть права и на треть наблюдаемость. Если ты видишь все tool-calls, аномалию легко заметить: агент внезапно читает `.env` или стучится на незнакомый домен. Без логов инцидент обнаруживается только по факту утечки. Поэтому при аудите первым делом спроси: где логи и что в них видно.

## Как разбирать инцидент с агентом

Порядок: восстанови хронологию tool-calls; найди точку инъекции (какой документ/ответ её принёс); определи, какие данные прочитаны; куда ушли (сеть, git, DNS); какие права позволили; что нужно было подтверждение, но его не было. Из разбора вытекают меры: закрыть канал, сузить права, добавить детект. Этот же порядок годится для CTF: лог показывает и путь, и флаг.
'''

def insert_before_quiz(path, extra):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    idx = text.find('\n## Квиз')
    if idx < 0:
        raise SystemExit('no Квиз in ' + path)
    text = text[:idx] + '\n' + extra.strip() + '\n' + text[idx:]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)

for lid, extra in EXPANSIONS.items():
    insert_before_quiz(os.path.join(CONTENT, lid + '.md'), extra)
    print('expanded3', lid)
print('b4 expand3 done')
