from __future__ import annotations
import re, sys

ADDS = {}

ADDS["forensics-cloud-serverless"] = r"""## Эфемерность и её последствия

Serverless-функция — это контейнер, который создаётся под запрос и уничтожается после
него. Между вызовами платформа может **переиспользовать** тот же экземпляр (warm
start), поэтому данные в `/tmp` иногда переживают несколько вызовов. Это важно для
форензика: атакующий может оставить в `/tmp` инструмент или файл, и он будет доступен
следующему вызову. Но после «остывания» (cold start) всё исчезает. Диск не сохраняется,
память не сохраняется — остаются только логи, метрики и конфигурация. Отсюда правило:
**в serverless форензика начинается с логирования**, а не с диска.

## Устройство логов CloudWatch

Каждая функция пишет в свою **лог-группу** `/aws/lambda/<имя>`. Внутри — **лог-потоки**,
обычно по одному на экземпляр, а в них — строки вида:

```
2026-01-14T03:20:00.123Z  START RequestId: 8f2b-... Version: $LATEST
2026-01-14T03:20:01.456Z  downloading http://203.0.113.5/x
2026-01-14T03:20:02.789Z  END RequestId: 8f2b-...
2026-01-14T03:20:02.789Z  REPORT RequestId: 8f2b-... Duration: 2665.12 ms Billed Duration: 2666 ms
```

`START`/`END`/`REPORT` платформа добавляет сама; между ними — вывод `stdout`/`stderr`
функции. Именно там оказываются URL, ошибки, отладочные строки. `RequestId` связывает
строки одного вызова, а `Duration` помогает заметить выбросы (например, майнинг или
ожидание C2).

## Атаки на serverless

Типовые векторы:

- **инъекция в event** — данные из API Gateway/S3 попадают в код без валидации
  (command injection, SSRF, десериализация);
- **отравление зависимостей/слоёв** — вредоносный пакет в слое или `requirements`;
- **кража временных креденшелов** — `AWS_ACCESS_KEY_ID`/`AWS_SECRET_ACCESS_KEY`/
  `AWS_SESSION_TOKEN` лежат в переменных окружения функции;
- **злоупотребление ролью** — функция с широкими правами превращается в точку входа;
- **использование функции как прокси** — SSRF или майнинг за счёт платформы;
- **изменение кода** — `UpdateFunctionCode` заменяет функцию вредоносной.

В расследовании ищи в логах аномальные внешние соединения, необычные ошибки, признаки
SSRF, а в CloudTrail — изменения кода и прав.

## Роль, временные креды и движение

Функция исполняется под **IAM-ролью**; платформа выдаёт временные креды через переменные
окружения. Компромисс функции = компромисс её прав. Дальше атакующий может:

- вызывать другие AWS-сервисы в рамках прав роли (`sts:AssumeRole`, доступ к S3,
  DynamoDB, Secrets Manager);
- повышать привилегии через `iam:PassRole` + запуск функции/задачи с более широкой ролью;
- использовать `sts:GetCallerIdentity` для разведки.

Проверь, какие действия совершались под ролью функции в CloudTrail после инцидента —
это покажет «куда пошёл» атакующий.

## Версии, слои и конфигурация

- **версии функции** — каждая публикация имеет номер; сравни код `$LATEST` с предыдущей
  версией, чтобы найти изменения;
- **слои (layers)** — общие библиотеки; отравленный слой затрагивает много функций;
- **переменные окружения** — секреты, которые могли утечь;
- **таймаут и память** — изменение в сторону увеличения намекает на майнинг;
- **триггеры** — откуда приходят события (API Gateway, S3, EventBridge, SQS).

Конфигурацию смотри через `aws lambda get-function-configuration`; историю версий —
через `list-versions-by-function`.

## Восстановление картины: X-Ray и CloudTrail

**AWS X-Ray** строит трассировку вызовов: видно, какие внешние сервисы дёргала функция,
сколько это заняло. Это помогает обнаружить неожиданные обращения (SSRF/C2).
**CloudTrail** фиксирует management-события: `UpdateFunctionCode`, `CreateFunction`,
`AddPermission`, `PutRolePolicy`. Совмещая трассировку и API-логи, восстанавливают
цепочку: что функция делала и кто её менял.

## Практический разбор

Функция `image-resize` неожиданно стала обращаться к внешнему IP. Ход:

1. `aws logs filter-log-events --log-group-name /aws/lambda/image-resize` — ищем URL/IP
   в stdout.
2. Смотрим `START`/`REPORT`: длительность выросла — признак ожидания или майнинга.
3. `aws lambda get-function-configuration` — проверяем роль, env, слои.
4. `aws cloudtrail lookup-events --lookup-attributes AttributeKey=EventName,AttributeValue=UpdateFunctionCode`
   — кто и когда менял код.
5. `aws lambda list-versions-by-function` — сравниваем версии.
6. Смотрим трассировки X-Ray на внешние вызовы.

Итог: находим изменённую версию, вредоносный код и внешний endpoint — с доказательствами.

## Частые ошибки

- **Ждать «дамп диска».** Его не будет; работай с логами и конфигом.
- **Игнорировать `/tmp`.** Warm-инстанс может хранить файлы между вызовами.
- **Смотреть только код.** Роль, слои и env не менее важны.
- **Забыть про версии.** Сравнение `$LATEST` с предыдущей версией часто и показывает
  взлом.
- **Не проверять CloudTrail.** Изменения функции видны только там.

## Что писать в отчёте

Источник логов и период, найденные URL/IP и аномалии, длительность вызовов, роль и её
права, изменённые версии и слои, события CloudTrail об изменении кода, трассировки
X-Ray. Каждый вывод — со ссылкой на строку лога или событие. Отметь, что логирование
могло быть выключено и что осталось вне охвата."""

ADDS["spec-gps"] = r"""## Форматы глубже: NMEA, FIT, KML

Кроме GPX встречаются:

- **NMEA 0183** — сырые строки от приёмника. Ключевые предложения: `$GPGGA` (фикс,
  координаты, высота, число спутников, HDOP), `$GPRMC` (дата/время, статус, скорость,
  курс), `$GPGSV` (видимые спутники). Пример:

```
$GPGGA,032000.00,5545.000,N,03737.000,E,1,08,0.9,156.0,M,11.0,M,,*6F
```

- **FIT** — бинарный формат спортивных устройств (Garmin, Polar): записи о точках,
  пульсе, каденсе. Разбирается `fitparse` или `gpsbabel`.
- **KML** — XML для Google Earth, часто производный от GPX.

Понимание формата важно: NMEA даёт «сырьё» (и погрешности), GPX/KML — уже
обработанный трек, FIT — богатый набор сенсорных данных.

## Время: GPS-время, UTC и leap seconds

GPS-приёмник считает время от эпохи 1980-01-06 (GPS time). Оно опережает UTC на число
**leap seconds** (на 2026 год — 18 секунд), потому что UTC периодически вставляют
секунды, а GPS — нет. Приёмник обычно сам конвертирует в UTC, но сырые NMEA-строки
могут содержать GPS-время. Всегда проверяй:

- есть ли `Z` в конце (UTC) или время локальное;
- соответствует ли дата реальной (устройства с севшей батареей сбрасываются к эпохе);
- нет ли **week rollover** (счётчик недель GPS обнулялся в 1999 и 2019).

Ошибка во времени ломает всю привязку трека к событиям — это первое, что проверяют.

## Точность и качество: HDOP и спутники

Точность точки оценивается по **HDOP** (Horizontal Dilution of Precision) и числу
спутников. HDOP < 1 — отлично, 1–2 — хорошо, > 5 — плохо. Мало спутников и высокий
HDOP означают, что координата может «уехать» на десятки метров. В помещении и тоннелях
фикс теряется, и трек «прыгает». При сопоставлении с местом события всегда указывай
HDOP/точность, иначе вывод уязвим: точка могла быть шумом.

## Подделка и глушение (spoofing/jamming)

GPS-сигнал слабый и незашифрованный, поэтому его можно **глушить** (jamming — пропадает
фикс) или **подменять** (spoofing — приёмник показывает ложные координаты). Признаки
подделки в треке:

- физически невозможная скорость (километры за секунды);
- идеально прямая линия там, где должна быть дорога;
- мгновенный «телепорт» в другую точку и обратно;
- координаты на нуле/за границей (артефакт сброса);
- рассинхрон с сотовыми/Wi-Fi-данными.

Подделанный трек выявляется **сопоставлением** с независимыми источниками.

## Сопоставление трека с делом

Трек сам по себе — лишь точки. Доказательную силу он получает в связке:

- **с событиями** (звонки, транзакции, логи входов) по времени;
- **с Wi-Fi/сотами** — где устройство было по сети;
- **с картой** — маршрут физически проходим?
- **со скоростью** — не превышает ли физических пределов;
- **со стоянками** — кластеры точек в одном месте = пребывание.

Совпадение трека и другого артефакта по времени и месту резко повышает достоверность.

## Инструменты

- **`gpsbabel`** — конвертация между GPX/NMEA/KML/FIT и фильтрация;
- **`exiftool`** — чтение GPS-меток из фото/видео;
- **QGIS/Google Earth** — визуализация маршрута;
- **`gpxpy`** (Python) — программный разбор GPX;
- **`fitparse`** — разбор FIT.

Визуализация важна: на карте аномалии («телепорты», прямые линии) видны сразу.

## Практический разбор

Трек из навигатора нужно привязать к времени звонка. Ход:

1. Разбираем GPX: `gpsbabel -i gpx -f track.gpx -o csv -F track.csv`.
2. Проверяем время: все ли точки с `Z`, нет ли сброса к 1980.
3. Строим маршрут на карте, ищем стоянки и аномалии.
4. Находим точку, ближайшую ко времени звонка.
5. Считаем скорость между соседними точками — физически возможна?
6. Сверяем с сотовыми данными за тот же период.

Итог — обоснованное «в момент звонка устройство было здесь», с оговоркой о точности.

## Частые ошибки

- **Доверять времени как есть.** Часовой пояс и leap seconds ломают привязку.
- **Игнорировать точность.** Без HDOP точка недоказуема.
- **Путать спидометр и трек.** Скорость из трека может «шуметь».
- **Считать трек подлинным.** Слабый сигнал подделывается; нужна перекрёстная проверка.
- **Забывать про конвертацию.** Разные форматы по-разному кодируют время и координаты."""

ADDS["doc-xps"] = r"""## Анатомия пакета OPC

XPS построен на **Open Packaging Conventions (OPC)** — той же основе, что и OOXML.
Структура:

```
[Content_Types].xml            # типы всех частей
_rels/.rels                    # корневые связи (указывает на FixedDocumentSequence)
FixedDocumentSequence.fdseq    # «оглавление»: список документов
Documents/1/FixedDocument.fdoc # фиксированный документ
Documents/1/Pages/1.fpage      # страница (XML с содержимым)
Documents/1/Resources/...      # ресурсы (шрифты, изображения)
Metadata/...                   # свойства документа
```

`[Content_Types].xml` и `_rels` — «навигация» пакета. `FixedDocumentSequence` указывает,
какие документы входят в пакет, `FixedDocument` — какие страницы, `FixedPage` — что на
странице. Всё это XML; связи между частями заданы в `_rels`.

## Извлечение текста: Glyphs и UnicodeString

Текст страницы лежит не как обычные символы, а в элементах `Glyphs` с атрибутом
`UnicodeString` (и `Indices` — картой глифов):

```xml
<Glyphs OriginX="96" OriginY="96" FontUri="/Resources/Fonts/1.ttf"
        UnicodeString="Confidential Report" Indices=",,;,,,,,;" />
```

Быстрое извлечение:

```
$ unzip -p doc.xps 'Documents/1/Pages/1.fpage' | grep -o 'UnicodeString="[^"]*"' | head
UnicodeString="Confidential Report"
```

Порядок фрагментов определяется `OriginX`/`OriginY` (координатами), поэтому для
правильного чтения нужно сортировать по позиции, а не по порядку в файле. `Indices`
описывает, какие именно глифы шрифта использованы — важно при извлечении нестандартных
шрифтов.

## Ресурсы: изображения, шрифты, кисти

Ресурсы XPS лежат в `Resources/`:

- **изображения** — внедрены как отдельные части (PNG/JPEG), на них ссылаются кисти
  `ImageBrush`;
- **шрифты** — могут быть внедрены (`FontUri`), что иногда даёт метаданные шрифта;
- **кисти** (`SolidColorBrush`, `VisualBrush`) — определяют оформление.

Внедрённые изображения можно вытащить и проанализировать (EXIF, стеганография).
Внешние ссылки (`xlink:href`) указывают на ресурсы вне пакета — их проверяют на
утечку/подгрузку.

## Метаданные и цифровая подпись

Свойства документа — в `Metadata/`, в формате XMP/`psf:DocumentProperties`:

```xml
<psf:DocumentProperties>
  <psf:Author>Ivan</psf:Author>
  <psf:Title>Договор</psf:Title>
</psf:DocumentProperties>
```

XPS поддерживает **цифровые подписи** (в отличие от простого ZIP с картинками): в
пакете могут быть части подписи (`_rels/.signature`) и `SignatureDefinitions`. Если
подпись есть — её стоит проверить: подлинность и целостность. Отсутствие подписи — не
признак подделки, но её наличие — сильное доказательство.

## OXPS и edge cases

- **OXPS** (OpenXPS) — открытая версия формата, структура та же; `file` может
  определить иначе, но разбор идентичен.
- **Повреждённый ZIP** — как и ODF, восстанавливается `unzip -FF`; страницы часто
  читаются даже из обрезанного файла.
- **Только изображения** — страница может быть целиком картинкой (`ImageBrush`), тогда
  текст извлекается OCR, а не из `UnicodeString`.
- **Множество документов** — `FixedDocumentSequence` может ссылаться на несколько
  `FixedDocument`; не ограничивайся первым.

## Практический разбор

Изъят `.xps` с «распиской». Ход:

1. `unzip -l doc.xps` — состав пакета.
2. `unzip -p doc.xps 'Metadata/*'` — автор и заголовок.
3. `unzip -p doc.xps 'Documents/1/Pages/1.fpage' | grep -o 'UnicodeString="[^"]*"'` —
   текст.
4. Проверяем координаты (`OriginX`/`OriginY`) для правильного порядка.
5. Ищем `Resources/` — внедрённые изображения.
6. Проверяем наличие подписи.

Итог — автор, текст, ресурсы и статус подписи, всё привязано к частям пакета.

## Частые ошибки

- **Путать XPS и PDF.** XPS — ZIP+XML, PDF — бинарный; методы разные.
- **Читать текст в порядке файла.** Нужна сортировка по координатам.
- **Игнорировать подпись.** Её наличие/отсутствие — важный факт.
- **Забыть про ресурсы.** Картинки могут содержать EXIF и стеганографию.
- **Считать, что текст всегда в `UnicodeString`.** Иногда страница — картинка.

## Что писать в отчёте

Состав пакета, метаданные (автор, заголовок), извлечённый текст с методом, найденные
ресурсы (с типом), статус цифровой подписи. Каждый вывод — со ссылкой на часть
контейнера. Отметь, если текст извлекался OCR и потому менее надёжен."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
