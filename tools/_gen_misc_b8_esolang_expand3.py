def ins(path, extra):
    with open(path, encoding='utf-8') as f:
        t = f.read()
    i = t.find('\n## Квиз')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(t[:i] + '\n' + extra.strip() + '\n' + t[i:])


