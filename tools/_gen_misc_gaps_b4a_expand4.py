"""Fourth top-up for MIS-GAP-4a lessons still under 1200 words."""
import re

CONTENT = 'content/misc/'


def add(lesson, text):
    p = CONTENT + lesson + '.md'
    s = open(p, encoding='utf-8').read()
    add_txt = text.strip()
    m = re.search(r'^## Квиз\s*$', s, re.MULTILINE)
    out = s[:m.start()] + add_txt + '\n\n' + s[m.start():]
    open(p, 'w', encoding='utf-8').write(out)
    print('topped', lesson)


add('misc-java-sandbox', '''
## Итоговый разбор по шагам

Соберём весь путь решения в одну последовательность, чтобы её можно было воспроизвести на любой похожей задаче. Сначала выясняем, включён ли менеджер и какая у него политика: `System.getSecurityManager()` возвращает объект или `null`. Затем пробуем очевидный `System.setSecurityManager(null)` — он почти всегда запрещён, и это нормально: запрет подтверждает, что менеджер активен. Дальше идём через рефлексию: получаем `Class` объекта `System`, достаём приватное поле `security`, вызываем `setAccessible(true)` и записываем `null`. Если политика не перечисляла `ReflectPermission("suppressAccessChecks")`, операция проходит.

После снятия менеджера работаем обычными API: `Files.readString`, `new FileInputStream`, `Runtime.getRuntime().exec`. Все они теперь не спрашивают разрешений. Если рефлексия закрыта, остаются `Unsafe`, JNDI и десериализация — каждый из них обходит модель по-своему, и в реальных задачах обычно находится хотя бы один незакрытый путь. Главное — не застревать на одном векторе и проверять конфигурацию политики, а не перебирать наугад.
''')

