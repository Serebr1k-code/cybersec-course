import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOB = os.path.join(ROOT, 'content', 'mobile')


def add_before_quiz(lid, extra):
    p = os.path.join(MOB, lid + '.md')
    t = open(p, encoding='utf-8').read()
    first = next((ln.strip() for ln in extra.splitlines() if ln.strip()), '')
    if first and first in t:
        print('skip (already deepened):', lid)
        return
    i = t.index('\n## Квиз')
    t = t[:i] + '\n' + extra.strip() + '\n' + t[i:]
    open(p, 'w', encoding='utf-8').write(t)
    print('deepened:', lid)


SIGN = '''
## Шаг 8: designated requirement — что именно проверяет система

У подписи есть не только сертификат, но и **Designated Requirement (DR)** — правило, по
которому систему решает, «тот ли это бинарник». DR формулируется как логическое выражение
поверх идентификатора и сертификата: «бинарник с таким-то identifier, подписанный
сертификатом такой-то команды». Когда система проверяет подпись, она проверяет именно DR, а
не просто «есть ли подпись».

```bash
$ codesign -d -r- example.app
designated => identifier "com.example.app" and anchor apple generic
  and certificate leaf[subject.OU] = "ABCDE12345"
```

Читаем: идентификатор `com.example.app`, корень — Apple, а лист сертификата принадлежит
команде `ABCDE12345`. Это и есть правило. Для атакующего важно: если DR слишком слабый
(например, не привязан к команде), то переподписанное чужое приложение может «подойти» под
него. Для защищающегося — DR должен быть максимально строгим.

## Шаг 9: подпись и джейлбрейк — ldid и fakesign

На джейлбрейкнутом устройстве проверку подписи можно ослабить. Инструмент `ldid` создаёт
«фейковую» подпись (`fakesign`), которой достаточно для запуска на устройстве с отключённой
проверкой `amfi`. Это позволяет устанавливать модифицированные сборки без валидного
сертификата Apple.

```bash
$ ldid -S -M -K key.p12 -s example_binary
```

Ключевой вывод: на чистом устройстве такой трюк не работает — там подпись проверяется
аппаратно и обойти её без уязвимости нельзя. Поэтому джейлбрейк — это не «мелочь», а условие,
при котором многие атаки на iOS вообще становятся возможными. Для пентеста это означает:
если приложение проверяет только «есть ли подпись», на джейлбрейке это ничего не значит.

## Шаг 10: полный разбор стороннего IPA

Соберём типичный сценарий анализа. Вы получили IPA и хотите понять, что внутри и как оно
подписано.

```bash
$ unzip -o target.ipa -d t/
$ codesign -dvvv t/Payload/Target.app 2>&1 | grep -E 'Authority|Team|Identifier'
Authority=Apple iPhone OS Application Signing
Authority=Apple Root CA
TeamIdentifier=ZZZ9999999
Identifier=com.vendor.target
$ codesign -d --entitlements :- t/Payload/Target.app
... (список прав)
$ security cms -D -i t/Payload/Target.app/embedded.mobileprovision | plutil -p - | head
{
  "Name" => "Target Distribution"
  "TeamIdentifier" => ["ZZZ9999999"]
}
```

Из этого сразу видно: команда (`ZZZ9999999`), идентификатор приложения, набор прав и тип
профиля. Дальше эти данные используются и для переподписи, и для серверных проверок, и для
понимания, какие возможности приложение реально использует. Именно с такого разбора
начинается любой серьёзный анализ iOS-приложения.

## Шаг 11: почему подпись — не «печать на бумаге»

Важно не воспринимать подпись как формальность. Она — активная защита: ядро сверяет её при
каждом запуске, а серверные схемы (App Attest) строятся поверх. Поэтому любые манипуляции с
бинарником — патч, инъекция, смена ресурсов — требуют переподписи, а переподпись требует
своего сертификата и профиля. Эта цепочка ограничений и есть то, что делает iOS в целом
устойчивее к модификации приложений, чем настольные системы.
'''

ENT = '''
## Шаг 8: App Groups и общие контейнеры

Помимо Keychain, приложения одного разработчика могут делить файловый контейнер через
`com.apple.security.application-groups`. Это используется для обмена данными между
приложением и его расширениями (виджеты, share-расширения). Право выглядит так:

```bash
$ codesign -d --entitlements :- Widget.appex
  <key>com.apple.security.application-groups</key>
  <array><string>group.com.example.shared</string></array>
```

Общий контейнер лежит по пути, начинающемуся с `group.`. Ошибка здесь — положить в общий
контейнер чувствительные данные (токены, ключи), к которым получают доступ все приложения
группы. Если хотя бы одно из них скомпрометировано, секреты утекают. Поэтому аудит должен
проверить, что именно лежит в общем контейнере, и нет ли там того, что должно быть приватным.

## Шаг 9: entitlement как цель атаки

Entitlements — не только защита, но и цель. Представим: приложение заявляет
`associated-domains` для `applinks:bank.example`. Сервер полагает, что открывать ссылки в
этом домене может только официальное приложение. Атакующий переподписывает свою сборку с тем
же `associated-domains` и bundle id — и серверные проверки, основанные только на домене,
обходятся.

Отсюда правило: **entitlements подтверждают возможности, но не личность**. Всё, что можно
переподписать, нельзя считать доказательством. Именно поэтому сильные схемы добавляют
аппаратную аттестацию, которая привязывает запрос к ключу в Secure Enclave и хешу конкретной
сборки.

## Шаг 10: чек-лист аудита entitlements

Практический список, по которому удобно проходить приложение:

1. Выгрузить все entitlements (`codesign -d --entitlements :-`).
2. Отметить отладочные права (`get-task-allow`, `task_for_pid-allow`) — в релизе их быть не
   должно.
3. Проверить группы Keychain и App Groups на предмет избыточной ширины (wildcard).
4. Убедиться, что нет `com.apple.private.*` у стороннего приложения.
5. Сверить entitlements в подписи и в профиле — расхождение подозрительно.
6. Для каждой возможности подумать, не полагается ли на неё сервер как на доказательство.

Такой проход занимает минуты, но регулярно выявляет как минимум избыточные права, а иногда и
серьёзные дыры в дизайне.

## Шаг 11: entitlement и расширения

Отдельный случай — расширения (app extensions). У каждого расширения свой набор entitlements
и свой sandbox. Общие данные между приложением и расширением передаются через App Groups или
общий Keychain. Ошибка в конфигурации группы приводит к тому, что расширение получает больше
доступа, чем нужно, — а расширения часто менее защищены и чаще содержат уязвимости. При
аудите полезно смотреть entitlements каждого `.appex` отдельно, а не только основного бандла.
'''

ATTEST = '''
## Шаг 8: как выглядит серверная проверка

Разберём правильную проверку аттестации на псевдокоде, чтобы стало понятно, где обычно
теряют защиту.

```text
def verify_attestation(obj, challenge, expected_rp):
    chain = obj.cert_chain
    assert verify_chain_to_apple_root(chain)      # 1. корень Apple
    assert obj.rp_id == expected_rp               # 2. bundle id / rpId
    assert obj.nonce == hash(challenge)           # 3. challenge
    assert obj.counter > last_seen_counter[rp]    # 4. монотонный счётчик
    assert obj.bundle_hash == expected_hash       # 5. хеш сборки
    return True
```

Пять проверок. На практике чаще всего пропускают **третью** (challenge) и **четвёртую**
(счётчик). Без challenge старый валидный ответ можно переиграть (replay), без счётчика — тем
более. Именно поэтому в реальных приложениях аттестация иногда оказывается «включена, но
бесполезна».

## Шаг 9: DeviceCheck подробнее

DeviceCheck — более простой API. Он хранит на стороне Apple **два бита** состояния для пары
(устройство, разработчик). Применение:

- «это устройство уже получало бесплатный период»;
- «это устройство уже использовало промокод»;
- антифрод-флаги.

```text
DCDevice.generateToken { token in
  // отправить token на сервер, сервер спросит Apple о битах
}
```

DeviceCheck не даёт криптографической аттестации — это просто состояние, которое хранит Apple
и которое нельзя подделать локально. Часто его комбинируют с App Attest: аттестация
доказывает подлинность, DeviceCheck хранит память о прошлых действиях.

## Шаг 10: границы и реальные обходы

Что реально встречается на пентестах:

- **Аттестация только на клиенте.** Приложение проверяет свой локальный флаг и не отправляет
  объект на сервер — обходится патчем.
- **Проверка без challenge.** Сервер принимает любой валидный объект, старые переигрываются.
- **Онбординг без проверки.** Первый запрос (регистрация ключа) не защищён, и можно
  зарегистрировать свой ключ.
- **Смешение окружений.** Development-аттестация принимается в production.

Ни один из этих обходов не ломает Secure Enclave — они ломают **логику проверки**. Вывод:
криптография здесь сильная, а слабое звено почти всегда — серверная реализация. Поэтому при
пентесте iOS-приложения с App Attest основное внимание стоит уделять бэкенду и границе
онбординга, а не попыткам «взломать» Secure Enclave.
'''

PROV = '''
## Шаг 7: как получить и обновить профиль

Профиль создаётся в Apple Developer Portal или через Xcode. В нём фиксируются: какой
сертификат использовать, какие устройства разрешены, какие entitlements допустимы. При
сборке профиль вшивается в бандл как `embedded.mobileprovision`, а на устройстве ещё
устанавливается как «профиль конфигурации».

```bash
$ security find-identity -v -p codesigning
  1) ABC... "Apple Development: Ivan (ABCDE12345)"
$ xcodebuild -exportArchive -archivePath App.xcarchive \
    -exportOptionsPlist export.plist -exportPath out/
```

Смысл: профиль — это не файл «на всякий случай», а активный документ, который Apple
подписывает и который устройство проверяет. Изменили устройство или права — нужно создать
новый профиль и переподписать сборку.

## Шаг 8: enterprise-профили и их злоупотребление

Enterprise (In-House) профили предназначены для внутреннего распространения в компании: они
не требуют UDID, поэтому приложение можно поставить на любое устройство. Это удобно для
сотрудников — и опасно, если профиль утечёт. Злоумышленники используют утекшие
enterprise-сертификаты, чтобы распространять подписанные приложения вне App Store, в обход
проверок магазина.

```bash
$ security cms -D -i leaked.mobileprovision | grep -A3 Entitlements
  <key>get-task-allow</key><false/>
  <key>application-identifier</key>
  <string>TEAMID.com.attacker.app</string>
```

Apple активно отзывает такие сертификаты, но до отзыва приложение работает. Отсюда правило
для серверов: **не доверяйте приложению только потому, что оно «подписано Apple»** —
enterprise-подпись может быть у злоумышленника.

## Шаг 9: практический чек-лист аудита профиля

При оценке профиля проверьте:

1. Тип профиля (`get-task-allow` обычно указывает на development).
2. Наличие и содержимое `ProvisionedDevices` — нет ли чужих UDID.
3. Сроки (`CreationDate`, `ExpirationDate`) — не истёк ли.
4. Совпадение `TeamIdentifier` с ожидаемым.
5. Соответствие entitlements в профиле и в подписи.

Профиль с чужими устройствами или истёкшим сроком — повод для находки. Профиль с
избыточными правами — повод проверить, не полагается ли на них сервер.

## Шаг 10: почему это часть общей картины

Provisioning-профиль замыкает цепочку iOS: сертификат → подпись → entitlements → профиль →
установка. Понимание этой цепочки позволяет и атаковать (переподпись, sideloading,
использование утекших enterprise-сертификатов), и защищаться (строгие серверные проверки,
аттестация, контроль профилей). В пентесте iOS-приложений аудит профиля и подписи — это
первый шаг, без которого не понять, какие атаки вообще применимы к конкретному приложению.
'''

