import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, 'content', 'osint')

def add(lesson_id, text):
    path = os.path.join(CONTENT, lesson_id + '.md')
    s = open(path, encoding='utf-8').read()
    if text.strip()[:40] in s:
        print('already:', lesson_id); return
    m = re.search(r"^## Квиз\s*$", s, re.MULTILINE)
    s = s[:m.start()] + text.strip() + "\n\n" + s[m.start():]
    open(path, 'w', encoding='utf-8').write(s)
    print('expanded', lesson_id)

