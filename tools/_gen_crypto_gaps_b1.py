AL = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'


SQ = 'ABCDEFGHIKLMNOPQRSTUVWXYZ'  # 5x5, I/J merged


def polybius_square():
    return {c: (i // 5, i % 5) for i, c in enumerate(SQ)}


def bifid_encrypt(pt):
    pos = polybius_square()
    pt = ''.join(c for c in pt.upper().replace('J', 'I') if c in AL)
    seq = [pos[c][0] for c in pt] + [pos[c][1] for c in pt]
    return ''.join(SQ[seq[i] * 5 + seq[i + 1]] for i in range(0, len(seq), 2))


def bifid_decrypt(ct):
    inv = {c: (i // 5, i % 5) for i, c in enumerate(SQ)}
    ct = ''.join(c for c in ct.upper().replace('J', 'I') if c in AL)
    seq = []
    for c in ct:
        seq += list(inv[c])
    n = len(ct)
    rows, cols = seq[:n], seq[n:]
    return ''.join(SQ[r * 5 + c] for r, c in zip(rows, cols))


def col_encrypt(pt, key):
    pt = ''.join(c for c in pt.upper() if c.isalpha())
    n = len(key)
    cols = [''] * n
    for i, c in enumerate(pt):
        cols[i % n] += c
    order = sorted(range(n), key=lambda i: (key[i], i))
    return ''.join(cols[i] for i in order)


def col_decrypt(ct, key):
    ct = ''.join(c for c in ct.upper() if c.isalpha())
    n = len(key)
    order = sorted(range(n), key=lambda i: (key[i], i))
    # lengths of each column in reading order
    lens = [0] * n
    for i in range(len(ct)):
        lens[i % n] += 1
    coltext = [''] * n
    p = 0
    for i in order:
        coltext[i] = ct[p:p + lens[i]]
        p += lens[i]
    out = ''
    for i in range(len(ct)):
        out += coltext[i % n][i // n]
    return out


def beaufort(pt, key):
    pt = ''.join(c for c in pt.upper() if c.isalpha())
    key = ''.join(c for c in key.upper() if c.isalpha())
    return ''.join(AL[(ord(key[i % len(key)]) - ord(pt[i])) % 26] for i in range(len(pt)))


def beaufort_dec(ct, key):
    # Beaufort is self-inverse
    return beaufort(ct, key)


def vigenere_enc(pt, key):
    pt = ''.join(c for c in pt.upper() if c.isalpha())
    key = ''.join(c for c in key.upper() if c.isalpha())
    return ''.join(AL[(ord(pt[i]) - 65 + ord(key[i % len(key)]) - 65) % 26] for i in range(len(pt)))


def vigenere_dec(ct, key):
    ct = ''.join(c for c in ct.upper() if c.isalpha())
    key = ''.join(c for c in key.upper() if c.isalpha())
    return ''.join(AL[(ord(ct[i]) - ord(key[i % len(key)])) % 26] for i in range(len(ct)))


