ADD['mobile-android-aidl'] = '''## Шаг 6: правильная защита на стороне сервиса

Мы увидели, что `enforceInterface` защищает только от «не того интерфейса». Настоящая
защита должна проверять **личность вызывающего**. Правильный шаблон:

```java
public boolean onTransact(int code, Parcel data, Parcel reply, int flags) {
  int uid = Binder.getCallingUid();
  String pkg = getPackageManager().getNameForUid(uid);
  if (!ALLOWED_PACKAGES.contains(pkg)) {
    return false;   // чужое приложение — отказ
  }
  return super.onTransact(code, data, reply, flags);
}
```

Ещё надёжнее — привязать доступ к подписи: сравнить подпись вызывающего пакета с
эталонной. Тогда даже переустановка приложения с тем же именем не поможет.

Почему `enforceInterface` обходят так легко? Потому что interface token — это просто
строка, которую клиент пишет в `Parcel` сам:

```java
Parcel data = Parcel.obtain();
data.writeInterfaceToken("com.example.bank.IBalance");  // клиент пишет вручную
data.writeInt(amount);
data.writeString(to);
binder.transact(TRANSACTION_transfer, data, reply, 0);
```

Ничто не мешает подставить правильный token. Он подтверждает лишь «я знаю имя
интерфейса», а имя интерфейса лежит в APK и известно любому.

## Если не сработало

* Сервис проверяет `checkCallingOrSelfPermission` — тогда ищи обходной компонент
  (Activity/Provider), который уже имеет это разрешение.
* Транзакция возвращает ошибку — сверь номер `code` и порядок аргументов: AIDL
  генерирует константы `TRANSACTION_*` по порядку объявления методов, и одна лишняя
  строка в контракте сдвигает их.
* В новых версиях Android часть системных Binder-интерфейсов закрыта дополнительно;
  тогда остаётся только динамический анализ с root.

'''

ADD['mobile-android-messenger-ipc'] = '''## Шаг 6: replyTo и обратный канал

У `Message` есть поле `replyTo` — это `Messenger` отправителя, по которому получатель
может ответить. Это и есть обратный канал: клиент шлёт запрос, сервис отвечает ему по
указанному `replyTo`.

```java
Messenger myReply = new Messenger(new Handler(Looper.getMainLooper()) {
  public void handleMessage(Message msg) {
    Log.d("attack", "service replied: " + msg.getData().getString("result"));
  }
});
Message m = Message.obtain(null, SyncService.MSG_SYNC);
m.replyTo = myReply;      // подсовываем свой обратный канал
svc.send(m);
```

Если сервис без проверки отправляет по `replyTo` чувствительные данные (токен,
результат операции, список файлов), они уйдут атакующему. Здесь важно, что сервис
доверяет полю из сообщения — а поле полностью контролирует клиент.

Вторая слабость — **исчерпание очереди**. `Handler` обрабатывает сообщения по одному;
если завалить сервис тысячами `MSG_SYNC`, очередь забьётся, а полезная работа встанет.
Это отказ в обслуживании на ровном месте, без единой уязвимости памяти.

## Если не сработало

* Сервис не экспортирован — тот же приём, что и с bound-сервисом: ищи посредника.
* `handleMessage` проверяет `Binder.getCallingUid()` — тогда подделка сообщения не
  пройдёт, и остаётся только replay, если нет nonce.
* Сообщения с неизвестным `what` просто игнорируются — сверь константы `MSG_*` в
  декомпилированном коде: возможно, ты шлёшь не тот номер команды.

'''

