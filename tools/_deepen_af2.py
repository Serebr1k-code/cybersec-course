ADD['af-timestomping-deep'] = """
## Инструменты timestomping

Атакующий пользуется готовыми средствами. Типовые:

| Инструмент | Что делает |
|------------|------------|
| `SetMace` | правит SI и FN-метки NTFS |
| `timestomp` (Meterpreter) | меняет метки файла |
| PowerShell `Set-ItemProperty` | меняет время через API |
| `touch -t` (Linux) | меняет mtime/atime |
| кастомные утилиты | точечная правка MFT |

Важно понимать разницу в глубине: инструменты, работающие **через API**, обычно трогают
только SI. Инструменты, пишущие **напрямую в MFT**, могут изменить и FN — но это сложнее и
опаснее (можно повредить ФС). Большинство атакующих выбирают простой путь и оставляют
расхождение SI/FN.

## Наш пример: круглые метки

Разберём случай, когда расхождения SI/FN нет, но подделка всё равно видна. Смотрим метки
файла:

```
Created:  2024-01-01 00:00:00.0000000
Modified: 2024-01-01 00:00:00.0000000
Accessed: 2024-01-01 00:00:00.0000000
```

Три метки совпадают до микросекунды и стоят ровно на полночь 1 января. Для реального файла
это почти невозможно: система ставит точные значения с микросекундами. Такое «идеальное»
совпадение — след ручной правки. Признак работает даже там, где FN недоступен.

## Сверка с другими артефактами

Метки времени файла — не единственный источник времени. Их сверяют с:

- **USN-журналом** — фиксирует изменения в NTFS независимо от меток;
- **Prefetch / Amcache** — когда программа запускалась;
- **журналами событий** — когда происходили системные действия;
- **сетевыми логами** — когда хост общался с внешним миром.

Если файл заявлен как «созданный в 2019», но USN говорит 2026, а Prefetch — что программа
запускалась в 2026, картина однозначна: метка подделана. Чем больше независимых источников
против одного, тем надёжнее вывод.

## Продвинутые приёмы и их разоблачение

Опытные атакующие пытаются обойти обнаружение:

- **правят и SI, и FN** — тогда расхождения нет; спасает сверка с USN;
- **копируют метки системного файла** — маскировка; спасает несоответствие содержимого;
- **устанавливают время «в прошлом», но позже установки ОС** — чтобы выглядело правдоподобно;
- **правят журналы** — но это оставляет свои следы (пропуски, разрывы).

Разоблачение всегда опирается на **независимость источников**: чем больше артефактов
подтверждают одно время, тем труднее подделать их все. Идеальная подделка требует правки
всех журналов, что само по себе оставляет следы.

## Влияние на таймлайн

Timestomping — атака именно на таймлайн, поэтому его обнаружение критично для выводов.
Практический порядок:

1. Построй таймлайн из всех источников.
2. Найди файлы с аномальными метками (расхождение, «круглые», невозможные даты).
3. Проверь эти файлы по независимым источникам.
4. Помечай подделанные метки в таймлайне, чтобы не строить на них выводы.
5. В отчёте укажи, что метки подделаны и на чём основан вывод.

Так подделка не сбивает расследование, а становится его частью — свидетельством умысла.

## Мини-упражнение

Возьми образ с NTFS, выгрузи метки SI и FN через MFTECmd и найди файлы, где времена создания
расходятся. Затем сверь их с USN-журналом. С большой вероятностью ты найдёшь хотя бы один
файл с подделанными метками — и поймёшь, как систематически ловить timestomping.

## Резюме

Timestomping подделывает метки времени, чтобы спрятать файлы и сбить таймлайн. Обнаружение
строится на расхождении SI/FN, аномальных значениях (круглые, обнулённые микросекунды,
невозможные даты) и, главное, на сверке с независимыми источниками — USN, Prefetch,
журналами. Идеальная подделка требует правки всех источников, что оставляет новые следы.
"""

