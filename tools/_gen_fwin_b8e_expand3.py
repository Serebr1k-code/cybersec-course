#!/usr/bin/env python3
"""Third top-up for batch E."""
import re

ADD = {}

ADD["win-evtx-tampering"] = r'''
## Типичные ошибки при проверке журналов

Соберём промахи в одном месте. Первый — считать журнал достоверным без проверки: если его
чистили, выводы на его основе шатки. Второй — путать «журнал короткий из-за ротации» и
«журнал вычищен»: ротация оставляет непрерывные record ID, а очистка — разрыв. Третий —
игнорировать метаданные файла: дата создания журнала нередко выдаёт подмену. Четвёртый — не
проверять теневую копию, где могут сохраниться удалённые записи. Пятый — не фиксировать сам
факт вмешательства: попытка скрыть следы — тоже улика. Держи эти пять пунктов в чек-листе, и
проверка журналов будет надёжной.
'''

ADD["win-registry-recovery"] = r'''
## Типичные ошибки при восстановлении реестра

Перечислим промахи. Первый — анализировать только «голый» hive и не смотреть `.LOG`-файлы:
там могут быть последние изменения. Второй — игнорировать слэк: удалённые ключи часто остаются
в неиспользованном месте. Третий — забывать про теневую копию: это самый надёжный источник
для сравнения. Четвёртый — делать вывод об отсутствии ключа по текущему hive, не проверив
альтернативные источники. Пятый — не связывать восстановленный ключ с журналами (7045/4697),
теряя подтверждение. Учитывая эти пункты, ты восстановишь то, что атакующий считал надёжно
удалённым.
'''

ADD["win-quarantine"] = r'''
## Типичные ошибки при работе с карантином

Соберём промахи. Первый — работать с оригиналом карантина вместо копии (риск повредить
данные). Второй — восстанавливать образец в систему, где он может выполниться (риск повторного
заражения). Третий — не считать хеш сразу после восстановления (образец теряет
идентификацию). Четвёртый — игнорировать метаданные, если образец восстановить не удалось
(путь и время всё равно ценны). Пятый — не сопоставлять карантин с AmCache/Prefetch (теряется
история файла). Держи эти пункты в чек-листе — и карантин даст максимум пользы без риска.
'''

ADD["win-windows-update"] = r'''
## Типичные ошибки при анализе обновлений

Перечислим промахи. Первый — смотреть только список KB и не разбирать журналы на предмет
откатов. Второй — игнорировать время установки: обновление вне окна обслуживания —
подозрительно. Третий — не проверять политику и источник обновлений. Четвёртый — не связывать
изменения с инцидентом (таймлайн). Пятый — делать вывод об уязвимости без сверки с базой CVE на
дату инцидента. Учитывая эти пункты, ты оценишь и уровень патчей, и возможные подмены, и их
связь с компрометацией.
'''

for lid, add in ADD.items():
    p = f"content/forensics/{lid}.md"
    t = open(p, encoding="utf-8").read()
    m = re.search(r"^## Квиз\s*$", t, re.MULTILINE)
    open(p, "w", encoding="utf-8").write(t[:m.start()] + add.strip() + "\n\n" + t[m.start():])
    print("topup", lid)
