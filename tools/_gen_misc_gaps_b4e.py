def quiz(qs):
    out = ['## Квиз', '', 'Проверь себя.', '', '```quiz']
    for q, opts, a, exp in qs:
        out.append('- question: ' + q)
        out.append('  options:')
        for o in opts:
            out.append('    - ' + o)
        out.append('  answer: ' + str(a))
        if exp:
            out.append('  explanation: ' + exp)
    out.append('```')
    return '\n'.join(out)


def add(lesson, text):
    p = 'content/misc/' + lesson + '.md'
    s = open(p, encoding='utf-8').read()
    m = re.search(r'^## Квиз\s*$', s, re.MULTILINE)
    out = s[:m.start()] + text.strip() + '\n\n' + s[m.start():]
    open(p, 'w', encoding='utf-8').write(out)


