#!/usr/bin/env python3
"""Split wave-created hubs with >5 children into sub-hubs (max 4 children each).

Creates new 'Модуль:' navigation pages under the original hub and reparents the
listed children into them.  Run from the repo root.
"""
import os
import re
import glob

CONTENT = "content"


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def get_fm(txt):
    m = re.match(r"^---\n(.*?)\n---\n", txt, re.S)
    if not m:
        return {}
    fm = {}
    for line in m.group(1).split("\n"):
        mm = re.match(r"^([A-Za-z0-9_]+):\s*(.*)$", line)
        if mm:
            fm[mm.group(1)] = mm.group(2).strip().strip('"').strip("'")
    return fm


# locate every lesson once
ID2PATH = {}
for p in glob.glob(os.path.join(CONTENT, "**", "*.md"), recursive=True):
    fm = get_fm(read(p))
    if fm.get("id"):
        ID2PATH[fm["id"]] = p


def title_of(cid):
    p = ID2PATH.get(cid)
    if not p:
        return cid
    return get_fm(read(p)).get("title", cid)


