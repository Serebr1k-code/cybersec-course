def bullets_block(children):
    out = []
    for c in children:
        out.append("- **%s** — %s." % (c, title_of(c)))
    return "\n".join(out)


def quiz_block(qs):
    out = []
    for question, options, ans, expl in qs:
        out.append("- question: %s" % question)
        out.append("  options:")
        for o in options:
            out.append('    - "%s"' % o)
        out.append("  answer: %d" % ans)
        out.append("  explanation: %s" % expl)
    return "\n".join(out) + "\n"


def list_block(items):
    return "\n".join("- %s" % x for x in items)


