def set_parent_order(path, parent, order):
    txt = read(path)
    m = re.match(r"^---\n(.*?)\n---\n", txt, re.S)
    if not m:
        raise SystemExit("no frontmatter: " + path)
    body = m.group(1)
    body = re.sub(r"(?m)^parent:\s*.*$", "parent: %s" % parent, body)
    body = re.sub(r"(?m)^order:\s*.*$", "order: %d" % order, body)
    new = txt[:m.start(1)] + body + txt[m.end(1):]
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)


def main():
    created = 0
    reparented = 0
    for spec in SPECS:
        parent = spec["parent"]
        cat = spec["cat"]
        # write sub-hubs + reparent
        for sub in spec["subs"]:
            path = os.path.join(CONTENT, cat, sub["id"] + ".md")
            if os.path.exists(path):
                print("skip existing", path)
            else:
                txt = TEMPLATE.format(
                    id=sub["id"], title=sub["title"], cat=cat, parent=parent,
                    order=sub["order"], summary=sub["covers"].capitalize(),
                    covers=sub["covers"], bullets=bullets_block(sub["children"]),
                    why=sub["why"], can=list_block(sub["can"]),
                    useful=list_block(sub["where"]),
                    quiz=quiz_block(sub["q"]), where=list_block(sub["where"]),
                )
                with open(path, "w", encoding="utf-8") as f:
                    f.write(txt)
                created += 1
                print("wrote", path)
            # reparent children
            for i, child in enumerate(sub["children"], start=1):
                cpath = ID2PATH.get(child)
                if not cpath:
                    print("  !! missing child", child)
                    continue
                set_parent_order(cpath, sub["id"], i)
                reparented += 1
    print("\ncreated=%d reparented=%d" % (created, reparented))


if __name__ == "__main__":
    main()
