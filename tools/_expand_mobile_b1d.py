"""Fourth expansion: final push of batch-1 mobile lessons over 1200 words."""
import re, os

ROOT = '/home/Serebr1k/learning_tree'


def append(lesson_id, add):
    p = os.path.join(ROOT, 'content/mobile', lesson_id + '.md')
    txt = open(p, encoding='utf-8').read()
    m = re.search(r'^## Квиз\s*$', txt, re.MULTILINE)
    assert m, lesson_id
    txt = txt[:m.start()] + add.strip() + '\n\n' + txt[m.start():]
    open(p, 'w', encoding='utf-8').write(txt)
    print('expanded', lesson_id)


append('mobile-android-accessibility', '''
## Шаг 16: как это выглядит в трафике и логах

Даже когда сервис не рисует overlay, его работа заметна. В `adb logcat` видны сообщения
самого приложения о прочитанных событиях, если разработчик оставил отладочный вывод. В
сетевом трафике — периодические POST-запросы на незнакомый домен сразу после ввода текста в
банковском приложении. Корреляция «пользователь ввёл пароль — ушёл POST» — сильный признак
кейлоггера. При анализе полезно запустить приложение на тестовом устройстве, ввести
контрольную строку в любое поле и посмотреть, не появится ли эта строка в исходящем запросе.
Это прямой эксперимент, который почти всегда подтверждает злоупотребление, если оно есть.
''')

