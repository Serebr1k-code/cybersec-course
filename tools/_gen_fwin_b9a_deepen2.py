ADD['win-dns-cache'] = r'''
## Разбор журнала DNS Client на конкретном примере

Представим выгрузку операционного журнала DNS Client. Каждое событие 3006 несёт поля
`QueryName` (имя), `QueryType` (тип записи, например `A`, `AAAA`, `TXT`), `QueryOptions`,
а событие 3008 добавляет `QueryResults` — полученные адреса. Разбирая их по порядку,
получаем поток запросов во времени:

```
QueryName=dc01.corp.local      QueryType=A     QueryResults=10.0.0.10
QueryName=update.cdn-static.net QueryType=A    QueryResults=185.199.108.153
QueryName=c2-beacon.evil-cdn.example QueryType=TXT QueryResults=45.77.12.9
```

Здесь видно два тревожных сигнала сразу: подозрительное имя с «beacon» и тип `TXT` для
внешнего домена. Обычные рабочие станции не запрашивают TXT у внешних доменов — это
типично для туннелей и управления через DNS.

## Файл hosts и обход DNS

Атакующий может вообще не давать DNS-запросов, если прописал домен в
`C:\Windows\System32\drivers\etc\hosts`. Файл статичен, не истекает и легко упускается.
Проверка `hosts` — обязательный шаг: сопоставьте записи в нём с временем модификации
файла. Если имя C2 прописано в `hosts` и файл менялся в окно активности — это прямой
след. Аналогично проверяют реестровые override-настройки DNS-клиента.

## Сопоставление DNS с прокси и фаерволом

DNS-запрос — только намерение. Чтобы доказать фактический контакт, находки из DNS
сопоставляют с:

- **логами прокси** — был ли исходящий HTTP(S) к найденному домену/IP;
- **логами фаервола** — устанавливалось ли соединение на 443/80 к тому адресу;
- **сетевыми соединениями из памяти** (`netscan` в Volatility) или выгрузкой `netstat`;
- **журналом SMB-клиента**, если имя было файловым сервером.

Связка «DNS-запрос + установленное соединение» — самый убедительный вывод. Один лишь
запрос может быть следствием сканирования или случайного перехода по ссылке.
'''

ADD['win-wer'] = r'''
## WER и LiveKernelReports

Помимо пользовательских падений, WER собирает отчёты о сбоях **ядра** — они лежат в
`C:\Windows\LiveKernelReports\`. Такие отчёты часто появляются, когда драйвер «зависает»
и система перезагружается. Для расследования они ценны по двум причинам:

- по имени драйвера в отчёте видно, **что** сломалось (вредоносные драйверы и руткиты
  часто и вызывают сбои);
- сам дамп ядра (`*.dmp`) содержит память ядра, где можно искать скрытые драйверы и
  внедрённый код.

Отчёты ядра переживают перезагрузку и хранятся дольше пользовательских.

## Чтение дампа без отладчика

Не всегда нужен полноценный отладчик. Быстрый триаж дампа:

```
$ strings -n 6 memory.hdmp | grep -Ei 'http|\.exe|\\\\Users|C2' | head
```

Строки выдают URL, пути, аргументы командной строки. Для более серьёзного разбора дамп
открывают в WinDbg с командой `!analyze -v` — она сама показывает модуль, адрес
исключения и стек. В отчёте фиксируют: имя процесса, путь, время падения и найденные
строки. Помните: дамп — это память **одного процесса**, а не всей системы.

## Типичные вопросы форензика к WER

- **Запускалась ли программа?** Наличие отчёта с её `AppName` — сильное подтверждение.
- **Откуда она запускалась?** `AppPath` даёт полный путь, даже если файл удалён.
- **Когда?** `EventTime` (FILETIME, UTC) кладётся на таймлайн.
- **С чем работала?** Строки и модули из дампа показывают библиотеки и адреса.
- **Не подделка ли?** Проверяют целостность каталога и `LastWriteTime` файлов.

WER хорошо сочетается с AmCache (хеши) и Prefetch (время): вместе они дают путь, хеш и
время запуска одной программы.
'''

ADD['win-edr-logs'] = r'''
## Построение таймлайна из детекций

Детекции EDR — это уже упорядоченный по времени поток, из которого собирается таймлайн.
Практический порядок:

1. Выгрузить все детекции за окно инцидента (в JSON/CSV).
2. Отсортировать по времени и нормализовать часовой пояс (обычно UTC).
3. Сгруппировать по процессу/пользователю, чтобы увидеть серии действий.
4. Наложить на MITRE ATT&CK: сопоставить каждую детекцию с техникой.

Получится примерно такая картина:

```
10:11  Recon              whoami                        T1033
10:12  CredentialTheft    lsass memory access           T1003.001
10:13  Persistence        run key added                 T1547.001
10:15  LateralMovement    smb admin share               T1021.002
```

Такой таймлайн читается как история атаки и напрямую ложится в отчёт.

## Ложные срабатывания и как их отсеивать

EDR ошибается: административные скрипты, системы резервного копирования и легитимные
инструменты (PsExec, PowerShell) вызывают те же детекции, что и атакующие. Отсеивают так:

- проверяют **подпись** и путь бинарника (легитимный подписан из `Program Files`);
- смотрят **родителя**: `services.exe → psexec` от администратора — норма;
- сверяют с **whitelist** и известными задачами (бэкап, мониторинг);
- учитывают **время**: активность в рабочее окно админа — вероятнее легитимна.

Правило: одна детекция — это сигнал, а не вывод. Вывод делают по совокупности и в
контексте.

## Что делать, если EDR нет вовсе

На части машин EDR не стоит. Тогда те же вопросы закрывают системными источниками:

- **Sysmon** (если настроен) — процессы, сеть, DNS, загрузки драйверов;
- **Security EVTX** — 4688 (создание процесса), 4624/4625 (входы), 4697/7045 (службы);
- **PowerShell 4104** — содержимое скриптов;
- **AmCache/Prefetch** — следы исполнения.

Отсутствие EDR не означает отсутствие следов — означает, что их придётся собирать из
нескольких системных журналов и связывать вручную.
'''

ADD['win-app-compat'] = r'''
## ShimCache против AmCache и Prefetch

Три артефакта часто путают, хотя у них разные роли:

- **ShimCache (AppCompat cache)** — пути файлов, прошедших через shim-движок; на новых
  Windows есть флаг исполнения. Отвечает на вопрос «существовал ли файл / запускался».
- **AmCache** — база `Amcache.hve` с записями о запущенных/установленных программах и
  их **SHA-1**. Даёт хеш файла, что бесценно для сверки с VirusTotal.
- **Prefetch** — файлы `C:\Windows\Prefetch\*.pf`, по одному на программу, с **временем
  запуска** и счётчиком. Самый точный источник «когда и сколько раз запускалось».

Идеальная связка: Prefetch (когда) + AmCache (что, с хешем) + ShimCache (откуда). Если
все три указывают на один файл — сомнений нет.

## Разбор значения вручную

Когда нет инструмента, значение `AppCompatCache` можно разобрать в hex. Ищем сигнатуру
`10ts` (Win10), затем читаем записи подряд: длина, длина пути, сам путь в UTF-16LE,
время в FILETIME, затем флаги. Пути в UTF-16LE дают характерный «перемежающийся нулями»
вид в hex-дампе:

```
$ xxd AppCompatCache.bin | head
0000: 31 30 74 73 ... 43 00 3a 00 5c 00 55 00 73 00 65 00
```

`43 00 3a 00 5c 00` — это `C:\` в UTF-16LE. Так вручную находят пути, даже без парсера.

## Что писать в отчёте

Формулировка вывода важна для корректности. Нельзя писать «программа запускалась», если
источник — только ShimCache на Windows 7. Корректно:

> В кусте SYSTEM (AppCompatCache) обнаружен путь `C:\Users\Public\svc.exe`,
> LastModified 2024-03-02 10:12 UTC. На данной версии Windows запись содержит флаг
> выполнения, что в совокупности с Prefetch (время запуска 10:13) указывает на запуск
> программы с указанного пути.

Такой стиль фиксирует источник, время, ограничение метода и подтверждающий артефакт —
именно так и строится защищаемый форензик-вывод.
'''

def main():
    for lid, add in ADD.items():
        path = os.path.join(ROOT, 'content', 'forensics', lid + '.md')
        lesson = open(path, encoding='utf-8').read()
