import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, 'content', 'osint')

def add(lesson_id, text):
    path = os.path.join(CONTENT, lesson_id + '.md')
    lesson = open(path, encoding='utf-8').read()
    if text.strip()[:40] in lesson:
        print('already:', lesson_id); return
    m = re.search(r"^## Квиз\s*$", lesson, re.MULTILINE)
    lesson = lesson[:m.start()] + text.strip() + "\n\n" + lesson[m.start():]
    open(path, 'w', encoding='utf-8').write(lesson)
    print('expanded3', lesson_id)

